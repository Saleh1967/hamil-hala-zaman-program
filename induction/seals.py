# بالوديعة المودَعة **بايتًا ببايت**، ثمّ يقرأ كلَّ ختمٍ **من المخرَج الطازج لا من
# الوديعة** ويصادمه. فلا رقمَ في هذا المجلَّد إلا وله مولِّدٌ حيٌّ يمرّ عليه CI.
#
# **الصنفُ يفصل العرضَ عن الحكم** — وهي العلّةُ الثانية («معرَّض»):
#   **بوّابة** — رقمٌ حاكم: انحرافُه يُسقط CI.
#   **شاهد**  — رقمٌ معروضٌ لا يحكم: يُطبَع موسومًا، ولا يُنشَر مجرَّدًا عن فاتورته.
