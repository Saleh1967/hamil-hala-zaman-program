MISSING = "\u2329مسارٌ مفقود\u232a"

# المسبارُ ومخرَجُه: أكثرُها يقبل `--json X`، ومحرّكُ الاستقراء يقبل `--json=X` وقيدَ المجمَّد.
PROBES = ("induction_engine", "online_peel", "mirror", "deposit_law",
          "tensor_law", "jami3_mani3", "hiyad")
DEPOSIT = {"induction_engine": "results"}
ARGV = {"induction_engine": lambda out: [f"--json={out}", "--require-corpus"]}


def dig(obj, path):
    for k in path:
        obj = obj[k]
    return obj


def regen(probe, out):
    """تشغيلُ المسبار من الصفر إلى ملفٍّ مؤقّت — لا قراءةَ من الوديعة."""
    args = ARGV.get(probe, lambda o: ["--json", o])(out)
    r = subprocess.run([sys.executable, os.path.join(ROOT, probe + ".py")] + args,
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        raise SystemExit(f"::error::المسبارُ {probe} سقط — {r.stderr.strip()[-400:]}")
    return out


def regen_all(check_bytes=True):
    """يعيد توليد الودائع كلِّها، ويصادم كلَّ وديعةٍ بايتًا ببايت، ويعيد المخرَجاتِ الطازجة."""
    fresh, diffs = {}, []
    tmp = tempfile.mkdtemp(prefix="seals-")
    for p in PROBES:
        out = regen(p, os.path.join(tmp, p + ".json"))
        fresh[p] = json.load(open(out, encoding="utf-8"))
        dep = os.path.join(ROOT, DEPOSIT.get(p, p) + ".json")
        if check_bytes:
            if not os.path.exists(dep):
                diffs.append((p, "الوديعةُ غائبة"))
            elif open(dep, "rb").read() != open(out, "rb").read():
                diffs.append((p, "الوديعةُ خالفت مخرَجَ المولِّد"))
    return fresh, diffs


def falsify(fresh):
    """اختبارُ التكذيب: حارسٌ لا يستطيع أن يرفض ليس حارسًا.
    يُبدَّل رقمُ ختمٍ ويُخرَّب مسارُ آخرَ في الذاكرة، ويُتحقَّق أنّ كليهما يسقط."""
    trials, ok = [], True
    for name, mut in (("رقمٌ مبدَّلٌ بواحد", "قيمة"), ("مسارٌ مخرَّب", "مسار")):
        s = dict(SEALS[7])                       # الفاتورة · المودَع يُقبَل (−15,321)
        s[mut] = (s["قيمة"] + 1 if mut == "قيمة" else s["مسار"] + ["لا_شيء"])
        try:
            got = dig(fresh[s["وديعة"]], s["مسار"])
        except (KeyError, IndexError, TypeError):
            got = MISSING
        rejected = got != s["قيمة"]
        trials.append(dict(محاولة=name, مرفوضة=rejected))
        ok &= rejected
    return trials, ok


def main():
    ap = argparse.ArgumentParser(description="سجلُّ الأختام الحيّ — يولِّد ويصادم")
    ap.add_argument("--json")
    ap.add_argument("--no-bytes", action="store_true",
                    help="تخطّي مصادمة الودائع بايتًا ببايت (للتشخيص وحدَه)")
    a = ap.parse_args()

    print("سجلُّ الأختام الحيّ — كلُّ رقمٍ يولَّد ثمّ يُصادَم، ولا ثابتَ ميتٌ يُطبَع")
    print(f"  المسبارات: {len(PROBES)} · الأختام: {len(SEALS)} "
          f"({sum(1 for s in SEALS if s['صنف'] == بوّابة)} بوّابةً · "
          f"{sum(1 for s in SEALS if s['صنف'] == شاهد)} شاهدًا)\n")

    fresh, diffs = regen_all(check_bytes=not a.no_bytes)
    print("— ① إعادةُ توليد الودائع ومصادمتُها بايتًا ببايت —")
    for p in PROBES:
        bad = next((d for q, d in diffs if q == p), None)
        print(f"  {p:14s} " + (f"✗ {bad}" if bad else "✓ مُعاد الإنتاج بفارق صفر"))
    print()

    print("— ② مصادمةُ الأختام على المخرَج الطازج (لا على الوديعة) —")
    broken, missing = [], []
    for s in SEALS:
        try:
            got = dig(fresh[s["وديعة"]], s["مسار"])
        except (KeyError, IndexError, TypeError):
            got = MISSING
            missing.append(s)
        ok = got == s["قيمة"]
        tag = f"[{s['صنف']}]"
        print(f"  {'✓' if ok else '✗'} {tag:9s} {s['اسم']:32s} {s['قيمة']!s:>12s} "
              f"{s['مقام']}" + ("" if ok else f"  ⟵ المولِّدُ أعطى {got!r}"))
        if not ok:
            broken.append((s, got))

    trials, falsifiable = falsify(fresh)
    print("\n— ③ اختبارُ التكذيب (حارسٌ لا يرفض ليس حارسًا) —")
    for t in trials:
        print(f"  {'✓' if t['مرفوضة'] else '✗'} {t['محاولة']:20s} "
              f"{'رُفض' if t['مرفوضة'] else 'مرّ — الحارسُ أعمى'}")
    if not falsifiable:
        print("::error::سجلُّ الأختام لا يستطيع أن يرفض — حارسٌ أعمى — صريخ")

    print("\n— ④ الحكم —")
    # المسارُ المفقودُ قاتلٌ مهما كان الصنف: شاهدٌ لا يولَّد رقمٌ ميتٌ أيضًا،
    # وإسكاتُه بحجّة «إنه لا يحكم» إعادةٌ للعلّة من بابها.
    gates = [b for b in broken if b[0]["صنف"] == بوّابة or b[1] is MISSING]
    wits = [b for b in broken if b not in gates]
    if gates:
        for s, got in gates:
            why = ("مسارُه غائبٌ عن مخرَج المولِّد — ختمٌ بلا مولِّدٍ حيّ"
                   if got is MISSING else f"المودَع {s['قيمة']!r} والمولِّدُ {got!r}")
            print(f"::error::ختمٌ سقط: {s['اسم']} — {why}. "
                  "لا يمرّ إلا بتعديل seals.py باشتقاقٍ معلنٍ في رسالة الالتزام")
    if diffs:
        for p, d in diffs:
            print(f"::error::وديعةٌ خالفت مولِّدَها: {p} — {d}")
    if wits:
        for s, got in wits:
            print(f"::warning::ختمُ شاهدٍ انحرف: {s['اسم']} ({s['قيمة']!r} ⟶ {got!r}) "
                  "— شاهدٌ لا يحكم، لكنّ انحرافَه يُسمّى")

    ok = not gates and not diffs and falsifiable
    print("  " + ("كلُّ ختمٍ نابضٌ بمولِّده، والودائعُ مُعادةُ الإنتاج بفارق صفر ✓"
                  if ok else "سقط: ختمٌ حاكمٌ انحرف أو وديعةٌ خالفت مولِّدَها ✗"))
    print("  والشواهدُ موسومةٌ لا تحكم — وعدّادُ الإجماع منها بنصِّ برهانه "
          "(مختلقٌ 0.0953 > مودَع 0.0649)")

    R = dict(مسبارات=list(PROBES),
             أختام=[dict(اسم=s["اسم"], صنف=s["صنف"], قيمة=s["قيمة"], مقام=s["مقام"],
                         وديعة=s["وديعة"], ملاحظة=s["ملاحظة"]) for s in SEALS],
             بوّابات=sum(1 for s in SEALS if s["صنف"] == بوّابة),
             شواهد=sum(1 for s in SEALS if s["صنف"] == شاهد),
             ودائعُ_خالفت=[p for p, _ in diffs],
             أختامٌ_انحرفت=[s["اسم"] for s, _ in broken],
             أختامٌ_بلا_مولِّد=[s["اسم"] for s in missing],
             اختبارُ_التكذيب=trials,
             الحكم="حيٌّ: كلُّ ختمٍ يولَّد ويُصادَم" if ok else "ساقط")
    if a.json:
        json.dump({"سجلُّ_الأختام": R}, open(a.json, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=2, sort_keys=True, default=str)
        print(f"JSON ⟵ {a.json}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
