#
# **حارسُ التغيُّر**: إن تبدّل رقمُ ختمٍ سقط CI، ولا يمرّ إلا بتعديلٍ **في هذا الملفّ**
# مع اشتقاقٍ معلنٍ في رسالة الالتزام. فلا يتغيّر رقمٌ صامتًا، ولا يبقى رقمٌ لا يولَّد.
