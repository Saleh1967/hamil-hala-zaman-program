def discovery_ledger():
    """سجلُّ مرشّحي الختم: رصيدُ كلِّ مصدرٍ غيرِ مختوم — **يُعرَض على المالك ولا يحكم**.

    فحين يكتمل الرصيدُ يصير السؤالُ مستحقًّا بشهادة اكتشافاتٍ لا تخمينًا: «هذا المصدرُ
    أنتج N تطابقاتٍ فأرْجِحه؟» — والجوابُ بيد المالك وحدَه، بإحضارِ البايتات وكتابةِ
    FROZEN. ولا يرقّي هذا السجلُّ مصدرًا بعدده مهما بلغ.
    """
    ledger = {}
    for d in DISCOVERIES:
        entry = ledger.setdefault(d["مصدر"], {"وسم": d["وسم"], "رصيد": 0,
                                              "أختامٌ_طابقها": []})
        entry["رصيد"] += 1
        entry["أختامٌ_طابقها"].append(d["ختمٌ_مطابق"])
    return {
        "مرشّحو_الختم": ledger,
        "الكلّ": len(DISCOVERIES),
        "الحكم": "لا حكم — رصيدُ ترشيحٍ يُعرَض، والختمُ بإحضار البايتات وحدَه",
    }


