# deposit_law.py — قانون الوديعة الصالحة: لا إجماعَ يرتفع إلا بوديعةٍ تجتاز فحصًا **يمكن أن يرفض**.
#
# القانونُ المُسلَّم كان أربعةَ شروط: ① انعكاس ② كرافت ≤ 1 ③ اشتقاق ≤ سعة ④ حارسٌ صفر.
# وقد عُرضت الأربعةُ على سؤالٍ واحد — **هل يستطيع هذا الشرطُ أن يرفض؟** — فسقط ثلاثةٌ منها:
#
#   ① **الانعكاس لا يرفض**: `build(*peel(w))` يلصق `suf` على `sk[:-len(suf)]` فيعيد `sk`
#      **جبرًا**، مهما كان الجدول. (مقيسٌ في mirror.py: أربعةُ جداولَ مكذِّبةٍ أعطت 1.0000.)
#   ② **الكرافتُ لا يرفض**: شجرةُ هوفمان **كاملةٌ ببنائها**، فـΣ2^−dᵢ = 1 على كلِّ توزيع.
#      جُرّب على 2,000 توزيعٍ عشوائيّ وعلى منحرفٍ [1,1,1,10⁹] وعلى [5] — فكانت 1.0 كلُّها.
#      فالسطرُ يطبع ثابتًا لا قياسًا. (والإغلاقُ التامُّ ليس فضيلةَ الوديعة بل خاصّةَ هوفمان.)
#   ③ **السعةُ لم تُقارَن**: `cap` يُحسَب ويُطبَع ولا يُعرَض عليه مشتقٌّ قطّ. فالشرطُ مكتوبٌ
#      لا مُجرًى. (وقد أُجري هنا: H₀ الحالات المرخَّصة **1.7793** تحت السقف **1.9227** بفجوة
#      0.1434 — فالشرطُ **يمرّ حقًّا**، لكنّه لم يكن ممرورًا قبل أن يُقارَن.)
#   ④ **الحارسُ الرابع وحدَه يرفض** — وهو المعجونُ الوحيدُ في المُسلَّم: قائمةُ حراسٍ معلّقةٍ
#      بأسمائها. فبقي من الأربعة **واحد**.
#
# ── القانونُ بعد الإصلاح: شرطُ القبول واحدٌ وقابلٌ للرفض ────────────────────────────
#   وديعةٌ d صالحة ⟺  ① **الفاتورة**: Δ = L(D|M) + L(M) − L₀ < 0   (الوصفُ الأدنى)
#                    ∧ ② **السقف**: مشتقُّها ≤ سعةُ مستواها المحروسة
#                    ∧ ③ **الحارس**: حدُّها صفرٌ أو استثناءٌ مسمًّى معدود
#   والفرقُ الجوهريُّ عن عدّاد الإجماع: **الفاتورةُ تُحاسِب على الجدول**. وعدّادُ الإجماع لا
#   يُحاسب، فكافأ جدولًا مختلقًا بـ0.0953 فوق المودَع 0.0649. والفاتورةُ ترفضه: Δ = +6,281.
#
# ── ثابتُ النظام ──────────────────────────────────────────────────────────────────
#   الخام = المشتق + المحمول · والإجماعُ عرضٌ موسوم لا حَكَم؛ **الحَكَمُ الفاتورةُ**.
