# ── ⓪ المصادقُ المركزيّ: حَكَمٌ واحدٌ يستدعيه كلُّ محرّك ─────────────────────────────
#   العلّةُ التي يقتلها: كان نصُّ الحكم مُعادَ الكتابةِ في أربعة محرّكاتٍ وفي سجلِّ الأختام
#   نفسِه («يُقبَل» if Δ<0 else «يُرفَض»، و«منحلّ» if |Σ|/N>0.5). فكان القانونُ خمسَ نسخٍ
#   متوافقةٍ بالصدفة لا بالبناء: لو تغيّر الحدُّ في واحدةٍ لتخالفت الودائعُ صامتةً، ولصادَق
#   المدقِّقُ نفسَه بقانونٍ غيرِ قانونِ المُدقَّق. فصار الحكمُ هنا وحدَه، وكلُّ محرّكٍ **وديعةٌ
#   عند القانون** لا جارٌ عليه — ويفحص `seals.contracts` أن لا نسخةَ سادسةَ تُولَد.
ACCEPT, REJECT = "يُقبَل", "يُرفَض"
DEGENERACY_CEILING = 0.5        # |Σ|/N فوقه: السياقاتُ تكاد تُفرَد، فالمكسبُ إفراطُ تخصيص


def verdict(delta):
    """حكمُ الفاتورة الوحيد: Δ = L(D|M) + L(M) − L₀ — والقبولُ **دون الصفر قطعًا**.

    الحدُّ صارم (`< 0` لا `<= 0`): وديعةٌ بفاتورةٍ صفرٍ لا تشتري شيئًا، فلا تُودَع.
    وتُرفَض القيمةُ غيرُ المحدَّدة صراحةً: لا حكمَ على ما لا يُقاس.
    """
    delta = float(delta)
    if delta != delta or delta in (float("inf"), float("-inf")):
        raise ValueError(f"فاتورةٌ غيرُ محدَّدة ({delta}) — لا حكمَ على ما لا يُقاس")
    return ACCEPT if delta < 0 else REJECT


def degenerate(alphabet, length):
    """حارسُ الانحلال |Σ|/N: يُرَدّ (النسبةُ مدوَّرةً، أمنحلٌّ هي؟) — ولا يُنقَل رقمُ المنحلّ."""
    if length <= 0:
        raise ValueError("طولٌ غيرُ موجبٍ — لا انحلالَ يُقاس على فراغ")
    deg = alphabet / length
    return round(deg, 4), deg > DEGENERACY_CEILING


# ── ⓪½ البندُ صفر: المكيالُ العام — دالّةٌ واحدةٌ تُسعِّر تيّارَ رموزٍ أيًّا كان مصدرُه ──
#   العلّةُ التي يقتلها: `verdict` وحّد **الحكم** ولم يوحِّد **الكيل**. فكان كلُّ بابٍ يكتب
#   ثمنَه بيده (`bill` مخيطٌ على القلع، و`rung` كان يكتب b + خلايا·log₂(N+1) في جسده)، فلو
#   تخالفت سياسةُ الترميز بين بابين لتقابلت فاتورتاهما بالصدفة لا بالبناء — وهو عينُ العطل
#   الذي قتله `sole_judge` في الحكم. فصار الكيلُ هنا وحدَه، و`rung` **وديعةٌ عنده** لا جارٌ
#   عليه: أُزيل جسدُه الحسابيُّ وصار يستدعي `price` مرّتين — بفارق صفرٍ على الأرقام المختومة.
#
#   والسياسةُ المعلنةُ (موروثةٌ من `induction_engine`، لا مخترعةٌ هنا):
#     L(D|M) = Σ −n·log₂(n/الحاضنة)      الحاضنةُ: N في الرتبة ٠ · ctx[a] في الرتبة ١
#     L(M)   = (عددُ الخلايا)·log₂(N+1)   ترميزُ عدٍّ مسطَّحٌ للخلية
#   والمصدرُ **لا يدخل الحساب البتّة**: لا يقرأ `price` ملفًّا ولا يعرف مجمَّدًا من شاهد —
#   يأخذ رموزًا قابلةً للتجزئة ويردّ بتّات. وهذا شرطُ عموميّته: يُسعَّر به مصدران في تجربةٍ
#   واحدةٍ فتكون كلفتاهما **مقارَنتين** لا رقمين متجاورين.
PRICE_ORDERS = (0, 1)


def price(stream, order=0):
    """المكيالُ العام: كلفةُ تيّارِ رموزٍ بتًّا = L(D|M) + L(M).

    `stream` أيُّ متكرِّرٍ من رموزٍ قابلةٍ للتجزئة (حروفٌ · هيئاتٌ · كلماتٌ · أزواجٌ …)
    من أيِّ مصدرٍ كان. و`order` ٠ (بلا شرط) أو ١ (مشروطٌ على الجار).
    يُرَدّ قاموسٌ بحقوله، ولا يُدوَّر شيءٌ هنا: التدويرُ حقُّ المستهلك لا حقُّ المكيال.
    """
    if order not in PRICE_ORDERS:
        raise ValueError(f"رتبةٌ غيرُ معلنة ({order}) — المعلَنُ {PRICE_ORDERS}")
    seq = list(stream)
    N = len(seq)
    if N == 0:
        raise ValueError("تيّارٌ فارغ — لا كلفةَ تُقاس على فراغ")
    c0 = Counter(seq); V = len(c0)
    if order == 0:
        ld = sum(-n * log2(n / N) for n in c0.values())
        cells = V
    else:
        if N < 2:
            raise ValueError("رتبةٌ ١ على تيّارٍ بطولِ ١ — لا جارَ يُشرَط عليه")
        ctx = Counter(); joint = Counter()
        for a, b in zip(seq, seq[1:]):
            ctx[a] += 1; joint[(a, b)] += 1
        ld = sum(-n * log2(n / ctx[a]) for (a, b), n in joint.items())
        cells = len(joint)
    lm = cells * log2(N + 1)
    return dict(رتبة=order, طول=N, حجمُ_الأبجدية=V, خلايا=cells,
                بيانات=ld, نموذج=lm, كلفة=ld + lm)


def price_two_sources(streams):
    """تجربةُ القبول للبند صفر: **مصدران مختلفان يُسعَّران بتجربةٍ واحدة**.

    `streams` قاموسُ {اسمُ المصدر: تيّار}. تُقاس كلفةُ كلِّ تيّارٍ بالرتبتين بالدالّة
    نفسِها، ويُرَدّ معها **بتٌّ للرمز** — وهو وحدَه ما يجوز أن يُقارَن بين مصدرين
    مختلفَي الطول. والدالّةُ تصرخ إن لم يكن المصدرُ مصدرين فأكثر: تجربةٌ على مصدرٍ
    واحدٍ لا تُثبِت عموميّةَ مكيالٍ البتّة.
    """
    if len(streams) < 2:
        raise ValueError("مصدرٌ واحدٌ لا يُثبِت عموميّةَ المكيال — التجربةُ تقتضي مصدرين فأكثر")
    out = {}
    for name, s in streams.items():
        seq = list(s)
        rows = {}
        for o in PRICE_ORDERS:
            p = price(seq, o)
            rows[f"رتبة{o}"] = dict(كلفة=round(p["كلفة"]), بتٌّ_للرمز=round(p["كلفة"] / p["طول"], 4),
                                    خلايا=p["خلايا"])
        out[name] = dict(طول=len(seq), حجمُ_الأبجدية=len(Counter(seq)), **rows,
                         فرق=round(rows["رتبة1"]["كلفة"] - rows["رتبة0"]["كلفة"]))
    return out


# ── ② الكرافتُ لا يرفض: يُبرهَن بالتوليد لا بالدعوى ────────────────────────────────
def kraft(counts):
    """Σ2^−dᵢ لأطوال هوفمان. **ثابتٌ عند 1** لأنّ الشجرة كاملةٌ ببنائها — لا قياس."""
    h = sorted(counts)
    if len(h) <= 1:
        return 1.0
    toks = list(range(len(h))); depth = {t: 0 for t in toks}; serial = len(h)
    heap = [(v, t, [t]) for v, t in zip(h, toks)]; heapq.heapify(heap)
    while len(heap) > 1:
        v1, _, g1 = heapq.heappop(heap); v2, _, g2 = heapq.heappop(heap)
        for t in g1 + g2:
            depth[t] += 1
        heapq.heappush(heap, (v1 + v2, serial, g1 + g2)); serial += 1
    return sum(2.0 ** -d for d in depth.values())


def kraft_is_constant(trials=2000, seed=0):
    """شاهدُ السقوط: 2,000 توزيعٍ عشوائيٍّ ببذرةٍ معلنة + منحرفٌ + مفرد."""
    rng = random.Random(seed); vals = set()
    for _ in range(trials):
        n = rng.randint(1, 40)
        vals.add(round(kraft([rng.randint(1, 10 ** 6) for _ in range(n)]), 9))
    for extra in ([1, 1, 1, 10 ** 9], [5], [1, 1]):
        vals.add(round(kraft(extra), 9))
    return sorted(vals)


# ── ① الفاتورة: المعيارُ الذي يرفض ─────────────────────────────────────────────────
def peel(sk, table):
    stem, suf = sk, None
    if not sk.endswith(GUARD_TA):
        for s in table:
            if sk.endswith(s) and len(sk) - len(s) >= 2:
                stem, suf = sk[:-len(s)], s; break
    return stem, suf


def bill(words, table):
    """L(D|M) + L(M). الرموزُ: حروفُ الجذع ورمزُ لاحقةٍ واحدٌ لكلِّ كلمة (و«بلا» رمزٌ قائم).
    وL(M) **ثمنُ الجدول نفسِه**: كلُّ لاحقةٍ تُملى حرفًا حرفًا من أبجديةٍ معلنة، وطولُ
    الجدول يُرمَّز. وهنا مقتلُ القلع الشره: كلُّ بابٍ يُفتَح يُدفَع ثمنُه مرّتين — في
    الجدول، وفي تشتيت التوزيع الذي يرفع L(D|M)."""
    stream = Counter()
    for sk in words:
        stem, suf = peel(sk, table)
        for c in stem:
            stream[("ح", c)] += 1
        stream[("ل", suf)] += 1
    N = sum(stream.values())
    ld = sum(-n * log2(n / N) for n in stream.values())
    lm = log2(len(table) + 1) + sum((len(s) + 1) * log2(ALPHA) for s in table)
    return ld, lm, ld + lm


# ── السلّمُ الفراكتاليّ: مُشغِّلٌ واحدٌ على كلِّ مستوًى، وفاتورةٌ بالصيغة نفسِها ────────
def rung(seq):
    """المشغّلُ: «اشرطْ على الجار» (رتبة ٠ ⟶ رتبة ١) — و**الكيلُ ليس هنا**: يُستدعى
    `price` مرّتين، فلا نسخةَ ثانيةَ من سياسة الترميز في هذا الجسد. ويُرَدّ معه
    **|Σ|/N** حارسًا للانحلال: إن قاربت السياقاتُ أن تُفرَد فالمكسبُ إفراطُ تخصيصٍ
    لا قانون، ولا يُنقَل رقمُه."""
    p0 = price(seq, 0); p1 = price(seq, 1)
    N, V = p0["طول"], p0["حجمُ_الأبجدية"]
    t0, t1 = p0["كلفة"], p1["كلفة"]
    deg, is_deg = degenerate(V, N)
    return dict(حجمُ_الأبجدية=V, طول=N, رتبة٠=round(t0), رتبة١=round(t1),
                فرق=round(t1 - t0), ρ=round(1 - t1 / t0, 4),
                انحلال=deg, منحلّ=is_deg)


