# online_peel.py — التقشير الفوري: لا معجمَ كامل يُطالب باستقلال الجذع، بل لواحقَ معلنة
# تُقشَر أولًا بأول (أطولُ لاحقةٍ أولًا) كلما وردت الكلمة — فتُعمَّم على غير المشهود.
# الجدول المعلن (من جدول الأدوار): اللواحق الصريحة + حارسا التاء والمبني.
# الحارسان: ① التاء المربوطة ليست هاءً ضميرًا أبدًا ② المبنيّات المنتهية بصورة الضمير.
# ═══════════ الجولة الثانية — وفاءٌ بالديون الثلاثة المسمّاة، ولا رقمَ ماضٍ يُمَسّ ═══════════
# ديونُ الجولة الأولى قُيِّدت بأسمائها، وهذه أداؤها الثلاثة — وأحكامُ الأولى **مجمَّدةٌ بنصّها**
# في `SEALED_R1` وتُصادَم بمصالحةٍ محروسة، على سنّة `jar_gate.SEALED_VERDICTS`:
#   ① **فصلُ عدّاد الحارسين**: كان العدّادُ واحدًا (2,952) يجمع التاءَ المربوطة وقائمةَ
#      المبنيّات معًا فيُسمَّى «حارسَ التاء» — وهو اسمٌ لغيره. فُصِل بعدّادين: التاءُ 2,344
#      والمبنيّاتُ 608، ومجموعُهما 2,952 بفارق صفر.
#   ② **فاتورةُ الجدول على 11 لا 12**: `SUF` أحدَ عشرَ مدخلًا لا اثني عشر، و`assert` يحرسه
#      فلا يُنقَل ثانيةً عددٌ بمقامٍ خاطئ. وكلُّ فاتورةٍ حُسبت على 12 **تُعاد على 11**.
#   ③ **قيدُ باب «ي» بشاهدٍ من البايتات**: بابُ «ي» (2,132) كان يبتلع الموصولَ (الذي 268 ·
#      التي 57) وياءَ الأصل (النبي · بني) ولامَ الناقص (تجري · يهدي) والجارَّ الملتصق (وفي ·
#      لفي). والقيدُ **شاهدٌ لا قائمةٌ يدويّة** — على سنّة «الشاهدُ من المجمَّد أو لا طرحَ»:
#      **شاهدُ النسق**: لا تُقلَع «ي» إلّا أن يكون الجذعُ نفسُه قد شُوهد ملتصقًا **بلاحقةٍ
#      أخرى من الجدول**. فـ«رب» شوهد بـ(ك·كم·كما·نا·ه·ها·هم·هما) فتُقلَع ياؤه، و«الذ» و«تجر»
#      و«النب» لم يُشهَد لها إلّا بـ«ي» فتُحجَب. **ولا يُشترَط استقلالُ الجذع** — وهو الشرطُ
#      الذي أسقط المعجمَ الكامل؛ المطلوبُ التصاقٌ آخرُ لا ورودٌ مستقلّ.
#      والشاهدُ **فوريٌّ حاكمًا**: يُبنى من السابقة المرئيّة وحدَها، ولا يمسح المجمَّدَ قبل أن
#      يحكم. والدفعيُّ (المجمَّد كلُّه أوّلًا) يُعرَض **عرضًا موسومًا** لا حكمًا، وفارقُهما
#      معدودٌ بالاسم (91 موضعًا) — فمن نقل رقمًا فليَنقُل مقامَه معه.
#      **وثمنُه مدفوعٌ معروضٌ لا مستور**: الحجبُ 1,495 موضعًا في 482 هيئة، فيه صحيحُ الحجب
#      (الذي · تجري · النبي · وفي) وفيه مظلومٌ بأثر الترتيب الفوريّ («ذريتي» وردت قبل
#      «ذريته» فحُجبت) — والقيدُ لا يبلغ الصفر ولا يُدَّعى له. وما بقي مُقشورًا فيه إيجابٌ
#      كاذبٌ مسمًّى («يأتي» 21: «يأت» شُوهد بـك·كم·ه·هم فأعطى الشاهدُ ما لا يستحقّه).
# ═══════════ الجولة الثالثة — وفاءٌ بالإيجاب الكاذب المسمّى، بشاهدٍ مضادٍّ من البايتات ═══════
# الإيجابُ الكاذبُ سُمّي في الجولة الثانية: «يأتي» قُشرت لأنّ «يأت» شُوهد بـ(ك·كم·ه·هم) —
# وتلك لواحقُ **مفعولٍ على فعل**، لا مضافٍ إليه على اسم. فشاهدُ النسق أعطى ما لا يستحقّه.
# والحلُّ **شاهدٌ مضادٌّ** لا قائمةُ أفعالٍ يدويّة، وسندُه قاعدةٌ صرفيةٌ لا استثناءَ فيها:
#   **ياءُ المتكلّم لا يَلحقها ضميرٌ آخر أبدًا.** فإن شُوهدت الهيئةُ **بيائها** حاملةً لاحقةً
#   أخرى من الجدول («يأتيكم» · «يأتيه» · «أيديهم») فياؤها **أصلٌ في الجذع** لا ضمير.
#   والشاهدُ من المجمَّد وحدَه: `para[sk] − {ي} ≠ ∅` — أي الهيئةُ التامّةُ نفسُها جذعٌ مشهود.
# ▸ **وإعفاءُ المقصور، وهو شرطُ ألّا يصير الشاهدُ المضادُّ مِكنسة**: «إليه» و«لديه» و«أبيه»
#   شواهدُ كاذبةٌ للأصل — لأنّ الجذعَ فيها منتهٍ بألفٍ مقصورة (إلى · لدى) تنقلب ياءً عند
#   الإضافة، فالياءُ المقلوعةُ من «إلي» ضميرٌ حقًّا. وكاشفُه **شاهدٌ من البايتات أيضًا**:
#   الهيئةُ بألفها المقصورة (`sk[:-1] + "ى"`) مشهودةٌ في المجمَّد ⟹ يُعفى الموضعُ من الشاهد
#   المضادّ. وبهذا الإعفاء نزل الحجبُ من 136 إلى 58 — **ولولاه لابتلع الجارَّ والمضاف**.
# ▸ الحصيلةُ معروضةٌ بمقاميها: الحاكمُ **فوريّ** (579) والدفعيُّ **عرضٌ موسوم** (672).
#   وثمنُه مسمًّى ولا يُدَّعى له صفر: في المحجوب **مظلومٌ بأثر الترتيب الفوريّ** («ولي» 9
#   حُجبت قبل أن تُشهَد «ولى») و**مظلومٌ حقيقيّ** («أهلي» 2) — بإزاء صحيحِ الحجب («يأتي» 21
#   · «يغني» 7 · «تأتي» 3 · «أيدي» 2 · «يدي» 9 مثنًى في «بين يدي»). والميزانُ موجبٌ معروضٌ
#   لا مُدَّعًى: **لا يُنقَل 579 «ياءَ متكلّمٍ صحيحةً»**، بل «ما بقي بعد شاهدين مضادَّين».
import sys, os, json
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from induction_engine import parse_verses

CORPUS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "mujammad.txt")
SUF = ("هما", "كما", "هن", "هم", "كن", "كم", "نا", "ها", "ه", "ك", "ي")
assert len(SUF) == 11, "فاتورةُ الجدول تُحسَب على إحدى عشرة لاحقةً — لا اثنتي عشرة"
GUARD_TA = "ة"                                   # لا تُقشَر هاءً قط
GUARD_WORDS = {"هذه", "هذي", "ذه", "هؤلاء", "فيه", "عليه", "إليه", "لديه", "أنه", "إنه"}
MIN_STEM = 2                                     # جذعٌ أجوف/ناقص لا يقل عن حرفين بعد القلع
WITNESS_SUF = "ي"                                # البابُ المقيَّد بشاهد النسق — وحدَه
MAQSURA = "ى"                                    # إعفاءُ الشاهد المضادّ: جذعٌ منقلبةٌ ألفُه ياءً

# أحكامُ الجولة الأولى مجمَّدةً بنصّها: لا تُعاد حسابًا حيًّا، وتُصادَم مصالحةً محروسة.
SEALED_R1 = {"مقشور": 17979, "حارس": 2952, "بلا-لاحقة": 56870, "كلمات": 77801, "ي": 2132}
# وأحكامُ الجولة الثانية كذلك — لا يُبدّلها انقلابُ بابٍ في الثالثة صامتًا.
SEALED_R2 = {"مقشور": 16484, "حارس-النسق(ي)": 1495, "حارس-التاء": 2344, "حارس-المبنيّ": 608,
             "ي": 637}


def peel(sk):
    """الجولة الأولى بنصّها — تبقى كما خُتمت، ومخرجُها هو المقامُ الذي تُصادَم به الثانية."""
    if sk in GUARD_WORDS or sk.endswith(GUARD_TA):
        return sk, None, "حارس"
    for s in SUF:
        if sk.endswith(s) and len(sk) - len(s) >= MIN_STEM:
            return sk[:-len(s)], s, "مقشور"
    return sk, None, "بلا-لاحقة"


def longest_suffix(sk):
    """أطولُ لاحقةٍ معلنةٍ تنطبق، أو None — القلعُ الخامُ قبل أيّ حارس."""
    for s in SUF:
        if sk.endswith(s) and len(sk) - len(s) >= MIN_STEM:
            return s
    return None


def peel2(sk, para):
    """الجولة الثانية: الحارسان **مفصولان بالاسم**، وبابُ «ي» مقيَّدٌ بشاهد النسق.
    `para` جذعٌ ⟼ مجموعةُ اللواحق المشهودةِ له — يُمرَّر ولا يُبنى هنا، فمقامُ الشاهد
    (فوريٌّ من السابقة أم دفعيٌّ من الكلّ) يُعلَن عند البناء لا يُخفى داخل الدالّة."""
    if sk in GUARD_WORDS:
        return sk, None, "حارس-المبنيّ"
    if sk.endswith(GUARD_TA):
        return sk, None, "حارس-التاء"
    s = longest_suffix(sk)
    if s is None:
        return sk, None, "بلا-لاحقة"
    if s == WITNESS_SUF and not (para.get(sk[:-len(s)], frozenset()) - {WITNESS_SUF}):
        return sk, None, "حارس-النسق(ي)"      # لم يُشهَد للجذع بلاحقةٍ أخرى — لا قلعَ بلا شاهد
    return sk[:-len(s)], s, "مقشور"


def build_paradigm(verses):
    """الشاهدُ الدفعيّ — **عرضٌ موسومٌ لا حكم**: يمسح المجمَّدَ كلَّه قبل أن يحكم، فهو غيرُ
    فوريٍّ بالبنية. يُعرَض ليُعرَف فارقُه عن الفوريّ، ولا يُنقَل رقمُه وحدَه."""
    para = defaultdict(set)
    for v in verses:
        for w in v:
            sk = "".join(c for c, _ in w)
            if sk in GUARD_WORDS or sk.endswith(GUARD_TA):
                continue
            s = longest_suffix(sk)
            if s:
                para[sk[:-len(s)]].add(s)
    return para


def peel3(sk, para, forms):
    """الجولة الثالثة: شاهدُ النسق كما هو، **وفوقه شاهدٌ مضادٌّ لياء الأصل**.
    `forms` هيئاتُ الكلمات المشهودة — تُمرَّر كـ`para`، فمقامُها يُعلَن عند البناء.
    والقاعدةُ التي يقوم عليها الشاهدُ المضادّ صرفيّةٌ لا استثناءَ فيها: **ياءُ المتكلّم لا
    يلحقها ضميرٌ آخر**، فالهيئةُ بيائها إن حملت لاحقةً أخرى فياؤها أصل. ويُعفى منه ما شُهدت
    هيئتُه بألفٍ مقصورة (إلى · لدى · أبى)، فالياءُ هناك انقلابُ ألفٍ والضميرُ قائم."""
    stem, s, how = peel2(sk, para)
    if how != "مقشور" or s != WITNESS_SUF:
        return stem, s, how
    counter = bool(para.get(sk, frozenset()) - {WITNESS_SUF})
    exempt = (sk[:-1] + MAQSURA) in forms
    if counter and not exempt:
        return sk, None, "حارس-الأصل(ي)"
    return stem, s, how


def build_forms(verses):
    """هيئاتُ المجمَّد كلِّها — **الشاهدُ الدفعيُّ لإعفاء المقصور**، عرضٌ موسومٌ لا حكم."""
    return {"".join(c for c, _ in w) for v in verses for w in v}


def residue_ledger(verses, blk_asl):
    """**سجلُّ السقوط مسمًّى بالعدّ — لا بابٌ مظنون.** الجنسُ الباقي («أهلي») جذعٌ صحيحُ
    الآخر يقبل الضميرين معًا، فلا يفصله شاهدٌ من البايتات عندنا. وقاعدةُ الدار أنّ **الصمتَ
    ليس حكمًا**: فيُبوَّب كلُّ موضعٍ باسمه وشاهدِه، ويُقسَم قسمةً **من البايتات وحدَها** —
    لا بدعوى نحوٍ ولا بقائمةٍ يدويّة:
      ⓐ **مظلومُ الترتيب الفوريّ**: مقصورُه (`…ى`) مشهودٌ في المجمَّد لكنّه **ورد بعد**
         موضع الحجب، فالإعفاءُ كان موجودًا في اللغة غائبًا عن السابقة. وهو يزول بالمقام
         الدفعيّ، فثمنُه **ثمنُ الفورية معدودًا** لا عطلَ كاشف.
      ⓑ **الجنسُ المسمّى بلا كاشف**: لا مقصورَ له في المجمَّد البتّة. وهذا هو الدَّينُ
         بعينه — يُعَدّ ويُسمّى بشواهده، **ولا يُفتَح له باب**.
    ولا يُدَّعى في ⓑ أنّها كلَّها خطأٌ ولا كلَّها صواب: فيها ما الحجبُ فيه صحيح، وفيها
    «أهلي» وأخواتُها. والفصلُ بينهما **يحتاج مقامًا فوق الكلمة**، وهو محالٌ بالاسم."""
    all_forms = build_forms(verses)
    ledger, tail = {}, Counter()
    para = build_paradigm(verses)
    for sk, n in blk_asl.items():
        late = (sk[:-1] + MAQSURA) in all_forms          # مقصورٌ في المجمَّد، وقد فات وقتُه
        kind = "مظلومُ-الترتيب-الفوريّ" if late else "جنسٌ-بلا-كاشف"
        ledger[sk] = dict(عدد=n, صنف=kind,
                          شواهد=sorted(para.get(sk, ())),
                          مقصورٌ_في_المجمَّد=late)
        tail[kind] += n
    return ledger, tail


def run3(verses, online=True):
    """الجولة الثالثة. `online=True` **الحاكم**: الشاهدان (النسقُ والهيئات) يُبنيان من
    السابقة المرئيّة وحدَها، والتحديثُ **بعد** الحكم فلا يشهد موضعٌ لنفسه."""
    para = defaultdict(set) if online else build_paradigm(verses)
    forms = set() if online else build_forms(verses)
    stat = Counter(); by_suf = Counter(); blk_nasaq = Counter(); blk_asl = Counter()
    for v in verses:
        for w in v:
            sk = "".join(c for c, _ in w)
            _, suf, how = peel3(sk, para, forms)
            stat[how] += 1
            if suf:
                by_suf[suf] += 1
            if how == "حارس-النسق(ي)":
                blk_nasaq[sk] += 1
            elif how == "حارس-الأصل(ي)":
                blk_asl[sk] += 1
            if online:
                forms.add(sk)
                s = longest_suffix(sk)
                if s and how not in ("حارس-المبنيّ", "حارس-التاء"):
                    para[sk[:-len(s)]].add(s)
    return stat, by_suf, blk_nasaq, blk_asl


def run2(verses, online=True):
    """الجولة الثانية على المجمَّد. `online=True` هو **الحاكم**: الشاهدُ يُبنى من السابقة
    المرئيّة وحدَها فيتقدّم مع التيار، وكلُّ موضعٍ يُحكَم بما رُئي قبله لا بما سيُرى بعده."""
    para = defaultdict(set) if online else build_paradigm(verses)
    stat = Counter(); by_suf = Counter(); blocked_ya = Counter()
    for v in verses:
        for w in v:
            sk = "".join(c for c, _ in w)
            _, suf, how = peel2(sk, para)
            stat[how] += 1
            if suf:
                by_suf[suf] += 1
            if how == "حارس-النسق(ي)":
                blocked_ya[sk] += 1
            if online:                    # التحديثُ **بعد** الحكم — لا يرى الموضعُ نفسَه شاهدًا لنفسه
                s = longest_suffix(sk)
                if s and how not in ("حارس-المبنيّ", "حارس-التاء"):
                    para[sk[:-len(s)]].add(s)
    return stat, by_suf, blocked_ya


def main():
    verses = parse_verses(CORPUS)
    stat = Counter(); by_suf = Counter(); blocked = Counter()
    witness = {}
    for v in verses:
        for w in v:
            sk = "".join(c for c, _ in w)
            stem, suf, how = peel(sk)
            stat[how] += 1
            if suf:
                by_suf[suf] += 1
            if how == "حارس":
                blocked[sk] += 1
            for key in ("أيديهم", "أيديهم", "الآخرة", "ربكم", "بكم", "قبلك", "ملكه", "هداهم"):
                if sk == key and key not in witness:
                    witness[key] = (stem, suf, how)
    R = dict(كلمات=sum(stat.values()), أحوال=dict(stat), لواحق=dict(by_suf.most_common()),
             حارس_التاء=sum(blocked.values()), شواهد=witness)
    print("الأحوال:", dict(stat), "| الكلمات:", sum(stat.values()))
    print("أعلى اللواحق:", by_suf.most_common(8))
    print("حارس التاء حجب:", sum(blocked.values()))
    for k, val in witness.items():
        print(f"  {k} ⟵ جذع: {val[0]} · لاحقة: {val[1]} · {val[2]}")
    # ═══ مصالحةُ الجولة الأولى بأحكامها المجمَّدة — فارقُ صفرٍ أو صراخ ═══
    for k in ("مقشور", "حارس", "بلا-لاحقة"):
        assert stat[k] == SEALED_R1[k], f"انقلابُ حكمٍ مجمَّد في «{k}»"
    assert sum(stat.values()) == SEALED_R1["كلمات"] and by_suf["ي"] == SEALED_R1["ي"], \
        "مصالحةُ الجولة الأولى خُولفت"

    # ═══ الجولة الثانية: الحاكمُ فوريٌّ، والدفعيُّ عرضٌ موسومٌ بفارقه ═══
    s_on, suf_on, blk = run2(verses, online=True)
    s_bt, suf_bt, _ = run2(verses, online=False)
    ta, mabni = s_on["حارس-التاء"], s_on["حارس-المبنيّ"]
    assert ta + mabni == SEALED_R1["حارس"], "فصلُ الحارسين لا يصالح المجمَّد"
    assert s_on["مقشور"] + s_on["حارس-النسق(ي)"] + ta + mabni + s_on["بلا-لاحقة"] \
        == SEALED_R1["كلمات"], "مصالحةُ الجولة الثانية خُولفت"
    assert s_on["مقشور"] + s_on["حارس-النسق(ي)"] == SEALED_R1["مقشور"], "المحجوبُ لا يردّ الفارق"
    R2 = dict(الحاكم="فوريّ — الشاهدُ من السابقة المرئيّة وحدَها",
              أحوال_فوريّ=dict(s_on), أحوال_دفعيّ_عرضًا=dict(s_bt),
              لواحق_فوريّ=dict(suf_on.most_common()),
              ياء=dict(قبل_القيد=SEALED_R1["ي"], فوريّ=suf_on["ي"], دفعيّ_عرضًا=suf_bt["ي"],
                       محجوب=sum(blk.values()), هيئات_المحجوب=len(blk),
                       أعلى_المحجوب=dict(blk.most_common(10))),
              فاتورة=dict(لواحق=len(SUF), ملاحظة="أحدَ عشرَ لا اثني عشر — كلُّ فاتورةٍ على 12 تُعاد"),
              حارسان=dict(التاء=ta, المبنيّ=mabni, المجموع_المجمَّد=SEALED_R1["حارس"]),
              مصالحة=dict(مقشور=s_on["مقشور"], محجوب_ي=s_on["حارس-النسق(ي)"],
                          مجموعهما=s_on["مقشور"] + s_on["حارس-النسق(ي)"],
                          المجمَّد=SEALED_R1["مقشور"], فارق=0))
    print("\n— الجولة الثانية —")
    print(f"الحارسان مفصولين: تاءٌ {ta} · مبنيٌّ {mabni} = {ta + mabni} (المجمَّد {SEALED_R1['حارس']}) ✓")
    print(f"فاتورةُ الجدول: {len(SUF)} لاحقةً — لا 12")
    print(f"بابُ «ي»: {SEALED_R1['ي']} ⟵ {suf_on['ي']} حاكمًا (فوريًّا) · {suf_bt['ي']} دفعيًّا عرضًا "
          f"| محجوبٌ {sum(blk.values())} في {len(blk)} هيئة")
    print("  أعلى المحجوب:", blk.most_common(8))
    print(f"  فارقُ المقامين (فوريّ ⟷ دفعيّ): {suf_bt['ي'] - suf_on['ي']} موضعًا — لا يُجسَر بينهما")
    for k, val in SEALED_R2.items():
        got = s_on[k] if k != "ي" else suf_on["ي"]
        assert got == val, f"انقلابُ حكمٍ مجمَّد من الجولة الثانية في «{k}»: {got} ≠ {val}"
    R["الجولة_الثانية"] = R2

    # ═══ الجولة الثالثة: الشاهدُ المضادُّ لياء الأصل، وإعفاءُ المقصور ═══
    t_on, tsuf_on, tn_on, ta_on = run3(verses, online=True)
    t_bt, tsuf_bt, tn_bt, ta_bt = run3(verses, online=False)
    assert t_on["مقشور"] + t_on["حارس-النسق(ي)"] + t_on["حارس-الأصل(ي)"] == SEALED_R1["مقشور"], \
        "مصالحةُ الجولة الثالثة خُولفت"
    assert t_on["حارس-التاء"] + t_on["حارس-المبنيّ"] == SEALED_R1["حارس"] and \
        sum(t_on.values()) == SEALED_R1["كلمات"], "مصالحةُ الحارسين/الكلمات خُولفت"
    assert tsuf_on["ي"] + sum(ta_on.values()) == SEALED_R2["ي"], \
        "بابُ «ي» لا يردّ فارقَ الجولة الثانية"
    R3 = dict(الحاكم="فوريّ — الشاهدان من السابقة المرئيّة وحدَها",
              أحوال_فوريّ=dict(t_on), أحوال_دفعيّ_عرضًا=dict(t_bt),
              ياء=dict(الجولة_الثانية=SEALED_R2["ي"], فوريّ=tsuf_on["ي"],
                       دفعيّ_عرضًا=tsuf_bt["ي"],
                       محجوب_بالأصل=sum(ta_on.values()),
                       هيئات=len(ta_on), أعلى=dict(ta_on.most_common(10))),
              قاعدة="ياءُ المتكلّم لا يلحقها ضميرٌ آخر — فالهيئةُ بيائها إن حملت لاحقةً فياؤها أصل",
              إعفاء=dict(كاشف="الهيئةُ بألفٍ مقصورة مشهودةٌ في المجمَّد",
                         أثره="الحجبُ 136 ⟵ 58 دفعيًّا — بدونه يبتلع الجارَّ والمضاف"),
              مصالحة=dict(مقشور=t_on["مقشور"], محجوب_نسق=t_on["حارس-النسق(ي)"],
                          محجوب_أصل=t_on["حارس-الأصل(ي)"], المجمَّد=SEALED_R1["مقشور"], فارق=0))
    ledger, tail = residue_ledger(verses, ta_on)
    assert sum(v["عدد"] for v in ledger.values()) == sum(ta_on.values()), "سجلُّ السقوط لا يستوعب المحجوب"
    R3["سجلّ_السقوط"] = dict(أصناف=dict(tail), مواضع=ledger,
                             قاعدة="الصمتُ ليس حكمًا — يُعَدّ ويُسمّى، ولا يُفتَح بابٌ مظنون")
    print("\n— الجولة الثالثة: الشاهدُ المضادُّ لياء الأصل —")
    print(f"بابُ «ي»: {SEALED_R2['ي']} ⟵ {tsuf_on['ي']} حاكمًا (فوريًّا) · {tsuf_bt['ي']} دفعيًّا عرضًا")
    print(f"  محجوبٌ بالأصل: {sum(ta_on.values())} في {len(ta_on)} هيئة — {ta_on.most_common(8)}")
    print(f"  المصالحة: {t_on['مقشور']} + {t_on['حارس-النسق(ي)']} + {t_on['حارس-الأصل(ي)']} = "
          f"{SEALED_R1['مقشور']} ✓")
    print("  سجلُّ السقوط (لا بابَ مظنونًا):", dict(tail))
    for sk, d in sorted(ledger.items(), key=lambda kv: -kv[1]["عدد"]):
        print(f"    {sk} ×{d['عدد']} · شواهدُه {d['شواهد']} · {d['صنف']}")
