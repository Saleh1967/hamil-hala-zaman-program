    print(f"  {J['الوحدات']:,} = {J['داخل_112']:,} داخل + {J['هامشُ_الحرف']:,} هامشَ حرفٍ "
          f"+ {J['هامشُ_الحالة']:,} هامشَ حالةٍ − {J['تقاطعُ_الهامشين']:,} تقاطعًا")
    print(f"  المنشأ: {J['المنشأ']} · خلايا مشغولة {J['خلايا_مشغولة']} من 112")
    assert J["الوحدات"] == SEALED_112["units"], "الوحداتُ خالفت المودَع"
    assert J["داخل_112"] == SEALED_112["inside"], "داخلُ الحقل خالف المودَع"
    assert J["هامشُ_الحرف"] == SEALED_112["margin_letter"], "هامشُ الحرف خالف"
    assert J["هامشُ_الحالة"] == SEALED_112["margin_state"], "هامشُ الحالة خالف"
    assert J["تقاطعُ_الهامشين"] == SEALED_112["margin_both"], "التقاطعُ خالف"
    assert J["المنشأ"]["رسم"] == SEALED_112["rasm"] and J["المنشأ"]["R5"] == SEALED_112["r5"] \
        and J["المنشأ"]["R4"] == SEALED_112["r4"], "المنشأُ خالف المودَع"
    assert J["خلايا_مشغولة"] == SEALED_JM["خلايا_مشغولة"]
    print("  ✓ صُودمت بأرقام field112_laws.json بفارق صفر — بناءٌ مستقلٌّ لا نسخ\n")

    # ── المانع ──
    print("— ② المانع: الارتدادُ فاحصًا يرفض —")
    rt, ex1 = {}, None
    for d, nm in (("فتحة", "خنجريةٌ فتحةً (الاتفاقيةُ المودَعة)"),
                  ("حالة", "خنجريةٌ حالةً خامسةً (140 خليّة)"),
                  ("وسم", "خنجريةٌ وسمًا مرافقًا (112 + بُعد)")):
        ok, bad, ex = mani3_roundtrip(verses, d)
        rt[d] = ok
        if d == "فتحة":
            ex1 = ex
        print(f"  {nm:38s} {ok:,}/77,801 = {ok / 77801:.4f}"
              + (f"  ✗ تالفٌ {77801 - ok:,} · {bad}" if ok < 77801 else "  ✓ تامّ"))
    for a, b in [(a, b) for (a, b), _ in ex1[:3]]:
        print(f"      مثالُ الضياع: {a} ⟶ {b}")
    assert rt["وسم"] == SEALED_JM["ارتداد_وسمًا"], "الارتدادُ التامُّ خُولف"
    assert rt["فتحة"] == SEALED_JM["ارتداد_فتحةً"], "ارتدادُ الاتفاقية المودَعة خُولف"
    assert rt["حالة"] == SEALED_JM["ارتداد_حالةً_خامسة"], "ارتدادُ الحالة الخامسة خُولف"
    F = mani3_fold(verses)
    print(f"  تجربةُ منعٍ مضادّة (طيُّ الهمزات): {F['متعددةُ_الأصل']} هيئةً متعددةَ الأصل · "
          f"{F['أصولٌ_لا_تُستردّ']} أصلًا لا يُستردّ — {F['الحكم']}")
    for e in F["أمثلة"][:3]:
        print("      ", e)
    assert F["متعددةُ_الأصل"] == SEALED_JM["طيُّ_الهمزات_هيئاتٌ_متعددةُ_الأصل"]
    assert F["أصولٌ_لا_تُستردّ"] == SEALED_JM["طيُّ_الهمزات_أصولٌ_لا_تُستردّ"]
    print()

    # ── الحَكَم ──
    B = bill(verses)
    print("— ③ الحَكَم: فاتورةُ الوصف الأدنى —")
    print(f"  الخام  {B['رموزُ_الخام']:,} رمزًا من {B['أبجديةُ_الخام']} : {B['الخام']:,} بت")
    print(f"  الحقل  {B['وحدات']:,} وحدةً : {B['خلايا']:,} + منشأٌ {B['المنشأ']:,} "
          f"+ خنجريةٌ {B['الخنجرية']:,} = {B['الحقل']:,} بت")
    print(f"  Δ = {B['فرق']:+,} ⟹ {B['حكم']}  (ونقيضُه حكمُ التنسور +69,037 — والحَكَمُ واحد)\n")
    assert B["الخام"] == SEALED_JM["فاتورة_الخام"] and B["الحقل"] == SEALED_JM["فاتورة_الحقل"] \
        and B["فرق"] == SEALED_JM["فرق"], "الفاتورةُ خالفت المجمَّد"

    # ── السلّم ──
    L = ladder(verses)
    print("— ④ السلّم: خمسُ درجاتٍ صعودًا ونزولًا —")
    print(f"  {'الدرجة':26s} {'طول':>9s} {'أبجدية':>8s} {'رتبة٠':>11s} {'رتبة١':>11s} "
          f"{'فرق':>9s} {'انحلال':>8s}")
    for r in L:
        print(f"  {r['الدرجة']:26s} {r['طول']:>9,} {r['أبجدية']:>8,} {r['رتبة٠']:>11,} "
              f"{r['رتبة١']:>11,} {r['فرق']:>+9,} {r['انحلال']:>8.4f}"
              + ("  ✗ منحلّ" if r["منحلّ"] else ""))
    print("  الحدُّ المقيس: الشرطُ يربح نزولًا حتى الكلمة، ثمّ تنحلّ الآيةُ فلا يُنقَل رقمُها\n")

    # ── مبرهنة الحفظ على المحكّ ──
    A = preservation_audit(cell, rt)
    print("— ⑤ دعاوى «مبرهنة الحفظ»: هل يستطيع هذا الشرطُ أن يرفض؟ —")
    for a in A:
        sign = "✓ يرفض" if a["يرفض"] else ("… معلَّق" if a["يرفض"] is None else "✗ لا يرفض")
        print(f"  {sign}  {a['الشرط']}")
        print(f"          {a['البيان']}")

    return dict(المجمَّد=dict(آيات=len(verses), كلمات=sum(len(v) for v in verses), ختم=SEAL),
                الجامع=J, المانع=dict(ارتداد={k: v for k, v in rt.items()}, طيُّ_الهمزات=F),
                الحَكَم=B, السلّم=L, مبرهنةُ_الحفظ=A,
                الحكم="جامعٌ مصالَحٌ بفارق صفر · مانعٌ بشرطٍ مقيس (الخنجريةُ وسمٌ لا حالة) · "
                      "وديعةٌ صالحةٌ بالفاتورة −310,993 · والسقفُ المدَّعى مردودٌ بالحساب")


