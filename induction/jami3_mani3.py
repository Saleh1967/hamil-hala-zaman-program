# ═══ ١) من الصفر: البايتاتُ بختمها ═══════════════════════════════════════════════
def read_verses(path=CORPUS):
    """المجمَّدُ بختمه ⟼ آياتٌ ⟼ كلماتٌ خام. لا استيرادَ — القراءةُ هنا بيدها."""
    blob = open(path, "rb").read()
    assert hashlib.sha256(blob).hexdigest() == SEAL, "ليس المجمَّد — البصمةُ خُولفت"
    verses = []
    for ln in blob.decode("utf-8-sig").splitlines():
        if not ln.strip() or not any(AR(c) for c in ln):
            continue
        ws = [w for w in ln.split(" ") if any(AR(c) for c in w)]
        if ws:
            verses.append(ws)
    assert len(verses) == SEALED_112["verses"], "عددُ الآيات خُولف"
    assert sum(len(v) for v in verses) == SEALED_112["words"], "عددُ الكلمات خُولف"
    return verses


# ═══ ٢) النزول: كلمةٌ خامٌ ⟼ وحداتُ الحقل ════════════════════════════════════════
def descend(word, dagger="وسم"):
    """كلمةٌ ⟼ [(حرف، حالة، منشأ، خنجرية)].
    قاعدتان معلنتان: R5 الشدّةُ ساكنٌ ثمّ متحرّك · R4 التنوينُ حركةٌ ثمّ نونٌ ساكنة.
    والخنجريةُ على ثلاث اتفاقياتٍ متنافسةٍ تُعرَض كلُّها على الفاحص نفسِه:
      «فتحة»  — الاتفاقيةُ المودَعة: تبتلعها حركةً، فتضيع مع حركةٍ أخرى.
      «حالة»  — حالةٌ خامسةٌ تزاحم الحركاتِ الأربع: تنجو منفردةً وتضيع مقترنة.
      «وسم»   — بُعدٌ مرافقٌ لا يزاحم: لا يضيع البتّة."""
    out, i, n = [], 0, len(word)
    while i < n:
        ch = word[i]
        if not AR(ch):
            i += 1
            continue
        marks = []
        while i + 1 < n and (0x064B <= ord(word[i + 1]) <= 0x0652 or ord(word[i + 1]) == MADD):
            i += 1
            marks.append(ord(word[i]))
        tan = next((m for m in marks if m in TANM), None)
        vow = next((m for m in marks if m in VOWM), None)
        dg = MADD in marks
        if vow:
            st = VOWM[vow]
        elif tan:
            st = TANM[tan]
        elif dg:
            st = {"فتحة": "فتحة", "حالة": "خنجرية", "وسم": BARE}[dagger]
        else:
            st = BARE
        if SHADDA in marks:                       # R5 — الحرفُ نفسُه موضعين
            out.append((ch, "سكون", "R5", False))
        out.append((ch, st, "R4" if tan and not vow else "رسم", dg and dagger == "وسم"))
        if tan:                                   # R4 — النونُ الساكنة موضعٌ ثانٍ
            out.append(("ن", "سكون", "R4", False))
        i += 1
    return out


# ═══ ٣) الصعود: وحداتُ الحقل ⟼ الكلمةُ بايتًا ببايت ══════════════════════════════
def ascend(units, dagger="وسم"):
    """الصعودُ حتميٌّ لا خيارَ فيه: R5 يُطوى شدّةً، وR4 يُطوى تنوينًا، والباقي يُملى.
    وليس فيه اطّلاعٌ على الكلمة الأصل — فلا يستطيع أن يخفي ضياعًا."""
    mk = dict(MK)
    if dagger == "حالة":
        mk["خنجرية"] = "\u0670"
    out, i, n = "", 0, len(units)
    while i < n:
        ch, st, src, dg = units[i]
        if src == "R5":                           # الطيُّ العكسيّ للشدّة
            ch, st, src, dg = units[i + 1]
            sh = "\u0651"
            i += 2
        else:
            sh = ""
            i += 1
        tail = "\u0670" if dg else ""
        if src == "R4":                           # الطيُّ العكسيّ للتنوين: تُبتلع النون
            out += ch + sh + TN[st] + tail
            i += 1
        else:
            out += ch + sh + (mk.get(st, "") if st != BARE else "") + tail
    return out


# ═══ ٤) الجامع: القسمةُ بالتضمين والاستبعاد، لا سلّةَ «أخرى» ═════════════════════
def jami3(verses):
    """كلُّ وحدةٍ تُسنَد: خليّةٌ من 112 · هامشُ حرفٍ مسمًّى · هامشُ حالةٍ مسمًّى.
    والمصالحةُ الوحيدةُ المقبولة: داخلٌ + هامشان − تقاطعُهما = الكلّ. تُحرَس بـassert."""
    total = inside = both = 0
    out_letter, out_state, by_src, cell = Counter(), Counter(), Counter(), Counter()
    for v in verses:
        for w in v:
            for ch, st, src, _ in descend(w, "فتحة"):
                total += 1
                by_src[src] += 1
                lo, so = ch not in BASE28, st not in HARAKAT4
                if lo:
                    out_letter[ch] += 1
                if so:
                    out_state[st] += 1
                if lo and so:
                    both += 1
                if not lo and not so:
                    inside += 1
                    cell[(ch, st)] += 1
    assert inside + sum(out_letter.values()) + sum(out_state.values()) - both == total, \
        "الجامعُ انكسر — موضعٌ مبتلَع بين الحقل وهامشه"
    return dict(الوحدات=total, داخل_112=inside, هامشُ_الحرف=sum(out_letter.values()),
                هامشُ_الحالة=sum(out_state.values()), تقاطعُ_الهامشين=both,
                المنشأ={k: by_src[k] for k in ("رسم", "R5", "R4")},
                خلايا_مشغولة=len(cell),
                بالحروف=dict(out_letter.most_common()),
                الحكم="جامعٌ: المجموعُ مصالَحٌ بالتضمين والاستبعاد، والهامشُ مسمًّى بعدده"), cell


# ═══ ٥) المانع: الارتدادُ فاحصًا يرفض ═══════════════════════════════════════════
def mani3_roundtrip(verses, dagger):
    """نزولٌ ثمّ صعودٌ ثمّ مقابلةُ بايتاتٍ ببايتات. الفاسدُ يُصنَّف بسببه لا يُعَدّ جملةً."""
    ok, bad, ex = 0, Counter(), Counter()
    for v in verses:
        for w in v:
            src, got = KEEP(w), ascend(descend(w, dagger), dagger)
            if got == src:
                ok += 1
            else:
                bad["خنجريةٌ ضائعة" if chr(MADD) in src else "أخرى"] += 1
                ex[(src, got)] += 1
    return ok, dict(bad), ex.most_common(4)


def mani3_fold(verses):
    """تجربةُ منعٍ مضادّة: طيُّ الهمزات وأخواتِها إلى الثمانية والعشرين.
    فتصير القسمةُ **جامعةً** (لا هامشَ حرفٍ البتّة) و**غيرَ مانعة** — والثمنُ يُعَدّ:
    هيئاتٌ يسكنها أكثرُ من أصل، وأصولٌ لا تُستردّ في الصعود."""
    FOLD = {"أ": "ا", "إ": "ا", "آ": "ا", "ؤ": "و", "ئ": "ي", "ى": "ي", "ة": "ه"}
    g = defaultdict(set)
    for v in verses:
        for w in v:
            sk = "".join(c for c in w if AR(c))
            g["".join(FOLD.get(c, c) for c in sk)].add(sk)
    amb = [(k, sorted(s)) for k, s in g.items() if len(s) > 1]
    return dict(هيئاتٌ_مطويّة=len(g), متعددةُ_الأصل=len(amb),
                أصولٌ_لا_تُستردّ=sum(len(s) - 1 for _, s in amb),
                أمثلة=[f"{k} ⟵ {' · '.join(s)}" for k, s in
                       sorted(amb, key=lambda x: -len(x[1]))[:5]],
                الحكم="جامعٌ بلا مانع: الهامشُ اختفى والموضعُ ازدوج — والثمنُ معدود")


# ═══ ٦) الحَكَم: فاتورةُ الوصف الأدنى نفسُها (لا عدّادَ إجماع) ═══════════════════
def cost(c):
    n = sum(c.values())
    return -sum(k * math.log2(k / n) for k in c.values())


def bill(verses):
    """الخامُ: تسلسلُ المحارف كما هي. الحقلُ: خلايا + **ثمنُ المنشأ** + **ثمنُ الخنجرية**.
    ولا يُشترى القبولُ بإخفاء ثمن: البُعدان المرافقان مدفوعان بأبجديتيهما."""
    chars, cell, org, dgv = Counter(), Counter(), Counter(), Counter()
    for v in verses:
        for w in v:
            chars.update(KEEP(w))
            for ch, st, src, dg in descend(w, "وسم"):
                cell[(ch, st)] += 1
                org[src] += 1
                dgv[dg] += 1
    raw, fc, fo, fd = cost(chars), cost(cell), cost(org), cost(dgv)
    tot = fc + fo + fd
    return dict(الخام=round(raw), رموزُ_الخام=sum(chars.values()), أبجديةُ_الخام=len(chars),
                الحقل=round(tot), خلايا=round(fc), المنشأ=round(fo), الخنجرية=round(fd),
                وحدات=sum(org.values()), فرق=round(tot - raw),
                حكم="يُقبَل" if tot < raw else "يُرفَض")


# ═══ ٧) السلّم: صعودًا ونزولًا، بالصيغة الموروثة وحارسِ الانحلال ═════════════════
def rung(seq, name):
    """رتبةُ صفرٍ ورتبةُ واحدٍ بترميز عدٍّ مسطَّح log₂(N+1) للخليّة — ترميزُ المستودع.
    وحارسُ الانحلال |Σ|/N: إن قاربت الرموزُ أن تُفرَد فالمكسبُ إفراطُ تخصيصٍ لا قانون."""
    N = len(seq)
    c0 = Counter(seq)
    V = len(c0)
    b0 = sum(-n * math.log2(n / N) for n in c0.values())
    ctx, joint = Counter(), Counter()
    for a, b in zip(seq, seq[1:]):
        ctx[a] += 1
        joint[(a, b)] += 1
    b1 = sum(-n * math.log2(n / ctx[a]) for (a, b), n in joint.items())
    t0, t1 = b0 + V * math.log2(N + 1), b1 + len(joint) * math.log2(N + 1)
    deg = V / N
    return dict(الدرجة=name, طول=N, أبجدية=V, رتبة٠=round(t0), رتبة١=round(t1),
                فرق=round(t1 - t0), انحلال=round(deg, 4), منحلّ=deg > 0.5)


def ladder(verses):
    """خمسُ درجات: خليّة · حرف · وحدة · كلمة · آية — نزولًا من المجمَّد وصعودًا إليه."""
    units = [u for v in verses for w in v for u in descend(w, "وسم")]
    words = ["".join(c for c in w if AR(c)) for v in verses for w in v]
    return [rung([st for _, st, _, _ in units], "L٠ الحالة (5)"),
            rung([ch for ch, _, _, _ in units], "L١ الحرف"),
            rung([(ch, st) for ch, st, _, _ in units], "L٢ الخليّة (وحدةُ الحقل)"),
            rung(words, "L٣ الكلمة"),
            rung([" ".join(v) for v in verses], "L٤ الآية")]


