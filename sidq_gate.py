# ═══ ⑨ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ، ونجاحُ واحدةٍ يُسقِط البابَ ═════
def falsify(stream, axis, prm, price, fld, ma3na, ifrad, ihmal, sdq, inq, fab,
            ctl, axs):
    T = []

    # ① الإذنُ مقروءٌ لا مفترَض: مكيالُ المحورِ الثاني «الوضع» بحرفه.
    T.append(("مكيالُ المحورِ الثاني ليس الوضعَ وقد قيس به",
              AXIS_GAUGE not in (prm["المحورُ_الثاني"]["مكيال"] or "")))

    # ② **الجدولُ المجّانيّ** — أخطرُها: قياسٌ بمكيالٍ لم يُدفَع ثمنُه.
    T.append(("قيس بالوضعِ ولا ثمنَ موجبٌ لطبقتيه — ربحٌ من جدولٍ مجّانيّ",
              not (price["ثمنُ_الخريطة"] > 0 and price["ثمنُ_جدولِ_الأوزان"] > 0
                   and price["ثمنُ_الوضعِ_كاملًا"] > 0)))
    T.append(("ثمنُ الوضعِ ليس مجموعَ طبقتيه — رقمٌ لُفِّق",
              round(price["ثمنُ_الخريطة"] + price["ثمنُ_جدولِ_الأوزان"], 1)
              != price["ثمنُ_الوضعِ_كاملًا"]))

    # ③ المقامُ صريحٌ: خاناتُ الميدانِ الثلاثُ تجمع المقامَ ولا تزيد ولا تنقص.
    T.append(("خاناتُ الميدانِ لا تجمع المقام — نسبةٌ بلا مقام",
              fld["مجموعُ_الخانات"] != fld["مقام"]))
    T.append(("ميدانُ الوضعِ دون حدِّ التسعيرِ وقد سُعِّر عليه",
              fld["خانات"]["لَه_وضعٌ_مختوم"] < MIN_N))

    # ④ خطأُ الوسيطِ يُعَدُّ ولا يُستَر: فواتحُ نُسب إليها وضعٌ عددُها معروض.
    T.append(("خطأُ الوسيطِ ادُّعي ولم يُعَدّ — عيبٌ مستور",
              fld["خطأُ_الوسيط"]["فواتحُ_نُسب_إليها_وضع"] < 0))
    T.append(("فواتحُ السورِ غابت عن المجمَّد — لا ميدانَ لعدِّ الخطأ",
              fld["خطأُ_الوسيط"]["مواضعُ_الفواتح"] <= 0))

    # ⑤ الفصلُ لا يقوم إلا بشرطه المعلن: خانةٌ قامت وحكمُها ليس البرهان.
    cells = ma3na["خانات"] + ihmal["خانات"]
    T.append(("خانةٌ خُتمت قائمةً وحكمُها ليس «مُودَعةٌ بالبرهان» — شرطٌ زُحزح",
              any(c["قامت"] and c.get("حكم") != "مُودَعةٌ بالبرهان" for c in cells)))
    T.append(("خانةٌ دون حدِّ التسعيرِ خُتمت قائمةً — عتبةٌ خُرِقت",
              any(c["قامت"] and not c["بلغَت_حدَّ_التسعير"] for c in cells)))
    T.append(("القسمةُ خُتمت صادقةً وفيها فصلٌ لم يقم",
              sdq["صدقت"] and sdq["قامت"] != sdq["فصول"]))

    # ⑥ والفصلُ الذي رفع الوضعُ مقامَه: لو لم يرتفع لَما كانت ههنا محطّةٌ أصلًا.
    T.append(("ميدانُ فصلِ المعنى لم يرتفع عن ميدانِ السطح — لا جديدَ ههنا",
              ma3na["ميدانُ_الفصل"] <= ma3na["ميدانُه_على_السطح"]))
    T.append(("خانتا فصلِ المعنى تقاطعتا — فصلٌ ليس بمانع",
              ma3na["تقاطعُ_الخانتين"] != 0))

    # ⑦ فصلُ الوحدةِ: لو لم يُطلِق على الميدانِ كلِّه لَما صحَّ وصفُه بالانحلال.
    T.append(("فصلُ الوحدةِ خُتم منحلًّا ونصيبُه دون السقف",
              ifrad["منحلّة"] and ifrad["نصيب"] < TG.COVER_CEILING))

    # ⑧ فصلُ الإهمال: التطابقُ مع قاطعِ المعنى يُعلَن — فلو ادُّعي فصلٌ لَكذب.
    T.append(("ادُّعي أنّ المكيالَ يفصل المستعمَلَ من المعنى وهما قاطعٌ واحد",
              not ihmal["قاطعُ_المستعمَلِ_هو_قاطعُ_المعنى"]))

    # ⑨ المحطّةُ ④: عمودُ الصورةِ مُصادَمٌ، والنجاةُ بشرطيها لا بأحدهما.
    T.append(("درجٌ من السلّمِ غاب عن القياس — سلّمٌ نُقِص",
              len(inq["أدراج"]) != len(AG.RUNGS)))
    T.append(("خُتمت النجاةُ والحكمُ غيرُ مستقرٍّ على الأدراج",
              inq["نجا"] and not inq["حكمٌ_مستقرّ"]))
    T.append(("خُتمت النجاةُ والخفضُ دون ثمنِ الوضع — اشتراءٌ سُمّي برهانًا",
              inq["نجا"] and not inq["الخفضُ_يهزم_الثمن"]))
    T.append(("أعلى خفضٍ يهزم الثمنَ وقد خُتم أنّه لا يهزمه",
              (inq["أعلى_خفضٍ"] > inq["ثمنُ_الوضع"]) != inq["الخفضُ_يهزم_الثمن"]))
    T.append(("درجٌ بلا ضابطِ خصمٍ — قراءةٌ عُرِضت بلا رقيبٍ عشوائيّ",
              any(r["ضابطُ_الخصم"]["إطلاق"] <= 0 for r in inq["أدراج"])))

    # ⑩ **المكيالُ المصنوع**: لو قُبِلت قراءةٌ لا أصلَ لها سقط البابُ كلُّه.
    T.append(("قُبِلت قراءةٌ مصنوعةٌ في درجٍ — مكيالٌ يقبل كلَّ ما يُسمّى مدلولًا",
              fab["مقبولةٌ_في_أدراج"] > 0))

    # ⑪ **ضابطُ القبول**: الحَكَمُ ليس عاجزًا في هذا الميدان.
    T.append(("ضابطُ القبولِ لم يُودَع — فالردُّ عجزُ مكيالٍ لا حكمُ مقياس",
              ctl["حكم"] != "مُودَعةٌ بالبرهان"))

    # ⑫ المحورُ الثالثُ: لا يُفتَح إلا بقيامِ أفرادِه، ولا يُنسَخ حالُه من غيره.
    T.append(("المحورُ الثالثُ فُتح ولم يقم فردٌ من فرديه — اجتماعٌ قبل أفرادِه",
              axs["ينفتح"] and not (sdq["صدقت"] and inq["نجا"])))
    T.append(("حالُ المحورِ الثالثِ لم يُشتَقّ من المحطّتين — نسخٌ لا اشتقاق",
              axs["حالُ_المحطّات"]["قامت_القسمة"] != sdq["صدقت"]
              or axs["حالُ_المحطّات"]["نجا_التضمّن"] != inq["نجا"]))

    # ⑬ الديونُ تُسمّى ولا تُرقَّم.
    T.append(("دَينٌ حملَ رقمًا — وما لم يُقَس لا يُسعَّر",
              any(any(ch.isdigit() for ch in d) for d in DEBTS)))
    T.append(("الديونُ طُوِيت — وغيابُ القياس يُعلَن ولا يُحذَف", not DEBTS))

    fired = [n for n, hit in T if hit]
    if fired:
        raise SidqError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return len(T)


