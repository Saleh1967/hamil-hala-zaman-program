    idle = {i for i in range(len(stream)) if i not in field}
    forms = sorted({stream[i] for i in field})
    row = _cell(stream, forms, idle, "لا وضعَ له في خريطتنا", len(idle) >= MIN_N)
    return dict(
        فصل=FASL_IHMAL, مكيال="الوضعُ — ومَن لا وضعَ له فهل هو المهمَل؟",
        مراسٍ=anchors,
        قاطعُ_المستعمَلِ_هو_قاطعُ_المعنى=bool(used == field),
        خانات=[row], قام=False,
        بيان_التطابق=("الخانةُ الموجَبةُ ههنا **هي عينُها في فصلِ المعنى**: "
                      "«له وضعٌ مختوم» = «مستعمَل» بمكيالِنا الحاضر. فالمكيالُ "
                      "**لا يفصل الفصلين**، والفارقُ بينهما دَينٌ مسمًّى"),
        حكم=("ساقطٌ بالوسيطِ ومردودٌ بالانحلالِ معًا — لا مملوءٌ بالإهمال: "
             "خانةُ «لا وضعَ له» نصيبُها فوق السقف، ونصُّ صاحبِ القسمة يكذّب "
             "تسميتَها إهمالًا، وقاطعُها هو عينُ قاطعِ المعنى مقلوبًا"),
    )


