# ═══ ④ الميدانُ الوضعيّ — مقامٌ واحدٌ بثلاثِ خاناتٍ مجموعُها المقام ══════════
def corpus():
    try:
        verses, stream, _texts = TG.corpus_surfaces()
        candidates, counts = TG.hypothesis_space(stream)
    except TG.Ta3allumError as exc:
        raise SidqError(E_MISSING, exc.message) from exc
    if len(stream) < MIN_N:
        raise SidqError(E_SHAPE, f"مقامُ الكلماتِ {len(stream)} دون حدِّ التسعير")
    return verses, stream, candidates, counts


def wad3_map(stream):
    """مكيالُ الوضعِ منفَّذًا: لكلِّ موضعٍ **محورُه الدلاليُّ** أو لا شيء.

    والطريقُ طبقتان معلنتان: صورةٌ ⟶ جذرٌ بأوسعِ طبقاتِ `awzan_engine`، ثمّ
    جذرٌ ⟶ محورٌ من خريطةِ «مقاييس اللغة» المختومة. ولا طبقةَ ثالثةَ ولا يدَ
    تُصلِح موضعًا بعينه.

    وتقطيعُ `awzan_engine` يُصادَم بتقطيعِ المقام: لو اختلفا موضعًا واحدًا لَصار
    المحورُ يُنسَب إلى غيرِ صاحبه — فيُصرَخ ولا يُقاس.
    """
    rich = [w for verse in AE.tokenize_rich() for w in verse]
    if len(rich) != len(stream):
        raise SidqError(E_SHAPE, f"تقطيعُ الأوزانِ {len(rich)} خالف مقامَ التعلُّم "
                                 f"{len(stream)} — لا يُنسَب محورٌ إلى غيرِ صاحبه")
    memo = {}
    roots = []
    for word in rich:
        key = tuple(word)
        if key not in memo:
            hit = AE.hit(word, ROOT_LAYER)
            memo[key] = hit[1] if hit else None
        roots.append(memo[key])
    rows = ML.read_table()               # البوّابةُ: الطولُ ثمّ البصمةُ قبل أيِّ قراءة
    entries = {}
    for r in rows:
        entries.setdefault(r["root_full"], r)
    declared, _widest = ML.awzan_roots()
    mapped = {r: (entries[r].get("semantic_axes") or "").strip()
              for r in declared
              if r in entries and (entries[r].get("semantic_axes") or "").strip()}
    axis = [mapped.get(r) if r else None for r in roots]
    return roots, axis, mapped


def field_station(verses, stream, counts, candidates, roots, axis, mapped):
    """الميدانُ **بمقامٍ صريحٍ لا بنسبةٍ عائمة**: ثلاثُ خاناتٍ مجموعُها المقام.

    وخطأُ الوسيطِ يُعَدُّ ولا يُستَر: فواتحُ السورِ نُسب إلى بعضها وضعٌ لأنّ
    الجذرَ استُخرج من **رسمها**، ونصُّ المحورِ الثاني «ولا يُعرَف الوضعُ
    بالصورة» — فهذا عددُ ما أخطأ به الوسيطُ معروضًا لا مطويًّا.
    """
    field = [i for i, a in enumerate(axis) if a]
    rooted = sum(1 for r in roots if r)
    no_root = len(stream) - rooted
    root_no_axis = rooted - len(field)
    if len(field) + root_no_axis + no_root != len(stream):
        raise SidqError(E_SHAPE, "خاناتُ الميدانِ لا تجمع المقام — مقامٌ عائم")
    if len(field) < MIN_N:
        raise SidqError(E_SHAPE, f"ميدانُ الوضعِ {len(field)} دون حدِّ التسعير — "
                                 "ولا يُسعَّر فصلٌ على ميدانٍ لا يحتمله")
    forms = sorted({stream[i] for i in field})
    faw = {DG.fold(f) for f in MDG.FAWATIH}
    faw_pos = [i for i, s in enumerate(stream) if s in faw]
    faw_wad3 = [i for i in faw_pos if axis[i]]
    return dict(
        مقام=len(stream), آيات=len(verses), صورٌ_متمايزة=len(counts),
        مرشّحون=len(candidates),
        خانات=dict(لَه_وضعٌ_مختوم=len(field), جذرٌ_بلا_وضعٍ_مختوم=root_no_axis,
                   لا_جذرَ_له=no_root),
        مجموعُ_الخانات=len(field) + root_no_axis + no_root,
        صورُ_الميدان=len(forms),
        ثمنُ_إعلانِ_صورِ_الميدان=round(TG.declaration_cost(forms), 1),
        جذورٌ_مخرَّطة=len(mapped),
        حدُّ_التسعير=MIN_N, سقفُ_الانحلال=TG.COVER_CEILING,
        بذرةُ_الضابط=TG.CONTROL_SEED,
        خطأُ_الوسيط=dict(
            مواضعُ_الفواتح=len(faw_pos),
            فواتحُ_نُسب_إليها_وضع=len(faw_wad3),
            صورُها=sorted({stream[i] for i in faw_wad3}),
            بيان=("الوضعُ قُرئ عبر جذرٍ مُستخرَجٍ من **الرسم**، ونصُّ المحورِ "
                  "الثاني «ولا يُعرَف الوضعُ بالصورة» — فهذا عددُ ما أخطأ به "
                  "الوسيطُ معروضًا، وهو دَينٌ مسمًّى لا عيبٌ مستور")),
        بيان=("مقامٌ واحدٌ بثلاثِ خاناتٍ مجموعُها المقام — ولا نسبةَ بلا مقام"),
    )


# ═══ ⑤ الفصولُ الثلاثةُ تُعرَض على مكيالِ الوضع ══════════════════════════════
def _bill(stream, forms, fire):
    try:
        return TG.rule_bill(stream, tuple(forms), fire, random.Random(TG.CONTROL_SEED))
    except TG.Ta3allumError as exc:
        raise SidqError(exc.code if exc.code in (E_SEAL, E_SHAPE) else E_SEAL,
                        exc.message) from exc


def _cell(stream, forms, fire, name, priced):
    """خانةٌ تُسعَّر أو تسقط بالمقام — والسقوطُ يُعلَن ولا يُلفَّق له حكم."""
    share = round(len(fire) / len(stream), 4)
    row = dict(خانة=name, إطلاق=len(fire), نصيب=share,
               بلغَت_حدَّ_التسعير=bool(len(fire) >= MIN_N))
    if not fire:
        row.update(حكم="ساقطةٌ بالمقام — لا موضعَ لها في المجمَّد", قامت=False)
        return row
    bill = _bill(stream, forms, fire)
    row.update({"Δ": bill["Δ"]}, ضابط=bill["ضابط"], منحلّة=bill["منحلّة"],
               حكمُ_الفاتورة=bill["حكم"])
    if not priced:
        row.update(حكم=("ساقطةٌ بالمقام — ميدانُها دون حدِّ التسعير، "
                        "فاتورتُها تُعرَض ولا يُحتَجُّ بها"), قامت=False)
    else:
        row.update(حكم=bill["حكم"], قامت=bill["حكم"] == "مُودَعةٌ بالبرهان")
    return row


def fasl_ma3na_station(stream, axis, counts):
    """الفصلُ الذي **رفع الوضعُ مقامَه**: على السطحِ كان ميدانُه موضعين فسقط
    بالمقام، وبالوضعِ صار ألفًا وستّمئةٍ ونيّفًا فبلغ الحدَّ وسُعِّر.

    وخانتاه معلنتان قبل القياس:
      • «مدلولُه معنًى» — للموضعِ محورٌ دلاليٌّ في الخريطة المختومة.
      • «مدلولُه لفظ»  — صورتُه من طائفةِ أسماءِ اللفظِ المغلقةِ في `qisma_gate`.
    والتقاطعُ يُعَدُّ ولا يُفترَض: فلو وقع موضعٌ في الخانتين لَبطل الفصل.

    **وأبجديّةُ الإعلانِ لا تُقتَطَع**: يُدفَع ثمنُ صورِ الميدانِ كلِّها **مع
    الطائفةِ المغلقةِ بتمامها** — لا بما وقع منها فقط. إذ لا يُنطَق الفصلُ إلا
    بتسميةِ الطائفةِ كلِّها، ولو سُعِّر الواقعُ وحدَه لصار سائرُها جدولًا
    مجّانيًّا. وعدَّتُها **مصادَمةٌ بوديعةِ القسمة** لا مكتوبةٌ ههنا.
    """
    hija, lafz, _ma3na = QG.lafz_names()
