# ═══ ① الودائعُ القائمةُ تُقرَأ ولا تُنسَخ ═══════════════════════════════════
def _deposit(name):
    path = os.path.join(ROOT, name)
    if not os.path.exists(path):
        raise SidqError(E_MISSING, f"وديعةٌ غائبةٌ عن الشجرة: {name}")
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


# ═══ ② محطّةُ الإذن — المحورُ الثاني مفتوحٌ بمكياله، وجوابُ السطحِ سلبيٌّ ═══════
def permission_station():
    """إذنُ القياس مقروءٌ من وديعتين، **ولا يُقرَأ منهما حالُ المحورِ الثالث**.

    ① `mihwar_v0.json`: المحورُ الثاني مفتوحٌ وشرطُه متحقّق، ومكيالُه المنصوصُ
       فيه لفظُ «الوضع» — فإن زُحزح المكيالُ صرخ البابُ ولم يقس بغير ما أُذن به.
    ② `qisma_v0.json`: جوابُ **السطحِ** سلبيٌّ بعدده — فصلُ المعنى واللفظِ ساقطٌ
       بالمقام (ميدانُه دون الحدّ) وفصلُ الوحدةِ منحلّ. ولولا ذلك لكان هذا
       البابُ تكرارًا لا محطّةً جديدة.
    """
    mih = _deposit(MIHWAR_DEPOSIT)["المحاور_v0"]
    by_name = {a.get("محور"): a for a in (mih.get("المحاور") or [])}
    if AXIS_OPEN not in by_name or AXIS_SHUT not in by_name:
        raise SidqError(E_SEAL, "محورٌ من المحورين غائبٌ عن وديعة المحاور")
    second = by_name[AXIS_OPEN]
    if not (second.get("مفتوح") and second.get("تحقّقَ_شرطُه")):
        raise SidqError(E_SEAL, f"محورُ «{AXIS_OPEN}» ليس مفتوحًا — لا يُقاس فيه")
    if AXIS_GAUGE not in (second.get("مكيال") or ""):
        raise SidqError(E_SEAL, "مكيالُ المحورِ الثاني زُحزح عن «الوضع» — صريخ")

    qis = _deposit(QISMA_DEPOSIT)["القسمة_v0"]
    surf = qis["مقيس"]
    surface_field = surf["ميدانُ طائفةِ أسماء اللفظ"]
    if surface_field >= MIN_N:
        raise SidqError(E_SEAL, "جوابُ السطحِ بلغ حدَّ التسعير — فلا محطّةَ ههنا")
    if surf["نصيبُ المفرد"] < TG.COVER_CEILING:
        raise SidqError(E_SEAL, "فصلُ الوحدةِ على السطحِ ليس منحلًّا — صريخ")
    return dict(
        المحورُ_الثاني=dict(محور=AXIS_OPEN, مكيال=second.get("مكيال"), مفتوح=True,
                            رتبة=second.get("رتبة")),
        جوابُ_السطح=dict(
            وديعة=QISMA_DEPOSIT,
            ميدانُ_فصلِ_المعنى_واللفظ=surface_field, حدُّ_التسعير=MIN_N,
            نصيبُ_المفرد=surf["نصيبُ المفرد"], سقفُ_الانحلال=TG.COVER_CEILING,
            حكم=qis["الحكم"]),
        المحورُ_الثالث=dict(
            محور=AXIS_SHUT,
            بيان=("حالُه **لا يُقرَأ ههنا**: يُشتَقُّ في §⑧ من نتيجةِ المحطّتين. "
                  "ولو قُرئ من وديعةِ المحاور لصار البرهانُ دائرةً")),
        بيان=("الإذنُ مقروءٌ لا مفترَض: المحورُ الثاني مفتوحٌ بمكيالِ «الوضع»، "
              "وجوابُ السطحِ سلبيٌّ بعدده — فهذه محطّةٌ جديدةٌ لا إعادة"),
    )


# ═══ ③ ثمنُ الوضع — يُقرَأ من ختمه **قبل** أن يُستعمَل ═══════════════════════
def price_station():
    """ثمنُ المكيالِ كلِّه: خريطةُ (جذرٍ ⟶ محورٍ) + جدولُ (صورةٍ ⟶ جذر).

    وكلاهما **مُصادَمٌ بوديعته بفارق صفر**: ثمنُ الخريطةِ يُعاد قياسُه حيًّا من
    `mihwar_gate.reference_price` ويُقابَل بالمودَع في `mihwar_v0.json`، وثمنُ
    جدولِ الأوزانِ يُقرَأ من `awzan_v0.json`. ولا يُكتَب واحدٌ منهما بيد.

    **ولماذا قبل الاستعمال؟** لأنّ هذا المجموعَ هو ما يجب أن يهزمه كلُّ خفضٍ
    في Δ يُدَّعى للمدلول في §⑦. ولو قيس بعدَ الخفضِ لأمكن أن يُقتطَع منه.
    """
    try:
        live = MHG.reference_price()
    except MHG.MihwarError as exc:
        raise SidqError(exc.code if exc.code in (E_MISSING, E_SEAL) else E_MISSING,
                        exc.message) from exc
    sealed = _deposit(MIHWAR_DEPOSIT)["المحاور_v0"]["ثمنُ_المرجع"]
    if live["ثمنُ_الخريطة_بتًّا"] != sealed["ثمنُ_الخريطة_بتًّا"]:
        raise SidqError(E_SEAL, f"ثمنُ الخريطةِ الحيُّ {live['ثمنُ_الخريطة_بتًّا']} "
                                f"خالف المودَع {sealed['ثمنُ_الخريطة_بتًّا']}")
    if live["مخرَّطة"] != sealed["مخرَّطة"]:
        raise SidqError(E_SEAL, "عدُّ الجذورِ المخرَّطةِ خالف وديعةَ المحاور")
    awzan = _deposit(AWZAN_DEPOSIT)["الأوزان_v0"]
