# sidq_gate.py — بابُ الصدق: **أتصدُقُ قسمةُ «المدلولِ وحدَه» بمكيالِ الوضع، وأينقَذُ
#                التضمّنُ بقراءةِ المدلول؟** — المحطّتان ③ و④ من سلّم `MIHWAR.md §⑧`.
#
# §٠ الدَّينانِ المعروضانِ للسداد بنصِّهما، ولا يُوسَّعُ واحدٌ منهما:
#    ① «صدقُ قسمةِ المدلولِ وحدَه (المحطّةُ ③)» — `mihwar_gate.DEBTS` بحرفه:
#       «قسمتُه الخمسُ **مبنيّةٌ** ومختومةُ الاشتقاق في `aqsam_v0.json`، و**صدقُها
#       لم يُقَس**». وقد عُرِضت على **سطحِ الدالِّ وحدَه** في `qisma_gate` فلم
#       تُحسَم: فصلُ الوحدةِ منحلٌّ · ومكيالُ الإهمالِ مردودٌ بعدده · وفصلُ المعنى
#       واللفظِ **ساقطٌ بالمقام** (ميدانُه موضعان). فهذا البابُ يُعيد عرضَها
#       بالمكيالِ الذي نصَّ عليه المحورُ الثاني: **الوضع**.
#    ② «إنقاذُ التضمّنِ بقراءة المدلول (المحطّةُ ④)» — وهو تنبّؤٌ **مسجَّلٌ قبل
#       القياس** في `MIHWAR.md §④`: إن كانت رتبُ الدلالة إنّما تتمُّ بالدالِّ
#       والمدلولِ معًا، فقراءةُ المدلول يجب أن تُنزِلَ Δ التضمّنِ إلى المُودَع.
#       «فإن لم تفعل فالدعوى **مكذَّبةٌ بالرقم وتُعلَن**» — ونصُّه أيضًا: «النجاةُ
#       بجدولٍ غيرِ مسعَّرٍ **اشتراءٌ لا برهان**».
#
# §١ المكيالُ واحدٌ ومُعلَنٌ قبل القياس: **الوضع**. وهو مركَّبٌ من طبقتين مختومتين
#    لا ثالثَ لهما، وكلتاهما **مُسعَّرةٌ قبل أن تُستعمَل**:
#      • صورةٌ ⟶ جذرٌ بأوسعِ طبقاتِ `awzan_engine` — وثمنُ جدولِها مختومٌ في
#        `awzan_v0.json`.
#      • جذرٌ ⟶ محورُه الدلاليُّ من خريطةِ «مقاييس اللغة» المختومةِ ببصمتها —
#        وثمنُ خريطتها مقيسٌ في `mihwar_gate.reference_price` ومختومٌ في
#        `mihwar_v0.json`.
#    فمجموعُهما **ثمنُ الوضع**، وهو الرقمُ الذي يجب أن يهزمه كلُّ ربحٍ يُدَّعى
#    للمدلول ههنا. ولا يُقاس ثمنٌ بعد الربح — بل يُقرأ من ختمه قبلَه.
#
# §٢ والحَكَمُ فاتورةُ `ta3allum_gate.rule_bill` وحدَها بترتيبها المعلن (الانحلالُ
#    أوّلًا · ثمّ الفاتورةُ · ثمّ الضابطُ العشوائيّ)، ولا عتبةَ سواها ولا يدُ أحد.
#    وحدُّ التسعيرِ `MIN_N` هو عينُ المعلنِ في `qisma_gate` و`ihala_gate` — لا
#    يُزَحزَح ههنا ولا يُستحدَث له مثيل.
#
# §٣ والقواعدُ **مُعلَنةٌ قبل أن تُقاس**، فلا تُضبَط على نتيجةٍ رُئيت:
#    ① **متى يقوم فصل؟** ميدانُه يبلغ حدَّ التسعير · وليس منحلًّا · وحكمُ خانتِه
#       «مُودَعةٌ بالبرهان». والقسمةُ **صادقةٌ** إن قامت فصولُها الثلاثةُ كلُّها.
#    ② **متى ينجو التضمّن؟** بشرطين معًا: حكمٌ «مُودَعةٌ بالبرهان» **مستقرٌّ على
#       الأدراج الثلاثة وفي القراءتين معًا** (وهو شرطُ `aqsam_gate` بعينه، لا
#       يُخفَّف ههنا)، **و**خفضُ Δ يهزم ثمنَ الوضع. فإن قُبِل في درجٍ ورُدَّ في
#       آخرَ فذاك **تقلُّبٌ بالدرج** لا نجاة، وإن كان الخفضُ دون الثمن فذاك
#       **اشتراءٌ لا برهان**.
#    ③ وقراءتا المدلولِ معلنتان قبل القياس ولا ثالثةَ لهما: **تضمينًا** (الصورةُ
#       تقع في نصِّ المحورِ جزءًا) و**قائمًا بذاته** (تقع كلمةً تامّةً فيه).
#
# §٤ والضوابطُ ثلاثةٌ لا تُطوى واحدةٌ منها:
#    ① **ضابطُ الخصم**: القراءةُ نفسُها بصورٍ **عشوائيةٍ** من الفضاء بالبذرةِ
#       المعلنة — فإن ساوت صورُ المصادفةِ صورَ الشواهدِ فالمكسبُ من القراءة لا
#       من الشواهد.
#    ② **مكيالٌ مصنوع**: مدلولٌ يُطلِق بأوّل حرفٍ من صورِ الشواهد — دلالةٌ لا
#       أصلَ لها، تُعرَض لتُرَدّ. فإن قُبِلت سقط البابُ.
#    ③ **ضابطُ القبول**: قاعدةٌ مختومةٌ في `ta3allum_v0.json` تُعاد فاتورتُها
#       وتُصادَم بختمها — ليُعلَم أنّ الحَكَمَ **يقبل** في هذا الميدان نفسِه.
#
# §٥ وما لا يُدَّعى — ويُختَم بعدده ولا يُحذَف:
#    ① **لا يُدَّعى أنّ القسمةَ باطلةٌ في العربية**: المقيسُ قيامُها **بمكيالِ
#       الوضعِ المتاحِ اليوم** على هذا المقام — وحكمٌ على مكيالٍ ومقامٍ لا على لغة.
#    ② **لا يُدَّعى أنّ ما لا وضعَ له مهمَل**: الخريطةُ ناقصةٌ بعددها المعروض،
#       والوسيطُ (الصورةُ ⟶ الجذر) يُخطئ بعددٍ معروضٍ كذلك — فالخانةُ **ساقطةٌ
#       بالوسيط** لا مملوءةٌ بالإهمال.
#    ③ **لا يُفتَح المحورُ الثالث**: وحالُه ههنا **يُشتَقّ** من نتيجةِ المحطّتين
#       ولا يُنسَخ من وديعةِ المحاور — فهذا البابُ مصدرُ ذلك الحكمِ لا ناقلُه.
#
