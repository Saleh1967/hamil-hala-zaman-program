def collide(measured):
    extra = [k for k in measured if k not in SEALED_SIDQ]
    if extra:
        raise SidqError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    bad = [(k, SEALED_SIDQ[k], measured.get(k)) for k in SEALED_SIDQ
           if k not in measured or measured[k] != SEALED_SIDQ[k]]
    if bad:
        raise SidqError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_SIDQ)


