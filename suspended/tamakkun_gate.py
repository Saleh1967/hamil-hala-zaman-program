# tamakkun_gate.py — بابُ التمكّن: أيتبدَّلُ آخِرُ الصورةِ بتبدُّلِ موضعها؟
#
# ــ ٠) الدعوى المقيسة ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# الدعوى: **التمكّنُ صفةٌ للصورةِ لا للموضع** — فالصورةُ المتمكّنةُ يتبدَّلُ آخِرُها
# بتبدُّلِ موضعها، وغيرُ المتمكّنةِ يلزَمُ آخِرُها حالًا واحدة. وهذه دعوى قابلةٌ
# للتكذيب متى عُيِّن المقياسُ قبل العدّ.
#
#   • **القسمةُ ثلاثٌ لا رابعَ لها**: اسمٌ وفعلٌ وحرف. وليس في هذا البابِ صنفٌ
#     اسمُه «مشتبه»: فما لم يقطع به المصنِّفُ ليس قسمًا رابعًا في اللسان، بل
#     **دَينٌ على المصنِّف** — يُعَدّ بعدده ويُسمّى ويُضيَّق، ولا يُودَع خانةً
#     في القسمة. ومحاولةُ تكذيبٍ تصرخ لو ظهرت في الوديعة خانةٌ رابعة.
#
#   • **الحَكَم على التمكّن**: ليس عدَّادَ «تبدَّلَ أو لم يتبدَّل» وحدَه — فذاك
#     هشٌّ يقلِبُ الصورةَ كلَّها بموضعٍ شاذٍّ واحد. بل **درجةُ التمكّن** موزونةً
#     بالمواضع: ١ ناقصَ نصيبِ الحالةِ الغالبةِ في الصورة. ويُصادَم الرقمان معًا.
#
#   • **الضوابط**: المتوقَّعُ تحليليًّا من النُّدرةِ وحدَها (Σ pˢ ⁿ)، وإحدى عشرةَ
#     فرقةً عشوائيّةً تَخلِطُ الخواتمَ داخلَ القسمِ بحفظِ عدَّةِ كلِّ صورة
#     (بذرةُ `ta3allum_gate.CONTROL_SEED`). ولا يُفصَل قسمٌ إلا إن غلبهما معًا.
#
# ــ ١) ثلاثةُ أثمانٍ تُعلَن وتُقاس قبلَ أن تُستعمَل ــــــــــــــــــــــــــــــــ
#   ① **ثمنُ التقنيع (دفعُ الدَّوْر)**: مصنِّفُ `jar_gate.nominal_mark` يقرأ
#      **خاتمةَ الكلمة** (تنوينًا أو كسرة) — وهي عينُ ما نقيس تبدُّلَه. فلو
#      صُنِّفَ بها لَصُنِّفَت الصورةُ بما نريد قياسَه: دَوْرٌ. فيُقرَأ الصنفُ على
#      كلمةٍ **مقنَّعةِ الخاتمة** (آخِرُها «عري»)، ويُقاس ثمنُ ذلك بالمواضع.
#   ② **ثمنُ المعجمِ المعلَن**: قوائمُ الحروفِ والضمائرِ والإشارةِ والجارِّ
#      معلَنةٌ بنصِّها، وثمنُها بـ`ta3allum_gate.declaration_cost` **يُقاس قبل
#      أن تُستعمَل** — فلا تُشترى التغطيةُ بتكديسِ الصور مجّانًا.
#   ③ **ثمنُ طرحِ الموقوف**: حالتا «سكون» و«عري» في `harakat_layer.STATES`
#      تتناوبان بالوقفِ والوصلِ لا بالموضعِ من الإعراب — وتلك قاعدةٌ موروثةٌ
#      منصوصةٌ هناك لا اجتهادَ منّا. فيُقتصَر القياسُ على الحركاتِ المعرِبةِ
#      الستّ، ويُعَدّ المطروحُ بعدده.
#
# ــ ٢) المحطّاتُ الخمس ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
#   ① **القسمة** — ثلاثةُ أقسامٍ ودَينُ المصنِّف، برحلةِ جمعٍ ومنع. ويُقاس
#      **تضييقُ الدَّين**: المصنِّفُ الموروثُ وحدَه ⟷ هو والمعجمُ المعلَن.
#   ② **التمكّن** — لكلِّ صورةٍ لها موضعان فأكثرُ في قسمها: أثابتةُ الخاتمةِ
#      هي أم متبدِّلة، ودرجتُها.
#   ③ **الحَكَم** — المتوقَّعُ التحليليُّ وضوابطُ المثل، في الأقسامِ الثلاثة.
#   ④ **النيابةُ عن العلامة** — دَينٌ قائمٌ في `wad3_v0.json` **يُسعَّر ههنا**:
#      حقلُ `harakat_layer.STATES` حقلٌ للحركةِ وحدَها، فما كان إعرابُه بثبوتِ
#      النونِ وحذفِها (ون · ين · ان) ظهرَ «غيرَ متمكّن» بذنبِ الحقلِ لا بذنبِ
#      البناء. ويُقاس نصيبُ ذوات النونِ من ثابتِ الفعلِ ومن متبدِّله.
#   ⑤ **الضابط** — الحرفُ قسمٌ إجماعُه أنّه مبنيّ، فهو **مكيالُ صدقِ المقياس**
#      لا محلُّ اكتشاف: إن لم يكن أثبتَ الثلاثةِ درجةً فالمقياسُ ساقط.
#
# ــ ٣) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا يُدَّعى أنّ المصنِّفَ يبلغُ المقامَ كلَّه: دَينُه **مقيسٌ منشور**، وما
#     دام قائمًا فأرقامُ الأقسامِ أرقامُ ما قُطِعَ به لا أرقامُ اللسان.
#   • لا يُدَّعى أنّ «متبدِّلَ الخاتمة» إعرابٌ ولا أنّ الثابتَ بناء: المقيسُ
#     **تبدُّلُ حالةٍ من حقلٍ مختومٍ بتبدُّلِ الموضع**، والتسميةُ بعدَه لا قبلَه.
#   • لا يُدَّعى أنّ بندَ الفعلِ يحصُرُ الأفعال: صدرُ المضارعِ وواوُ الجماعةِ
#     والقالبُ الحاسمُ قرائنُ سطحٍ تصيب بعضَها، وضجيجُها مسمًّى معدود.
