def falsify(qis, rows, tam, hak, niy, dab):
    T = []
    T.append(("خانةٌ رابعةٌ في القسمة",
              bool(set(qis["الأقسامُ_الثلاثة"]) - set(AQSAM))))
    T.append(("قسمٌ من الثلاثةِ خلا من المواضع",
              any(qis["الأقسامُ_الثلاثة"][q] == 0 for q in AQSAM)))
    T.append(("رحلةُ القسمةِ لم تُغلَق",
              qis["مواضعُ_قُطِعَ_بها"] + qis["دَينُ_المصنِّف"] != qis["مواضعُ_المقام"]))
    T.append(("المعجمُ المعلَنُ لم يُضيِّق دَينًا",
              qis["ما_ضيَّقَه_المعجمُ_المعلَن"] <= 0))
    T.append(("المعجمُ المعلَنُ بلا ثمنٍ مقيس",
              qis["ثمنُ_إعلانِ_المعجم"] <= 0))
    T.append(("التقنيعُ لم يُغيِّر شيئًا — فالدَّوْرُ لم يُدفَع",
              qis["ثمنُ_التقنيعِ_بالمواضع"] <= 0))
    T.append(("الموقوفُ لم يُطرَح", tam["_موقوف"] == 0))
    for q in AQSAM:
        T.append((f"قسمُ «{q}» لم يغلِب النُّدرةَ والمثلَ معًا",
                  not hak[q]["غلبَ_النُّدرةَ_والمثلَ"]))
        T.append((f"درجةُ «{q}» خارجَ [0,1]",
                  not 0.0 <= tam[q]["درجةُ_التمكّن"] <= 1.0))
    T.append(("الحرفُ ليس أثبتَ الأقسامِ — فالمقياسُ ساقطٌ بضابطه",
              not dab["الحرفُ_أثبتُها"]))
    T.append(("الاسمُ ليس أمكنَ من الفعلِ بالدرجة", not dab["الاسمُ_أمكنُ_من_الفعل"]))
    T.append(("النيابةُ بالنونِ لم تُسعَّر", not niy["الدَّينُ_مسعَّر"]))
    T.append(("خاتمةٌ موقوفةٌ تسرَّبت إلى المقيس",
              any(e in MAWQUF for _, e, _ in rows)))
    T.append(("موضعٌ بلا قسمٍ تسرَّب إلى المقيس",
              any(k not in AQSAM for _, _, k in rows)))
    fired = [t for t, hit in T if hit]
    if fired:
        raise TamakkunError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return [{"محاولة": t, "بيان": "لم تنجح"} for t, _ in T]


