# sigha_gate.py — بابُ الصيغة: أتسدِّدُ صيغةُ الفعلِ دَينَ المصنِّف؟
#
# ــ ٠) الدعوى المقيسة ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# خلَّفَ `tamakkun_gate` دَينًا منشورًا: **٢٦٬٨١٨** موضعًا لا يقطع بها المصنِّف،
# أكثرُها الماضي — إذ لا يُميَّز صدرُه من السطحِ بغير معجم. والدعوى ههنا:
# **صيغةُ الفعلِ وبابُ اعتلالِه يسدِّدان بعضَ ذلك الدَّينِ بقياسٍ لا بمعجم**.
#
#   • **الشبكةُ مولَّدةٌ لا مُنتقاة**: ضربٌ ديكارتيٌّ تامٌّ **٦ صيغٍ × ٧ أبوابِ
#     علّةٍ = ٤٢** خليّةً، تُسعَّر بـ`ta3allum_gate.declaration_cost` **قبل** أن
#     تُستعمَل. والخلايا الخاليةُ تُعَدّ ولا تُطوى: كثرةُ الحَملِ بلا صيدٍ هي
#     الفرقُ بين قاعدةٍ وقائمةِ استثناءات.
#
#   • **والحَكَمُ مصنِّفٌ مستقلٌّ لا الصيغةُ نفسُها**: لو حُكِمَ على الصيغةِ
#     بأنّها فعلٌ لأنّها صيغةُ فعلٍ لكان دَوْرًا. فالحَكَمُ **قسمةُ
#     `tamakkun_gate` الثلاثيّةُ المختومة**، وهي مبنيّةٌ على قرائنَ أخرى
#     (التعريفُ · التاءُ المربوطة · الجارُّ قبلَه · القالبُ الحاسم). و**نقاءُ
#     الخليّة** = نصيبُ «فعل» من **مصنَّفِها وحدَه** — والدَّينُ لا يُحتسَب في
#     المقام، فلا تُقاس الخليّةُ بما لم يُقطَع به.
#
#   • **والحدُّ موروثٌ لا مضبوطٌ باليد**: الخليّةُ تسدِّد إن جاوزَ نقاؤها
#     `1 − ta3allum_gate.COVER_CEILING` — أي أغلبيّةً مقيسةً بحدٍّ قائمٍ في
#     الشجرة، لا برقمٍ اختير بعدَ رؤية الجدول.
#
#   • **وضوابطُ المثل**: إحدى عشرةَ فرقةً تَخلِط أسماءَ الخلايا على المواضع
#     بحفظِ حجمِ كلِّ خليّة (بذرةُ `ta3allum_gate.CONTROL_SEED`). فإن سدَّدَ
#     المثلُ ما سدَّدَه المرصودُ فالشبكةُ لا تحمل خبرًا.
#
# ــ ١) الدَّوْرُ الذي وقعَ ويُعلَن: خلايا المضارعِ تحصيلُ حاصل ــــــــــــــــــــ
# `tamakkun_gate` يقرأ المضارعَ بصدرِه الساكنِ الفاء. فكلُّ خليّةٍ صيغتُها
# «مضارع» أو «مضارع مجهول» **تُعيد قاعدةَ الحَكَمِ نفسَها**، فنقاؤها ١٫٠٠٠٠
# بصفرِ اسمٍ — وهي بعينها علامةُ **المرآة** المسمّاةُ في سجلِّ أجناس العطل:
# آلةٌ بُنِيت على النتيجة. فهذه الخلايا **تُقاس ولا تسدِّد**، حجرًا بإعلانٍ
# سابقٍ للعدّ، ويُودَع عددُها ونقاؤها ليُرى الحجرُ لا ليُدَّعى.
#
# ــ ٢) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا يُدَّعى أنّ الخليّةَ المسدِّدةَ خالصةٌ للفعل: نقاؤها **مقيسٌ مودَعٌ**،
#     وصورُ دَينِها المسدَّدِ مسمّاةٌ لا مطويّة (قال · كان · جاء في الأجوف ⟷
#     ابن · اسم · اثنين في السالم).
#     فالسدادُ **مسعَّرٌ لا مجّانيّ**.
#   • لا يُدَّعى أنّ «ماضٍ مجرَّد» تحليلٌ صرفيّ: هو **ميزانٌ سطحيٌّ معلَن**
#     (ثلاثةُ أحرفٍ صدرُها فتحة) يصيب الماضيَ ويصيب معه غيرَه — والمقياسُ
#     يُظهِر ذلك بعدده لا يستره.
#   • لا يُدَّعى أنّ الدَّينَ سُدِّد: المسدَّدُ **١٬٢١٤ من ٢٦٬٨١٨**، والباقي
#     يُودَع رقمًا منشورًا لا وعدًا.
#   • ولا تُمَسّ وديعةُ `tamakkun_v0.json` ولا أختامُها: هذا بابٌ **فوقَها**
#     يقرأ قسمتَها ولا يكتب فيها، وحارسُ رحلةٍ يصرخ إن تبدّلَ مصنَّفٌ قائم.
