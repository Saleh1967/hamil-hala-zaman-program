E_OK, E_FIELD, E_SHAPE, E_SEAL = 0, 1, 2, 3


class SighaError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code, self.message = code, message


# ═══ ⓪ الإعلاناتُ المجمَّدةُ قبل القياس ════════════════════════════════════════
#
# ستُّ صيغٍ — كلُّ واحدةٍ ميزانٌ سطحيٌّ من حالات `harakat_layer.STATES` وحدَها
# على الكلمةِ **مقنَّعةَ الخاتمة** (تقنيعُ `tamakkun_gate.masked` بعينه، دفعًا
# للدَّوْر: لا يُقرَأ آخِرُ الكلمةِ في تحديد صيغتها).
SIYAGH = ("ماضٍ مجرَّد", "ماضٍ مجهول", "أمر", "أمر أجوف", "مضارع", "مضارع مجهول")

# سبعةُ أبوابٍ للاعتلال — مشتقّةٌ من حروفِ العلّةِ والهمزِ والتضعيفِ وحدَها.
ABWAB = ("سالم", "مثال", "أجوف", "ناقص", "لفيف", "مضعَّف", "مهموز")

# الشبكةُ ضربٌ ديكارتيٌّ تامّ — لا خليّةَ تُزاد بعدَ رؤية الجدول.
SHABAKA = tuple((g, b) for g in SIYAGH for b in ABWAB)

# الصيغُ المحجورةُ للدَّوْر: `tamakkun_gate` يقرأ المضارعَ بصدرِه الساكن،
# فخلاياه تُعيد قاعدةَ الحَكَمِ نفسَها. تُقاس ولا تسدِّد.
MAHJURA = ("مضارع", "مضارع مجهول")

# حدُّ النقاءِ موروثٌ لا مضبوطٌ باليد: أغلبيّةٌ بحدِّ السقفِ القائمِ في الشجرة.
NAQA_BAR = 1.0 - TG.COVER_CEILING

ILLA = ("و", "ي", "ا", "ى")                  # حروفُ العلّةِ في الرسم
HAMZ = ("أ", "إ", "ؤ", "ئ", "ء", "آ")        # صورُ الهمزةِ في الرسم
MUDARI3_PRE = TK.MUDARI3_PRE                 # ثلاثةٌ لا أربعة — مورثةٌ من باب التمكّن
CONTROL_TRIALS = 11


# ═══ ① بابُ الاعتلال وصيغةُ الوزن — من الرسمِ والحركةِ وحدَهما ═════════════════
def bab_of(s, m):
    """بابُ الاعتلال: لفيفٌ إن اجتمع علّتان · مثالٌ · أجوفُ · ناقصٌ · مضعَّفٌ · مهموزٌ · سالم."""
    jawf = any(0 < j < len(m) - 1 for j, (c, st) in enumerate(m)
               if c in ILLA and st == "عري")
    fa = s[0] in ("و", "ي")
    lam = s[-1] in ILLA
    if (fa and lam) or (jawf and lam) or (fa and jawf):
        return "لفيف"
    if fa:
        return "مثال"
    if jawf:
        return "أجوف"
    if lam:
        return "ناقص"
    if len(s) >= 2 and s[-1] == s[-2]:
        return "مضعَّف"
    if any(c in HAMZ for c in s):
        return "مهموز"
    return "سالم"


def sigha_of(m):
    """صيغةُ الوزنِ من الميزانِ السطحيِّ وحدَه — أو None إن لم تطابق واحدةٌ منها."""
    p = [st for _, st in m]
    s = [c for c, _ in m]
    n = len(m)
    if (n >= 4 and s[0] in MUDARI3_PRE and p[0] == "ضمة"
            and p[1] == "سكون" and p[2] == "فتحة"):
        return "مضارع مجهول"                                 # يُفعَل
    if n >= 4 and s[0] in MUDARI3_PRE and p[0] in ("فتحة", "ضمة") and p[1] == "سكون":
        return "مضارع"                                       # يَفعَل
    if n >= 3 and s[0] == "ا" and p[0] == "عري" and p[1] == "سكون" and s[1] != "ل":
        return "أمر"                                         # افْعَلْ — و«ال» مستثناةٌ بإعلان
    if n == 2 and p[0] in ("ضمة", "كسرة") and p[1] == "عري":
        return "أمر أجوف"                                    # قُلْ · بِعْ
    if n >= 3 and p[0] == "ضمة" and p[1] == "كسرة":
        return "ماضٍ مجهول"                                  # فُعِلَ
    if n == 3 and p[0] == "فتحة" and p[1] in ("فتحة", "كسرة", "ضمة", "عري"):
        return "ماضٍ مجرَّد"                                 # فَعَلَ · فَعِلَ · فَعُلَ · فَاعَ
    return None


def khalya_of(w):
    """خليّةُ الكلمةِ من الشبكة، أو None — والتقنيعُ يمنع قراءةَ الخاتمة."""
    m = TK.masked(w)
    g = sigha_of(m)
    return (g, bab_of(HL.skel(w), m)) if g else None


# ═══ ② محطّةُ الشبكة — ما حُمِلَ وما اصطيدَ به ══════════════════════════════════
def rows_of():
    """(خليّة · حكمُ المصنِّفِ المستقلِّ · صورة) لكلِّ موضعٍ طابقَ صيغةً."""
    out = []
    for words in TK.corpus():
        for i, w in enumerate(words):
            k = khalya_of(w)
            if k:
                out.append((k, TK.qism_of(words, i), HL.skel(w)))
    return out


def shabaka_station(rows):
    seen = collections.Counter(k for k, _, _ in rows)
    unknown = set(seen) - set(SHABAKA)
    if unknown:
        raise SighaError(E_FIELD, f"خليّةٌ خارجَ الشبكة المُعلَنة: {sorted(unknown)}")
    if len(SHABAKA) != len(SIYAGH) * len(ABWAB):
        raise SighaError(E_SHAPE, "الشبكةُ ليست ضربًا ديكارتيًّا تامًّا")
    names = tuple(f"{g}-{b}" for g, b in SHABAKA)
    return {
        "صيغٌ_مُعلَنة": len(SIYAGH),
        "أبوابُ_اعتلالٍ_مُعلَنة": len(ABWAB),
        "خلايا_الشبكة": len(SHABAKA),
        "خلايا_أصابت": len(seen),
        "خلايا_ميدانُها_صفر": len(SHABAKA) - len(seen),
        "مواضعُ_طابقت_صيغة": len(rows),
        "ثمنُ_إعلانِ_الشبكة": round(TG.declaration_cost(names), 1),
    }


# ═══ ③ محطّةُ النقاء — الحَكَمُ مصنِّفٌ مستقلّ، والدَّينُ خارجَ المقام ══════════
def cells_of(rows):
    t = collections.defaultdict(collections.Counter)
    for k, q, _ in rows:
        t[k][q or "دَين"] += 1
    return t


def naqa_of(c):
    """نصيبُ «فعل» من **مصنَّفِ** الخليّةِ وحدَه — ولا يُقاس ما لم يُقطَع به."""
    classified = c["اسم"] + c["فعل"] + c["حرف"]
    return (c["فعل"] / classified if classified else 0.0), classified


def naqa_station(rows):
    cells = cells_of(rows)
    table, paying, circ = [], [], []
    for g, b in SHABAKA:
        c = cells.get((g, b))
        if not c:
            continue
        pur, classified = naqa_of(c)
        hajr = g in MAHJURA
        pays = bool(pur > NAQA_BAR and not hajr and c["دَين"] > 0)
        row = {
            "الصيغة": g, "الباب": b, "ميدان": sum(c.values()),
            "اسم": c["اسم"], "فعل": c["فعل"], "حرف": c["حرف"], "دَين": c["دَين"],
            "مصنَّف": classified, "نقاء": round(pur, 4),
            "محجورةٌ_للدَّوْر": hajr, "تسدِّد": pays,
        }
        table.append(row)
        if pays:
            paying.append(row)
        if hajr:
            circ.append(row)
    return cells, table, paying, circ


# ═══ ④ محطّةُ الدائرة — تحصيلُ الحاصلِ يُقاس ليُرى، لا يُدَّعى ════════════════
def dawra_station(circ):
    if not circ:
        raise SighaError(E_SHAPE, "لا خليّةَ محجورةً — والحجرُ مُعلَنٌ قبل العدّ")
    tautological = [r for r in circ if r["نقاء"] == 1.0 and r["اسم"] == 0]
    return {
        "خلايا_محجورةٌ_للدَّوْر": len(circ),
        "منها_نقاؤها_تامٌّ_بصفرِ_اسم": len(tautological),
        "أدنى_نقاءٍ_في_المحجورة": round(min(r["نقاء"] for r in circ), 4),
        "ميدانُ_المحجورة": sum(r["ميدان"] for r in circ),
        "دَينُ_المحجورة": sum(r["دَين"] for r in circ),
        "بيان": ("صيغُ المضارعِ تُعيد قاعدةَ الحَكَمِ نفسَها في tamakkun_gate — "
                 "فدَينُها صفرٌ بالبناءِ لا بالكشف: الحَكَمُ قطعَ بكلِّ موضعٍ "
                 "منها قبلَ أن تُسأل. فنقاؤها تحصيلُ حاصلٍ لا شهادة، "
                 "وهو جنسُ «المرآة» بعينه"),
    }


# ═══ ⑤ محطّةُ ضوابط المثل — أتحمل الشبكةُ خبرًا؟ ══════════════════════════════
def _score(labels, verdicts):
    t = collections.defaultdict(collections.Counter)
    for k, q in zip(labels, verdicts):
        t[k][q or "دَين"] += 1
    cells = paid = 0
    for (g, _), c in t.items():
        pur, classified = naqa_of(c)
        if classified and pur > NAQA_BAR and g not in MAHJURA and c["دَين"] > 0:
            cells += 1
            paid += c["دَين"]
    return cells, paid


def mithl_station(rows, paying):
    labels = [k for k, _, _ in rows]
    verdicts = [q for _, q, _ in rows]
    obs_cells, obs_paid = _score(labels, verdicts)
    rng = random.Random(TG.CONTROL_SEED)
    hi_cells = hi_paid = -1
    for _ in range(CONTROL_TRIALS):
        sh = labels[:]
        rng.shuffle(sh)
        c, p = _score(sh, verdicts)
        hi_cells, hi_paid = max(hi_cells, c), max(hi_paid, p)
    if obs_cells != len(paying):
        raise SighaError(E_SHAPE, "عدُّ الخلايا المسدِّدةِ اختلفَ بين محطّتين")
    return {
        "ضوابطُ_المثل": CONTROL_TRIALS,
        "خلايا_تسدِّدُ_مرصودة": obs_cells,
        "أعلى_خلايا_في_المثل": hi_cells,
        "دَينٌ_يُسدَّدُ_مرصود": obs_paid,
        "أعلى_دَينٍ_في_المثل": hi_paid,
        "غلبَ_المثلَ": bool(obs_cells > hi_cells and obs_paid > hi_paid),
    }


# ═══ ⑥ محطّةُ السداد — ولا يُمَسُّ مصنَّفٌ قائم ══════════════════════════════
def sadad_station(rows, paying, qis):
    pay_keys = {(r["الصيغة"], r["الباب"]) for r in paying}
    moved = collections.Counter()
    noise = collections.defaultdict(collections.Counter)
    paid = 0
    for k, q, s in rows:
        if k not in pay_keys:
            continue
        if q is None:
            paid += 1
            noise[k][s] += 1
        else:
            moved[q] += 1                     # مصنَّفٌ قائمٌ في خليّةٍ مسدِّدة
    # حارسُ الرحلة: السدادُ لا ينتزع مصنَّفًا من قسمِه — إنّما يقرأ الدَّينَ وحدَه.
    before = dict(qis["الأقسامُ_الثلاثة"])
    after = dict(before)
    after["فعل"] += paid
    dayn_after = qis["دَينُ_المصنِّف"] - paid
    if sum(after.values()) + dayn_after != qis["مواضعُ_المقام"]:
        raise SighaError(E_SHAPE, "رحلةُ السداد لم تُغلَق")
    if any(after[k] < before[k] for k in before):
        raise SighaError(E_SHAPE, "السدادُ أنقصَ قسمًا — وهو لا يمسُّ إلا الدَّين")
    agg_pure = sum(r["فعل"] for r in paying) / max(
        1, sum(r["مصنَّف"] for r in paying))
    return {
        "خلايا_مسدِّدة": len(paying),
        "دَينٌ_سُدِّدَ": paid,
        "نصيبُ_المسدَّدِ_من_الدَّين": round(paid / qis["دَينُ_المصنِّف"], 4),
        "دَينٌ_باقٍ": dayn_after,
        "نقاءٌ_مجموعٌ_للمسدِّدة": round(agg_pure, 4),
        "مصنَّفاتٌ_قائمةٌ_في_الخلايا_المسدِّدة": dict(moved),
        "القسمةُ_قبل": before,
        "القسمةُ_بعد": after,
        "صورُ_الدَّينِ_المسدَّد": {f"{g}-{b}": [f for f, _ in noise[(g, b)].most_common(4)]
                          for (g, b) in sorted(pay_keys)},
    }


# ═══ ⑦ محاولاتُ التكذيب ══════════════════════════════════════════════════════
def falsify(rows, sh, tab, daw, mit, sad, qis):
    T = []
    T.append(("الشبكةُ ليست ضربًا تامًّا",
              sh["خلايا_الشبكة"] != sh["صيغٌ_مُعلَنة"] * sh["أبوابُ_اعتلالٍ_مُعلَنة"]))
    T.append(("الشبكةُ أصابت بكلِّ خلاياها — قائمةٌ لا قاعدة",
              sh["خلايا_ميدانُها_صفر"] == 0))
    T.append(("الشبكةُ استُعمِلت بلا ثمنٍ مقيس", sh["ثمنُ_إعلانِ_الشبكة"] <= 0))
    T.append(("خليّةٌ حُكِمَ عليها بلا مصنَّفٍ من الحَكَم",
              any(r["تسدِّد"] and r["مصنَّف"] == 0 for r in tab)))
    T.append(("خليّةٌ محجورةٌ سدَّدت", any(r["محجورةٌ_للدَّوْر"] and r["تسدِّد"] for r in tab)))
    T.append(("الدَّوْرُ لم يظهر — فالحجرُ بلا شاهدٍ مقيس",
              daw["منها_نقاؤها_تامٌّ_بصفرِ_اسم"] == 0))
    T.append(("دَينُ المحجورةِ ليس صفرًا — فالدَّوْرُ مُدَّعًى لا مقيس",
              daw["دَينُ_المحجورة"] != 0))
    T.append(("المحجورةُ بلا ميدانٍ — فالحجرُ على فراغ",
              daw["ميدانُ_المحجورة"] <= 0))
    T.append(("الشبكةُ لم تغلِب ضوابطَ المثل", not mit["غلبَ_المثلَ"]))
    T.append(("المثلُ سدَّدَ دَينًا — فالخليّةُ لا تحمل خبرًا",
              mit["أعلى_دَينٍ_في_المثل"] > 0))
    T.append(("لا خليّةَ سدَّدت", sad["خلايا_مسدِّدة"] == 0))
    T.append(("السدادُ بلغَ الدَّينَ كلَّه — ادّعاءٌ لا قياس",
              sad["دَينٌ_باقٍ"] <= 0))
    T.append(("نقاءُ المسدِّدةِ دون الحدِّ الموروث",
              sad["نقاءٌ_مجموعٌ_للمسدِّدة"] <= NAQA_BAR))
    T.append(("رحلةُ السداد لم تُغلَق",
              sum(sad["القسمةُ_بعد"].values()) + sad["دَينٌ_باقٍ"]
              != qis["مواضعُ_المقام"]))
    T.append(("السدادُ مسَّ قسمًا قائمًا",
              any(sad["القسمةُ_بعد"][k] < sad["القسمةُ_قبل"][k]
                  for k in sad["القسمةُ_قبل"])))
    T.append(("القسمةُ بعدَ السدادِ ليست ثلاثًا",
              set(sad["القسمةُ_بعد"]) != set(TK.AQSAM)))
    T.append(("صورُ الدَّينِ غيرُ مسمّاةٍ في خليّةٍ مسدِّدة",
              any(not v for v in sad["صورُ_الدَّينِ_المسدَّد"].values())))
    # ⑰ صيغةٌ مصنوعةٌ بميزانٍ لا يقع: تُلصَق بأبوابها فلا تصطاد ولا تسدِّد.
    fabricated = [(("صيغةٌ مصنوعة", b), q, s) for (_, b), q, s in rows[:200]]
    fab_cells, fab_paid = _score([k for k, _, _ in fabricated],
                                 [q for _, q, _ in fabricated])
    T.append(("صيغةٌ مصنوعةٌ خارجَ الشبكةِ نالت سدادًا",
              bool(fab_cells and fab_paid and fab_cells > mit["خلايا_تسدِّدُ_مرصودة"])))
    T.append(("خليّةٌ خارجَ الشبكةِ المُعلَنةِ تسرَّبت",
              any(k not in set(SHABAKA) for k, _, _ in rows)))
    fired = [t for t, hit in T if hit]
    if fired:
        raise SighaError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return [{"محاولة": t, "بيان": "لم تنجح"} for t, _ in T]


