# alama_layer.py — بابُ العلامة الظاهرة والمقدَّرة، وبابُ المعتلِّ بالأزواج الدنيا الواقعة.
#
# ــ ٠) التسجيلُ المسبق، وإعلانُ المسبار قبله ــــــــــــــــــــــــــــــــــــــــــــــ
# هذا البابُ **سُبق بمسبارٍ مُعلَن**، ولا يُكتَم: قبل تجميد أصنافه قِيست على المجمَّد أربعةُ
# مقادير — عددُ الشدّات، وموضعُها من الكلمة، وحالُ سابقةِ الشدّةِ الأولى، وخلوُّ الخاتمة
# العارية من الشدّة. فليس هذا تسجيلًا أعمى ولا يُدَّعى أنّه كذلك؛ وإنّما هو، كما في
# الجولة الثالثة من jumla_links، **تسجيلٌ بعد مسبارٍ مُصرَّحٍ به بموضعه**: الأصنافُ
# وترتيبُها والفواصلُ وn₀ مجمَّدةٌ في رأس الملفّ، والأعدادُ تُشتَقّ عند كلِّ تشغيل.
#
# ــ ١) العلّةُ التي يفتحها هذا البابُ: عمًى في الجرد لا في البيان ـــــــــــــــــــــــ
# جردُ الحركات في induction_engine خمسةٌ وعري (VOW ∪ TAN ∪ «عري»)، و**نقطةُ الشدّة
# 0x0651 ليست فيه البتّة**. والقارئُ يقرأ marks كلَّها ثمّ يُسقِط ما ليس في VOW/TAN،
# فالشدّةُ تُبتلَع صامتةً: لا تُعَدّ ولا تُوسَم ولا تظهر في عدّادٍ واحد. وهي في المجمَّد
# مقدارٌ يُشتقُّ هنا — لا يُنقَل — من بايتاته بختمها.
# والشدّةُ في الحقيقة **مركَّب**: حرفان متّحدان، أوّلُهما **ساكنٌ صامت** والثاني متحرّك.
# ففكُّها يُدخِل الجردَ صنفًا لم يكن فيه قطّ.
#
# ــ ٢) والفكُّ الساذجُ يخرق حارسًا مختومًا — فيُقيَّد ولا يُستثنى ــــــــــــــــــــــ
# في harakat_layer حارسٌ صوتيٌّ مختوم: «بداية-حامل — لا كلمةَ تبدأ بسكونٍ صرفيّ». ومن
# شدّات المجمَّد طائفةٌ **على أوّل حرفٍ من الكلمة** (مِّن · رَّبِّهِمْ · لَّا). فلو فُكّت
# كما تُفَكّ الداخليةُ لَوُلِد سكونٌ صامتٌ في بداية الكلمة، ولانخرق الحارسُ صامتًا.
# والصوابُ أنّ سكونَها **ليس لها**: هو إدغامُ خاتمةِ الكلمةِ السابقة فيها، فيُنسَب إلى
# موضعه — صنفًا خامسًا مسمًّى «عابرٌ للحدّ»، لا استثناءً يُمنَح للحارس.
# وهذا هو **درسُ ٩٦٣** بعينه (jar_gate): شرطٌ مُسارعٌ ابتلع ٩٦٣ موضعًا هي ألفُ الجماعة،
# فقُصِر ولم يُستثنَ منه. فلا صنفَ هنا يُمنَح سعةً ليبتلع ما ليس له.
#
# ــ ٣) والصنفُ المعدومُ يُعلَن معدومًا ــــــــــــــــــــــــــــــــــــــــــــــــــ
# كان في الخطّة أن تُجعل «الشدّة» صنفًا من أصناف تفكيك العريِّ الخاتميّ. فصادمها
# المسبارُ فسقطت: **لا خاتمةَ عاريةً عليها شدّةٌ في المجمَّد البتّة**. فالصنفُ يبقى
# مُعلنًا في القائمة المجمَّدة و**عددُه صفرٌ يُطبَع**، لأنّ المعدومَ المُعلَن شاهدٌ
# والمعدومَ المطويَّ ثغرة. والشدّةُ تمسُّ الجردَ الداخليَّ لا الخاتمةَ العارية.
#
# ــ ٤) الأحكامُ البنيويةُ الثلاثة — مكتوبةٌ هنا لا موصوفةٌ في تقرير ــــــــــــــــــــ
#   ① **ω = 0 يحذف الحافةَ لا العقدة**: الزوجُ الذي لا تقع إحدى صورتيه في المجمَّد
#      حافتُه ساقطة (`omega_drop`)، والدعوى تبقى ما بقيت حافةٌ موجبةٌ تصلها، وتسقط
#      إن انقطعت. لا حكمين متناقضين على حالةٍ واحدة.
#   ② **الصدقُ الخاوي محجوزٌ بـn₀**: كلُّ دعوى هنا معها حدٌّ أدنى للشواهد معلنٌ قبل
#      القياس، ودونه حكمُها `غيرُ مختبَرة` — لا `صادقة`. فالقاعدةُ التي لا يشهد لها
#      إلا جذرٌ واحدٌ اسمٌ آخرُ للحفظ، لا قاعدة.
#   ③ **الفاصلُ ذو الاتجاهين يُبرَّر بابًا بابًا**: لكلِّ فاصلٍ هنا سطرُ تبريرٍ في
#      تسجيله يقول ما الذي يُسقِطه وما الذي يُصعِده — ولا فاصلَ يُنقَل عادةً من باب.
#
# ــ ٥) والكيلُ ليس هنا ـــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
