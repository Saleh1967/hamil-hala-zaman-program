def show(R):
    print("— فكُّ الشدة: صنفٌ دخل الجردَ لأوّل مرّة —")
    f = R["فكُّ الشدة".replace(" ", "_")]
    print(f"  شدّاتٌ في المجمَّد: {f['شدّاتٌ_في_المجمَّد']:,} — وكانت صفرًا في كلِّ عدّاد")
    for k, n in f["مواضعُها"].items():
        print(f"    {k:22s} {n:>7,}")
    print("  مقصدُ سكونِ الشدّةِ الأولى:")
    for k, n in f["مقصدُ_سكونِ_الشدّةِ_الأولى"].items():
        print(f"    {k:26s} {n:>7,}")

    print("\n— جردُ السكونات: أربعةٌ وخامسُها اقتضته الشجرة —")
    for k, n in R["جردُ_السكونات"]["أصناف"].items():
        print(f"  {k:22s} {n:>7,}")
    print(f"  {'المجموع':22s} {R['جردُ_السكونات']['مجموع']:>7,}")

    print("\n— تفكيكُ الخاتمة العارية بأصنافٍ مرتَّبةٍ مجمَّدة —")
    t = R["تفكيكُ_العري"]
    for k, _ in BARE_ORDER:
        n = t["أصناف"].get(k, 0)
        mark = " ⟵ معدومٌ مُعلَن" if n == 0 else ""
        print(f"  {k:22s} {n:>7,}  {'·'.join(t['أمثلة'].get(k, [])[:3])}{mark}")
    print(f"  {'المجموع':22s} {t['خاتمةٌ_عارية']:>7,}")
    print(f"  نصيبُ «المقدَّر» الحقيقيّ: {t['نصيبُ_المقدَّر']['عدد']:,} "
          f"({t['نصيبُ_المقدَّر']['نسبة']:.2%} من العري) — مرشَّحٌ لا مقدَّر")

    print("\n— بابُ المعتلّ بالأزواج الدنيا الواقعة —")
    d = R["بابُ_المعتلّ"]
    for r in d["أزواج"]:
        m = "✓" if r["واقعٌ"] else "✗ ω=0 ⟵ حافةٌ ساقطة"
        print(f"  {r['جذر']}  {r['ماضٍ']:>5s} {r['وقوعُ_الماضي']:>4,} · "
              f"{r['مضارع']:>6s} {r['وقوعُ_المضارع']:>4,}  {m}")
    for bab, b in d["فواتير"].items():
        if b.get("حكم") == "غيرُ مختبَرة":
            print(f"  [{bab}] {b['حكم']} — {b['علّة']}")
        else:
            print(f"  [{bab}] صورٌ {b['صورٌ']} · جذور {b['جذور']} · توكينات {b['توكينات']:,} · "
                  f"L(M) صورٌ {b['نموذجُ_الصور']} ⟷ جذورٌ {b['نموذجُ_الجذور']} · "
                  f"Δ {b['Δ']:+.2f} · {b['حكم']}")
    print(f"  الحكم: {d['حكم']}")

    print("\n— البند صفر: مكيالٌ واحد، مصدران، تجربةٌ واحدة —")
    for src, v in R["البندُ_صفر"]["تجربةُ_القبول"]["مصادر"].items():
        print(f"  {src:28s} طول {v['طول']:>9,} · |Σ| {v['حجمُ_الأبجدية']:>3,} · "
              f"رتبة٠ {v['رتبة0']['بتٌّ_للرمز']:.4f} ب/رمز · "
              f"رتبة١ {v['رتبة1']['بتٌّ_للرمز']:.4f} ب/رمز · Δ {v['فرق']:+,}")
    print(f"  ومصدرٌ واحدٌ يصرخ: {R['البندُ_صفر']['تجربةُ_القبول']['مصدرٌ_واحدٌ_يصرخ']}")

    ok = sum(1 for t in R["محاولاتُ_التكذيب"] if not t["نجحت"])
    print(f"\n— محاولاتُ التكذيب: {ok}/{len(R['محاولاتُ_التكذيب'])} رُدّت ✓")


