# ═══ ① القارئُ الموسَّع: يرى الشدّة، ويُصادَم بالقارئ المختوم بفارق صفر ═══════════════
def parse_marked(path):
    """كلُّ آيةٍ ⟼ كلمات، وكلُّ كلمةٍ ⟼ (حرف، هيئة، أمشدَّدٌ هو؟).

    الهيئةُ تُشتَقُّ بسياسة `induction_engine.parse_verses` بحرفها، ويُضاف إليها حقلٌ
    واحدٌ فقط: أعلى الحرفِ شدّةٌ أم لا. وهذا التوسيعُ **يُبرهَن لا يُدَّعى**: `collide`
    أدناه يُسقِط الحقلَ الجديد فيجب أن يعود القارئان سواءً بفارق صفر.
    """
    blob = open(path, "rb").read()
    assert hashlib.sha256(blob).hexdigest() == SEAL, "ليس المجمَّد — البصمة خُالفت"
    verses = []
    for ln in blob.decode("utf-8-sig").splitlines():
        if not ln.strip() or not any(AR(c) for c in ln):
            continue
        words = []
        for w in ln.split(" "):
            pos, i, n = [], 0, len(w)
            while i < n:
                if AR(w[i]):
                    ch = w[i]
                    marks = []
                    while i + 1 < n and (0x064B <= ord(w[i + 1]) <= 0x0652 or ord(w[i + 1]) == DAGGER):
                        i += 1; marks.append(ord(w[i]))
                    vs = [m for m in marks if m in VOW]; ts = [m for m in marks if m in TAN]
                    st = TAN[ts[0]] if ts else VOW[vs[0]] if vs else "فتحة" if DAGGER in marks else "عري"
                    pos.append((ch, st, SHADDA in marks))
                i += 1
            if pos:
                words.append(pos)
        if words:
            verses.append(words)
    return verses


def collide(marked, plain):
    """مصادمةُ القارئين: إسقاطُ حقل الشدّة يجب أن يعيد القارئَ المختومَ بعينه."""
    a = [[[(c, s) for c, s, _ in w] for w in v] for v in marked]
    return a == plain


# ═══ ② فكُّ الشدة: حرفان متّحدان — والموضعُ يحكم أين يقع سكونُ الشطر الأوّل ═══════════
def unfold(marked):
    """يُرَدّ (المواضعُ مفكوكةً، عدّادُ مواضع الشدّة بأصنافها).

    شدّةٌ داخلَ الكلمة ⟶ يُدرَج قبل الحرف موضعٌ (الحرف، «سكونٌ صامت»).
    شدّةٌ على أوّل الكلمة ⟶ **لا يُدرَج فيها شيء**: سكونُها يُنسَب إلى خاتمة الكلمة
    السابقة وسمًا «عابرٌ للحدّ»، فلا تبدأ كلمةٌ بساكنٍ ولا يُخرَق حارسُ «بداية-حامل».
    """
    out, kinds = [], Counter()
    for v in marked:
        vv = []
        for wi, w in enumerate(v):
            nw = []
            for li, (ch, st, sh) in enumerate(w):
                if sh and li == 0:
                    kinds["عابرٌ للحدّ"] += 1
                elif sh:
                    kinds["صامتٌ داخل الشدة"] += 1
                    nw.append((ch, "سكونٌ صامت", "مشتقّ"))
                nw.append((ch, st, "مرسوم"))
            vv.append(nw)
        out.append(vv)
    return out, kinds


def initial_shadda_landing(marked):
    """أين يقع سكونُ الشدّةِ الأولى؟ يُعَدّ حالُ خاتمةِ الكلمة السابقة، ولا يُدَّعى حكم."""
    land = Counter()
    for v in marked:
        for wi, w in enumerate(v):
            if not w or not w[0][2]:
                continue
            if wi == 0:
                land["رأسُ الآية — لا سابقةَ لها"] += 1
            elif v[wi - 1][-1][1] == "عري":
                land["سابقتُها عاريةُ الخاتمة"] += 1
            else:
                land["سابقتُها متحرّكةُ الخاتمة"] += 1
    return land


