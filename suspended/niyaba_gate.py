# ═══ ⑤ محطّةُ ضوابط المثل — على الميدانِ الصادقِ بلا «ال» ════════════════════
def _score(labels, verdicts):
    t = collections.defaultdict(collections.Counter)
    for k, q in zip(labels, verdicts):
        t[k][q or "دَين"] += 1
    marks = paid = 0
    tops = set()
    for c in t.values():
        top, pur, classified = naqa_of(c)
        if classified and pur > NAQA_BAR and c["دَين"] > 0:
            marks += 1
            paid += c["دَين"]
            tops.add(top)
    return marks, paid, len(tops)


def licensed_of(rows):
    """العلامةُ المرخَّصة: غالبُها على المثلِ الصادقِ بلا «ال» بنقاءٍ فوقَ الحدّ."""
    clean = collections.defaultdict(collections.Counter)
    for a, q, _, al, _, _ in rows:
        if not al:
            clean[a][q or "دَين"] += 1
    out = {}
    for a in ALAMAT:
        top, pur, classified = naqa_of(clean[a])
        if classified and pur > NAQA_BAR and clean[a]["دَين"] > 0:
            out[a] = top
    return out


