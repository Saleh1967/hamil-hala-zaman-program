# النواسخُ — قائمةٌ مُعلَنةٌ مُسعَّرة. ثمنُها يُدفَع سواءٌ أثبتت أم سقطت.
NAWASIKH = ("كان", "كانت", "كانوا", "تكون", "يكون", "نكون", "ليس",
            "إن", "أن", "إنا", "إنه", "إنك", "إنكم", "إنما",
            "لعل", "ليت", "لكن", "أصبح", "صار", "ظل", "بات", "أمسى")

NAQA_BAR = 1 - TG.COVER_CEILING
