# niyaba_gate.py — بابُ النيابة: أيُعرَبُ بالحرفِ حيث عميَ حقلُ الحركة؟
#
# ــ ٠) الدعوى المقيسة ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# في `tamakkun_gate` دَينٌ **مسمًّى مسعَّرٌ ولم يُسدَّد**: «النيابةُ عن العلامة».
# وعلّتُه بنيويّةٌ لا عَرَضيّة — `harakat_layer.STATES` حقلُ **حركةٍ وحدَها**
# بثمانِ حالات، فما كانت علامتُه **حرفًا** (واوًا أو ياءً أو ألفًا أو نونًا)
# لا يراه الحقلُ البتّة. فالدعوى المعروضةُ للتكذيب:
# **أنّ في سطحِ المجمَّدِ حقلًا ثانيًا للعلامةِ هو حقلُ الحرف، وأنّه يحمل
# خبرًا يسدِّد من دَينِ المصنِّفِ الثلاثيّ.**
#
# وتُعرَض في **ميدانين منفصلين يُحكَم على كلٍّ منهما وحدَه**:
#   • **ميدانُ خواتمِ النون**: `ون · ين · ان` — حقلٌ مُعلَنٌ مغلقٌ مُسعَّر.
#   • **ميدانُ الأسماءِ الخمسة**: قائمةٌ موروثةٌ بصورِها الثلاثِ — مُسعَّرةٌ كذلك.
# والحَكَمُ في كليهما مصنِّفُ `tamakkun_gate` **المستقلّ**، لا العلامةُ نفسُها؛
# وقد تُحقِّقَ أنّه لا يقرأ هذه الخواتمَ البتّة: فروعُه خاتمةُ «وا» وصدرُ
# المضارعِ و«ال» والتاءُ المربوطةُ والقوالب. والحدُّ موروث:
# `1 − ta3allum_gate.COVER_CEILING`.
#
# ــ ١) الحُكم: ميدانٌ سقط وميدانٌ قام ــــــــــــــــــــــــــــــــــــــــــــــ
# **خواتمُ النونِ ساقطة.** تسدِّد في ظاهرِ الأمرِ آلافًا، وتتبدَّل على الجذرِ
# الواحدِ في مئةٍ وخمسين جذرًا، وينحاز تبدُّلُها مع الجارِّ. ثمّ يُقابَل ذلك
# كلُّه بـ**ضابطِ الافتعال**: ثلاثُ خواتمَ من حرفين تُسحَب بالقرعةِ من
# المجمَّدِ **خارجَ المُعلَن** بميدانٍ لا يقلُّ عنه. فإذا الفرقةُ المصنوعةُ
# **تبلغ المرصودَ أو تغلبه في كلِّ إحصاءٍ قِيس**: في عددِ الجذورِ المتبدِّلةِ
# وفي الميدانِ وفي انحيازِ الجارِّ وفي فصلِ القسمين. فالخبرُ إذن في **كونِ
# الخاتمةِ خاتمةً** لا في كونِها **علامةَ إعراب**؛ والسدادُ الذي كان سيُدَّعى
# **يُودَع ممتنعًا مقيسًا ولا يُطبَّق**.
#
# **والأسماءُ الخمسةُ قائمة.** وبرهانُها إحصاءٌ آخرُ بالكامل: **إكمالُ
# الثلاثيّةِ** — أن يرد الجذرُ الواحدُ بالواوِ وبالألفِ وبالياءِ جميعًا. وهذه
# نادرةٌ في المجمَّد: من آلافِ الجذورِ التي تقع قبلَ إحدى هذه الثلاثِ لا
# يُكملها إلّا نفرٌ يُعَدّ. والقائمةُ الموروثةُ تصيب منه ما تصيب، وتغلب
# الفرقةَ المصنوعةَ من جذورٍ تُسحَب بالقرعةِ بميدانٍ مثلِها.
#
# ــ ٢) ما سقطَ ههنا ويُودَع كما يُودَع القائم ــــــــــــــــــــــــــــــــــــــ
#   • **فخُّ «ال»**: نقاءُ «ين» على الميدانِ المخلوطِ ٠٫٩٧٩ ويبدو قاطعًا —
#     وأكثرُ مصنَّفِها يحمل «ال»، و«ال» **أحدُ فروعِ الحَكَمِ نفسِه**. فالنقاءُ
#     **مستعارٌ**. والمثلُ الصادقُ للدَّينِ هو المصنَّفُ **بلا «ال»** وحدَه،
#     وعليه **تنقلب** «ان» من اسمٍ إلى فعل. والانقلابُ يُودَع رقمًا.
#   • **النواسخُ لا تُثبِت نفسَها**: أثرُ الناسخِ في العلامةِ دونَ أثرِ الجارّ،
#     فدعوى «الناسخُ عاملُ نصبٍ يُرى في الحرف» **لا تقوم بهذا القياس**.
#     وثمنُ إعلانِ قائمتِها **مدفوعٌ ولا مردودَ له** — وذلك معنى التسعيرِ قبلَ
#     الاستعمال.
#   • **«فو» تُحجَر**: صورتُها المجرورةُ «في» عينُ حرفِ الجرِّ في الرسم، فأكثرُ
#     مصنَّفِها **حرف** — والحَكَمُ قد قطعَ فيها قبلَ أن تُسأل. ويُودَع سببُ
#     حجرِها رقمًا لا وصفًا. و**«حم»** لها ميدانٌ ولا مصنَّفَ فيه فلا تُرخَّص.
#
# ــ ٣) فائدةٌ منهجيّةٌ تُودَع ــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# **ضابطُ الخلطِ أضعفُ من ضابطِ الافتعال.** خلطُ الأسماءِ يُبقي الحقلَ كما هو
# ويُبدِّل عناوينَه، فيسهل أن يُغلَب. وضابطُ الافتعالِ يأتي بحقلٍ **آخرَ
# بالكامل** بميدانٍ مثلِه. وقد اجتازَ هذا البابُ الأوّلَ **وسقطَ في الثاني** —
# فلولا الثاني لَأُودِعَ سدادٌ كاذبٌ بالآلاف. ومَن أرادَ إعادةَ النظرِ في
# أبوابٍ قبلَه فليُقابِلها بضابطِ الافتعالِ لا بالخلطِ وحدَه.
#
# ــ ٤) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا يُدَّعى أنّ سقوطَ خواتمِ النونِ **نفيٌ للإعرابِ بالحرف** في العربيّة:
#     المقيسُ أنّ **هذا الحقلَ بهذا الحَكَمِ على هذا المجمَّد** لا يفصل نفسَه
#     من فرقةٍ مصنوعةٍ بمثلِ حجمه. وما وراءَ ذلك دعوى لا رقمَ لها ههنا.
#   • ولا تُمَسُّ وديعةٌ قائمةٌ ولا ختمٌ: السدادُ يُقاس ولا يُكتَب في التمكّن.
#   • والسدادُ **لا يُجمَع** إلى سدادِ بابَي الصيغةِ والوصل: المشتركُ مقيسٌ
#     مودَعٌ، والجديدُ وحدَه هو ما لم يسدِّده بابٌ قبلَه.
