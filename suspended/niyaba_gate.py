# ═══ ⑤½ محطّةُ الافتعال — حقلٌ آخرُ بالكامل، لا خلطُ عناوين ═════════════════
def _arena(marks, endings):
    """إحصاءاتُ حقلٍ من خواتمَ: (جذورٌ متبدِّلة · ميدانُها · أثرُ الجارِّ ·
    أقسامٌ غالبةٌ متمايزةٌ على المثلِ الصادقِ بلا «ال» · دَينٌ يُسدَّد)."""
    st = collections.defaultdict(collections.Counter)
    recs, clean_l, clean_v = [], [], []
    for e in marks:
        for s, g, q, al in endings[e]:
            st[s[:-len(e)]][e] += 1
            recs.append((s[:-len(e)], e, g))
            if not al:
                clean_l.append(e)
                clean_v.append(q)
    alt = {b for b, c in st.items() if len(c) > 1}
    sub = [r for r in recs if r[0] in alt]
    t = collections.defaultdict(collections.Counter)
    for _, e, g in sub:
        t[g][e] += 1

    def share(g, e):
        n = sum(t[g].values())
        return t[g][e] / n if n else 0.0

    jarr = max(share("جارّ", e) - share("غيرُه", e) for e in marks)
    n_marks, paid, tops = _score(clean_l, clean_v)
    return (len(alt), len(sub), round(jarr, 4), tops, paid)


