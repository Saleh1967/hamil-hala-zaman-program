    shared_sigha = shared_wasl = alone = 0
    for words in TK.corpus():
        for i, w in enumerate(words):
            s = HL.skel(w)
            b = _bare(s)
            stem = next((k for k in sorted(khamsa)
                         if any(b == f or (b.startswith(f)
                                           and b[len(f):] in TK.PRON_SUF)
                                for f in KHAMSA[k])), None)
            if stem is None or TK.qism_of(words, i) is not None:
                continue
            paid[khamsa[stem]] += 1
            noise[stem][s] += 1
            if SG.khalya_of(w):
                shared_sigha += 1
            elif WG.is_asm_wasl(s):
                shared_wasl += 1
            else:
                alone += 1
    total = sum(paid.values())
    before = dict(qis["الأقسامُ_الثلاثة"])
