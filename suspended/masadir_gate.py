# masadir_gate.py — بابُ المصادر: التبويبُ يُولَّد من البيان ولا يُنسَخ عنه.
#
# ══ العلّةُ التي يقتلها هذا الباب ══════════════════════════════════════════════════
# التبويبُ جدولٌ يُكتَب بيدٍ عادةً: صفٌّ لكلِّ مصدرٍ، وخاناتٌ تُملأ بالنظر. وهذا **جنسُ
# العطل الذي يشيخ صامتًا**: البيانُ يتغيّر والجدولُ لا يتغيّر، فيبقى صادقَ الظاهرِ
# كاذبَ المقدار. وقد وقع بعينه: رأسُ تقريرٍ أعلن «٣١ مصدرًا (٢٧ مختومًا)» ومتنُه
# يعدّ ٢٨، والبيانُ يحمل ٣٢ صفًّا — انحرافٌ بواحدٍ لا مصادمَ له.
#
# فههنا **لا يُكتَب صفٌّ ولا تُملأ خانةٌ بيد**. البيانُ `sources_manifest.tsv` مصدرُ
# حقيقةٍ واحد، والتبويبُ مشتقٌّ منه ومن **قوائمَ تُستورَد من أبوابها** — فإن تغيّر
# البيانُ أو تغيّرت قائمةٌ، تغيّر التبويبُ من لحظته وسقطت المصادمةُ في CI.
#
# ══ المحاورُ الأربعة — كلُّ خانةٍ مشتقّةٌ أو دَينٌ مسمًّى ═══════════════════════════
# على سنّةِ `mawsua_gate.py`: الخانةُ إمّا **مُحَلَّةٌ** لها `(سندٌ · موضعٌ · قيمةٌ)
# تُشتَقُّ عند التشغيل، وإمّا **دَينٌ مسمًّى لا قيمةَ له البتّة**.
#
#   ① **المُدَّعي** — أيُّ قائمةٍ في الشفرة تدّعي هذا المصدرَ شاهدًا لها؟ والقائمةُ
#      **تُستورَد من بابها** (`aqsam_gate.IMAMS` · `dalalat_gate.HADITH_BOOKS` …)
#      لا تُنسَخ ههنا. ومصدرٌ لا يدّعيه أحدٌ **دَينٌ بلا دورٍ**، يُسمّى ولا يُرقَّم.
#   ② **طبقةُ الختم** — مشتقّةٌ من حقول البيان نفسِها: الحقولُ الثلاثةُ (بصمةُ الكائن ·
#      الطولُ · sha256) حاضرةً ⟶ **طبقةُ الحاوية (٠)**. ولا طبقةَ أعلى في الشجرة،
#      **وهذا صفرٌ يُقاس بمسحٍ لا يُدَّعى بنثر**.
#   ③ **رتبةُ الثبوت** — مشتقّةٌ من عدِّ المرايا المختومة للكتاب الواحد في البيان:
#      كتابٌ بمرآتين فأكثرَ ⟷ كتابٌ بمرآةٍ واحدة. **ولا يُدَّعى توافقُ المرايا**:
#      هي نسخٌ متخالفةُ البايتات بالضرورة، والعددُ عددُ شهودٍ لا عددُ اتّفاق.
#      وضمُّ المرايا **يُشتَقُّ بوجهين يُصادَمان** لا بوجهٍ يُوثَق به: بقطع لاحقةِ
#      المعرِّف · وبقطع صدرِ الملحوظة. وهما **يتخالفان مقيسًا**، والأوّلُ هو الغالط:
#      يضمُّ «متن قطر الندى» إلى «شرحه» وهما كتابان، و«ج١» إلى «ج٣» وهما جزآن.
#      فيُؤخَذ **الأفرقُ** ويُعرَض ضمُّ الأخصِّ باسمه — لا يُطوى ولا يُصحَّح صامتًا.
#   ④ **حالُ البيان** — مختومٌ بالتحقُّق الثلاثيِّ · أو معذورٌ بسببه المكتوب.
#
# ══ الخطرُ الأكبرُ الذي يحرسه هذا الباب ══════════════════════════════════════════════
# **العضويةُ مطابقةٌ تامّةٌ لا مشط.** المعرِّفُ `nahhas_icrab_sham` **بادئةُ** المعرِّف
# `nahhas_icrab_shamay`، فمن بوّب بـ`grep` ادّعى أنّ الأوّلَ في `sources_census.CENSUS`
# وليس فيها البتّة — والثاني هو الذي فيها. وهذا **عينُ درسِ `resolve_one`** في
# `fetch_source.sh`: المسارُ يُحلُّ بنمطٍ يصرخ على 0 أو >1، لا بمسارٍ مُدَّعًى.
# فالانحرافُ ههنا **مقيسٌ ومُودَعٌ**: يُحسَب التبويبُ بالوجهين ويُعرَض فرقُهما.
#
