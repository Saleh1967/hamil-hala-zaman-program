def main(argv=None):
    ap = argparse.ArgumentParser(description="بابُ المصادر — التبويبُ مولَّدًا")
    ap.add_argument("--json", default=os.path.join(ROOT, "masadir_v0.json"))
    ap.add_argument("--md", default=os.path.join(ROOT, "MASADIR.md"))
    try:
        args = ap.parse_args(argv)
    except SystemExit:
        return E_USAGE
    try:
        return run(args.json, args.md)
    except MasadirError as exc:
        print(f"::error::{exc.message}")
        return exc.code


if __name__ == "__main__":
    sys.exit(main())
