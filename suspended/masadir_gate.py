    for name, cl in D["دعاوى_مسجَّلةٌ_قبل_التشغيل"].items():
        a(f"### {name}\n")
        a(f"- **البيان**: {cl['البيان']}")
        a(f"- **المتوقَّع**: {cl['المتوقَّع']}")
        a(f"- **الحكم**: {R[name]['حكم']}")
