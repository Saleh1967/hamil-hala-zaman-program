    a("| --- | :---: |")
    for t in D["محاولاتُ_التكذيب"]:
        a(f"| {t['محاولة']} | {'✓' if t['رُدَّ'] else '✗'} |")
    a(f"\nجملةً **{m['محاولاتُ_تكذيب']}** محاولات، رُدَّت كلُّها — وحارسٌ لا يَعُدُّ "
      "غيرَ الصفر في وضعٍ مكذِّبٍ حارسٌ بلا مادّة.\n")
    a("## ⑦ ما ليس في التبويب بعد\n")
    a(f"**{m['ديونٌ_مسمّاةٌ_بلا_رقم']}** خانةً دَينًا، مسمّاةٌ بأسبابها في")
    a("`masadir_v0.json`. وأثقلُها أربعة:\n")
    a(f"- **لا طبقةَ ١ في الشجرة إطلاقًا** — {m['طبقةُ_المنقَّح']} مستخرَجًا منقَّحًا "
      "مختومًا، فكلُّ مختومٍ حاويةٌ خام، **وقانونُ المقامات يحكم الجميع: تقييدٌ بلا "
      "استدعاء**.")
    a(f"- **{m['مصادرُ_بلا_مدّعٍ']} مصدرًا لا يدّعيه أحد** — مختومةُ البايتات، ولا "
      "قائمةَ في الشفرة تتّخذها شاهدًا. فلا دورَ لها في قياسٍ قائم.")
    a("- **جنسُ النصِّ لكلِّ مصدر** — ليس مشتقًّا من بايتاته ولا من حقول البيان، "
      "فلا يُكتَب بالنظر ويُسمّى دَينًا حتى يُقاس أو يُختَم في وديعة.")
    a("- **ضمُّ المرايا مشتقٌّ من حقل الملحوظة** — وهو حقلٌ يكتبه المالكُ بلسانه لا "
      f"بايتاتٌ تُقاس. فالكتبُ **{m['كتبٌ_بالوجه_الأفرق']}** صادقةٌ بكاتبها ههنا، "
      "لا بمصادمةٍ — وهو دَينٌ مسمًّى في كلِّ صفّ.\n")
