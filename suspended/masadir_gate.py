# ═══ ④ أدواتُ الخانة — مُحَلَّةٌ بسندٍ أو دَينٌ بلا رقم ══════════════════════════════
def cell(name, value=None, where=None, debt=None):
    """خانةٌ لا تخرج عن حالَين: مُحَلَّةٌ لها (سندٌ · موضعٌ · قيمةٌ)، أو دَينٌ بسببٍ."""
    if debt is not None:
        return {"خانة": name, "حال": "دَين", "سبب": debt}
    return {"خانة": name, "حال": "مُحَلَّة", "سند": where, "قيمة": value}


def audit_cell(c):
    """صدقُ الخانة: الدَّينُ له سببٌ **ولا قيمةَ له**، والمُحَلَّةُ لها سندٌ وقيمة."""
    if c["حال"] == "دَين":
        return "قيمة" not in c and bool(c.get("سبب"))
    return "قيمة" in c and bool(c.get("سند"))


# ═══ ⑤ قراءةُ البيان — حقولُه عشرةٌ، والسطرُ ناقصُ الحقول صريخ ═══════════════════════
def manifest_rows(path):
    if not os.path.isfile(path):
        raise MasadirError(E_MISSING, f"البيان غائبٌ: {path}")
    rows = []
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != len(FIELDS):
                raise MasadirError(
                    E_SEAL, f"سطر {n} في البيان بـ{len(parts)} حقلًا لا {len(FIELDS)}")
            rows.append(dict(zip(FIELDS, parts)))
    if not rows:
        raise MasadirError(E_MISSING, "البيانُ بلا صفوف — لا تبويبَ على فراغ")
    return rows


def contract_counts(path):
    """عدَّتا سطر العقد تُنتزَعان من بايتات الوثيقة — لا تُكتَبان ههنا."""
    if not os.path.isfile(path):
        raise MasadirError(E_MISSING, f"وثيقةُ العقد غائبةٌ: {path}")
    out = {}
    for line in open(path, encoding="utf-8"):
        if not line.startswith("|"):
            continue
        col = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(col) >= 2 and col[0] in ("شهودٌ مختومون", "معذورون بالاسم"):
            if not col[1].isdigit():
                raise MasadirError(E_SEAL, f"خانةُ «{col[0]}» في سطر العقد ليست عددًا")
            out[col[0]] = int(col[1])
    missing = {"شهودٌ مختومون", "معذورون بالاسم"} - set(out)
    if missing:
        raise MasadirError(E_SEAL, f"سطرُ العقد بلا بندِ {' · '.join(sorted(missing))}")
    return out


# ═══ ⑥ اشتقاقُ المحاور ═════════════════════════════════════════════════════════════
def sealed(row):
    """طبقةُ الحاوية: الحقولُ الثلاثةُ حاضرةً كلُّها — وناقصُها ليس مختومًا بحال."""
    return all(row[k] != NIL and row[k] for k in ("blob", "bytes", "sha256"))


def book_by_id(ident):
    """الوجهُ الأخصُّ (الغالط): قطعُ لاحقةِ المرآة من المعرِّف — الحقلُ الأخيرُ بعد _.

    ولا يُكتَب جدولُ كتبٍ ههنا: لو كُتب لشاخ. وهذا الوجهُ **يُشغَّل ليُقاس عطلُه**
    لا ليُعتمَد: يضمُّ ما لا يُضَمّ، وفرقُه عن الوجه الأفرق مُودَعٌ بأسماء مواضعه.
    """
    return ident.rsplit("_", 1)[0]


# فواصلُ الملحوظة المعلنة: ما بعدَها وصفُ المرآة، وما قبلَها اسمُ الكتاب.
NOTE_CUTS = ("شاهدُ", "نسخةُ", "مرآةُ", "مودَعٌ", "فُتِّشت")


def book_by_note(note):
    """الوجهُ الأفرق: صدرُ حقل الملحوظة إلى أوّل فاصلٍ معلن — أو None إن لم يقع.

    وهو الذي يفرّق «متن قطر الندى» من «شرحه» و«ج١» من «ج٣». وغيابُ الفاصل
    **لا يُسَدُّ بحدسٍ**: يرجع None فتصير الخانةُ دَينًا باسمه.
    """
    parts = note.split("_")
    for n, p in enumerate(parts):
        if p in NOTE_CUTS:
            return "_".join(parts[:n]) or None
    return None


def coarsens(fine, coarse):
    """هل الوجهُ الأخصُّ **تخشينٌ** للأفرق؟ أي: كلُّ طائفةٍ أفرقَ داخلَ طائفةٍ أخشن.

    وهذا حارسٌ يبقى ذا مادّةٍ ولو أُصلحت المعرِّفاتُ غدًا: لو انشقّت طائفةٌ أفرقُ
    بين خشنَين لكان الوجهان **متقاطعَين لا مترتّبَين**، فلا يُؤخَذ أحدُهما أصلًا.
    """
    seen = {}
    for ident, f in fine.items():
        seen.setdefault(f, set()).add(coarse[ident])
    return all(len(v) == 1 for v in seen.values())


def by_comb(idents, pool):
    """التبويبُ بالمشط: يدّعي العضويّةَ لكلِّ معرِّفٍ **يقع جزءًا** في نصِّ القائمة.

    وهذه هي الطريقةُ الغالطةُ بعينها، تُشغَّل ههنا **لتُقاس لا لتُستعمَل**: تُعرَض
    زيادتُها على المطابقة التامّة في البند ④، فيُرى العطلُ بعدده لا بوصفه.
    """
    blob = " ".join(pool)
    return sorted(i for i in idents if i in blob)


def entries(rows, roster):
    """مدخلٌ لكلِّ صفٍّ في البيان — وكلُّ خانةٍ مشتقّةٌ أو دَينٌ مسمًّى."""
    claim_of = {}
    for role, where, ids in roster:
        for i in ids:
            claim_of.setdefault(i, []).append((role, where))

    fine = {r["id"]: book_by_note(r["note"]) for r in rows}
    mirrors = {}
    for r in rows:
        if sealed(r) and fine[r["id"]]:
            mirrors.setdefault(fine[r["id"]], []).append(r["id"])

    out = []
    for r in rows:
        ident, cells = r["id"], []

        # ① المُدَّعي — مقروءٌ من قائمةٍ مستورَدةٍ، أو دَينٌ بلا دور.
        if ident in claim_of:
            roles = claim_of[ident]
            cells.append(cell("الدور", [x[0] for x in roles],
                              " · ".join(x[1] for x in roles)))
        else:
            cells.append(cell("الدور", debt=DEBT_NO_CLAIMANT))

        # ② طبقةُ الختم — مشتقّةٌ من حقول البيان، والمنقَّحُ دَينٌ للجميع بلا استثناء.
        if sealed(r):
            cells.append(cell("طبقةُ الحاوية", 0,
                              f"{MANIFEST} → {ident} → blob·bytes·sha256"))
        else:
            cells.append(cell("طبقةُ الحاوية", debt=DEBT_NO_SEAL))
        cells.append(cell("طبقةُ المنقَّح", debt=DEBT_NO_LAYER1))

        # ③ رتبةُ الثبوت — بالوجه الأفرق وحدَه، وعددُ شهودٍ لا عددُ اتّفاق.
        book = fine[ident]
        if book is None:
            cells.append(cell("كتابُ الصفّ", debt=DEBT_NO_BOOK_CUT))
            cells.append(cell("مرايا مختومة", debt=DEBT_NO_BOOK_CUT))
        else:
            cells.append(cell("كتابُ الصفّ", book, f"{MANIFEST} → {ident} → note"))
            kin = mirrors.get(book, [])
            if kin:
                cells.append(cell("مرايا مختومة", len(kin), f"{MANIFEST} → {book}"))
            else:
                cells.append(cell("مرايا مختومة", debt=DEBT_NO_SEAL))
        cells.append(cell("ضمُّ المرايا", debt=DEBT_NOTE_IS_PROSE))

        # ④ حالُ البيان — منقولٌ بحرفه من حقله، وهو الحقلُ الذي يعدُّه سطرُ العقد.
        cells.append(cell("حالُ البيان", r["state"], f"{MANIFEST} → {ident} → state"))

        # ⑤ الجنسُ — دَينٌ للجميع: ليس مشتقًّا من بايتةٍ ولا من حقل.
        cells.append(cell("جنسُ النصّ", debt=DEBT_NO_GENUS))

        out.append({"مصدر": ident, "كتاب": book,
                    "كتابٌ بالمعرِّف": book_by_id(ident),
                    "طريق": r["repo"], "خانات": cells})
    return out


# ═══ ⑦ محاولاتُ التكذيب — تُشغَّل في كلِّ مرّة، وحارسٌ لا يعدُّ غيرَ الصفر بلا مادّة ═══
def falsify(rows, roster, ents):
    trials = []
    idents = {r["id"] for r in rows}

    # ① مصدرٌ مصنوعٌ خارجَ البيان: لا مدخلَ له — فالتبويبُ لا يخترع صفًّا.
    trials.append(dict(محاولة="مصدرٌ مصنوعٌ خارجَ البيان", معرِّف="qwerty_zzz",
                       رُدَّ="qwerty_zzz" not in {e["مصدر"] for e in ents}))

    # ② دَينٌ يحمل رقمًا: تُصنَع خانةُ دَينٍ ومعها قيمةٌ، ويجب أن يصرخ المصادق.
    trials.append(dict(محاولة="دَينٌ يحمل رقمًا",
                       رُدَّ=not audit_cell(dict(خانة="مصنوعة", حال="دَين",
                                                سبب="مصنوع", قيمة=1))))

    # ③ خانةٌ بقيمةٍ بلا سند: القيمةُ بلا موضعٍ تُقرَأ منه مردودةٌ كذلك.
    trials.append(dict(محاولة="خانةٌ بقيمةٍ بلا سند",
                       رُدَّ=not audit_cell(dict(خانة="مصنوعة", حال="مُحَلَّة", قيمة=7))))

    # ④ ختمٌ ثلاثيٌّ ناقص: صفٌّ بحقلَين من ثلاثةٍ ليس مختومًا — ولا يُتساهَل فيه.
    lame = dict(id="x", blob="a" * 40, bytes="10", sha256=NIL)
    trials.append(dict(محاولة="ختمٌ ثلاثيٌّ ناقصٌ يُعَدُّ مختومًا", رُدَّ=not sealed(lame)))

    # ⑤ **المشطُ يزيد على المطابقة**: يُشغَّل الطريقان على قائمةٍ واحدةٍ فيُعرَض فرقُهما.
    #    وهذا هو موضعُ المادّة: لو تساويا لَمَا كان في البند ④ خبرٌ البتّة.
    pool = [x for _, _, ids in roster for x in ids]
    comb = set(by_comb(idents, pool)) - set(pool)
    trials.append(dict(محاولة="المشطُ يدّعي عضويّةَ البادئة", رُدَّ=bool(comb),
                       ما_ادّعاه_المشطُ_زورًا=sorted(comb)))

    # ⑥ مدّعٍ بمعرِّفٍ ليس في البيان: قائمةٌ تدّعي شاهدًا لا صفَّ له — يجب أن يُلتقَط.
    orphan = sorted({i for _, _, ids in roster for i in ids} - idents)
    trials.append(dict(محاولة="مدّعٍ بشاهدٍ لا صفَّ له في البيان", رُدَّ=not orphan,
                       أيتام=orphan))

    # ⑦ معذورٌ يحمل بصمةً: المعذورُ غيابٌ مسمًّى، فلو حمل ختمًا لانهدم معنى العذر.
    excused_sealed = [r["id"] for r in rows if r["state"] == "معذور" and sealed(r)]
    trials.append(dict(محاولة="معذورٌ يحمل ختمًا", رُدَّ=not excused_sealed,
                       مخالفون=excused_sealed))

    # ⑧ الوجهُ الأخصُّ تخشينٌ للأفرق: لو تقاطعا لَما صحَّ أخذُ أحدهما أصلًا.
    fine = {r["id"]: book_by_note(r["note"]) for r in rows if book_by_note(r["note"])}
    coarse = {i: book_by_id(i) for i in fine}
    trials.append(dict(محاولة="وجها الضمِّ متقاطعان لا مترتّبان",
                       رُدَّ=coarsens(fine, coarse)))

    # ⑨ صفٌّ بلا فاصلٍ معلنٍ **يصير دَينًا لا حدسًا**: يُتحقَّق من خانته بعينها.
    cut_less = {r["id"] for r in rows if book_by_note(r["note"]) is None}
    guessed = [e["مصدر"] for e in ents if e["مصدر"] in cut_less
               and any(c["خانة"] == "كتابُ الصفّ" and c["حال"] == "مُحَلَّة"
                       for c in e["خانات"])]
    trials.append(dict(محاولة="صفٌّ بلا فاصلٍ معلنٍ يُحزَر كتابُه", رُدَّ=not guessed,
                       صفوفٌ_بلا_فاصل=sorted(cut_less), محزورون=guessed))

    return trials


# ═══ ⑧ التشغيل ═════════════════════════════════════════════════════════════════════
def run(as_json=None, as_md=None):
    rows = manifest_rows(os.path.join(ROOT, MANIFEST))
    contract = contract_counts(os.path.join(ROOT, CONTRACT))
    roster = claimants()
    ents = entries(rows, roster)

    cells = [c for e in ents for c in e["خانات"]]
    done = [c for c in cells if c["حال"] == "مُحَلَّة"]
    debts = [c for c in cells if c["حال"] == "دَين"]
    unsound = [c for c in cells if not audit_cell(c)]
    trials = falsify(rows, roster, ents)

    fails, R = [], {}

    # ── ① الاستنفادُ والمصادمةُ بسطر العقد ────────────────────────────────────────
    idents = [r["id"] for r in rows]
    outside = [e["مصدر"] for e in ents if e["مصدر"] not in idents]
    unused = [i for i in idents if i not in {e["مصدر"] for e in ents}]
    n_sealed = sum(1 for r in rows if r["state"] == "مختوم")
    n_excused = sum(1 for r in rows if r["state"] == "معذور")
    matched = (n_sealed == contract["شهودٌ مختومون"]
               and n_excused == contract["معذورون بالاسم"])
    R["① البيانُ مستنفَدٌ ومصادَمٌ بسطر العقد"] = {
        "صفوفُ البيان": len(rows), "مداخلُ التبويب": len(ents),
        "مدخلٌ خارجَ البيان": outside, "صفٌّ بلا مدخل": unused,
        "مختومٌ في البيان": n_sealed, "مختومٌ في سطر العقد": contract["شهودٌ مختومون"],
        "معذورٌ في البيان": n_excused, "معذورٌ في سطر العقد": contract["معذورون بالاسم"],
        "حكم": "تحقَّق" if matched and not outside and not unused else "سقط",
    }
    if R["① البيانُ مستنفَدٌ ومصادَمٌ بسطر العقد"]["حكم"] == "سقط":
        fails.append("① التبويبُ لم يستنفد البيانَ أو خالف سطرَ العقد")

    # ── ② الدورُ مقروءٌ من مدّعيه ──────────────────────────────────────────────────
    orphan = sorted({i for _, _, ids in roster for i in ids} - set(idents))
    with_role = [e for e in ents
                 if e["خانات"][0]["حال"] == "مُحَلَّة"]
    R["② الدورُ مقروءٌ من مدّعيه لا مكتوبًا"] = {
        "قوائمُ مستورَدة": len(roster),
        "مصادرُ يدّعيها مدّعٍ": len(with_role),
        "مصادرُ بلا مدّعٍ": len(ents) - len(with_role),
        "شاهدٌ في قائمةٍ بلا صفٍّ في البيان": orphan,
        "حكم": "تحقَّق" if not orphan and with_role else "سقط",
    }
    if orphan or not with_role:
        fails.append(f"② قائمةٌ تدّعي شاهدًا لا صفَّ له: {orphan}")

    # ── ③ لا طبقةَ ١ مختومةٌ — صفرٌ مقيسٌ بمسحِ الحقول ─────────────────────────────
    layer0 = sum(1 for e in ents if e["خانات"][1]["حال"] == "مُحَلَّة")
    layer1 = sum(1 for e in ents if e["خانات"][2]["حال"] == "مُحَلَّة")
    R["③ لا طبقةَ ١ مختومةٌ في الشجرة"] = {
        "طبقةُ الحاوية": layer0, "مختومٌ في البيان": n_sealed,
        "طبقةُ المنقَّح": layer1,
        "أثرُه": "كلُّ مختومٍ مقيَّدٌ بلا استدعاء حتى تُختَم طبقتُه الأولى",
        "حكم": "تحقَّق" if layer0 == n_sealed and layer1 == 0 else "سقط",
    }
    if layer0 != n_sealed or layer1:
        fails.append("③ طبقةُ الحاوية لم تستغرق المختومَ أو ادُّعيت طبقةٌ أولى")

    # ── ④ العضويةُ مطابقةٌ لا مشط — الفرقُ مقيسٌ ومسمًّى ───────────────────────────
    pool = [x for _, _, ids in roster for x in ids]
    combed = by_comb(set(idents), pool)
    liars = sorted(set(combed) - set(pool))
    R["④ العضويةُ مطابقةٌ لا مشط"] = {
        "بالمطابقة التامّة": len(set(pool)),
        "بالمشط": len(combed),
        "ما ادّعاه المشطُ زورًا": liars,
        "حكم": "تحقَّق" if liars else "سقط",
    }
    if not liars:
        fails.append("④ المشطُ لم يزد على المطابقة — فالحارسُ بلا مادّة")

    # ── ⑤ وجها الضمِّ — متخالفان ومترتّبان، والأخصُّ يُعرَض ضمُّه زورًا ─────────────
    fine_map = {r["id"]: book_by_note(r["note"]) for r in rows}
    no_cut = sorted(i for i, b in fine_map.items() if b is None)
    fine_ok = {i: b for i, b in fine_map.items() if b}
    coarse_map = {i: book_by_id(i) for i in fine_ok}
    n_fine, n_coarse = len(set(fine_ok.values())), len(set(coarse_map.values()))
    merged = sorted({c for c in set(coarse_map.values())
                     if len({fine_ok[i] for i in fine_ok if coarse_map[i] == c}) > 1})
    ordered = coarsens(fine_ok, coarse_map)
    R["⑤ ضمُّ المرايا بوجهَين مترتّبَين لا بوجهٍ واحد"] = {
        "كتبٌ بالوجه الأفرق": n_fine, "كتبٌ بالوجه الأخصّ": n_coarse,
        "ما ضمَّه الأخصُّ زورًا": merged,
        "صفوفٌ بلا فاصلٍ معلن": no_cut,
        "المأخوذ": "الأفرقُ — والأخصُّ مقيسٌ معروضٌ لا مُعتمَد",
        "حكم": "تحقَّق" if ordered and n_fine > n_coarse and merged else "سقط",
    }
    if not ordered:
        fails.append("⑤ وجها الضمِّ متقاطعان — فلا أصلَ في أحدهما")
    elif not merged or n_fine <= n_coarse:
        fails.append("⑤ الوجهان لم يتخالفا — فالبندُ بلا مادّة")

    # ── ⑥ لا خانةَ بلا سند ────────────────────────────────────────────────────────
    R["⑥ لا خانةَ بلا سند"] = {
        "خانات": len(cells), "مُحَلَّة": len(done), "دَين": len(debts),
        "خاناتٌ بلا سند": len(unsound),
        "حكم": "تحقَّق" if not unsound else "سقط",
    }
    if unsound:
        fails.append(f"⑥ {len(unsound)} خانةً بلا سندٍ — قيمةٌ بلا موضعٍ أو دَينٌ برقم")

    for t in trials:
        if not t["رُدَّ"]:
            fails.append(f"محاولةُ تكذيبٍ لم تُردّ: {t['محاولة']}")

    broken = [k for k, v in R.items() if v["حكم"] == "سقط"]
    suspended = {
        "المواصفة": SUSPENDED,
        "الحال": "معلَّق — لا بندَ متوقَّعٍ سابقًا للتشغيل، فلا يُحتَجُّ برقمه",
        "مصادرُ يدّعيها مدّعٍ": len(with_role), "مصادر": len(ents),
        "نصيب": round(len(with_role) / len(ents), 4),
    }

    out = {"المصادر_v0": {
        "الحدّ": "التبويبُ مولَّدٌ من البيان وقوائمِ الشفرة — لا يُكتَب صفٌّ بيد",
        "المصدر": f"{MANIFEST} — مصدرُ حقيقةٍ واحدٌ بعشرة حقول",
        "دعاوى_مسجَّلةٌ_قبل_التشغيل": CLAIMS,
        "مدَّعون": [{"دور": r, "موضع": w, "شهود": len(i)} for r, w, i in roster],
        "بنود": R,
        "معلَّق": suspended,
        "مصادر": ents,
        "محاولاتُ_التكذيب": trials,
        "مقيس": {
            "مصادر": len(ents),
            "مختوم": n_sealed,
            "معذور": n_excused,
            "خانات": len(cells),
            "خاناتٌ_مُحَلَّة": len(done),
            "ديونٌ_مسمّاةٌ_بلا_رقم": len(debts),
            "خاناتٌ_بلا_سند": len(unsound),
            "قوائمُ_مستورَدة": len(roster),
            "مصادرُ_يدّعيها_مدّعٍ": len(with_role),
            "مصادرُ_بلا_مدّعٍ": len(ents) - len(with_role),
            "طبقةُ_الحاوية": layer0,
            "طبقةُ_المنقَّح": layer1,
            "ما_ادّعاه_المشطُ_زورًا": len(liars),
            "كتبٌ_بالوجه_الأفرق": n_fine,
            "كتبٌ_بالوجه_الأخصّ": n_coarse,
            "ما_ضمَّه_الأخصُّ_زورًا": len(merged),
            "صفوفٌ_بلا_فاصلٍ_معلن": len(no_cut),
            "بنودٌ_محكومة": len(R),
            "بنودٌ_ساقطة": len(broken),
            "أسماءُ_الساقطة": broken,
            "محاولاتُ_تكذيب": len(trials),
        },
        "حكم": "خضراء" if not fails else "ساقطة",
        "مآخذ": fails,
    }}

    print("— بابُ المصادر: التبويبُ مولَّدًا —")
    for name, r in R.items():
        print(f"    {name}: {r['حكم']}")
        for k, v in r.items():
            if k == "حكم" or v in (None, [], {}):
                continue
            print(f"        {k}: {v:,}" if isinstance(v, int) else f"        {k}: {v}")
    print(f"    ⑦ [معلَّق] {SUSPENDED}: {suspended['نصيب']} "
          f"({suspended['مصادرُ يدّعيها مدّعٍ']} من {suspended['مصادر']}) — "
          f"يُعرَض ولا يُحتَجُّ به")
    print(f"    محاولاتُ تكذيبٍ رُدَّت: {sum(1 for t in trials if t['رُدَّ'])}/{len(trials)}")
    for f in fails:
        print(f"::error::{f}")
    print(f"    {'✓' if not fails else '✗'} مصادرُ {len(ents)} · "
          f"مُحَلَّةٌ {len(done):,} · ديونٌ مسمّاةٌ {len(debts):,}")

    if as_json:
        with open(as_json, "w", encoding="utf-8") as fh:
            json.dump(out, fh, ensure_ascii=False, indent=1)
    if as_md:
        with open(as_md, "w", encoding="utf-8") as fh:
            fh.write(write_doc(out))
    return 0 if not fails else 1


