# mihwar_gate.py — بابُ المحاور: ديوانُ الدالِّ وحدَه، وشرطُ إمكان المدلول.
#
# ══ الحدُّ المعلن قبل كلِّ شيء ═══════════════════════════════════════════════════════
# هذا البابُ **لا يقيس قاعدةً جديدة**. وظيفتُه أن يفصل محاورَ القياس في هذا المستودع
# فصلًا **منفَّذًا بحارسٍ لا موصًى به بكلام**، وأن يُثبت دعوى انغلاقٍ واحدة:
#
#   **كلُّ بتٍّ سُعِّر في هذا المستودع حتى اليوم إنّما سُعِّر على الصورة وحدَها.**
#
# وهذه دعوى **انغلاقٍ لا دعوى رقم**، فبرهانُها جمعٌ ومصادمةٌ لا قياسٌ جديد. ولذلك:
#   ① **لا رقمَ يُكتَب في هذا الملفّ البتّة.** كلُّ بندٍ في الديوان يُسمّي **ختمًا
#      قائمًا** في `induction/seals.py` باسمه، فتُقرأ قيمتُه من وديعته بمساره
#      المختوم وتُصادَم. فمن أراد أن يُدخل رقمًا من عنده لم يجد له بابًا.
#   ② **والدَّينُ لا رقمَ له**: ما لم يُختَم لا يُكتَب عددُه ههنا ولو كان معلومًا —
#      بل يُسمّى باسمه وموضعِه ويُوسَم دَينًا. فلو حُمِّل دَينٌ رقمًا سقط البابُ.
#      وهذا أشدُّ ما في الباب: **الدَّينُ يُعلَن ولا يُسعَّر**.
#
# ══ المحاورُ الثلاثةُ وترتيبُها ══════════════════════════════════════════════════════
# القسمةُ في «أبحاث اللغة» ثلاثُ حيثياتٍ على مقسَمٍ واحد (`aqsam_gate.QISMAT`)،
# وههنا تُقرأ **محاورَ قياسٍ مرتَّبةً** لا قسماتٍ فحسب:
#
#   ⓵ **الدالُّ وحدَه** — مكيالُه الصورةُ وحدَها، بلا قراءةِ مدلولٍ البتّة.
#        شرطُ إمكانه: **لا شرط** — فالصورةُ بايتاتٌ حاضرة. وهو **مفتوحٌ ومسدَّد**.
#   ⓶ **المدلولُ وحدَه** — مكيالُه يحتاج **وضعًا**، والوضعُ لا يُعرَف بالصورة.
#        شرطُ إمكانه: **مرجعٌ مختومٌ حاضرٌ بالبصمة، وثمنُ جدوله مقيسٌ معلن**.
#   ⓷ **الدالُّ والمدلولُ معًا** — شرطُ إمكانه: **أن يقوم الأوّلان**؛ فلا يُقاس
#        اجتماعُ شيئين قبل أن يقوم كلٌّ منهما وحدَه.
#
# **ولمَ الترتيبُ لازمٌ لا استحسانيٌّ؟** لأنّ المستودعَ قاسه بنفسه ولم نقرِّره: حين
# حاول أن يقسّم الاسمَ والفعلَ والحرفَ **بالصورة وحدَها** لم يدفع القسمُ فاتورتَه،
# وسُجِّل حينها بالنصّ: «الذاكرةُ تسكن العلامةَ لا الصنف»، و«الدَّينُ: المعجم»
# (`peeling_proof.md` §٢٠). فحدُّ المحور الأوّل **مقيسٌ لا مرسوم**، وما بعده لا
# يُبنى إلا بمدلول. وهذا البابُ يُنفِّذ ذلك الحدَّ حارسًا.
#
# ══ الخطرُ الذي يحرسه هذا الباب ═══════════════════════════════════════════════════
# **الجدولُ المجّانيّ.** فتحُ المحور الثاني يُدخل مرجعًا بملايين البايتات. فلو
# استُعمل بلا ثمنٍ لصار كلُّ ربحٍ بعده **مسروقًا من جدولٍ لم يُدفَع**. والسنّةُ قائمةٌ
# في هذا المستودع: ماركوفُ العبور **رُدَّ وإن ربح** لأنّه لم يستأجر جدولَه. فههنا
# يُقاس ثمنُ المرجع **قبل أن يُستعمَل**، ويُودَع رقمًا يُصادَم — فمن أراد أن يربح به
# غدًا وجد ثمنَه مكتوبًا عليه سلفًا لا يستطيع إنكارَه.
#
