# ═══ ② الديوان: القيمةُ تُقرأ من ختمها وتُصادَم بوديعتها ═══════════════════════════════
def seal_by_name(name):
    """الختمُ باسمه من `SEALS` — ولا يُقبَل اسمان لختمٍ واحدٍ ولا اسمٌ بلا ختم."""
    hits = [s for s in SEALS if s["اسم"] == name]
    if len(hits) != 1:
        raise MihwarError(E_SEAL,
                          f"بندُ ديوانٍ لا ختمَ له أو له أختامٌ متعدّدة: «{name}» ({len(hits)})")
    return hits[0]


def deposit_value(seal):
    """قيمةُ الختم **من وديعتها لا من نصِّ السجلّ** — فالمصادمةُ ههنا لا نقل."""
    path = os.path.join(DEPOSIT_DIR.get(seal["وديعة"], os.path.join(ROOT, "induction")),
                        seal["وديعة"])
    if not os.path.exists(path):
        raise MihwarError(E_MISSING, f"وديعةٌ غائبةٌ: {path}")
    node = json.load(open(path, encoding="utf-8"))
    for key in seal["مسار"]:
        # المسارُ يمرُّ بالخرائط وبالقوائم معًا — وكلاهما يقع في ودائع هذا المستودع،
        # فلا يُقصَر الحلُّ على المفاتيح وإلا صُرِخ على ختمٍ صحيحٍ بحجّة أنّه لم يُحَلّ.
        if isinstance(node, dict) and key in node:
            node = node[key]
        elif isinstance(node, list) and isinstance(key, int) and -len(node) <= key < len(node):
            node = node[key]
        else:
            raise MihwarError(E_SEAL,
                              f"مسارُ الختم «{seal['اسم']}» لا يُحَلُّ في وديعته عند: {key}")
    return node


def ledger_row(entry):
    """صفُّ ديوانٍ كامل: الختمُ يُسمّى، وقيمتُه تُقرأ من الوديعة وتُصادَم بالمسجَّل."""
    seal = seal_by_name(entry["ختم"])
    got = deposit_value(seal)
    if got != seal["قيمة"]:
        raise MihwarError(E_SEAL,
                          f"بندُ «{entry['ختم']}»: الوديعةُ {got} خالفت ختمَها {seal['قيمة']}")
    return dict(entry, وديعة=seal["وديعة"], مسار=list(seal["مسار"]),
                قيمة=got, دالّة=seal["دالّة"], مقام=seal["مقام"], صنف=seal["صنف"])


def diwan():
    """ديوانُ المسعَّر موسومًا بمحاوره — وانغلاقُه: مختومٌ أو دَينٌ بلا رقم، ولا ثالث."""
    rows = [ledger_row(e) for e in LEDGER]
    names = [r["ختم"] for r in rows]
    if len(set(names)) != len(names):
        raise MihwarError(E_SEAL, "بندٌ مكرَّرٌ في الديوان — رقمٌ يُحسَب مرّتين")
    debts = [dict(d) for d in DEBTS]
    return dict(
        بيان=("ديوانُ ما سُعِّر: كلُّ بندٍ يُسمّي ختمًا قائمًا فتُقرأ قيمتُه من وديعته "
              "وتُصادَم — ولا رقمَ مكتوبٌ في هذا الباب. والدَّينُ يُسمّى ولا يُسعَّر"),
        بنود=rows, ديون=debts,
        بالمحور=dict(Counter(r["محور"] for r in rows).most_common()),
        ديونٌ_بالمحور=dict(Counter(d["محور"] for d in debts).most_common()))


# ═══ ③ شرطُ الإمكان: المرجعُ بالبصمة، وثمنُ جدوله مقيسٌ قبل أن يُستعمَل ═══════════════
def field_alphabet(values):
    """أبجديةُ حقلٍ **معدودةٌ من بايتاته** لا مفترَضة — فلا يُسعَّر نصٌّ بأبجديةٍ أضيقَ منه."""
    return len({c for v in values for c in v})


def reference_price(table=ML.TABLE):
    """**ثمنُ المرجع بالبتّات**: كم يكلّف إملاءُ خريطةِ (جذرٍ ⟵ محورِه الدلاليِّ)؟

    وتُسعَّر بسنّة `ta3allum_gate.declaration_cost` بعينها — إملاءٌ حرفًا حرفًا
    بأبجديةٍ **معدودةٍ من الحقل نفسِه**، وترميزُ عدَّة المداخل. ولا يُخصَم منها شيء:
    فمرجعٌ بمحاورَ مسهَبةٍ يدفع أكثرَ ممّا يدفع مرجعٌ بمحاورَ موجزة.

    **ولماذا يُقاس ههنا قبل أن يُستعمَل؟** لأنّ هذا الرقمَ هو ما يجب أن يهزمه أيُّ
    ربحٍ يُدَّعى للمدلول غدًا. فلو قيس بعد الربح لأمكن أن يُقتطَع منه ما يُناسب.
    """
    if not os.path.isfile(table):
        # **ولا يُقدَّر ثمنٌ لغائب**: لو رُدَّ ههنا رقمٌ تقديريٌّ لصار المحورُ الثاني
        # يُفتَح على جدولٍ لم يُقرَأ. فيُصرَخ بالمخرج ٣ ويُجلَب أوّلًا.
        raise MihwarError(E_MISSING,
                          "جدولُ المقاييس غائبٌ عن القرص — ولا يُقدَّر ثمنٌ لغائب. "
                          "يُجلَب بـ./fetch_maqayis.sh ثمّ يُعاد التشغيل")
    rows = ML.read_table(table)          # البوّابةُ: الطولُ ثمّ البصمة قبل أيِّ قراءة
    entries = {}
    for r in rows:
        entries.setdefault(r["root_full"], r)
    roots, widest = ML.awzan_roots()
    mapped = {r: (entries[r].get("semantic_axes") or "").strip()
              for r in roots if r in entries and (entries[r].get("semantic_axes") or "").strip()}
    if not mapped:
        raise MihwarError(E_SEAL, "لا جذرَ من مقامنا له محورٌ في المرجع — لا خريطةَ تُسعَّر")
    a_root = field_alphabet(mapped)
    a_axis = field_alphabet(mapped.values())
    bits = (sum((len(k) + 1) * log2(a_root) for k in mapped)
            + sum((len(v) + 1) * log2(a_axis) for v in mapped.values())
            + log2(len(mapped) + 1))
    return dict(
        حاضر=True, بصمة=ML.SEAL, طول=ML.SEAL_BYTES, مصدر=ML.SOURCE,
        سجلّات=len(rows), جذورٌ_متمايزة=len(entries),
        حلقةُ_الأوزان=widest, جذورُ_مقامنا=len(roots), مخرَّطة=len(mapped),
        أبجديةُ_الجذر=a_root, أبجديةُ_المحور=a_axis,
        ثمنُ_الخريطة_بتًّا=round(bits, 1),
        بيان=("ثمنُ إملاءِ خريطةِ الجذرِ ومحورِه بسنّة declaration_cost — يُقاس قبل "
              "أن يُستعمَل، فكلُّ ربحٍ يُدَّعى للمدلول غدًا يجب أن يهزم هذا الرقمَ أوّلًا"))


def reference_rows():
    """المراجعُ بأحوالها — والحاضرُ يُصادَم ببايتاته، ولا يمرُّ اسمٌ بلا بصمةٍ ولا عذر."""
    rows = []
    for r in REFERENCES:
        sealed = r["حال"] == "مختومٌ حاضرٌ بالبصمة"
        present = sealed and os.path.isfile(ML.TABLE)
        rows.append(dict(r, مختوم=sealed, حاضر=present))
    if not any(r["مختوم"] for r in rows):
        raise MihwarError(E_SEAL, "لا مرجعَ مختومٌ في الإعلان — وشرطُ الوضع مرجع")
    return rows


def axis_rows(price, refs):
    """أيُّ المحاور مفتوح؟ **بشرطِ إمكانه لا بإرادتنا**، ومرتَّبًا لا يُقفَز.

    والترتيبُ منفَّذٌ: محورٌ لا يُفتَح وقبلَه محورٌ مغلق، وإن تحقّق شرطُه بذاته.
    وفتحُ محورٍ **ليس حكمًا بصدق قسمته** — بل إذنٌ بأن يُقاس، لا غير.
    """
    sealed_present = [r for r in refs if r["مختوم"] and r["حاضر"]]
    priced = bool(price.get("حاضر")) and price.get("ثمنُ_الخريطة_بتًّا", 0) > 0
    rows, blocked = [], False
    for ax in AXES:
        if ax["رتبة"] == 1:
            met, why = True, "الصورةُ بايتاتٌ حاضرة — ولا شرطَ على المكيال الأوّل"
        elif ax["رتبة"] == 2:
            met = bool(sealed_present) and priced
            why = ("مرجعٌ مختومٌ حاضرٌ وثمنُ خريطته مقيسٌ معلن" if met else
                   "لا مرجعَ حاضرٌ بالبصمة أو لم يُقَس ثمنُ خريطته — فلا وضعَ يُقرَأ")
        else:
            met, why = False, ("شرطُه أن يقوم المحوران قبله: و**صدقُ المدلولِ وحدَه "
                               "لم يُقَس بعد** — فالاجتماعُ لا يُقاس قبل أفرادِه")
        opened = met and not blocked
        if not opened:
            blocked = True
        rows.append(dict(ax, تحقّقَ_شرطُه=met, مفتوح=opened,
                         سبب=why if opened else
                         (why if not met else "محورٌ قبله مغلقٌ — ولا يُقفَز الترتيب")))
    return rows


# ═══ ④ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ ════════════════════════════════════════
def falsify(D, price, refs, axes):
    """عشرٌ تُشغَّل في كلِّ تشغيل. ونجاحُ واحدةٍ يُسقِط البابَ — لا يُخفَّف ولا يُؤجَّل."""
    T = []

    # ① **المحكُّ الأمّ**: بندٌ في الديوان بلا ختمٍ قائمٍ في `SEALS`. فلو مرَّ لَصار
    #    الديوانُ وعاءً لأرقامٍ تُكتَب بأيدينا، وهو نقيضُ الغرض منه.
    def unsealed():
        try:
            seal_by_name("بندٌ لا ختمَ له البتّة")
            return True
        except MihwarError:
            return False
    T.append(("بندُ ديوانٍ بلا ختمٍ قائمٍ مرَّ — ديوانٌ يقبل رقمًا بلا سند", unsealed()))

    # ② قيمةٌ خالفت وديعتَها: يُصنَع ختمٌ بمسارٍ لا يُحَلُّ فيجب أن يُصرَخ.
    def broken_path():
        try:
            deposit_value(dict(seal_by_name("الفاتورة · الأساس"),
                               مسار=("لا", "مسارَ", "لها")))
            return True
        except MihwarError:
            return False
    T.append(("مسارُ ختمٍ لا يُحَلُّ في وديعته ومرَّ — مصادمةٌ صوريّة", broken_path()))

    # ③ **الدَّينُ لا يُسعَّر**: دَينٌ حُمِّل رقمًا يعني أنّ ما لم يُختَم صار يُحتَجُّ به.
    T.append(("دَينٌ يحمل رقمًا — وما لم يُختَم لا يُسعَّر",
              any(any(isinstance(v, (int, float)) and not isinstance(v, bool)
                      for v in d.values()) for d in D["ديون"])))

    # ④ ولا يُطوى دَينٌ بالصمت: ديوانٌ بلا دَينٍ دعوى كمالٍ لا دعوى قياس.
    T.append(("الديونُ طُوِيت — وغيابُ القياس يُعلَن ولا يُحذَف", not D["ديون"]))

    # ⑤ **الانغلاق**: بندٌ في الديوان خارجَ المحاور المعلنة، أو في محورٍ غيرِ مفتوح.
    declared = {a["محور"] for a in AXES}
    open_axes = {a["محور"] for a in axes if a["مفتوح"]}
    T.append(("بندٌ مسعَّرٌ في محورٍ غيرِ معلنٍ أو غيرِ مفتوح — قفزُ محور",
              any(r["محور"] not in declared or r["محور"] not in open_axes
                  for r in D["بنود"])))

    # ⑥ الترتيبُ منفَّذٌ لا موصًى به: محورٌ مفتوحٌ وقبلَه مغلق.
    def order_broken():
        seen_shut = False
        for a in sorted(axes, key=lambda x: x["رتبة"]):
            if a["مفتوح"] and seen_shut:
                return True
            if not a["مفتوح"]:
                seen_shut = True
        return False
    T.append(("محورٌ فُتح وقبلَه محورٌ مغلق — ترتيبٌ قُفِز", order_broken()))

    # ⑦ المحورُ الثالثُ فُتح: وصدقُ الثاني لم يُقَس بعد. وهذا هو الحارسُ الذي يمنع
    #    أن نقيس «معًا» قبل أن يقوم كلُّ واحدٍ وحدَه.
    T.append(("المحورُ الثالثُ فُتح قبل أن يقوم الثاني — اجتماعٌ قبل أفرادِه",
              any(a["رتبة"] == 3 and a["مفتوح"] for a in axes)))

    # ⑧ **مرجعٌ مصنوعٌ** يمرُّ بالاسم وحدَه: فلو مرَّ لَجاز أن يُحتَجَّ بمعجمٍ لا وجود له.
    T.append(("مرجعٌ مصنوعٌ وقع في المراجع المعلنة — احتجاجٌ باسمٍ بلا بصمة",
              any(FABRICATED_REFERENCE in r["مرجع"] for r in refs)))

    # ⑨ **الجدولُ المجّانيّ** — أخطرُها: مرجعٌ حاضرٌ بلا ثمنٍ مقيسٍ موجب. فلو مرَّ
    #    لَأمكن أن يُربَح بالمدلول غدًا من جدولٍ لم يُدفَع ثمنُه.
    T.append(("مرجعٌ حاضرٌ ولا ثمنَ مقيسٌ لخريطته — ربحٌ مسروقٌ من جدولٍ مجّانيّ",
              bool(price.get("حاضر")) and not price.get("ثمنُ_الخريطة_بتًّا", 0) > 0))

    # ⑩ وأخيرًا: ديوانٌ خلا من بندٍ في المحور الأوّل. فالدعوى المرادُ برهانُها أنّ ما
    #    سُعِّر إنّما سُعِّر بالصورة وحدَها — وديوانٌ فارغٌ لا يبرهن شيئًا.
    T.append(("الديوانُ خلا من بندٍ في المحور الأوّل — دعوى انغلاقٍ بلا مضمون",
              not any(r["محور"] == FIRST_AXIS for r in D["بنود"])))

    return [dict(محاولة=n, نجحت=bool(v)) for n, v in T]


# ═══ ⑤ التشغيل ═════════════════════════════════════════════════════════════════════
def run():
    D = diwan()
    price = reference_price()
    refs = reference_rows()
    axes = axis_rows(price, refs)
    trials = falsify(D, price, refs, axes)
    measured = {
        "محاور": len(AXES),
        "بنودُ الديوان": len(D["بنود"]),
        "بنودٌ في الدالِّ وحدَه": sum(1 for r in D["بنود"] if r["محور"] == FIRST_AXIS),
        "ديونٌ مسمّاة": len(D["ديون"]),
        "ديونٌ بلا رقم": sum(
            1 for d in D["ديون"]
            if not any(isinstance(v, (int, float)) and not isinstance(v, bool)
                       for v in d.values())),
        "مراجعُ مُعلَنة": len(refs),
        "مراجعُ مختومةٌ حاضرة": sum(1 for r in refs if r["مختوم"] and r["حاضر"]),
        "محاورُ مفتوحة": sum(1 for a in axes if a["مفتوح"]),
        "محاورُ مغلقة": sum(1 for a in axes if not a["مفتوح"]),
        "محاولاتُ_تكذيب": len(trials),
    }
    for k, v in SEALED_MIHWAR.items():
        if measured.get(k) != v:
            raise MihwarError(E_SEAL,
                              f"حكمٌ مختومٌ خولف: {k} = {measured.get(k)} ≠ {v}")
    if any(t["نجحت"] for t in trials):
        raise MihwarError(E_SEAL, "محاولةُ تكذيبٍ نجحت — البابُ ساقط")
    return {"المحاور_v0": {
        "الحدُّ_المُعلَن": (
            "بابٌ **لا يقيس قاعدةً جديدة**: يفصل محاورَ القياس فصلًا منفَّذًا، ويُثبت "
            "دعوى انغلاقٍ واحدة — أنّ كلَّ بتٍّ سُعِّر في هذا المستودع إنّما سُعِّر على "
            "الصورة وحدَها. ولا رقمَ مكتوبٌ فيه البتّة: كلُّ بندٍ يُسمّي ختمًا قائمًا "
            "فتُقرأ قيمتُه من وديعته وتُصادَم. **والدَّينُ يُسمّى ولا يُسعَّر** ولو كان "
            "عددُه معلومًا. وفتحُ محورٍ **إذنٌ بأن يُقاس لا حكمٌ بصدق قسمته**. وثمنُ "
            "المرجع يُقاس **قبل أن يُستعمَل** لئلّا يُربَح غدًا من جدولٍ مجّانيّ."),
        "المحاور": axes, "الديوان": D, "المراجع": refs, "ثمنُ_المرجع": price,
        "محاولاتُ_التكذيب": trials, "مقيس": measured}}


