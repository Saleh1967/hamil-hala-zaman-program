def collide(measured):
    bad = [(k, SEALED_IHALA[k], measured[k]) for k in SEALED_IHALA
           if k not in measured or measured[k] != SEALED_IHALA[k]]
    extra = [k for k in measured if k not in SEALED_IHALA]
    if extra:
        raise IhalaError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    if bad:
        raise IhalaError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_IHALA)


