# ═══ ① الإحداثياتُ — كلُّها من البايتاتِ وحدَها ════════════════════════════════
def core_of(w):
    """جذعُ الكلمةِ بعد نزعِ العاطفِ الملتصق — بدالّةِ `jumla_links` بعينها."""
    return _body(w)[1] if JL.attached_atf(w) else w


def alama_of(w):
    """علامةُ الآخِر: الفرعيّةُ تسبق الأصليّة، والعُريُ غيابُ العلامةِ معدودًا."""
    s = sk(w)
    if s.endswith("ون") and len(s) > 2:
        return "فرعية-واو/نون"
    if s.endswith(("ين", "ان")) and len(s) > 2:
        return "فرعية-ياء/ألف+نون"
    return {"ضمة": "أصلية-رفع", "تنوين ضم": "أصلية-رفع",
            "فتحة": "أصلية-نصب", "تنوين فتح": "أصلية-نصب",
            "كسرة": "أصلية-جر", "تنوين كسر": "أصلية-جر",
            "سكون": "أصلية-جزم"}.get(END(w), "عري")


def damir_of(s):
    """صورةُ الضميرِ الغائبِ المتصل — أو None. والأطولُ يُجرَّب أوّلًا، ويُشترَط
    جذعٌ من حرفين فصاعدًا لئلّا تُقرأ الكلمةُ كلُّها ضميرًا."""
    for d in DAMAIR:
        if s.endswith(d) and len(s) > len(d) + 1:
            return d
    return None


def sura_of(s):
    """صورةُ الاسمِ السطحيةُ — من الرسمِ وحدَه، ستُّ خلايا مغلقةٌ لا سلّةَ فيها
    للباقي إلا «مفرد-عارٍ» وهي **مسمّاةٌ** بحدِّها لا مكنسةً صامتة."""
    if s.endswith("ات") and len(s) > 3:
        return "جمع-مؤنث-سالم"
    if s.endswith(("ون", "ين")) and len(s) > 3:
        return "جمع-مذكر/مثنى"
    if s.endswith("ان") and len(s) > 3:
        return "مثنى/آخره ان"
    if s.endswith("ة") and len(s) > 2:
        return "مؤنث-بالتاء"
    if s.endswith("ى") and len(s) > 2:
        return "مقصور"
    return "مفرد-عارٍ"


def is_mawsul(w):
    """موصولٌ من المعجمِ المغلقِ في `jumla_links` — بجذعه أو بصورته الملتصقة."""
    return sk(w) in JL.MAWSUL or sk(core_of(w)) in JL.MAWSUL


def indef_acc(w):
    """نكرةٌ منصوبة: تنوينُ فتحٍ ولا تعريفَ بأل. وهذا **حدُّ السطحِ كلُّه** —
    ولا يُدَّعى أنّه حدُّ النحاة."""
    s = sk(w)
    return END(w) == "تنوين فتح" and not s.startswith("ال") and len(s) > 2


def ce(keys, vals, m):
    return HL.heldout_ce(list(zip(keys, vals)), 0, m)


def shuffled_gain(keys, vals, m, base):
    """ضوابطُ المثل: تُخلَط المفاتيحُ وحدَها — يبقى المقامُ ويبقى الهامشُ ويُهدَم
    الاقترانُ. فإن ربحَ المخلوطُ مثلَ المودَعِ فالمكسبُ فارقُ مقامٍ لا فارقُ قاعدة."""
    out = []
    for t in range(RIVALS):
        ks = list(keys)
        random.Random(SEED * 100 + t + 1).shuffle(ks)
        out.append(round(base - ce(ks, vals, m), 4))
    return out


def priced(name, keys, vals, m):
    """صفٌّ مُسعَّر: الحدُّ الأدنى مفتاحٌ واحدٌ ثابت (لا معرفةَ)، والمكسبُ فوقَه،
    والحكمُ يُشتَقّ من إشارةِ المكسبِ ومن غلبتِه على أعلى ضوابطِ المثل."""
    base = ce([0] * len(vals), vals, m)
    cond = ce(keys, vals, m)
    gain = round(base - cond, 4)
    rivals = shuffled_gain(keys, vals, m, base)
    top = max(rivals)
    return {
        "الاسم": name, "مقام": len(vals), "حجمُ_الحقل": m,
        "بلا_معرفة": round(base, 4), "بالمعرفة": round(cond, 4),
        "المكسب": gain, "أعلى_المثل": top, "ضوابطُ_المثل": rivals,
        "حكم": "مُودَعٌ بالبرهان" if gain > 0 and gain > top else "ساقطٌ بالثمن",
    }


# ═══ ② الميدان — المجمَّدُ وحدَه ══════════════════════════════════════════════
def corpus():
    verses = parse_verses(HL.CORPUS)
    if not verses:
        raise IhalaError(E_CORPUS, "المجمَّدُ خالٍ — لا مقامَ يُقاس عليه")
    words = [w for v in verses for w in v]
    if len(words) < MIN_N:
        raise IhalaError(E_SHAPE, f"مقامُ الكلماتِ {len(words)} دون الحدِّ المعلن")
    return verses, words


def field_station(verses, words):
    forms = sorted({sk(w) for w in words})
    return {
        "آيات": len(verses), "كلمات": len(words),
        "خلايا_الضمير": M_DAMIR, "خلايا_الصورة": M_SURA, "خلايا_العلامة": M_ALAMA,
        "نافذةُ_العائد": AID_WINDOW, "سَعَةُ_فاصلِ_التمييز": len(ADAD),
        "صورٌ_حاضرة": {k: sum(1 for w in words if sura_of(sk(w)) == k) for k in SUWAR},
        "ثمنُ_إعلانِ_الخريطة": round(TG.declaration_cost(forms), 1),
    }


# ═══ ③ محطّةُ الإحالة ══════════════════════════════════════════════════════════
def ihala_station(verses):
    """كلُّ ضميرٍ غائبٍ متصلٍ سُبق باسم: المفتاحُ **صورةُ أقربِ اسمٍ قبلَه**،
    والمحكومُ **صورةُ الضمير**. فإن اشترت الصورةُ بتًّا فالإحالةُ أثرٌ مقيسٌ في
    البايتات — وإن لم تشترِ خُتم ذلك بعدده."""
    rows = []
    for v in verses:
        prev = None
        for w in v:
            d = damir_of(sk(w))
            if d and prev is not None:
                rows.append((sura_of(sk(prev)), d))
            if word_class(w) == "اسم":
                prev = w
    if len(rows) < MIN_N:
        raise IhalaError(E_SHAPE, f"ميدانُ الإحالةِ {len(rows)} دون {MIN_N}")
    keys = [a for a, _ in rows]
    vals = [b for _, b in rows]
    row = priced("صورةُ المرجعِ ⟶ صورةُ الضمير", keys, vals, M_DAMIR)
    return {
        "ميدانُ_الإحالة": len(rows),
        "ضمائرُ_حاضرة": {k: sum(1 for _, b in rows if b == k) for k in DAMAIR},
        "صورُ_المراجع": {k: sum(1 for a, _ in rows if a == k) for k in SUWAR},
        "صفّ": row,
        "حكم": row["حكم"],
    }


# ═══ ④ محطّةُ العطف — التبعيةُ فوقَ الجوار ═════════════════════════════════════
def atf_pairs(verses):
    """ميدانان **لا يُجمَعان**: المعطوفُ (اسمٌ صدرُه عاطفٌ ملتصقٌ بعدَ اسم) و
    الجوارُ (اسمٌ يلي اسمًا بلا حرف). والثاني هو الحدُّ الأدنى المقيسُ عليه."""
    atf, jiwar = [], []
    for v in verses:
        for i in range(1, len(v)):
            p, w = v[i - 1], v[i]
            if word_class(p) != "اسم":
                continue
            if JL.attached_atf(w):
                c = _body(w)[1]
                if len(c) >= 2 and word_class(c) == "اسم":
                    atf.append((alama_of(p), alama_of(c)))
            elif word_class(w) == "اسم":
                jiwar.append((alama_of(p), alama_of(w)))
    return atf, jiwar


def atf_station(verses):
    atf, jiwar = atf_pairs(verses)
    for nm, f in (("العطف", atf), ("الجوار", jiwar)):
        if len(f) < MIN_N:
            raise IhalaError(E_SHAPE, f"ميدانُ {nm} {len(f)} دون {MIN_N}")
    r_atf = priced("علامةُ المتبوعِ ⟶ علامةُ المعطوف",
                   [a for a, _ in atf], [b for _, b in atf], M_ALAMA)
    r_jiw = priced("علامةُ السابقِ ⟶ علامةُ الجار",
                   [a for a, _ in jiwar], [b for _, b in jiwar], M_ALAMA)
    excess = round(r_atf["المكسب"] - r_jiw["المكسب"], 4)
    return {
        "ميدانُ_العطف": len(atf), "ميدانُ_الجوار": len(jiwar),
        "صفُّ_العطف": r_atf, "صفُّ_الجوار": r_jiw,
        "فضلُ_التبعيةِ_على_الجوار": excess,
        "حكم": ("مُودَعٌ بالبرهان"
                if r_atf["حكم"] == "مُودَعٌ بالبرهان" and excess > 0
                else "ساقطٌ بالثمن"),
    }


# ═══ ⑤ محطّةُ الموصول — شاهدُ العائد، ورقمان يُختَمان معًا ══════════════════════
def aid_rows(verses):
    """لكلِّ موضعٍ في المجمَّد: أموصولٌ هو؟ وأفي نافذتِه عائدٌ (ضميرٌ غائبٌ متصل)؟"""
    rows = []
    for v in verses:
        for i in range(len(v) - 1):
            hit = any(damir_of(sk(x)) is not None for x in v[i + 1:i + 1 + AID_WINDOW])
            rows.append((is_mawsul(v[i]), hit))
    return rows


def mawsul_station(verses):
    rows = aid_rows(verses)
    flags = [a for a, _ in rows]
    hits = [b for _, b in rows]
    n = sum(flags)
    if n < 100:
        raise IhalaError(E_SHAPE, f"مواضعُ الموصولِ {n} دون مئةٍ — لا شاهدَ يُقام")
    obs = round(sum(h for f, h in rows if f) / n, 4)
    other = len(rows) - n
    bg = round(sum(h for f, h in rows if not f) / other, 4)
    rivals = []
    for t in range(RIVALS):
        fs = list(flags)
        random.Random(SEED * 100 + t + 1).shuffle(fs)
        rivals.append(round(sum(h for f, h in zip(fs, hits) if f) / n, 4))
    top = max(rivals)
    # والرقمُ الثاني: أتشتري «سابقُه موصولٌ» بتًّا على المقامِ الكاملِ؟
    bill = priced("موصولٌ قبلَه ⟶ عائدٌ في نافذته", flags, hits, 2)
    # وصنفُ التالي — يُعَدّ عدًّا ولا يُسعَّر: المصنِّفُ أضيقُ من أن يحكم.
    after = Counter()
    for v in verses:
        for i in range(len(v) - 1):
            if is_mawsul(v[i]):
                after[word_class(v[i + 1])] += 1
    return {
        "مواضعُ_الموصول": n,
        "نصيبُ_العائدِ_بعدَ_الموصول": obs,
        "نصيبُه_في_سواه": bg,
        "أعلى_المثل": top, "ضوابطُ_المثل": rivals,
        "شاهدٌ_غلبَ_مثلَه": bool(obs > top),
        "فاتورةُ_المقامِ_الكامل": bill,
        "أصنافُ_ما_بعدَ_الموصول": {k: after[k] for k in ("اسم", "فعل", "حرف", "مشتبه")},
        "حكم": ("شاهدُ نسبةٍ غلبَ مثلَه ولا يشتري بتًّا على المقام الكامل"
                if obs > top and bill["حكم"] != "مُودَعٌ بالبرهان"
                else "شاهدٌ وفاتورةٌ اتّفقا" if obs > top
                else "ساقطٌ بالنسبة"),
    }


# ═══ ⑥ محطّةُ التمييزِ والحال — عَرضٌ للفصل، وسقوطٌ يُختَم بعدده ═════════════════
def tamyiz_station(verses):
    """النكرةُ المنصوبةُ ميدانٌ واحدٌ لا يُفرَز بالسطحِ إلى تمييزٍ وحال. فيُعَدُّ
    الميدانُ، ويُعرَض الفاصلُ المعلَن (وقوعُها بعدَ عددٍ أو مقدارٍ مسمًّى)،
    ويُعلَن نصيبُه. والحكمُ يُشتَقّ من بلوغِ الميدانِ حدَّ التسعيرِ لا من الرغبة."""
    field, kinds = [], Counter()
    for v in verses:
        for i, w in enumerate(v):
            if not indef_acc(w):
                continue
            p = v[i - 1] if i > 0 else None
            if p is None:
                kinds["∅"] += 1
                field.append(False)
                continue
            kinds[word_class(p)] += 1
            field.append(sk(p) in ADAD or sk(core_of(p)) in ADAD)
    n = len(field)
    fires = sum(field)
    return {
        "ميدانُ_النكرةِ_المنصوبة": n,
        "أطلقَ_الفاصل": fires,
        "نصيبُ_الفاصل": round(fires / n, 4) if n else 0.0,
        "أصنافُ_السابق": {k: kinds[k] for k in ("اسم", "فعل", "حرف", "مشتبه", "∅")},
        "بلغَ_حدَّ_التسعير": bool(n >= MIN_N),
        "حكم": ("ساقطٌ بالمقام — الميدانُ دون حدِّ التسعير، فلا يُسعَّر عليه قانون"
                if n < MIN_N else
                "ساقطٌ بالفاصل — الميدانُ بلغَ الحدَّ ولم يُفرِز الفاصل"
                if fires * 4 < n else "مُودَعٌ بالفصل"),
        "الدَّينُ_باقٍ": True,
    }


# ═══ ⑦ ديونٌ تُسمّى بلا رقم ════════════════════════════════════════════════════
def debts_station():
    return {"عدد": len(DEBTS), "بنود": list(DEBTS)}


# ═══ ⑧ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ، ونجاحُ واحدةٍ يُسقِط البابَ ═══════
def falsify(verses, fld, ihl, atf, mws, tmz):
    T = []

    # ① الحقولُ مغلقةٌ معلنةُ الحجم، ولا واحدَ منها خلوٌ بالبناء.
    T.append(("خلايا الضمير خالفت إعلانَها", len(DAMAIR) != M_DAMIR))
    T.append(("خلايا الصورة خالفت إعلانَها", len(SUWAR) != M_SURA))
    T.append(("خلايا العلامة خالفت إعلانَها", len(ALAMAT) != M_ALAMA))

    # ② صورةُ الاسمِ مغلقةٌ حقًّا: أيُّ رسمٍ يقع في خانةٍ مسمّاةٍ، ولا خانةَ سرّيّة.
    T.append(("صورةٌ خارجَ الخلايا الستّ",
              any(sura_of(sk(w)) not in SUWAR for v in verses for w in v)))

    # ③ الضميرُ لا يبتلع الكلمةَ كلَّها: «هم» وحدَها ليست ضميرًا متصلًا.
    T.append(("«ه» قُرئت ضميرًا في كلمةٍ من حرفين", damir_of("له") is not None))
    T.append(("الأطولُ لم يُقدَّم — «عليهم» قُرئت «ه»", damir_of("عليهم") != "هم"))

    # ④ الإحالةُ لا تربح بالبناء: ضوابطُ المثل يجب أن تسقط كلُّها.
    T.append(("ضابطُ مثلٍ ربحَ في الإحالة مثلَ المودَع",
              ihl["صفّ"]["أعلى_المثل"] >= ihl["صفّ"]["المكسب"]))
    T.append(("مكسبُ الإحالةِ سالبٌ وقد خُتم مُودَعًا",
              ihl["حكم"] == "مُودَعٌ بالبرهان" and ihl["صفّ"]["المكسب"] <= 0))

    # ⑤ الميدانان لا يُخلَطان: العطفُ غيرُ الجوارِ عددًا، والجوارُ أكبرُ بالبناء.
    T.append(("ميدانُ العطفِ ساوى ميدانَ الجوار",
              atf["ميدانُ_العطف"] == atf["ميدانُ_الجوار"]))
    T.append(("الجوارُ لم يكن أوسعَ من العطف",
              atf["ميدانُ_الجوار"] <= atf["ميدانُ_العطف"]))

    # ⑥ الفضلُ محسوبٌ من الرقمين المختومين لا مكتوبٌ بيد.
    T.append(("فضلُ التبعيةِ لم يُوافق فرقَ الصفّين",
              abs(atf["فضلُ_التبعيةِ_على_الجوار"]
                  - (atf["صفُّ_العطف"]["المكسب"] - atf["صفُّ_الجوار"]["المكسب"])) > 1e-9))
    T.append(("الجوارُ وحدَه لا يشتري — فالمكسبُ في العطفِ تحصيلُ حاصل",
              atf["صفُّ_الجوار"]["المكسب"] <= 0))

    # ⑦ شاهدُ العائدِ ليس تحصيلَ حاصل: لو خُلطت المواضعُ لَما بقي الفضل.
    T.append(("ضابطُ مثلٍ بلغَ نصيبَ العائدِ بعدَ الموصول",
              mws["أعلى_المثل"] >= mws["نصيبُ_العائدِ_بعدَ_الموصول"]))
    T.append(("نصيبُ العائدِ لم يغلب نصيبَه في سواه",
              mws["نصيبُ_العائدِ_بعدَ_الموصول"] <= mws["نصيبُه_في_سواه"]))

    # ⑧ والرقمُ الثاني يُختَم ولو خالفَ الأوّل: فاتورةُ المقامِ الكاملِ حاضرةٌ
    #    بحكمها، ولا تُحذَف لأنّها لم توافق الشاهد.
    T.append(("فاتورةُ المقامِ الكاملِ غابت عن الوديعة",
              "حكم" not in mws["فاتورةُ_المقامِ_الكامل"]))

    # ⑨ التمييزُ والحال: الدَّينُ لا يُرفَع بالسكوت — والحكمُ يُشتَقّ من المقام.
    T.append(("ميدانُ النكرةِ المنصوبةِ بلغَ الحدَّ وخُتم ساقطًا بالمقام",
              tmz["بلغَ_حدَّ_التسعير"] and "بالمقام" in tmz["حكم"]))
    T.append(("الدَّينُ رُفِع والميدانُ دون الحدّ",
              not tmz["بلغَ_حدَّ_التسعير"] and not tmz["الدَّينُ_باقٍ"]))
    T.append(("النكرةُ المنصوبةُ قُرئت في معرَّفٍ بأل",
              any(indef_acc(w) and sk(w).startswith("ال")
                  for v in verses for w in v)))

    # ⑩ حدُّ `jumla_links` لا يُمَسّ: المعجمُ مقروءٌ من موضعه لا منسوخٌ ههنا.
    T.append(("معجمُ الموصولاتِ نُسخ ههنا ولم يُقرأ من موضعه",
              set(JL.MAWSUL) != set(JL.MAWSUL) or len(JL.MAWSUL) < 5))

    # ⑪ خريطةُ الصورِ مُسعَّرةٌ قبل أن تُستعمَل — ولا يُقدَّر ثمنٌ لغائب.
    T.append(("ثمنُ إعلانِ الخريطةِ غيرُ موجب", fld["ثمنُ_إعلانِ_الخريطة"] <= 0))

    # ⑫ الديونُ تُسمّى ولا تُرقَّم.
    T.append(("دَينٌ حملَ رقمًا", any(any(ch.isdigit() for ch in d) for d in DEBTS)))

    fired = [name for name, hit in T if hit]
    if fired:
        raise IhalaError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return len(T)


