# ihala_gate.py — بابُ الإحالةِ والتوابع: أيُقام على السطحِ وحدَه شاهدُ الإحالةِ
#                 وتبعيةِ المعطوف وصلةِ الموصول، وأيُفصَل التمييزُ من الحال؟
#
# §٠ الدَّينُ المعروضُ للسداد. خمسةُ أبوابٍ من «الشخصية الإسلامية» (ج٣ — أبحاثُ
#    اللغة) تُعرَض ههنا للقياس لا للدعوى: **الإحالةُ** بالضمير، و**العطفُ**
#    تابعًا في الإعراب، و**الأسماءُ الموصولة** بصلتها وعائدها، و**التمييزُ**
#    و**الحالُ** نكرتين منصوبتين. ولكلٍّ سؤالٌ واحدٌ قابلٌ للتكذيب، وجوابُه
#    رقمٌ يُشتَقّ بتشغيل الكود على المجمَّد ويُصادَم بوديعته — أو سقوطٌ يُختَم
#    بعدده ولا يُرفَع بتبويب.
#
# §١ الجبرُ حاكمٌ لا محكوم. لا قاعدةَ ههنا تُصدَّق لأنّها مكتوبةٌ في الكتاب: كلُّ
#    دعوى تُترجَم إلى **مكسبِ بتّاتٍ فوقَ حدٍّ أدنى معلن**، ويُصادَم مكسبُها
#    بـ**إحدى عشرةَ فرقةً مخلوطة** (ضوابطُ المثل) تُبقي المقامَ والهامشَ وتهدم
#    الاقتران وحدَه. والفاتورةُ الموروثةُ وحدَها حَكَمٌ: `harakat_layer.heldout_ce`.
#
# §٢ وحدُّ «الحدِّ الأدنى» في كلِّ محطّةٍ **الجوارُ لا العدم**. فالبديلُ الأصغرُ
#    من «هذا معطوفٌ يتبع متبوعَه» ليس «لا شيءَ» بل «اسمٌ يلي اسمًا بلا حرف».
#    فالمقيسُ **فضلُ التبعيةِ على الجوار**، لا فضلُ الجوارِ على العدم — وهذه
#    سنّةُ `jumla_gate` بعينها، وهي التي تمنع أن يكون المكسبُ تحصيلَ حاصل.
#
# §٣ وما لا يُدَّعى — ويُختَم سقوطُه بعدده، ولا يُحذَف:
#    ① **لا يُدَّعى أنّ مرجعَ الضميرِ مُعيَّن**: المقيسُ أنّ **صورةَ أقربِ اسمٍ
#       قبلَه** تشتري بتًّا في صورةِ الضمير، لا أنّ ذلك الاسمَ هو المرجع. وتعيينُ
#       المرجعِ بعينه دَينٌ يُسمّى بلا رقم.
#    ② **لا يُدَّعى أنّ صلةَ الموصولِ جملةٌ مُثبَتة**: مصنِّفُ الأفعالِ الموروثُ
#       ضيّقٌ بإعلانه، فما بعدَ الموصولِ لا يُقرَأ فعلًا إلا نادرًا — ويُعَدّ
#       ذلك بعدده. والمُقامُ ههنا **شاهدُ العائد** وحدَه: نسبةٌ تُصادَم بضوابطِ
#       مثلها، و**لا تشتري بتًّا على المقام الكامل** — والرقمان يُختَمان معًا.
#    ③ **لا يُدَّعى فصلُ التمييزِ من الحال**: الميدانُ يُعَدّ ويُسمّى بحدِّه،
#       والفاصلُ المعروضُ (وقوعُ النكرةِ بعدَ عددٍ أو مقدارٍ مسمًّى) يُقاس ويُعلَن
#       نصيبُه. فإن لم يبلغ الميدانُ حدَّ التسعير، أو لم يُفرِز الفاصلُ، خُتم
#       السقوطُ بعدده وبقي الدَّينُ باسمه — على سنّةِ منعِ الصرفِ في `mabna_gate`.
#    ④ **ولا يُمَسّ حكمُ `jumla_links`**: تغطيةُ الأسبابِ الاثني عشرَ تبقى 0.3289
#       و0.3416 ساقطةً مختومة. المأخوذُ من ذلك المحرّكِ **معجمُ الموصولاتِ
#       المغلقُ وحدَه** و**دالّةُ العاطفِ الملتصق** — لا حكمُه ولا أسبابُه.
