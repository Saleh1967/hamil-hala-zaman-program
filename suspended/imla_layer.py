    print(f"كلفةُ الطبقة معلنة: {R['كلفةُ_الطبقة_بتًّا']} بت — "
          "⚑ والمعجمُ والكلفةُ السابقة لم تُمسّا، ولا وديعةَ قائمةً مُسَّت")


