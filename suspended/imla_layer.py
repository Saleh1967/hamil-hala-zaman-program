def apply_rules(word):
    """آلةُ التحويل ٢(توقيفيّ) ⟶ ٣(إملائيّ): تمرّةٌ واحدةٌ بجِوارٍ محدود — لا جدولَ مواضع."""
    out, n = [], len(word)
    for i, ch in enumerate(word):
        last = i == n - 1
        hit = None
        for _, src, ctx, dst in RULES:
            if ch != src:
                continue
            if ctx == "مطلق" or (ctx == "في الآخر") == last:
                hit = dst
                break
        out.append(hit if hit is not None else ch)
    return "".join(out)


