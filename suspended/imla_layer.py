# ═══ ⑪ محاولاتُ التكذيب — كلُّها يجب أن تُرَدّ ═════════════════════════════════════════
def falsify(pairs):
    T = []

    # ① الآلةُ ليست هويةً: لو لم تغيّر شيئًا لَتساوت البواقي بالمخالف كلِّه.
    diff = sum(1 for _v, _w, u, m in pairs if u != m)
    res = sum(1 for _v, _w, u, m in pairs if apply_rules(u) != m)
    T.append(("الآلةُ هويةٌ لا تغيّر شيئًا", res >= diff))

    # ② الآلةُ لا تُفسِد موضعًا كان مطابقًا قبلها.
    broke = sum(1 for _v, _w, u, m in pairs if u == m and apply_rules(u) != m)
    T.append(("الآلةُ أفسدت موضعًا كان مطابقًا", broke > 0))

    # ③ سياقٌ غيرُ معلنٍ يُقبَل في القواعد.
    T.append(("سياقٌ غيرُ معلنٍ في جدول القواعد",
              any(c not in CONTEXTS for _n, _s, c, _d in RULES)))

    # ④ حارسُ الانحلال خاوٍ: نوعٌ لكلِّ موضعٍ يجب أن يُعَدّ منحلًّا.
    T.append(("نوعٌ لكلِّ موضعٍ لم يُعَدّ انحلالًا", not degenerate(10, 10)[1]))

    # ⑤ الرتبةُ خارجَ السلّم تُقبَل في قالب الدعوى — ولا سادسةَ للسلّم.
    try:
        C("خ", "مختلق", "دعوى برتبةٍ سادسة", 5, "مقام", "مكذِّب", "رسمٌ عثمانيّ")
        sixth = True
    except AssertionError:
        sixth = False
    T.append(("رتبةٌ سادسةٌ دخلت السلّم", sixth))

    # ⑥ دعوى بلا مكذِّبٍ تُقبَل في القالب.
    try:
        C("خ", "مختلق", "دعوى بلا مكذِّب", 2, "مقام", "", "رسمٌ عثمانيّ")
        naked = True
    except AssertionError:
        naked = False
    T.append(("دعوى بلا مكذِّبٍ دخلت المحكمة", naked))

    # ⑦ المكيالُ يسعّر جدولًا فارغًا.
    try:
        table_cost([], 10)
        empty = True
    except ValueError:
        empty = False
    T.append(("المكيالُ سعّر جدولًا فارغًا", empty))

    # ⑧ ω = 0 يحذف الحافةَ لا العقدة — الحارسُ مستدعًى لا منسوخ.
    T.append(("ω=0 أسقط الدعوى وثمَّ حافةٌ موجبة",
              not omega_drop([("أ", 0), ("ب", 3)])["موصولة"]))

    # ⑨ الحكمُ يُكتَب بيدٍ في قالب الدعوى.
    T.append(("قالبُ الدعوى يحمل حقلَ حكمٍ مكتوبًا",
              any("حكم" in c for c in CLAIMS)))

    return [dict(محاولة=n, نجحت=bool(b), حكم="نُقضت ✗" if b else "رُدّت ✓") for n, b in T]


