# imla_layer.py — بابُ الإملاءِ والترميز: ضبطُ الطبقاتِ مرّةً واحدةً إلى الأبد.
#
# ــ ٠) لماذا هذا البابُ مؤسِّس، ولماذا يُكتَب الآن لا قبلُ ولا بعدُ ــــــــــــــــــــ
# المشروعُ كلُّه يتعامل مع النصِّ عبر طبقاتٍ صارت **عمليًّا** ولم تُضبَط **نظريًّا**:
# المجمَّدُ إملائيٌّ محرَّك، والعثمانيُّ رسمٌ توقيفيّ، و`waqf_layer` يجسر بينهما بقاعدة
# مواءمةٍ معلنة، و`normalize` يفحص NFC ولا يفرضه، و`alama_layer` يفكّ الشدّة فوق الرسم.
# وكلُّ بابٍ سابقٍ افترض الطبقةَ **بصمت**. وهذا البابُ يعلنها: لكلِّ نصٍّ داخلٍ أربعةُ
# مقادير (الترميز · التطبيع · الرسم · الطبقة) تُصادَم ببايتاته، ولكلِّ تحويلٍ بين طبقتين
# **فاتورةٌ واحدة**. ولا طبقةَ سادسةَ تُختلَق.
#
# ــ ١) المسبارُ مُعلَنٌ قبل التجميد، ولا يُكتَم (سنّةُ alama_layer وmanhaj_gate) ــــــــ
# سُبق هذا البابُ بمسبارٍ على بايتات المقامين المختومين، وحصيلتُه أسقطت ثلاثةَ افتراضاتٍ
# كانت في خطّته الأولى — فتُكتَب ههنا لا في تقريرٍ يُنسى:
#   ① **المقامان المودَعان ليسا مطبَّعَين NFC**: التطبيعُ يُعيد ترتيبَ الشدّةِ والحركة في
#      المجمَّد (المجموعةُ محفوظةٌ والترتيبُ يتبدّل)، و**يُنقِص من العثمانيِّ نقاطَ ترميزٍ
#      معدودة** (تركيبٌ لا إعادةُ ترتيب). فلو طُبِّع في الظلام يومًا لانزاح كلُّ عددٍ في
#      `waqf_layer`. فالتطبيعُ **حقلٌ يُعلَن لكلِّ نصّ**، لا عادةٌ تُفترَض.
#   ② **قاعدةُ المواءمة تطوي ى ⟵ ي بنفسها**: فمواضعُ الألف المقصورة الباقيةُ في المجمَّد
#      تقع **خارجَ الأزواج**. وهذا عمًى معلنٌ معدود، لا يُدَّعى معه صمودُ دعوى القصر.
#   ③ **الشرطُ الفضفاض للحذف يلتقط مُشابهاتٍ لا حذفًا**: «هيئةٌ مقصورةٌ لها ممدودةٌ في
#      المتن» يعطي عشراتِ الألوف في صدارتها «من · إن · أن» — وهي المشابهةُ بعينها.
#      فالمقامُ الذي يميّز الأصلَ من المُشابه **زوجٌ مُواءَمٌ في الموضع نفسِه**، لا هيئةٌ
#      تُشبه هيئةً في مكانٍ آخر. وبه يُغلَق دَينُ «حذفِ الرسم التوقيفي».
#
# ــ ٢) سلّمُ الطبقاتِ الخمس — ولا سادسةَ لها ـــــــــــــــــــــــــــــــــــــــــــ
#   ٤ المقصد/اللفظ · ٣ الإملاء · ٢ الرسم (بخانتِه: توقيفيّ/إملائيّ) · ١ الرموز · ٠ البايتات
# وفوقَ السلّمِ **قاعدةُ الاشتقاق**: أيُّ تحويلٍ بين طبقتين انتقالٌ في آلةٍ منتظمةٍ منتهية
# له فاتورتُه — Δ = L(FST) + L(D|FST) − L(جدولِ المواضعِ فرادى). فلا نصَّ بلا طبقةٍ معلنة،
# ولا تحويلَ بلا فاتورة.
#
# ــ ٣) والكيلُ ليس هنا ـــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# كلُّ بتٍّ يخرج من `deposit_law.price`، وكلُّ حكمٍ من `deposit_law.verdict`، وحارسُ
# الانحلال |Σ|/N من `deposit_law.degenerate`، و`n₀` و`ω` من `alama_layer` — تُستدعى ولا
# تُنسَخ. ولا مواءمةَ ثانيةً ولا قارئَ ثانيًا: `waqf_layer.align_verse` بعينها.
#
# ⚑ ولا يُمَسُّ معجمٌ ولا كلفةٌ سابقة: هذه طبقةُ إعلانٍ وقياسٍ فوق الرسم، لا تصنيفُ كلمات.
