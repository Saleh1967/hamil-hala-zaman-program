# ═══ ⑥ الإحصاءُ على البايتات: كلُّ مقدارٍ مشتقٌّ من موضعه لا منقول ════════════════════
def census(path, seal):
    """يُرَدّ إحصاءُ نصٍّ مختومٍ بمقاديره الأربعةِ مقيسةً — ولا يُقرَأ رقمٌ من إعلانه."""
    blob = open(path, "rb").read()
    assert hashlib.sha256(blob).hexdigest() == seal, f"ختمٌ خُولف: {path}"
    text = blob.decode("utf-8-sig")
    body = [ln for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    head = [ln for ln in text.splitlines() if ln.lstrip().startswith("#")]
    B = "\n".join(body)
    nfc = unicodedata.normalize("NFC", B)
    return dict(
        بايتات=len(blob), بوم=NRM.has_bom(path), محارف=len(text),
        أسطرُ_متن=len(body), أسطرُ_ترويسة=len(head), نقاطُ_المتن=len(B),
        ألفُ_الوصل=B.count(WASL), الخنجرية=B.count(DAGGER),
        الألفُ_المقصورة=B.count(MAQSURA),
        الحركات=sum(1 for c in B if 0x064B <= ord(c) <= 0x0652),
        علاماتُ_الوقف=sum(1 for c in B if 0x06D6 <= ord(c) <= 0x06DC),
        أشكالُ_العرض=sum(1 for c in B if ord(c) in PRESENTATION),
        غيرُ_عربيٍّ_في_المتن=sum(1 for c in B
                                  if not (0x0600 <= ord(c) <= 0x06FF or c in " \n")),
        غيرُ_عربيٍّ_في_الترويسة=sum(1 for ln in head for c in ln
                                      if not (0x0600 <= ord(c) <= 0x06FF or c in " \n")),
        مطبَّعٌ_NFC=B == nfc,
        نقاطٌ_يُغيّرها_NFC=len(B) - len(nfc),
        مجموعةُ_النقاط_محفوظةٌ_تحت_NFC=Counter(B) == Counter(nfc),
        كلماتٌ_تتبدّل_بـNFC=sum(1 for a, b in zip(B.split(), nfc.split()) if a != b),
        NFC_ثابتٌ_على_نفسه=unicodedata.normalize("NFC", nfc) == nfc,
    )


def declare_layers():
    """يُصادَم إعلانُ كلِّ نصٍّ ببايتاته: دعوى الصفر ودعوى الوجود — والمخالفُ صريخ."""
    rows, problems = {}, []
    for name, d in TEXTS.items():
        m = census(d["مسار"], d["ختم"])
        checks = []
        for field in d["صفرًا"]:
            key = field.replace(" ", "_")
            got = m[key]
            ok = got == 0
            checks.append(dict(حقل=field, دعوى="صفرٌ معلن", مقيس=got, صمد=ok))
            if not ok:
                problems.append(f"«{name}»: أُعلن {field} صفرًا والبايتاتُ تعطي {got}")
        for field in d["موجودًا"]:
            key = field.replace(" ", "_")
            got = m[key]
            ok = got > 0
            checks.append(dict(حقل=field, دعوى="موجودٌ معلن", مقيس=got, صمد=ok))
            if not ok:
                problems.append(f"«{name}»: أُعلن {field} موجودًا والبايتاتُ تعطي صفرًا")
        rows[name] = dict(
            إعلان=dict(ترميز=d["ترميز"], تطبيع=d["تطبيع"], رسم=d["رسم"],
                       طبقة=f"{d['طبقة']} — {LAYER_NAME[d['طبقة']]}",
                       ختم=d["ختم"][:8] + "…"),
            مقيس=m, مصادمة=checks)
    return rows, problems


def declare_modules():
    """طبقاتُ المعالجة القائمة: ما تقرأ وما تكتب — والادّعاءُ يُصادَم بالاستيراد."""
    import importlib
    rows, problems = [], []
    for path, rd, wr, const, hadd in MODULES:
        mod_name = os.path.basename(path)[:-3]
        held = "—"
        if const:
            key, want = const
            mod = importlib.import_module(mod_name)
            got = getattr(mod, key, None)
            if key == "CORPUS":
                got = os.path.basename(got) if got else None
            held = "طابق" if got == want else f"خالف ({got})"
            if got != want:
                problems.append(f"«{path}»: ثابتُ مقامِه {key} = {got} ولا يطابق المُعلَن {want}")
        else:
            assert callable(getattr(NRM, "guard_nfc", None)), "normalize بلا حارس تطبيع"
        rows.append(dict(وحدة=path, يقرأ=f"{rd} — {LAYER_NAME[rd]}",
                         يكتب=f"{wr} — {LAYER_NAME[wr]}", حدّ=hadd, مقام=held))
    return rows, problems


# ═══ ⑦ الأزواجُ المُواءَمة: مواءمةُ waqf_layer بعينها — ولا ثانيةَ لها ════════════════
def aligned_pairs():
    """أزواجُ (رسمٌ توقيفيّ، رسمٌ إملائيّ) 1:1 في الموضع نفسِه، ومعها موضعُ كلِّ زوج.

    الرسمُ ههنا **حروفٌ بلا حركات**: من العثمانيِّ بمرشِّح `waqf_layer.LETTER` (فتبقى
    ٱ وٰ صورتين قائمتين)، ومن المجمَّد بقارئ `induction_engine.parse_verses` بعينه.
    والزوجُ غيرُ الأحاديّ (ضمٌّ أو فصل) **لا يدخل**: انتقالُ الآلةِ موضعٌ بموضع، والضمُّ
    والفصلُ بابٌ آخرُ يُعَدّ بالاسم ولا يُجسَر عليه.
    """
    verses = parse_verses(MUJAMMAD)
    body, _ = WQ.read_uthmani()
    pairs, joins = [], 0
    for vi, (line, verse) in enumerate(zip(body, verses), 1):
        uw, *_ = WQ.uthmani_verse(line)
        U = tuple(WQ.skeleton(w) for w in uw)
        M = tuple("".join(c for c, _ in w) for w in verse)
        _a, _c, _d, ps = WQ.align_verse(U, M)
        for (i, j, du, dm) in ps:
            if du == 1 and dm == 1:
                pairs.append((vi, j + 1,
                              "".join(ch for ch in uw[i] if WQ.LETTER(ch)), M[j]))
            else:
                joins += 1
    return pairs, joins


def residue_classes(pairs):
    """بواقي الآلة مصنَّفةً بقائمةٍ مرتَّبةٍ مجمَّدة — الموضعُ في أوّلِ صنفٍ يطابقه لا مرّتين."""
    cnt, ex = Counter(), {}
    for k in ("خاتمةُ المقصورة ى ⟵ ي", "خنجريةٌ لا تُكتَب ألفًا",
              "ألفٌ يزيدها الإملاء", "سواها — بالاسم"):
        cnt[k] = 0
    for vi, wi, u, m in pairs:
        g = apply_rules(u)
        if g == m:
            continue
        if g.endswith(MAQSURA) and m.endswith(YA) and g[:-1] == m[:-1]:
            k = "خاتمةُ المقصورة ى ⟵ ي"
        elif g.replace(ALIF, "") == m.replace(ALIF, "") and len(g) > len(m):
            k = "خنجريةٌ لا تُكتَب ألفًا"
        elif g.replace(ALIF, "") == m.replace(ALIF, "") and len(g) < len(m):
            k = "ألفٌ يزيدها الإملاء"
        else:
            k = "سواها — بالاسم"
        cnt[k] += 1
        ex.setdefault(k, []).append(f"{u} ⟵ {m} (الآية {vi} · الكلمة {wi})")
    return cnt, {k: v[:4] for k, v in ex.items()}


# ═══ ⑧ فاتورةُ الانتقال ٢⟶٣ — بالمكيال العامّ وحدَه ══════════════════════════════════
def spell(s):
    """ثمنُ إملاءِ سلسلةٍ بالأبجدية المعلنة — كما في alama_layer، لا سياسةَ ترميزٍ ثانية."""
    return (len(s) + 1) * log2(ALPHA)


def fst_cost():
    """L(FST): عددُ القواعد + كلُّ قاعدةٍ مُملاةً (مدخلٌ · سياقٌ من مفرداتٍ مغلقة · مخرَج)."""
    bits = log2(len(RULES) + 1)
    for _, src, ctx, dst in RULES:
        bits += spell(src) + log2(len(CONTEXTS)) + spell(dst)
    return bits


def table_cost(items, n_positions):
    """جدولٌ فراديّ: لكلِّ مدخلٍ **موضعٌ مفهرس** + صورتُه — والصورُ تُسعَّر بالمكيال العامّ."""
    if not items:
        raise ValueError("جدولٌ فارغٌ — لا كلفةَ تُقاس على فراغ")
    forms = [m for *_x, m in items]
    p = price(forms, 0)
    sites = len(items) * log2(n_positions + 1)
    return dict(مواضع=len(items), مواقعُ_مفهرسة=sites, بيانات=p["بيانات"],
                نموذج=p["نموذج"], كلفة=sites + p["كلفة"])


def transition_bill(pairs):
    """حكمُ دعوى H: n₀ ⟶ حارسُ الانحلال ⟶ الفاتورة — بهذا الترتيب لا بغيره."""
    N = len(pairs)
    diff = [(vi, wi, u, m) for vi, wi, u, m in pairs if u != m]
    res = [(vi, wi, u, m) for vi, wi, u, m in pairs if apply_rules(u) != m]
    enough, need = n0_gate("n₀ مواضع", len(diff), THRESHOLDS)

    kinds = len({(u, m) for *_a, u, m in res})
    ratio, degen = degenerate(kinds, len(res)) if res else (0.0, False)
    # والمكذِّبُ الثاني يُجرَّب لا يُوصَف: آلةٌ بقاعدةٍ لكلِّ موضعٍ شاذّ — نسبتُها 1.0 منحلّة.
    greedy_ratio, greedy_degen = degenerate(len(res), len(res))

    A = table_cost(diff, N)
    B = table_cost(res, N)
    fst = fst_cost()
    delta = (fst + B["كلفة"]) - A["كلفة"]

    if not enough:
        ruling = f"غيرُ مختبَرة — مواضعُ المخالفة {len(diff)} < {need}"
    elif degen:
        ruling = f"ساقطة — انحلالُ الشواذّ {ratio} فوق الحدّ: جدولُ مواضعَ باسمٍ آخر"
    else:
        ruling = ("صامدة — الفاتورةُ تقبلها: الآلةُ وبواقيها أرخصُ من الجدول الفراديّ"
                  if verdict(delta) == ACCEPT else
                  "ساقطة — الفاتورةُ ترفضها: الجدولُ الفراديُّ أرخصُ من الآلة")

    return dict(
        دعوى=CLAIM_H, أزواج=N, مواضعُ_المخالفة=len(diff),
        تغطيةُ_القاعدة=round((len(diff) - len(res)) / len(diff), 4),
        بواقٍ=len(res), أنواعُ_البواقي=kinds,
        **{"n₀": dict(حدّ=need, بلغ=enough)},
        حارسُ_الانحلال=dict(نسبة=ratio, منحلّ=degen,
                            قاعدةٌ_لكلِّ_موضع=dict(نسبة=greedy_ratio, منحلّ=greedy_degen)),
        جدولُ_المواضع=dict(A, كلفة=round(A["كلفة"], 2), بيانات=round(A["بيانات"], 2),
                            نموذج=round(A["نموذج"], 2), مواقعُ_مفهرسة=round(A["مواقعُ_مفهرسة"], 2)),
        الآلةُ_وبواقيها=dict(B, كلفة=round(B["كلفة"], 2), بيانات=round(B["بيانات"], 2),
                             نموذج=round(B["نموذج"], 2), مواقعُ_مفهرسة=round(B["مواقعُ_مفهرسة"], 2),
                             قواعد=round(fst, 2), مجموع=round(fst + B["كلفة"], 2)),
        Δ=round(delta, 2), حكمُ_الفاتورة=verdict(delta), حكم=ruling,
    )


# ═══ ⑨ مقامُ الطبقة ٢: الأصلُ من المُشابه — وبه يُغلَق دَينُ حذفِ الرسم التوقيفيّ ═══════
def rasm_deletion_station(pairs, verses):
    """الحذفُ يُشهَد له بالموضع لا بالشبَه.

    **الأصل**: زوجٌ مُواءَمٌ في الموضع نفسِه من مقامين مختومين، هيكلاه سواءٌ بعد طيِّ
    الألف، وألفاتُ الإملاء أكثرُ من ألفات الرسم — فههنا ألفٌ **حُذفت رسمًا** بشاهدها.
    **المُشابه**: هيئةٌ في المتن لها هيئةٌ أخرى تزيد ألفًا في أيِّ موضع — بلا مواءمةٍ ولا
    موضعٍ يجمعهما. وهذا هو الشرطُ الفضفاض الذي رُدَّ بالاسم في AUDIT-188 §١ صفّ ٤.
    """
    strict, ex = 0, []
    reverse = 0
    for vi, wi, u, m in pairs:
        g = apply_rules(u)
        if g.replace(ALIF, "") != m.replace(ALIF, ""):
            continue
        nu, nm = u.replace(WASL, ALIF).count(ALIF), m.count(ALIF)
        if nm > nu:
            strict += 1
            if len(ex) < 6:
                ex.append(f"{u} ⟵ {m} (الآية {vi} · الكلمة {wi})")
        elif nu > nm and DAGGER not in u:
            reverse += 1

    forms = Counter("".join(c for c, _ in w) for v in verses for w in v)
    have = set(forms)
    loose_types, loose_tokens, loose_ex = 0, 0, []
    for f, n in forms.items():
        if any(f[:i] + ALIF + f[i:] in have for i in range(len(f) + 1)):
            loose_types += 1
            loose_tokens += n
            loose_ex.append((n, f))
    loose_ex.sort(reverse=True)

    return dict(
        دَين="حذفُ الرسم التوقيفي — AUDIT-188 §١ صفّ ٤ (كان T₃ تعليقًا بالاسم)",
        مقام=("الطبقة ٢: زوجٌ مُواءَمٌ في الموضع نفسِه من مقامين مختومين — "
              "الشاهدُ الموضعُ لا الشبَه"),
        قاعدة=("يُعَدّ حذفًا موضعٌ استوى فيه الهيكلان بعد طيِّ الألف وزادت ألفاتُ الإملاء "
               "على ألفات الرسم؛ وما سواه ليس حذفًا وإن أشبهه"),
        حذفٌ_بالموضع=strict, أمثلة=ex,
        الاتجاهُ_المعاكس=reverse,
        الشرطُ_الفضفاض=dict(
            نصّ="هيئةٌ مقصورةٌ لها ممدودةٌ في المتن — بلا موضعٍ يجمعهما",
            أنواع=loose_types, مواضع=loose_tokens,
            صدارتُه=[f"{f} ({n:,})" for n, f in loose_ex[:6]],
            حكم=("مردودٌ بالاسم: صدارتُه «من · إن · أن» — مُشابهاتٌ لا حذف، "
                 "ونسبتُه إلى المقيس بالموضع تُطبَع ولا تُجسَر")),
        نسبةُ_التضخيم=round(loose_tokens / strict, 2) if strict else None,
        حكم=("مُغلَق — الحذفُ مقيسٌ بمقامٍ يميّز الأصلَ من المُشابه بقاعدةٍ معلنةٍ لا بالذوق"),
        معلَّقٌ_بصنفه=(
            "ما بقي معلَّقًا بصنفه: ① الأزواجُ غيرُ الأحادية (ضمٌّ وفصل) لا تدخل هذا "
            "المقام — انتقالُ الآلة موضعٌ بموضع، وعدُّها في waqf_layer بالاسم. "
            "② والكلماتُ غيرُ المُواءَمة أصلًا (فجوةُ waqf_layer المعلنة) لا يُقضى فيها "
            "بحذفٍ ولا بعدمه: لا موضعَ يجمع الصورتين فلا شاهد. "
            "③ ودعوى «الحذفُ لعلّةٍ صرفيةٍ مسمّاة» طبقةٌ ٤ لم تُفتَح هنا — T₃ بالاسم"),
    )


