# jumla_gate.py — بابُ الجملة: أيُفصَل العاطفُ من المستأنِفِ بالبتّ، وأيُقام
#                 شاهدُ الفاعليةِ والمفعوليةِ والسببيةِ والمسببيةِ على السطحِ وحدَه؟
#
# §٠ الدَّينُ المعروضُ للسداد — خُتم في `jumla_links` ثمّ في `nisab_gate` بنصِّه:
#    «العطفُ بالواو/الفاء تعليقٌ لا سببٌ من الاثني عشر … ولا يُفصَل العاطفُ من
#    المستأنِفِ بالسطحِ وحدَه». وههنا يُعرَض الفصلُ **للقياس لا للدعوى**: يُسأل
#    ســؤالٌ واحدٌ قابلٌ للتكذيب — **أتشتري معرفةُ الحرفِ بتًّا فوقَ معرفةِ
#    الجملةِ السابقةِ وحدَها؟** فإن اشترت فالعطفُ حدٌّ مقيسٌ لا وسمٌ مُدَّعًى،
#    وإن لم تشترِ خُتم السقوطُ بعددِه ولم يُرفَع بتبويب.
#
# §١ وحكمُ الجولة ١ في `jumla_links` **لا يُمَسّ**: تغطيةُ الأسباب الاثني عشر
#    تبقى 0.3289 و0.3416 ساقطةً مختومة، ولا يُبنى ههنا عليها شيء. المأخوذُ من
#    ذلك المحرّكِ **تقطيعُه وحدَه** — `segment` بعينها، بشاهدِها الإعرابيّ — لا
#    حكمُه ولا أسبابُه. فالتقطيعُ قياسٌ من البايتات، والحكمُ هو الذي سقط.
#
# §٢ الجبرُ حاكمٌ لا محكوم. الجملةُ تُختَزَل إلى **ثلاثةِ إحداثياتٍ مغلقةٍ
#    معلنةِ الحجم** — جنسُها (اسميةٌ · فعليةٌ · شبهُ جملةٍ · حرفيةٌ · مشتبهة) و
#    علامةُ آخِرِها (أصليّةٌ رفعًا/نصبًا/جرًّا · فرعيّةٌ بالحرف · جزمٌ · عُريٌ) و
#    أسلوبُها (خبرٌ · نفيٌ · استفهامٌ · نداءٌ · شرط) — ثمّ تُوزَّع البتاتُ على
#    هذه الحقولِ بالفاتورةِ الموروثةِ وحدَها (`harakat_layer.heldout_ce`).
#    و**«اسميّة» ههنا ليست سلّةَ الباقي**: المشتبهُ يُسمّى مشتبهًا والحرفيُّ
#    حرفيًّا، فلا يُهرَّب ثمنُ الاشتباهِ إلى خانةِ الاسم — على سنّةِ `jar_gate`.
#
# §٣ والجوارُ المقيسُ عليه **الاستئنافُ نفسُه**: الحدُّ الأدنى أن تُعرَف الجملةُ
#    السابقةُ ولا يُعرَف الحرف — أي «جملةٌ تلي جملةً بلا رابطٍ مقروء». فالمكسبُ
#    ثمنُ **الحرفِ فوقَ الاستئناف**، لا ثمنُ الجوارِ فوقَ العدم. وضوابطُ المثلِ
#    **خلطُ الحروفِ وحدَها** — تُبقي الجوارَ والهامشَ وتهدم اقترانَ الحرفِ به،
#    فلا يكون الفارقُ فارقَ مقامٍ ولا فارقَ توزيع.
#
# §٤ وشاهدُ السببيةِ والمسببيةِ مقيسٌ لا مُستشهَدٌ له: قاعدةُ الشخصيةِ أنّ الفاءَ
#    للترتيبِ والتسبيبِ وأنّ الواوَ لمطلقِ الجمع. ومقتضاها **قابلٌ للتكذيب**:
#    إن كانت الفاءُ تُسبِّب فهي تنقل الحالَ، وإن كانت الواوُ تجمع فهي تُبقيه.
#    فيُقاس **نصيبُ تغيُّرِ الإحداثيِّ** تحتَ كلٍّ منهما، ويُصادَم بضوابطِ المثل.
#
# §٥ ما لا يُدَّعى — ويُختَم سقوطُه بعدده:
#    ① **الحكمُ الموضعيُّ مقامٌ ثانٍ لا يُجمَع إلى الأوّل**: أن يُقال في واوٍ
#       بعينها «هذه عاطفةٌ» دعوى أُخرى غيرُ دعوى التوزيع. وقد عُرضت على القياس
#       **بأربعةِ مفاتيحَ** فغلبَ بعضُها القاعدةَ العظمى وسقط بعضُها — و**فضلُ
#       الغالبِ رقيقٌ يُعلَن برقمِه** ولا يُكبَّر بالعبارة: فوقَ قاعدةٍ عظمى
#       تقارب ثلاثةَ أرباعٍ، فليس فصلًا حاسمًا بل فضلٌ مقيسٌ غلبَ ضوابطَ المثل.
#    ② **لا يُدَّعى أنّ الفاعليةَ والمفعوليةَ مُقامتان**: مصنِّفُ الأفعالِ الموروثُ
#       ضيّقٌ بإعلانه (القالبُ المشتركُ «مشتبهٌ» لا فعل)، فميدانُ «بعدَ فعلٍ
#       حاسمٍ» صغيرٌ **مقيسًا**. فيُعَدّ الشاهدان عدًّا ويُسمّى الميدانُ بحدِّه،
#       ولا يُسعَّران قانونًا على مقامٍ لا يحتمله.
#    ③ **لا يُدَّعى استقصاءُ أساليبِ الإنشاء**: المقيسُ ما له **شاهدٌ في البايتات**
#       من قواعدِ الشخصية (أداةُ استفهامٍ · نداءٍ · شرطٍ · نفي)، وما لا شاهدَ له
#       في الرسمِ (الأمرُ والنهيُ بالصيغةِ · التمنّي · التعجّب) يُسمّى دَينًا.
