def collide(measured):
    if not SEALED_JUMLA:
        return
    bad = [f"  {k}: مقيسٌ {measured.get(k)} ⟷ مختومٌ {v}"
           for k, v in SEALED_JUMLA.items() if measured.get(k) != v]
    if bad:
        raise JumlaError(E_SEAL, "أرقامٌ خالفت أختامَها:\n" + "\n".join(bad))


