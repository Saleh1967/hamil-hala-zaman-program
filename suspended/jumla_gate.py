def main(argv=None):
    ap = argparse.ArgumentParser(description="بابُ الجملة — تمييزُ العطفِ من الاستئناف")
    ap.add_argument("--json", metavar="PATH", help="اكتب الوديعةَ إلى مسار")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        out, measured = run()
        collide(measured)
    except JumlaError as e:
        print(f"صريخٌ [{e.code}]: {e}", file=sys.stderr)
        return e.code
    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump(out, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
    if not args.quiet:
        show(out)
    return E_OK


if __name__ == "__main__":
    sys.exit(main())
