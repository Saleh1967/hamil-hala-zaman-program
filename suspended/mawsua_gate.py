# mawsua_gate.py — الموسوعة: المحطّةُ الأولى — مدخلٌ لا يُكتَب بل يُحَلّ.
#
# ══ الحدُّ المعلن قبل كلِّ شيء ═══════════════════════════════════════════════════════
# «الموسوعة» ههنا **ليست نصًّا يُكتَب**، بل **وديعةً تُولَّد**. والفرقُ بينهما هو الفرقُ
# بين النقل والبرهان: المكتوبُ يُصدَّق بكاتبه، والمولَّدُ يُصادَم بمولِّده.
#
# ولذلك بابُ الموسوعة **لا يقيس رقمًا في خانةٍ البتّة** — على سنّةِ `mihwar_gate.py`.
# كلُّ خانةٍ في كلِّ مدخلٍ واحدةٌ من اثنتين، ولا ثالثة:
#
#   ⓵ **مُحَلَّة**: لها `(وديعةٌ · مسارٌ)` يُفتَح عند التشغيل فتُقرأ قيمتُها منه. فمن
#      أراد أن يُدخل رقمًا من عنده لم يجد له بابًا: الخانةُ لا تقبل قيمةً مكتوبة.
#   ⓶ **دَينٌ مسمًّى**: لا مسارَ لها، **فلا رقمَ لها** ولو كان معلومًا في نثرٍ أو ذاكرة.
#      ويُسمّى الدَّينُ باسمه وموضعِه. ودَينٌ يحمل رقمًا **يُسقِط الباب**.
#
# والقياسُ الجديدُ الوحيدُ في هذا الملفّ **قياسُ الموسوعة على نفسها**: كم مدخلًا منها
# رُدَّ إلى بايتات المجمَّد؟ وهو قياسٌ بمقامٍ معلنٍ وحدٍّ موروث، يُودَع كما يقع.
#
# ══ السجلّان — مغلقان مختومان يُستنفَدان ═══════════════════════════════════════════
# لا يُخترَع مدخلٌ ولا يُطوى: القائمتان تُقرآن من `madlul_v0.json` وحدَها (٢٨ اسمَ هجاء
# و٨٤ أداةً في ١١ صنفًا و٢١ فرقة)، ويُشترَط **استنفادُهما**: لا مدخلَ خارجَ القائمة،
# ولا عضوَ في القائمة بلا مدخل — وإلّا كان السجلُّ يُعفي نفسَه.
#
# ══ الخطرُ الأكبرُ الذي يحرسه هذا الباب ══════════════════════════════════════════════
# **الاسمُ ليس صورة.** «الباء» و«واو القسم» و«تاء التأنيث الساكنة» **أسماءُ** أدواتٍ،
# وليست صورًا تقع في المجمَّد. والمقيسُ في `madlul_v0` ميدانًا **٣٩ صورةً** لا ٨٤ أداة.
# فلو عُدَّت الأسماءُ صورًا لانتفخت الموسوعةُ بأرقامٍ لا مقامَ لها. ولذلك تُقاس المطابقةُ
# **بمقامين معلنين لا يُجسَران**: بالحرف · وبعد الطيِّ المختوم — والطيُّ يُستدعى من بابه
# الوحيد `dalalat_gate.fold` **استدعاءً لا نسخًا**، فلا يُولَد طيٌّ سادسٌ في الشجرة.
#
# ══ مصادفةُ العدد — تُسمّى ويُمنَع الجسرُ عليها ═════════════════════════════════════
# ٢٨ + ٨٤ = **١١٢**، وهو بعينه عددُ خلايا الحقل في `burhan/cert_generations.py`.
# وهذا **تطابقُ عدٍّ لا جسرُ مقام**: مقامُ الحقل (حرفٌ × حالة) غيرُ مقام الموسوعة
# (اسمُ هجاءٍ + أداةُ معنًى). والمنعُ **منفَّذٌ بحارسٍ** لا موصًى به بكلام: لو ادُّعي
# اشتقاقُ أحدهما من الآخر سقط الباب. والعطلُ الأمُّ في هذا المستودع خلطُ المقامات،
# وقع مرّتين وكُشف مرّتين — فلا يقع ثالثةً في الموسوعة.
#
# المخارج: 0 نجاح · 2 استعمال · 3 وديعةٌ غائبة · 4 مسارٌ لا يُحَلّ أو عددٌ خالف مختومَه.
