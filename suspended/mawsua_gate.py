def deposit(name=MADLUL):
    path = os.path.join(ROOT, name)
    if not os.path.exists(path):
        raise MawsuaError(E_MISSING, f"وديعةٌ غائبةٌ: {path}")
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def resolve(node, path, where):
    """يُحَلُّ المسارُ في الوديعة أو يُصرَخ — ولا يُسكَت عن مسارٍ لم يُفتَح."""
    for key in path:
        if isinstance(node, dict) and key in node:
            node = node[key]
        elif isinstance(node, list) and isinstance(key, int) and -len(node) <= key < len(node):
            node = node[key]
        else:
            raise MawsuaError(E_SEAL, f"مسارُ «{where}» لا يُحَلُّ في وديعته عند: {key}")
    return node


def cell(name, value, path, reason=None):
    """خانةٌ واحدة: إمّا قيمةٌ بمسار، وإمّا دَينٌ بسببٍ **بلا رقم**. ولا ثالث."""
    if path is None:
        return dict(خانة=name, حال="دَين", سبب=reason)
    return dict(خانة=name, حال="مُحَلَّة", وديعة=MADLUL, مسار=list(path), قيمة=value)


def mabna_entries(dep):
    """مداخلُ حروف المباني — ٢٨ اسمًا، وكلُّ خانةٍ تُحَلُّ بمسارها في الوديعة."""
    base = ("المدلول_v0", "خانةُ_حروف_الهجاء", "أسماءُ_الهجاء")
    roster = resolve(dep, base, "أسماءُ الهجاء")
    out = []
    for i, item in enumerate(roster):
        cells = []
        for spec in MABNA_CELLS:
            if spec["مصدر"] is None:
                cells.append(cell(spec["خانة"], None, None, spec["سببُ_الدَّين"]))
                continue
            key = spec["مفتاح"]
            p = base + (i, key)
            cells.append(cell(spec["خانة"], resolve(dep, p, spec["خانة"]), p))
        out.append(dict(مدخل=item["اسم"], سجلّ="حروف المباني", خانات=cells))
    return out


def ma3na_entries(dep, forms):
    """مداخلُ حروف المعاني — ٨٤ أداةً، وصورتُها لا تُدَّعى إلا إن وقعت في المقام."""
    base = ("المدلول_v0", "معجمُ_حروف_المعاني", "أصناف")
    classes = resolve(dep, base, "أصنافُ المعجم")
    field = {c["صنف"]: (j, c) for j, c in
             enumerate(resolve(dep, ("المدلول_v0", "معجمُ_حروف_المعاني",
                                     "ميدان", "أصناف"), "أصنافُ الميدان"))}
    fbase = ("المدلول_v0", "معجمُ_حروف_المعاني", "ميدان", "أصناف")
    out = []
    for ci, cls in enumerate(classes):
        for fi, band in enumerate(cls["فرق"]):
            for ai, tool in enumerate(band["أدوات"]):
                p0 = base + (ci, "فرق", fi, "أدوات", ai)
                cells = []
                for spec in MA3NA_CELLS:
                    nm, src = spec["خانة"], spec["مصدر"]
                    if src == "سجلّ" and nm == "صنفُها":
                        p = base + (ci, "صنف")
                        cells.append(cell(nm, resolve(dep, p, nm), p))
                    elif src == "سجلّ" and nm == "فرقتُها":
                        p = base + (ci, "فرق", fi, "فرقة")
                        cells.append(cell(nm, resolve(dep, p, nm), p))
                    elif src == "سجلّ":
                        p = p0 + (spec["مفتاح"],)
                        val = resolve(dep, p, nm)
                        # مدلولٌ غيرُ منصوصٍ **دَينٌ لا خانةٌ فارغة**: النبهانيُّ عدَّ
                        # الأداةَ ولم ينصَّ على مدلولها، فلا يُملأ عنه.
                        cells.append(cell(nm, val, p) if val is not None
                                     else cell(nm, None, None, spec["سببُ_الدَّين"]))
                    elif src == "ميدان":
                        # **الاسمُ ليس صورة**: لا تُحَلُّ الخانةُ إلا إن وقع الاسمُ
                        # مطويًّا في الصور المختومة — ولا يُخترَع ردٌّ من عندنا.
                        folded = DG.fold(tool["أداة"])
                        if folded in forms:
                            p = ("المدلول_v0", "معجمُ_حروف_المعاني", "ميدان",
                                 "المعجمُ_كلُّه", "صور", forms[folded])
                            cells.append(cell(nm, resolve(dep, p, nm), p))
                        else:
                            cells.append(cell(nm, None, None, spec["سببُ_الدَّين"]))
                    else:                                   # صنفُ الميدان
                        # **لا يُقرأ رقمٌ لصنفٍ لم يدخل الميدان**: الثلاثةُ الخارجةُ
                        # ليست فقيرةَ خانةٍ بل خارجةٌ عن المقام أصلًا — فدَينٌ لا فراغ.
                        j, row = field.get(cls["صنف"], (None, {}))
                        if j is not None and row.get("في_الميدان"):
                            p = fbase + (j, spec["مفتاح"].replace(" ", "_"))
                            cells.append(cell(nm, resolve(dep, p, nm), p))
                        else:
                            cells.append(cell(nm, None, None, spec["سببُ_الدَّين"]))
                out.append(dict(مدخل=tool["أداة"], سجلّ="حروف المعاني", خانات=cells))
    return out


def corpus_cell(entry):
    """أيُّ خانةٍ في هذا المدخل تردُّه إلى بايتات المجمَّد؟ — واحدةٌ معلنةٌ لكلِّ سجلّ."""
    want = "صورتُها في المقام" if entry["سجلّ"] == "حروف المعاني" else "مواضعُه في المجمَّد"
    for c in entry["خانات"]:
        if c["خانة"] == want:
            return c
    raise MawsuaError(E_SEAL, f"مدخلٌ بلا خانةِ مقامٍ معلنة: {entry['مدخل']}")


def closure(mabna, ma3na, roster_mabna, sealed):
    """حاكمُ الانغلاق: يُستدعى في البند ① وفي محاولة التكذيب ⑦ — دالّةٌ واحدةٌ لا نسختان."""
    outside = [e["مدخل"] for e in mabna if e["مدخل"] not in roster_mabna]
    unused = [n for n in roster_mabna if n not in {e["مدخل"] for e in mabna}]
    return {
        "مدخلٌ_خارجَ_السجلّ": outside, "عضوٌ_بلا_مدخل": unused,
        "منغلق": (len(mabna) == sealed["أسماءُ الهجاء"]
                  and len(ma3na) == sealed["أدواتٌ مُعلَنة"]
                  and not outside and not unused),
    }


def falsify(dep, forms, entries):
    """محاولاتُ تكذيبٍ تُشغَّل في كلِّ مرّة — وحارسٌ لا يعدّ غيرَ الصفر حارسٌ بلا مادّة."""
    trials = []

    # ① مدخلٌ مصنوع: صورةٌ عربيّةُ الحروف لا تقع في سجلٍّ مختوم — تُردُّ بالقائمة.
    roster = {e["مدخل"] for e in entries}
    trials.append(dict(محاولة="مدخلٌ مصنوعٌ خارجَ السجلَّين",
                       صورة="ضهزو", رُدَّ="ضهزو" not in roster))

    # ② دَينٌ يحمل رقمًا: تُصنَع خانةٌ دَينٌ ومعها قيمة، ويجب أن يصرخ المصادق.
    forged = dict(خانة="مصنوعة", حال="دَين", سبب="مصنوع", قيمة=1)
    trials.append(dict(محاولة="دَينٌ يحمل رقمًا", رُدَّ=not audit_cell(forged)))

    # ③ خانةٌ بقيمةٍ بلا مسار: القيمةُ بلا سندٍ تُردّ.
    trials.append(dict(محاولة="خانةٌ بقيمةٍ بلا مسار",
                       رُدَّ=not audit_cell(dict(خانة="مصنوعة", حال="مُحَلَّة", قيمة=7))))

    # ④ مسارٌ لا يُحَلّ: يجب أن يُصرَخ لا أن يُسكَت عنه بقيمةٍ فارغة.
    try:
        resolve(dep, ("المدلول_v0", "بابٌ لا وجودَ له"), "تكذيب")
        screamed = False
    except MawsuaError:
        screamed = True
    trials.append(dict(محاولة="مسارٌ لا يُحَلُّ في الوديعة", رُدَّ=screamed))

    # ⑤ الطيُّ ذو أثر: اسمٌ لا يقع بالحرف ويقع بعد الطيّ — وإلّا فالمقامان واحد.
    moved = [t for t in ("إلى", "على", "حتى") if t not in forms and DG.fold(t) in forms]
    trials.append(dict(محاولة="الطيُّ المختومُ بلا أثر", رُدَّ=bool(moved),
                       أمثلة=moved[:3]))

    # ⑥ جسرُ الـ١١٢: يُعرَض الادّعاءُ صريحًا ويُردّ — المقامان لا يُشتَقّ أحدُهما من الآخر.
    trials.append(dict(محاولة="جسرُ ١١٢ خليّةً بـ١١٢ مدخلًا",
                       رُدَّ=BRIDGE_BAN["الحكم"].startswith("تطابقُ عدٍّ")))

    # ⑦ سجلٌّ غيرُ مستنفَد: يُنقَص مدخلٌ حقيقيٌّ من السجلّ، فيجب أن يُسقِطَه حاكمُ
    #    الانغلاق نفسُه الذي حكمَ في البند ①. حارسٌ لا يُشغَّل على مادّةٍ ناقصةٍ
    #    حارسٌ بلا مادّة — فالنقصُ يُصنَع هنا ويُعرَض أثرُه.
    roster_m = [x["اسم"] for x in resolve(
        dep, ("المدلول_v0", "خانةُ_حروف_الهجاء", "أسماءُ_الهجاء"), "س")]
    sealed = dep["المدلول_v0"]["مقيس"]
    mabna = [e for e in entries if e["سجلّ"] == "حروف المباني"]
    ma3na = [e for e in entries if e["سجلّ"] == "حروف المعاني"]
    whole = closure(mabna, ma3na, roster_m, sealed)
    maimed = closure(mabna[:-1], ma3na, roster_m, sealed)
    trials.append(dict(محاولة="سجلٌّ غيرُ مستنفَد",
                       رُدَّ=whole["منغلق"] and not maimed["منغلق"],
                       أعضاءٌ_بلا_مدخلٍ_بعد_النقص=len(maimed["عضوٌ_بلا_مدخل"])))

    return trials


def audit_cell(c):
    """صدقُ الخانة: المُحَلَّةُ لها مسارٌ وقيمة، والدَّينُ له سببٌ **ولا قيمةَ له**."""
    if c["حال"] == "دَين":
        return "قيمة" not in c and bool(c.get("سبب"))
    return "مسار" in c and "قيمة" in c


def run(as_json=None, as_md=None):
    dep = deposit()
    M = dep["المدلول_v0"]
    sealed = M["مقيس"]

    # الصورُ المختومةُ وحدَها مرجعَ الردِّ إلى المقام — ٣٩ صورةً لا ٨٤ اسمًا.
    all_forms = resolve(dep, ("المدلول_v0", "معجمُ_حروف_المعاني", "ميدان",
                              "المعجمُ_كلُّه", "صور"), "صورُ المعجم")
    forms = {s: i for i, s in enumerate(all_forms)}

    entries = mabna_entries(dep) + ma3na_entries(dep, forms)
    mabna = [e for e in entries if e["سجلّ"] == "حروف المباني"]
    ma3na = [e for e in entries if e["سجلّ"] == "حروف المعاني"]

    cells = [c for e in entries for c in e["خانات"]]
    resolved = [c for c in cells if c["حال"] == "مُحَلَّة"]
    debts = [c for c in cells if c["حال"] == "دَين"]
    unsound = [c for c in cells if not audit_cell(c)]

    fails, rows = [], {}

    # ── ① انغلاقُ السجلَّين: العددُ مُصادَمٌ بمختومه، والاستنفادُ مقيسٌ لا مدَّعًى ──
    roster_mabna = [x["اسم"] for x in
                    resolve(dep, ("المدلول_v0", "خانةُ_حروف_الهجاء", "أسماءُ_الهجاء"), "س")]
    shut = closure(mabna, ma3na, roster_mabna, sealed)
    outside, unused, closed = (shut["مدخلٌ_خارجَ_السجلّ"], shut["عضوٌ_بلا_مدخل"],
                               shut["منغلق"])
    rows["① انغلاقُ السجلَّين"] = {
        "مداخلُ_المباني": len(mabna), "مختومُ_المباني": sealed["أسماءُ الهجاء"],
        "مداخلُ_المعاني": len(ma3na), "مختومُ_المعاني": sealed["أدواتٌ مُعلَنة"],
        "مداخلُ_جملةً": len(entries),
        "مدخلٌ_خارجَ_السجلّ": outside, "عضوٌ_بلا_مدخل": unused,
        "حكم": "تحقَّق" if closed else "سقط",
    }
    if not closed:
        fails.append(f"① السجلّان لم ينغلقا: {rows['① انغلاقُ السجلَّين']}")

    # ── ② الاسمُ ليس صورة: مقامان يُعرَضان ولا يُجمَعان ───────────────────────────
    #     ومقامُ هذا البند **الأسماءُ المميّزةُ لا المداخل**: الأداةُ تتكرّر في أصناف،
    #     فلو قيست المطابقةُ على المداخل لَحُسب الاسمُ الواحدُ مرّتين.
    names = sorted({e["مدخل"] for e in ma3na})
    literal = sorted(n for n in names if n in forms)
    folded = sorted(n for n in names if DG.fold(n) in forms)
    effect = len(folded) > len(literal)
    rows["② الاسمُ ليس صورة"] = {
        "مطابقةٌ_بالحرف": len(literal),
        "مطابقةٌ_بعد_الطيِّ_المختوم": len(folded),
        "مقامُ_المطابقتَين": "أسماءٌ مميّزةٌ لا مداخل — ولا تُجمَع بمقام المداخل",
        "أسماءٌ_مميّزةٌ_لا_صورةَ_لها": len(names) - len(folded),
        "أسماءٌ_مميّزة": len(names),
        "صورُ_المقامِ_المختومة": len(all_forms),
        "أسماءُ_الأدواتِ_المُعلَنة": len(ma3na),
        "المقامان_لا_يُجمَعان": "نعم",
        "حكم": "تحقَّق" if effect else "سقط",
    }
    if not effect:
        fails.append("② الطيُّ المختومُ بلا أثر — المقامان واحدٌ فالحارسُ بلا مادّة")

    # ── ③ الموسوعةُ لا تكتمل بالنقل: مقامُه المداخلُ، وحدُّه موروثٌ يُستدعى ──────────
    grounded = [e for e in entries if corpus_cell(e)["حال"] == "مُحَلَّة"]
    # الحَكَمُ يُستدعى ولا يُنسَخ: `degenerate` يردُّ (النسبةَ · أمنحلٌّ هي؟) — فتُؤخَذ
    # النسبةُ من الحَكَم نفسِه لا من قسمةٍ ثانيةٍ عندنا، وإلّا وُلِد مكيالٌ سادس.
    share, is_deg = degenerate(len(grounded), len(entries))
    below = not is_deg
    # **وقع العددُ على الحدِّ بعينه**: 56 من 112 = ½ تمامًا، وحدُّ الحارس صارمٌ (> ½)،
    # فالحكمُ قائمٌ بشعرة. ويُسمّى هذا ولا يُطوى: لو رُدَّ مدخلٌ واحدٌ زائدًا إلى
    # المجمَّد لانقلب البندُ — فالنتيجةُ **غيرُ متينةٍ بإعلانٍ** لا بسكوت.
    on_edge = abs(share - HALF) < 1e-9
    rows["③ الموسوعةُ لا تكتمل بالنقل"] = {
        "مداخلُ_لها_خانةٌ_من_المجمَّد": len(grounded),
        "مداخلُ_جملةً": len(entries),
        "نصيبُها": share,
        "الحدُّ_الموروث": HALF,
        "حدُّ_الحارسِ_صارم": "نعم — منحلٌّ إن جاوز ½، فالمساواةُ تنجو",
        "على_الحدِّ_بعينه": "نعم" if on_edge else "لا",
        "لو_زاد_مدخلٌ_واحد": "لانقلب البندُ — فالنتيجةُ غيرُ متينةٍ بإعلان",
        "من_المباني": sum(1 for e in grounded if e["سجلّ"] == "حروف المباني"),
        "من_المعاني": sum(1 for e in grounded if e["سجلّ"] == "حروف المعاني"),
        "حكم": "تحقَّق" if below else "سقط",
    }
    if not below:
        fails.append(f"③ نصيبُ المردودِ إلى المجمَّد {share} منحلٌّ بالحدِّ الموروث")

    # ── ④ لا خانةَ بلا سند ───────────────────────────────────────────────────────
    rows["④ لا خانةَ بلا سند"] = {
        "خانات": len(cells), "مُحَلَّة": len(resolved), "دَين": len(debts),
        "خاناتٌ_بلا_سند": len(unsound),
        "حكم": "تحقَّق" if not unsound else "سقط",
    }
    if unsound:
        fails.append(f"④ {len(unsound)} خانةً بلا سندٍ — قيمةٌ بلا مسارٍ أو دَينٌ برقم")

    # ديونُ «مدلولٍ منصوص» تُصادَم بمختومها: ٢٤ في `madlul_v0` — فلا تنزاح صامتةً.
    no_madlul = sum(1 for c in cells
                    if c["خانة"] == "مدلولٌ منصوص" and c["حال"] == "دَين")
    if no_madlul != sealed["أدواتٌ بلا مدلولٍ منصوص"]:
        fails.append(f"ديونُ المدلول {no_madlul} خالفت مختومَها "
                     f"{sealed['أدواتٌ بلا مدلولٍ منصوص']}")

    trials = falsify(dep, forms, entries)
    for t in trials:
        if not t["رُدَّ"]:
            fails.append(f"محاولةُ تكذيبٍ لم تُردّ: {t['محاولة']}")

    suspended = dict(SUSPENDED["⑤ نصيبُ الخانات جملةً"])
    suspended.update({"خاناتٌ_مُحَلَّة": len(resolved), "خانات": len(cells),
                      "نصيب": round(len(resolved) / len(cells), 4)})

    broken = [k for k, v in rows.items() if v["حكم"] == "سقط"]
    out = {
        "الموسوعة_v0": {
            "الحدّ": "مدخلٌ لا يُكتَب بل يُحَلّ — كلُّ خانةٍ مسارٌ في وديعةٍ "
                     "أو دَينٌ مسمًّى بلا رقم، ولا ثالث",
            "المصدر": "madlul_v0.json — سجلّان مغلقان مختومان",
            "دعاوى_مسجَّلةٌ_قبل_التشغيل": CLAIMS,
            "منعُ_جسرِ_١١٢": BRIDGE_BAN,
            "بنود": rows,
            "معلَّق": suspended,
            "مداخل": entries,
            "محاولاتُ_التكذيب": trials,
            "مقيس": {
                "مداخل": len(entries),
                "مداخلُ_المباني": len(mabna),
                "مداخلُ_المعاني": len(ma3na),
                "خانات": len(cells),
                "خاناتٌ_مُحَلَّة": len(resolved),
                "ديونٌ_مسمّاةٌ_بلا_رقم": len(debts),
                "خاناتٌ_بلا_سند": len(unsound),
                "مداخلُ_مردودةٌ_إلى_المجمَّد": len(grounded),
                "نصيبُ_المردودِ_إلى_المجمَّد": round(share, 4),
                "مطابقةٌ_بالحرف": len(literal),
                "مطابقةٌ_بعد_الطيّ": len(folded),
                "بنودٌ_محكومة": len(rows),
                "بنودٌ_ساقطة": len(broken),
                "أسماءُ_الساقطة": broken,
                "محاولاتُ_تكذيب": len(trials),
            },
            "حكم": "خضراء" if not fails else "ساقطة",
            "مآخذ": fails,
        }
    }

    print("— الموسوعة: المحطّةُ الأولى —")
    for name, r in rows.items():
        print(f"    {name}: {r['حكم']}")
        for k, v in r.items():
            if k == "حكم" or v in (None, [], {}):
                continue
            print(f"        {k}: {v:,}" if isinstance(v, int) else f"        {k}: {v}")
    print(f"    ⑤ [معلَّق] نصيبُ الخانات جملةً: {suspended['نصيب']} "
          f"({suspended['خاناتٌ_مُحَلَّة']:,} من {suspended['خانات']:,}) — يُعرَض ولا يُحتَجُّ به")
    print(f"    محاولاتُ تكذيبٍ رُدَّت: {sum(1 for t in trials if t['رُدَّ'])}/{len(trials)}")
    for f in fails:
        print(f"::error::{f}")
    print(f"    {'✓' if not fails else '✗'} مداخلُ {len(entries)} · "
          f"مُحَلَّةٌ {len(resolved):,} · ديونٌ مسمّاةٌ {len(debts):,}")

    if as_json:
        with open(as_json, "w", encoding="utf-8") as fh:
            json.dump(out, fh, ensure_ascii=False, indent=1)
    if as_md:
        with open(as_md, "w", encoding="utf-8") as fh:
            fh.write(write_doc(out))
    return 0 if not fails else 1


def write_doc(out):
    """الوثيقةُ مولَّدةٌ من الوديعة: لا رقمَ فيها يُكتَب بيدٍ، وكلُّها مُصادَمةٌ في CI."""
    D = out["الموسوعة_v0"]
    m, L = D["مقيس"], []
    a = L.append
    a("# الموسوعة — المحطّةُ الأولى\n")
    a("> **هذه الوثيقةُ مولَّدةٌ.** تُكتَب بـ`python mawsua_gate.py --md MAWSUA.md`،")
    a("> وتُصادَم في CI بايتًا بايتًا. لا يُحرَّر منها سطرٌ بيد.\n")
    a("## ① ما هي الموسوعة هنا\n")
    a("ليست الموسوعةُ نصًّا يُكتَب، بل **وديعةً تُولَّد**. المدخلُ فيها جدولُ خانات،")
    a("وكلُّ خانةٍ لا تخرج عن حالَين لا ثالثَ لهما:\n")
    a("- **مُحَلَّة** — لها `وديعة` و`مسار` و`قيمة` تُقرَأ من الوديعة عند التشغيل.")
    a("- **دَينٌ مسمًّى** — له `سبب` و**لا قيمةَ له البتّة**. الدَّينُ يُسمّى ولا يُرقَّم.\n")
