# wasl_gate.py — بابُ الوصل: أيَفصِلُ ألفُ الوصلِ اسمَه من فعلِه؟
#
# ــ ٠) الدعوى المقيسة ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# خلَّفَ `sigha_gate` ضجيجًا **مسمًّى لا مطويًّا**: خليّةُ «أمر · سالم» نقاؤها
# ٠٫٧٨٥٧ وفي صورِ دَينِها **ابن · اسم · اثنين** — أسماءٌ لا أفعال. وعلّتُها
# مُعلَنةٌ في قاعدةِ الأمرِ نفسِها: صدرُها **ألفٌ عاريةٌ ساكنةُ الفاء**، وتلك
# **ألفُ الوصلِ** لا علامةُ أمرٍ — تقع في الأمرِ وتقع في أسماءٍ معدودةٍ وفي
# مصادرِ الخماسيِّ والسداسيّ. فالدعوى ههنا:
# **أنّ ميدانَ ألفِ الوصلِ ينقسم طبقتين تفصلهما قائمةٌ مغلقةٌ موروثةٌ من
# النحاةِ — لا معجمٌ ولا تحليلٌ — وأنّ الفصلَ يسدِّد دَينًا ويُصلِح نقاءً قائمًا.**
#
#   • **الطبقتان مولَّدتان قِسمةً تامّةً**: «اسمُ وصلٍ معدود» ⟷ «باقي الوصل».
#     لا ثالثةَ ولا بقيّةَ: كلُّ موضعٍ في الميدانِ يقع في واحدةٍ منهما بالبناء.
#   • **والقائمةُ مغلقةٌ مُسعَّرةٌ قبلَ أن تُستعمَل** بـ`ta3allum_gate.declaration_cost`
#     — إحدى عشرةَ صورةً هي أسماءُ الوصلِ المعدودةُ عند النحاة، لا صورةً
#     تُزاد بعدَ رؤية الجدول.
#   • **والحَكَمُ مصنِّفٌ مستقلٌّ لا القاعدةُ نفسُها**: قسمةُ `tamakkun_gate`
#     الثلاثيّةُ المختومة. ونقاءُ الطبقةِ نصيبُ **قسمِها الغالبِ** من مصنَّفِها
#     وحدَه، والدَّينُ خارجَ المقام.
#   • **والحدُّ موروث**: `1 − ta3allum_gate.COVER_CEILING`.
#
# ــ ١) ما سقطَ ههنا ويُودَع كما يُودَع الناجح ــــــــــــــــــــــــــــــــــــــ
#   • **«بن» ⟷ «ابن»**: قاعدةُ حذفِ الألفِ بين علمين لا ميدانَ لها في
#     المجمَّد البتّة — «بن» محذوفةَ الألفِ **صفرُ موضع**. فهي تُودَع **صفرًا
#     مقيسًا** لا تُطوى ولا يُدَّعى نفعُها.
#   • **«الألفُ عنصرٌ محايد»**: تُقاس بفاتورةِ الوصفِ الأدنى — كلفةُ إسقاطِ
#     كلِّ حرفٍ من الهيكلِ منسوبةً إلى عددِ مواضعه. والحيادُ رتبةٌ أولى بقربٍ
#     من الصفر؛ والألفُ **لم تنلها**، فالدعوى **ساقطةٌ برقمها** لا بردٍّ.
#   • **وضوابطُ المثل تُساوي المرصودَ في عدِّ الطبقاتِ وفي الدَّين**: لا يفصل
#     المرصودَ عنها إلا **عددُ الأقسامِ الغالبةِ المتمايزة**. وهذا يُعلَن:
#     الإحصاءُ المميِّزُ واحدٌ لا ثلاثة، والاثنان الآخران لا يحملان خبرًا.
#
# ــ ٢) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا تُمَسُّ وديعةُ `sigha_v0.json` ولا أختامُها ولا وديعةُ التمكّن: هذا بابٌ
#     **فوقَهما** يقرأ أرقامَهما ويقيس الإصلاحَ **قياسًا حيًّا**، ولا يكتب فيهما.
#   • ولا يُدَّعى أنّ الطبقةَ الاسميّةَ خالصة: نقاؤها **مقيسٌ مودَع** (ومن
#     صورِها «ابنوا» وهو أمرٌ بحقّ) — فالقائمةُ تُصيب وتُخطئ بعددها.
#   • والسدادُ ههنا **ليس مضافًا إلى سدادِ بابِ الصيغة**: المشتركُ بينهما
#     مقيسٌ مودَعٌ، والجديدُ وحدَه هو ما لم يكن بابُ الصيغةِ يسدِّده.
