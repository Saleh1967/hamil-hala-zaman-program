# ═══ ④ محطّةُ ضوابط المثل — أيُّ إحصاءٍ يحمل خبرًا؟ ═══════════════════════════
def _score(labels, verdicts):
    t = collections.defaultdict(collections.Counter)
    for k, q in zip(labels, verdicts):
        t[k][q or "دَين"] += 1
    bands = paid = 0
    tops = set()
    for c in t.values():
        top, pur, classified = naqa_of(c)
        if classified and pur > NAQA_BAR and c["دَين"] > 0:
            bands += 1
            paid += c["دَين"]
            tops.add(top)
    return bands, paid, len(tops)


def mithl_station(rows, paying):
    labels = [k for k, _, _ in rows]
    verdicts = [q for _, q, _ in rows]
    obs = _score(labels, verdicts)
    rng = random.Random(TG.CONTROL_SEED)
    hi = (-1, -1, -1)
    for _ in range(CONTROL_TRIALS):
        sh = labels[:]
        rng.shuffle(sh)
        hi = tuple(max(a, b) for a, b in zip(hi, _score(sh, verdicts)))
    if obs[0] != len(paying):
        raise WaslError(E_SHAPE, "عدُّ الطبقاتِ المسدِّدةِ اختلفَ بين محطّتين")
    return {
        "ضوابطُ_المثل": CONTROL_TRIALS,
        "طبقاتٌ_تسدِّدُ_مرصودة": obs[0],
        "أعلى_طبقاتٍ_في_المثل": hi[0],
        "دَينٌ_يُسدَّدُ_مرصود": obs[1],
        "أعلى_دَينٍ_في_المثل": hi[1],
        "أقسامٌ_غالبةٌ_متمايزةٌ_مرصودة": obs[2],
        "أعلى_أقسامٍ_متمايزةٍ_في_المثل": hi[2],
        "غلبَ_المثلَ": bool(obs[2] > hi[2]),
        "بيان": ("عددُ الطبقاتِ والدَّينُ المسدَّدُ **لا يحملان خبرًا**: يَبلغهما "
                 "المثلُ بخلطِ الأسماء. والفاصلُ إحصاءٌ واحدٌ لا ثلاثة — "
                 "**عددُ الأقسامِ الغالبةِ المتمايزة**: المرصودُ يفصل قسمين، "
                 "والمثلُ يجعل الطبقتين غالبَهما واحدٌ. فالخبرُ في الفصلِ لا في الكثرة"),
    }


# ═══ ⑤ محطّةُ الإصلاح — أرقامٌ قائمةٌ في بابِ الصيغةِ تُقاس قبلَ وبعد ═════════
def islah_station():
    """إعادةُ قياسِ خلايا `sigha_gate` **بطرحِ أسماءِ الوصل** — قياسًا حيًّا لا
    تعديلًا: وديعةُ `sigha_v0.json` لا تُمَسّ، وإنّما يُقاس فرقُ نقائها."""
    cells = collections.defaultdict(collections.Counter)
    after = collections.defaultdict(collections.Counter)
    for words in TK.corpus():
        for i, w in enumerate(words):
            k = SG.khalya_of(w)
            if not k:
                continue
            q = TK.qism_of(words, i) or "دَين"
            cells[k][q] += 1
            if not is_asm_wasl(HL.skel(w)):
                after[k][q] += 1
    rows, improved, worsened = [], 0, 0
    for k in sorted(cells, key=lambda x: (x[0], x[1])):
        b, a = cells[k], after[k]
        if b == a:
            continue
        _, pb, cb = naqa_of(b)
        _, pa, ca = naqa_of(a)
        if not (cb and ca):
            continue
        d = round(pa - pb, 4)
        rows.append({
            "الخليّة": f"{k[0]}-{k[1]}", "ميدانٌ_قبل": sum(b.values()),
            "ميدانٌ_بعد": sum(a.values()), "مطروح": sum(b.values()) - sum(a.values()),
            "نقاءٌ_قبل": round(pb, 4), "نقاءٌ_بعد": round(pa, 4), "فرق": d,
        })
        improved += d > 0
        worsened += d < 0
    if not rows:
        raise WaslError(E_SHAPE, "لا خليّةَ تأثّرت — فالإصلاحُ دعوى بلا ميدان")
    best = max(rows, key=lambda r: r["فرق"])
    return {
        "خلايا_تأثّرت": len(rows),
        "خلايا_ارتفعَ_نقاؤها": improved,
        "خلايا_انخفضَ_نقاؤها": worsened,
        "مواضعُ_طُرِحت": sum(r["مطروح"] for r in rows),
        "أعلى_ارتفاعِ_نقاء": best["فرق"],
        "خليّةُ_أعلى_ارتفاع": best["الخليّة"],
        "الجدول": rows,
    }


# ═══ ⑥ محطّةُ السداد — ولا يُمَسُّ مصنَّفٌ قائم ═══════════════════════════════
def sadad_station(rows, paying, qis):
    pay = {r["الطبقة"]: r["القسمُ_الغالب"] for r in paying}
    moved = collections.Counter()
    noise = collections.defaultdict(collections.Counter)
    paid = collections.Counter()
    shared = alone = 0
    for words in TK.corpus():
        for i, w in enumerate(words):
            s, m = HL.skel(w), TK.masked(w)
            if not is_wasl(s, m) or s[1] == "ل":
                continue
            k = tabaqa_of(s)
            if k not in pay:
                continue
            if TK.qism_of(words, i) is None:
                paid[pay[k]] += 1
                noise[k][s] += 1
                if SG.khalya_of(w):
                    shared += 1
                else:
                    alone += 1
            else:
                moved[TK.qism_of(words, i)] += 1
    total = sum(paid.values())
    before = dict(qis["الأقسامُ_الثلاثة"])
    after = dict(before)
    for q, n in paid.items():
        after[q] += n
    dayn_after = qis["دَينُ_المصنِّف"] - total
    if sum(after.values()) + dayn_after != qis["مواضعُ_المقام"]:
        raise WaslError(E_SHAPE, "رحلةُ السداد لم تُغلَق")
    if any(after[k] < before[k] for k in before):
        raise WaslError(E_SHAPE, "السدادُ أنقصَ قسمًا — وهو لا يمسُّ إلا الدَّين")
    if shared + alone != total:
        raise WaslError(E_SHAPE, "قِسمةُ المشتركِ والجديدِ لم تُغلَق")
    return {
        "طبقاتٌ_مسدِّدة": len(paying),
        "دَينٌ_سُدِّدَ": total,
        "موزَّعًا_على_الأقسام": dict(paid),
        "مشتركٌ_مع_بابِ_الصيغة": shared,
        "جديدٌ_لا_يسدِّدُه_بابُ_الصيغة": alone,
        "دَينٌ_باقٍ": dayn_after,
        "مصنَّفاتٌ_قائمةٌ_في_الطبقاتِ_المسدِّدة": dict(moved),
        "القسمةُ_قبل": before,
        "القسمةُ_بعد": after,
        "صورُ_الدَّينِ_المسدَّد": {k: [f for f, _ in noise[k].most_common(4)]
                          for k in sorted(noise)},
    }


# ═══ ⑦ محطّةُ الحياد — دعوى «الألفُ عنصرٌ محايد» تُقاس فتسقط برقمها ══════════
def hiyad_station():
    """حيادُ الحرف: أن يكون إسقاطُه من الهيكلِ **لا يغيّر فاتورةَ الوصف**.

    فيُقاس Δ لكلِّ حرفٍ من أكثرِ `HURUF_N` حروفًا ورودًا، منسوبًا إلى عددِ
    مواضعه — ثمّ تُرتَّب الحروفُ بقربِها من الصفر. والمحايدُ صاحبُ الرتبةِ
    الأولى؛ فإن لم تنلها الألفُ فهي **تحمل خبرًا** ودعوى الحيادِ ساقطة.
    """
    base = [HL.skel(w) for words in TK.corpus() for w in words]
    L0 = DL.price(base, 0)["كلفة"]
    freq = collections.Counter(c for s in base for c in s)
    rows = []
    for ch, n in freq.most_common(HURUF_N):
        dropped = ["".join(c for c in s if c != ch) or "∅" for s in base]
        d = DL.price(dropped, 0)["كلفة"] - L0
        rows.append({"حرف": ch, "مواضع": n, "فرقُ_الفاتورة": round(d, 1),
                     "فرقٌ_للموضع": round(d / n, 4)})
    rows.sort(key=lambda r: abs(r["فرقٌ_للموضع"]))
    rank = next(i + 1 for i, r in enumerate(rows) if r["حرف"] == "ا")
    alef = rows[rank - 1]
    return {
        "حروفٌ_قِيسَت": len(rows),
        "فرقُ_الألفِ_للموضع": alef["فرقٌ_للموضع"],
        "رتبةُ_الألفِ_في_القربِ_من_الحياد": rank,
        "أقربُ_حرفٍ_إلى_الحياد": rows[0]["حرف"],
        "فرقُ_الأقربِ_للموضع": rows[0]["فرقٌ_للموضع"],
        "الألفُ_محايدة": bool(rank == 1),
        "الجدول": rows,
        "بيان": ("الحيادُ رتبةٌ أولى بقربٍ من الصفر. والألفُ ليست أقربَ "
                 "الحروفِ إليه، فإسقاطُها **يُنقِص الفاتورة** أكثرَ ممّا "
                 "يُنقِصه إسقاطُ حروفٍ أقلَّ ورودًا منها — أي أنّها تحمل "
                 "خبرًا في الهيكل. فدعوى «الألفُ عنصرٌ محايد» **ساقطةٌ "
                 "برقمها**، وتُودَع ساقطةً كما يُودَع القائم"),
    }


