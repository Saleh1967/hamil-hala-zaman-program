# ═══ ① ميدانُ ألفِ الوصل — من الرسمِ والحركةِ وحدَهما ═════════════════════════
def is_wasl(s, m):
    """ألفُ وصلٍ: صدرُ الهيكلِ ألفٌ **عاريةٌ** — لا مهموزةٌ ولا محرَّكة."""
    return len(s) >= 2 and s[0] == "ا" and m[0][1] == "عري"


def is_asm_wasl(s):
    """من أسماءِ الوصلِ المعدودة — بصدرِ الهيكلِ لا بتمامِه."""
    return any(s.startswith(p) for p in ASMA_WASL)


def tabaqa_of(s):
    """طبقةُ الموضع — والقِسمةُ تامّةٌ بالبناء."""
    return TABAQAT[0] if is_asm_wasl(s) else TABAQAT[1]


def rows_of():
    """(طبقة · حكمُ المصنِّفِ المستقلِّ · صورة) لكلِّ موضعٍ من ميدانِ الوصل،
    مطروحًا منه **لامُ التعريف** — فألفُها ألفُ وصلٍ بحقٍّ لكنّها مطروحةٌ في
    `sigha_gate` بإعلانٍ سابق، فلا تُحاكَم مرّتين."""
    field = taarif = 0
    out = []
    for words in TK.corpus():
        for i, w in enumerate(words):
            s, m = HL.skel(w), TK.masked(w)
            if not is_wasl(s, m):
                continue
            field += 1
            if s[1] == "ل":
                taarif += 1
                continue
            out.append((tabaqa_of(s), TK.qism_of(words, i), s))
    return out, field, taarif


def maydan_station(rows, field, taarif):
    seen = {t for t, _, _ in rows}
    unknown = seen - set(TABAQAT)
    if unknown:
        raise WaslError(E_FIELD, f"طبقةٌ خارجَ القِسمةِ المُعلَنة: {sorted(unknown)}")
    if field != taarif + len(rows):
        raise WaslError(E_SHAPE, "ميدانُ الوصلِ لم يُغلَق")
    return {
        "مواضعُ_ألفِ_الوصل": field,
        "منها_لامُ_التعريف": taarif,
        "ميدانُ_المحاكمة": len(rows),
        "طبقاتٌ_مُعلَنة": len(TABAQAT),
        "طبقاتٌ_أصابت": len(seen),
        "صورٌ_في_القائمةِ_المغلقة": len(ASMA_WASL),
        "ثمنُ_إعلانِ_القائمة": round(TG.declaration_cost(ASMA_WASL), 1),
    }


# ═══ ② محطّةُ الطبقتين — الحَكَمُ مصنِّفٌ مستقلّ، والدَّينُ خارجَ المقام ═══════
def naqa_of(c):
    """(القسمُ الغالبُ · نقاؤه من المصنَّفِ وحدَه · عدُّ المصنَّف)."""
    classified = sum(c[q] for q in TK.AQSAM)
    top = max(TK.AQSAM, key=lambda q: (c[q], q))
    return top, (c[top] / classified if classified else 0.0), classified


def tabaqat_station(rows):
    t = collections.defaultdict(collections.Counter)
    for k, q, _ in rows:
        t[k][q or "دَين"] += 1
    forms = collections.defaultdict(collections.Counter)
    for k, _, s in rows:
        forms[k][s] += 1
    table, paying = [], []
    for k in TABAQAT:
        c = t.get(k)
        if not c:
            continue
        top, pur, classified = naqa_of(c)
        pays = bool(pur > NAQA_BAR and c["دَين"] > 0)
        row = {
            "الطبقة": k, "ميدان": sum(c.values()),
            "اسم": c["اسم"], "فعل": c["فعل"], "حرف": c["حرف"], "دَين": c["دَين"],
            "مصنَّف": classified, "القسمُ_الغالب": top, "نقاء": round(pur, 4),
            "تسدِّد": pays,
            "صور": [f for f, _ in forms[k].most_common(5)],
        }
        table.append(row)
        if pays:
            paying.append(row)
    return table, paying


