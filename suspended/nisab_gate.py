# ═══ أدواتُ السطحِ المشتركة ═══════════════════════════════════════════════════
def strip_pre(s):
    """نزعُ اللواصقِ الرسميّةِ للكشفِ عن «ال» وحدَها — إخراجٌ لا قلع، ولا جذعَ يُدَّعى."""
    t = s
    while t[:1] in PRE and len(t) > 2:
        t = t[1:]
    return t


def is_definite(s):
    return strip_pre(s).startswith("ال")


def gender_of(s):
    if s.endswith("ات"):
        return "مؤنث/جمع"
    if s.endswith("ة"):
        return "مؤنث/مفرد"
    return "غير موسوم"


def number_of(s):
    if s.endswith(("ون", "ين", "ات")):
        return "جمع-وسم"
    if s.endswith("ان"):
        return "مثنى-وسم"
    return "مفرد-وسم"


def sarf_coord(s):
    """إحداثيُّ اللفظِ المفرد: (جنس·عدد) — دالّةٌ في الصورةِ وحدَها، بلا معجم."""
    return gender_of(s) + "·" + number_of(s)


def is_mu3tall(s):
    return s[-1:] in ILLA


def ce(keys, targets, m):
    """بتّ/موضعٍ خارجَ العيّنة بسياسة `harakat_layer` عينِها — وحجمُ الحقلِ معلن."""
    if len(keys) != len(targets):
        raise NisabError(E_USAGE, "طولُ المكيال خالفَ طولَ الموصوف")
    if len(keys) < MIN_N:
        raise NisabError(E_SEAL, f"مقامٌ دونَ حدِّ العيّنة {MIN_N} — لا حكمَ عليه")
    return HL.heldout_ce(list(zip(keys, targets)), 0, m)


