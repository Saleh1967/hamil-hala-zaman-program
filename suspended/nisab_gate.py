# nisab_gate.py — بابُ النسبِ وجبرِ الإحداثيات: أتُشترى النسبةُ بالبتّ، وأيُرفَع
#                 دَينُ منعِ الصرفِ بالإحداثيِّ بدلَ وكيلِ الرسم؟
#
# §٠ الدعوى المعروضةُ للقياس — من درس بناء القواعد عند النبهاني («أبحاث اللغة»،
#    الشخصية ج٣): التركيبُ ثلاثُ نسبٍ — **إسناديّةٌ** (مُسنَدٌ ومُسنَدٌ إليه) و
#    **تضمينيّةٌ** (حرفٌ يُضمِّن ما بعدَه معناه) و**تقييديّةٌ** (وصفٌ وإضافةٌ تُقيِّد).
#    وكلُّ نسبةٍ تُعلَن ههنا **زوجًا متجاورًا بشرطٍ سطحيّ**، ثمّ تُعرَض للتكذيب.
#
# §١ الجبرُ حاكمٌ لا محكوم. لا يُسأل الميزانُ «أصدَقت النسبة؟» — بل تُتَمُّ
#    إحداثياتُ اللفظِ المفرد وتُوزَّع على الحقولِ المغلقة، ويُقرأ الحكمُ من
#    التوزيع. والفاتورةُ واحدةٌ موروثةٌ (`harakat_layer.heldout_ce`، تدريبٌ/اختبارٌ
#    متناوبان، α=1، وحجمُ الحقلِ **وسيطٌ معلن** لا ثابتٌ مضمر) لا عدّادٌ جديد.
#
# §٢ وجوارُ النسبةِ **المقامُ العاري لإحداثيِّ التالي**، لا صورتُه. والعلّةُ
#    مُعلَنةٌ لئلّا يقعَ ما وقع في `mirror.py`: الإحداثيُّ **دالّةٌ في الصورة**،
#    فلو شُرِط بالصورةِ لجاء المكسبُ صفرًا بالبناءِ لا بالقياس. فالمقيسُ ههنا
#    **ما تحمله السابقةُ عن التالية**، وضوابطُ المثلِ **خلطُ الأزواج** — فتُبقي
#    الهامشَ كما هو وتهدم الاقتران، فلا يكون الفارقُ فارقَ مقامٍ ولا فارقَ هامش.
#
# §٣ ومنعُ الصرفِ ههنا **لا يُقاس بوكيلِ رسمٍ** — فذاك حُجِر في `mabna_gate`
#    بخطئه المقيس 31.82%. بل بجبرِ الإحداثيات: صنفٌ **يُشتَقُّ من السطحِ وحدَه**
#    (معرَبٌ بتعدُّدِ العلامة · يرفع بالضمّة · لا يُنوَّن · يُجَرُّ بالفتحة ·
#    صحيحُ الآخِر · ليس أداةً ولا صدرًا فعليًّا)، ويُحاكَم **بصدقِه خارجَ موضعِه**:
#    أتَثبُت علامةُ جرِّ الصورةِ في موضعٍ حُجِب عن مُتنبِّئِه؟ — وهذا قياسٌ لا
#    يحتاج وزنًا ولا معجمًا، فيُرفَع به الدَّينُ أو يُثبَّت.
#
# §٤ ما لا يُدَّعى: لا يُقرَأ من هذا الباب أنّ العواملَ اللفظيةَ تسعةٌ وتسعون
#    ولا مئةٌ ولا مئةٌ واثنتا عشرة — بل يُقاس **ما يُحسَب سطحُه** من معجمِ
#    الشخصيةِ نفسِه، وتُصادَم الدعوى المُعلَنةُ بعددِه فيُسمّى الفرق. ولا يُدَّعى
#    أنّ العاملَ المعنويَّ أُقيم أو أُبطِل — بل يُسمّى دَينًا **بحدٍّ مقيسٍ**:
#    عدَّةُ المواضعِ التي لا عاملَ لفظيًّا فيها، وهي الميدانُ الذي عليه أن يسعَه.
