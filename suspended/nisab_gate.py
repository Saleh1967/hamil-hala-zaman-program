    add("⑧ الصنفُ لا يقوم على الفتحِ وحدَه",
        mam["كسرٌ"] > 0 and mam["فتحٌ"] > 0,
        f"كسرٌ {mam['كسرٌ']:,} ⟷ فتحٌ {mam['فتحٌ']:,}")
    add("⑨ خلايا الحقلِ الصرفيِّ لا تتجاوز إعلانَها",
        crd["خلايا_الحقلِ_الصرفيّ"] == M_SARF,
        f"{crd['خلايا_الحقلِ_الصرفيّ']} ⟷ {M_SARF} مُعلَنة")
    add("⑩ دعوى العواملِ تُصادَم ولا تُصدَّق",
        awa["فرقُ_الدعوى_عن_المقيس"] != 0 or awa["حكمُ_الدعوى"] == "مطابقةٌ",
        f"مقيسٌ {awa['عواملُ_محسوبةُ_السطح']} ⟷ مُدَّعًى {AWAMIL_CLAIM}")
