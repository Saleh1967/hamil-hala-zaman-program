def declared_tools():
    """أدواتُ المعجمِ الأحدَ عشرَ صنفًا مستورَدةً من `madlul_gate.MU3JAM` — لا نسخة."""
    table = {}
    for sanf in MG.MU3JAM:
        for firqa in sanf["فرق"]:
            for adat in firqa["أدوات"]:
                table.setdefault(adat[0], sanf["صنف"])
    if len(MG.MU3JAM) < 11 or len(table) < 60:
        raise NisabError(E_SEAL, "معجمُ الأدواتِ انكمشَ عن عدَّته — قسمةٌ بلا إعلان")
    return table


def is_jarr(form, tools):
    """جارٌّ مستقلٌّ أو ملتصقٌ — موروثٌ من `induction_engine` بعينه، لا يُسعَّر ثانيةً."""
    return form in JARR or (form[:1] in JPRE and form not in tools and len(form) > 2)


def corpus_pairs(tools):
    """المقامُ كلُّه: كلُّ كلمةٍ بإحداثياتِها، وكلُّ زوجٍ متجاورٍ **داخلَ الآية**.

    ولا يعبُر زوجٌ حدَّ الآيةِ المفروض — كما في `wad3_gate` و`mabna_gate` سواءً بسواء.
    """
    verses = parse_verses(HL.CORPUS)
    words, pairs = [], []
    for ws in verses:
        sk = [HL.skel(w) for w in ws]
        for i, w in enumerate(ws):
            if not w:
                continue
            words.append(dict(
                صورة=sk[i], علامة=w[-1][1],
                صرفي=sarf_coord(sk[i]),
                اعتلال="معتل" if is_mu3tall(sk[i]) else "صحيح",
                تعريف=str(is_definite(sk[i])),
                صدرٌ_فعليّ=str(w[0][0] in ANYT and w[0][1] in HEAD_STATES and len(w) > 2),
                موضع=("ابتداء" if i == 0 else
                      "وقف" if i == len(ws) - 1 else
                      "وصل" if HL.is_wasl_head(w) else "درج"),
                سابقة=sk[i - 1] if i else "∅"))
            if i:
                pairs.append(dict(
                    أولى=sk[i - 1], ثانية=sk[i], علامة=w[-1][1],
                    صدرُ_الأولى=ws[i - 1][0][0],
                    أولى_فعلية=(ws[i - 1][0][0] in ANYT
                                and ws[i - 1][0][1] in HEAD_STATES
                                and len(ws[i - 1]) > 2)))
    return words, pairs


def coords_station(words):
    """الإحداثياتُ المُعلَنةُ وشَغْلُها، **وثمنُ إعلانِها مقيسٌ قبل أن يُستعمَل**.

    وثمنُ الخريطةِ بسنّةِ `ta3allum_gate.declaration_cost` عينِها — إملاءٌ حرفًا
    حرفًا، لا خريطةَ تُستعمَل مجّانًا.
    """
    cells = Counter(w["صرفي"] for w in words)
    if len(cells) > len(GENDERS) * len(NUMBERS):
        raise NisabError(E_SEAL, "خلايا الحقلِ الصرفيِّ تجاوزت إعلانَها")
    if len(cells) != M_SARF:
        raise NisabError(E_SEAL, f"خلايا الحقلِ الصرفيِّ {len(cells)} ⟷ المُعلَن {M_SARF}")
    price = TG.declaration_cost(sorted(cells) + sorted(
        {w["موضع"] for w in words}) + sorted({w["اعتلال"] for w in words}))
    return dict(
        مقام=len(words),
        صورٌ_مختلفة=len({w["صورة"] for w in words}),
        خلايا_الحقلِ_الصرفيّ=len(cells),
        حجمُ_الحقلِ_الصرفيِّ_المُعلَن=M_SARF,
        شَغْلُ_الخلايا={k: v for k, v in cells.most_common()},
        المواضع={k: v for k, v in Counter(w["موضع"] for w in words).most_common()},
        الاعتلال={k: v for k, v in Counter(w["اعتلال"] for w in words).most_common()},
        ثمنُ_إعلانِ_الخريطة=round(TG.declaration_cost(sorted(cells)), 1),
        ثمنُ_إعلانِ_الإحداثياتِ_كلِّها=round(price, 1),
        بيان=("الإحداثيُّ **دالّةٌ في الصورةِ وحدَها**: لا معجمَ يُستشار ولا وزنَ "
              "يُدَّعى — ولذلك لا يُشترَط بالصورةِ في المحطّاتِ الآتية، إذ كان "
              "المكسبُ حينئذٍ صفرًا بالبناءِ لا بالقياس"),
    )


# ═══ ② ③ ④ النسبُ الثلاثُ: مكسبٌ فوقَ الهامشِ وخلطُ الأزواجِ حَكَمًا ═══════════
def relation_gain(keys, targets, m, shuffle_seed=None):
    """مكسبُ السابقةِ عن التاليةِ فوقَ **هامشِ التالية** — لا فوقَ صورتِها.

    و`shuffle_seed` يخلط المفاتيحَ خلطًا تامًّا: الهامشُ يبقى والاقترانُ يُهدَم،
    فيكون الفارقُ فارقَ نسبةٍ لا فارقَ مقامٍ ولا فارقَ هامش.
    """
    k = list(keys)
    if shuffle_seed is not None:
        random.Random(shuffle_seed).shuffle(k)
    base = ce(["∅"] * len(targets), targets, m)
    cond = ce(k, targets, m)
    return round(base - cond, 4), round(base, 4), round(cond, 4)


def nisba_row(name, keys, targets, m):
    """صفُّ نسبةٍ: مكسبُها، وإحدى عشرةَ فرقةً مخلوطةَ الأزواج، وحكمُها بالوجهين."""
    gain, base, cond = relation_gain(keys, targets, m)
    riv = [relation_gain(keys, targets, m, TG.CONTROL_SEED * 100 + t + 1)[0]
           for t in range(RIVALS)]
    beat = gain > max(riv)
    return dict(
        النسبة=name, شرطُها=NISAB_NOTE[name],
        مقام=len(targets), حجمُ_الحقل=m,
        بالهامشِ_وحدَه=base, بالنسبة=cond, مكسبٌ_فوقَ_الهامش=gain,
        مكسبٌ_كلّيٌّ_بالبتّ=round(gain * len(targets), 1),
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ضوابطُ_المثل=riv, أعلى_المثل=max(riv), غلبَ_المثل=beat,
        حكم=("مُودَعةٌ بالوجهين — اشترت بتًّا وغلبت مثلَها"
             if (gain > 0 and beat) else "ساقطةٌ — النسبةُ لا تُشترى بالبتّ"),
    )


def nisab_station(pairs, tools):
    """النسبُ الثلاثُ، كلٌّ بشرطِ زوجِه المُعلَنِ سطحيًّا قبلَ القياس."""
    isnad = [p for p in pairs if p["أولى_فعلية"]
             and p["أولى"] not in tools and p["ثانية"] not in tools]
    tadmin = [p for p in pairs if is_jarr(p["أولى"], tools) and p["ثانية"] not in tools]
    taqyid = [p for p in pairs if p["أولى"] not in tools and p["ثانية"] not in tools
              and is_definite(p["أولى"]) and is_definite(p["ثانية"])]
    rows = [
        nisba_row("الإسنادية", [p["صدرُ_الأولى"] for p in isnad],
                  [sarf_coord(p["ثانية"]) for p in isnad], M_SARF),
        nisba_row("التضمينية", [p["أولى"] for p in tadmin],
                  [p["علامة"] for p in tadmin], M_ALAMA),
        nisba_row("التقييدية", [sarf_coord(p["أولى"]) for p in taqyid],
                  [sarf_coord(p["ثانية"]) for p in taqyid], M_SARF),
    ]
    # شاهدُ التضمينيّةِ بالعدِّ لا بالبتّ وحدَه: نصيبُ الكسرِ داخلَ الجرِّ وخارجَه.
    outside = [p for p in pairs if not is_jarr(p["أولى"], tools)]
    kin = sum(1 for p in tadmin if p["علامة"] in KASR) / len(tadmin)
    kout = sum(1 for p in outside if p["علامة"] in KASR) / len(outside)
    return dict(
        صفوف=rows,
        مُودَعةٌ_بالوجهين=sum(1 for r in rows if r["غلبَ_المثل"] and r["مكسبٌ_فوقَ_الهامش"] > 0),
        ساقطة=sum(1 for r in rows if not (r["غلبَ_المثل"] and r["مكسبٌ_فوقَ_الهامش"] > 0)),
        نصيبُ_الكسرِ_بعدَ_الجار=round(kin, 4),
        نصيبُ_الكسرِ_في_سواه=round(kout, 4),
        فضلُ_الكسرِ_للتضمينيّة=round(kin - kout, 4),
        بيان=("النسبُ تُقاس **فوقَ الهامشِ لا فوقَ الصورة**، لأنّ الإحداثيَّ "
              "دالّةٌ في الصورة — وضوابطُ المثلِ خلطُ الأزواجِ لا خلطُ الصور"),
    )


# ═══ ⑤ منعُ الصرف: رفعُ الدَّينِ بجبرِ الإحداثياتِ لا بوكيلِ الرسم ═══════════
def mamnu_forms(words, tools):
    """صنفُ منعِ الصرفِ **مشتقًّا من السطحِ وحدَه** بستّةِ إحداثياتٍ مُعلَنةٍ معًا:

    معرَبٌ (علامتان فأكثر) · يرفع بالضمّة · لا يُنوَّن البتّة · يُجَرُّ بالفتحة
    ولا يُجَرُّ بالكسرة · صحيحُ الآخِر · ليس أداةً ولا معرَّفًا ولا صدرًا فعليًّا.

    ولا معجمَ ولا وزنَ ههنا — وهذا هو الفرقُ عن وكيلِ الرسمِ المحجورِ في `mabna_gate`.
    """
    by_form, jarr_of, verbal = defaultdict(Counter), defaultdict(Counter), set()
    for w in words:
        by_form[w["صورة"]][w["علامة"]] += 1
        if w["صدرٌ_فعليّ"] == "True":
            verbal.add(w["صورة"])
        if is_jarr(w["سابقة"], tools):
            jarr_of[w["صورة"]][w["علامة"]] += 1
    out = []
    for f, c in by_form.items():
        if (sum(c.values()) >= MAMNU_MIN and len(c) >= 2 and "ضمة" in c
                and not (set(c) & set(TANWIN)) and f not in tools
                and not is_definite(f) and not is_mu3tall(f) and f not in verbal
                and jarr_of[f] and "فتحة" in jarr_of[f]
                and not (set(jarr_of[f]) & set(KASR))):
            out.append(f)
    return sorted(out, key=lambda f: (-sum(by_form[f].values()), f)), by_form


def loyalty(pairs):
    """صدقُ الصورةِ **خارجَ موضعِها**: يُحجَب موضعٌ ويُتنبَّأ بأغلبِ ما بقي منه.

    والقاعدةُ العظمى (أغلبُ الميدانِ كلِّه) هي الجوار — فالفضلُ ما زاد عليها.
    وهذا قياسُ **ثباتِ الصنف**: إن كان صنفًا حقًّا ثبتَ في المحجوب، وإلّا فلا.
    """
    by_form = defaultdict(list)
    for f, mark in pairs:
        by_form[f].append(mark)
    top = Counter(m for _, m in pairs).most_common(1)[0][0]
    hit = base = tot = 0
    for ms in by_form.values():
        if len(ms) < MIN_JARR:
            continue
        for k in range(len(ms)):
            rest = ms[:k] + ms[k + 1:]
            hit += Counter(rest).most_common(1)[0][0] == ms[k]
            base += top == ms[k]
            tot += 1
    if not tot:
        raise NisabError(E_SEAL, "لا موضعَ يصلح لاختبار الصدق")
    return round(hit / tot, 4), round(base / tot, 4), tot


def mamnu_station(words, pairs, tools):
    """الدَّينُ يُرفَع أو يُثبَّت بالرقم، لا بالرأي.

    والمحاكمةُ في ميدانٍ معزولٍ: كلُّ موضعِ جرٍّ لصورةٍ غيرِ أداةٍ ولا معرَّفةٍ
    ولا معتلّة، علامتُه كسرٌ أو فتح. فإن ثبتَ صدقُ الصورةِ خارجَ موضعِها وغلبَ
    إحدى عشرةَ فرقةً مخلوطةَ العلاماتِ فالصنفُ **قائمٌ بالبرهان**.
    """
    occ = []
    for p in pairs:
        f = p["ثانية"]
        if (is_jarr(p["أولى"], tools) and f not in tools
                and not is_definite(f) and not is_mu3tall(f)):
            if p["علامة"] in KASR:
                occ.append((f, "كسر"))
            elif p["علامة"] in FATH:
                occ.append((f, "فتح"))
    if len(occ) < MIN_N:
        raise NisabError(E_SEAL, "ميدانُ الجرِّ دونَ حدِّ العيّنة")
    true_rate, base_rate, tested = loyalty(occ)
    riv = []
    for t in range(RIVALS):
        rng = random.Random(TG.CONTROL_SEED * 100 + t + 1)
        marks = [m for _, m in occ]
        rng.shuffle(marks)
        a, b, _ = loyalty(list(zip([f for f, _ in occ], marks)))
        riv.append(round(a - b, 4))
    excess = round(true_rate - base_rate, 4)
    beat = excess > max(riv)
    forms, by_form = mamnu_forms(words, tools)
    return dict(
        ميدانُ_الجرِّ_المفحوص=len(occ),
        كسرٌ=sum(1 for _, m in occ if m == "كسر"),
        فتحٌ=sum(1 for _, m in occ if m == "فتح"),
        مواضعُ_اختبارِ_الصدق=tested,
        صدقُ_الصورةِ_خارجَ_موضعِها=true_rate,
        القاعدةُ_العظمى=base_rate,
        فضلُ_الصدق=excess,
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ضوابطُ_المثل=riv, أعلى_المثل=max(riv), غلبَ_المثل=beat,
        صورُ_الصنفِ_المشتقّ=len(forms),
        أعلى_صورِ_الصنف=[f"{f}×{sum(by_form[f].values()):,}" for f in forms[:20]],
        عتبةُ_التواتر=MAMNU_MIN,
        حكم=("قائمٌ بالبرهان — الصنفُ يثبت خارجَ موضعِه ويغلب مثلَه"
             if (excess > 0 and beat) else "ساقطٌ — الصنفُ لا يثبت خارجَ موضعِه"),
        حالُ_الدَّين=("مرفوعٌ بالإحداثيِّ لا بوكيلِ الرسم"
                     if (excess > 0 and beat) else "ثابتٌ كما كان"),
        بيان=("وكيلُ الرسمِ المحجورُ في `mabna_gate` أخطأ 31.82% لأنّه رسمٌ؛ "
              "وههنا لا رسمَ يُدَّعى بل إحداثياتٌ تُجمَع، والحَكَمُ ثباتُ الصنفِ "
              "في موضعٍ حُجِب عن مُتنبِّئِه — فلا معجمَ يُشترى ولا وزنَ يُفترَض"),
    )


# ═══ ⑥ العواملُ اللفظيةُ والعاملُ المعنويّ ══════════════════════════════════════
def awamil_station(words, tools):
    """ما يُحسَب سطحُه من العوامل، والنواسخُ منها، والمعنويُّ دَينًا **بحدٍّ مقيس**."""
    forms = {w["صورة"] for w in words}
    govs = sorted({w["سابقة"] for w in words if w["سابقة"] in tools})
    nawasikh = sorted({a[0]
                       for s in MG.MU3JAM if s["صنف"] == "الحروف المشابهة للفعل"
                       for f in s["فرق"] for a in f["أدوات"]})
    if not nawasikh:
        raise NisabError(E_SEAL, "صنفُ النواسخِ غابَ عن المعجم — إعلانٌ بلا مصداق")
    # هويّةُ العاملِ لا صورتُه: الجارُّ الملتصقُ يُعَدُّ حرفَه الواحدَ لا كلَّ
    # كلمةٍ حملته — وإلّا عُدَّت الصورُ عواملَ، وهو خلطُ مقامين.
    jarrs = set()
    for w in words:
        p_ = w["سابقة"]
        if not is_jarr(p_, tools):
            continue
        jarrs.add(p_ if p_ in JARR else p_[0])
    jarrs = sorted(jarrs)
    # العاملُ المعنويُّ: صدرٌ اسميٌّ معرَّفٌ مرفوعٌ لا عاملَ لفظيًّا قبلَه.
    maanawi = sum(1 for w in words
                  if w["تعريف"] == "True" and w["علامة"] in RAF
                  and w["سابقة"] not in tools and not is_jarr(w["سابقة"], tools))
    surface = len(set(govs) | set(jarrs))
    return dict(
        أدواتٌ_مُعلَنةٌ_في_المعجم=len(tools),
        أدواتٌ_حاضرةٌ_صورةً=len(forms & set(tools)),
        أدواتٌ_وقعت_عاملةً=len(govs),
        هويّاتُ_الجرِّ_العاملة=len(jarrs),
        أسماءُ_الجرِّ_العاملة=jarrs,
        عواملُ_محسوبةُ_السطح=surface,
        الدعوى_المُعلَنة=AWAMIL_CLAIM,
        شرحُ_الدعوى=AWAMIL_CLAIM_NOTE,
        فرقُ_الدعوى_عن_المقيس=surface - AWAMIL_CLAIM,
        حكمُ_الدعوى=("مطابقةٌ" if surface == AWAMIL_CLAIM else
                     "مخالِفةٌ بعددٍ مسمًّى — والفرقُ دَينٌ لا يُطوى"),
        النواسخُ_المُعلَنة=nawasikh,
        نواسخُ_حاضرةٌ_عاملة=sorted(set(nawasikh) & set(govs)),
        النواسخُ_سطحٌ_محسوب=set(nawasikh) <= set(govs),
        حدُّ_العاملِ_المعنويِّ_المقيس=maanawi,
        نصيبُ_المعنويِّ_من_المقام=round(maanawi / len(words), 4),
        بيان=("العاملُ اللفظيُّ يُعَدُّ لأنّ له صورةً؛ والنواسخُ منه **سطحٌ "
              "محسوب**. والمعنويُّ لا صورةَ له، فلا يُقام ولا يُبطَل — بل "
              "يُسمّى دَينًا بحدِّه: هذه عدَّةُ المواضعِ التي عليه أن يسعَها"),
    )


