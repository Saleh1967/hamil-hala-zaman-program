def main(argv=None):
    ap = argparse.ArgumentParser(description="بابُ النسبِ وجبرِ الإحداثيات")
    ap.add_argument("--json", metavar="PATH", help="اكتب الوديعةَ إلى مسار")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        if not os.path.exists(HL.CORPUS):
            raise NisabError(E_MISSING, f"المجمَّدُ غائب: {HL.CORPUS}")
        out, measured = run()
        collide(measured)
        if args.json:
            with open(args.json, "w", encoding="utf-8") as fh:
                json.dump(out, fh, ensure_ascii=False, indent=2)
                fh.write("\n")
        if not args.quiet:
            show(out)
    except NisabError as e:
        print(f"صريخٌ [{e.code}]: {e}", file=sys.stderr)
        return e.code
    return 0


if __name__ == "__main__":
    sys.exit(main())
