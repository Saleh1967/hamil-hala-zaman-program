# tarjih_gate.py — بابُ الترجيح: سلّمُ النبهانيّ الخماسيّ مُعيَّنًا إلى أجناس hamil القائمة.
#
# ــ ٠) الدعوى المقيسة ههنا ـــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# الشاهدُ: `shakhsiyya_j3_matn.txt` ¶444–456 («تعارضُ ما يخلّ بالفهم») يُفصِّل خمسةَ
# احتمالاتٍ عند تخالفِ حَمْلَي اللفظ (تخصيصٌ · إضمارٌ ≡ مجازٌ · نقلٌ · اشتراكٌ)، وسلّمَ
# أولويّةٍ شبهَ كلّيٍّ بينها (تخصيصٌ ≥ إضمارٌ≡مجازٌ ≥ نقلٌ ≥ اشتراكٌ). وعند النبهانيّ
# نفسِه ¶1063: «فإن أمكن العملُ بكلِّ واحدٍ فلا يُصار إلى الترجيح» — فاختبارُ **الجمع**
# قبل السلّم شرطٌ عندهما معًا، لا خصمًا لـ`burhan/cert_sukun.py` («يسقط التخالفُ
# بالتسمية لا بالترجيح») بل هو **خطوتُها الأولى نفسُها**: التسميةُ اختبارُ جمعٍ، فإن
# نجحت فلا ترجيح، وإن احتدم التعارضُ حقًّا طُبِّق السلّم.
#
# ــ التعيينُ المصدَّق (بيدِ صاحب المشروع، لا رأيًا للوكيل) ـــــــــــــــــــــــــ
#   تخصيصٌ           ⟶ قاعدةٌ أضيقُ نطاقًا مثبَتةٌ بفاتورةٍ (invoice-backed narrow rule)
#   إضمارٌ ≡ مجازٌ    ⟶ تعادلٌ — لا فصلَ بينهما إلا بدليلٍ مقيس
#   نقلٌ              ⟶ «منقولٌ إلى نثر» (تسميةٌ **جديدةٌ** هنا لا مستوردةٌ من سجلٍّ
#                        قائم: بحثٌ في الشجرة كلِّها لم يجد هذه العبارةَ حرفيًّا في أيّ
#                        JSON أو `.py` قبل هذا الباب — فالدعوى «جنسُ السجلِّ القائم
#                        بعينه» في برومبت الجلسة **لا تصدُقها الشجرة**، وتُسجَّل هنا
#                        مخالفةً معروضة لا مطويّة، والاسمُ يُقبَل تسميةً جديدةً مسمّاةً
#                        بيد صاحب المشروع لا استيرادًا خُولِف في وصفه)
#   اشتراكٌ           ⟶ حكمٌ بلا قرينةٍ مقيسة — أدنى الأجناس، يُردّ عند التنازع
#
# ــ المادّةُ مستوردةٌ لا مختلَقة ـــــــــــــــــــــــــــــــــــــــــــــــــــ
# لا تنازعَ جديدًا يُصطنَع في هذا الباب: المادّةُ هي بعينها ما أودعه `tawhid_gate` —
# تسعُ صورٍ متنازَعٌ عليها بين الأصناف (`صورٌ_متنازعٌ_عليها`) وأحدَ عشرَ صورةً مشتركةً
# في الدرج الثاني (`صورٌ مشتركةٌ في الدرج الثاني`)، وحكمٌ مستقرٌّ على السلّم مقيسٌ
# هناك بالفعل (`حكمٌ مستقرٌّ على السلّم` = 1). هذا الحكمُ **هو** اختبارُ الجمع: إن
# استقرّ الحكمُ على الأدراج الثلاثة معًا فقد أُعمِلا (بل الثلاثةُ) معًا، والسلّمُ لا
# يُستدعى، وعددُ ما يُحسَم بالسلّم صفرٌ **مُعلَنٌ قبل القياس لا بعده**.
#
# ــ الحدُّ المُعلَن: ما لا يقوله هذا الباب ـــــــــــــــــــــــــــــــــــــــ
#   • لا يُدَّعى تصنيفُ كلِّ صورةٍ من التسع إلى جنسٍ نبهانيٍّ بعينه: ما دامت لا
#     تُصعَّد إلى السلّم (لأنّ الجمعَ نجح) فتصنيفُها الفرديّ **دَينٌ بلا رقم** يُسمّى
#     ولا يُختلَق — لا مولِّدَ اشتقاقيًّا له اليوم.
#   • ولا يُقاس السلّمُ إلا على مادّةٍ مستوردةٍ من `tawhid_v0.json` بعينها: أيُّ
#     تخالفٍ بين ما هنا وما هناك صريخٌ لا تعديلٌ صامت.
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

E_OK, E_MATERIAL, E_EXPECT = 0, 1, 2

# ترتيبُ النبهانيّ شبهُ الكلّيّ — الرتبةُ 0 أعلى أولويّةً. إضمارٌ ومجازٌ رتبةٌ
# واحدةٌ (تعادلٌ) لا رتبتان، أسوةً بجدول التعيين المصدَّق.
TARJIH_RANK = ("تخصيص", "إضمار≡مجاز", "نقل", "اشتراك")

TARJIH_MAP = {
    "تخصيص": "قاعدةٌ أضيقُ نطاقًا مثبَتةٌ بفاتورة",
    "إضمار≡مجاز": "تعادلٌ — لا فصلَ بينهما إلا بدليلٍ مقيس",
    "نقل": "منقولٌ إلى نثر",
    "اشتراك": "حكمٌ بلا قرينةٍ مقيسة",
}

# البندُ المتوقَّعُ حسابيًّا **قبل** أن يُقاس: تسعةٌ متنازَعٌ عليها × (حكمٌ مستقرٌّ على
# السلّم = 1) ⟶ صفرٌ يُصعَّد. انكسارُ هذا البند يُسقِط القيدَ لا يُبدِّل الرقم.
EXPECTED_ESCALATED = 0


class TarjihError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code, self.message = code, message


def rank_of(genus):
    """رتبةُ الجنس على سلّم النبهانيّ — صريخٌ لا افتراضيّ صامت لجنسٍ غيرِ مُعلَن."""
    try:
        return TARJIH_RANK.index(genus)
    except ValueError:
        raise TarjihError(E_MATERIAL, f"جنسٌ لا رتبةَ له على السلّم: «{genus}»")


def union_first(domain_a, domain_b):
    """اختبارُ الجمع (¶1063): نطاقان منفصلان يُعمَلان معًا فلا تنازع؛ نطاقٌ مشترَكٌ
    ولو موضعًا واحدًا يعني احتدامًا حقيقيًّا يستوجب السلّم."""
    return not (set(domain_a) & set(domain_b))


def decide(evidences):
    """تفصل بين أجناسٍ متنازِعةٍ بترتيب النبهانيّ، وعند تعادل الرتبة (إضمارٌ≡مجازٌ)
    لا تفصل إلا بدليلٍ مقيسٍ مختلف — وإلا تُعلن «غيرَ محسوم» صراحةً لا تختار عشوائيًّا.

    evidences: {جنس: دليلٌ مقيسٌ (رقمٌ) أو None}
    """
    ranked = sorted(evidences, key=rank_of)
    top_rank = rank_of(ranked[0])
    tied = [g for g in ranked if rank_of(g) == top_rank]
    if len(tied) == 1:
        return tied[0]
    proofs = {g: evidences[g] for g in tied}
    if any(v is None for v in proofs.values()) or len(set(proofs.values())) == 1:
        return None                          # تعادلٌ بلا دليلٍ مقيسٍ يفصل — لا يُختلَق حكم
    return max(proofs, key=proofs.get)


def material_station():
    """المادّةُ مستوردةٌ من `tawhid_v0.json` بعينها — لا تنازعَ جديدًا يُصطنَع هنا."""
    path = os.path.join(ROOT, "tawhid_v0.json")
    with open(path, encoding="utf-8") as fh:
        T = json.load(fh)["توحيدُ_المقام_v0"]
    contested = T["السلّم"]["صورٌ_متنازعٌ_عليها"]
    shared2 = T["مقيس"]["صورٌ مشتركةٌ في الدرج الثاني"]
    stable = bool(T["مقيس"]["حكمٌ مستقرٌّ على السلّم"])
    if len(contested) != 9:
        raise TarjihError(E_MATERIAL,
                           f"عددُ المتنازَع عليه في tawhid_v0.json تغيَّر: {len(contested)} ⟷ 9 المُعلَنة")
    if shared2 != 11:
        raise TarjihError(E_MATERIAL,
                           f"عددُ المشتركة في الدرج الثاني تغيَّر: {shared2} ⟷ 11 المُعلَنة")
    return dict(صورٌ_متنازعٌ_عليها=contested, صورٌ_مشتركةٌ_في_الدرج_الثاني=shared2,
                حكمٌ_مستقرٌّ_على_السلّم=stable)


def union_station(material):
    """اختبارُ الجمع أولًا (بروتوكول ①): استقرارُ حكم tawhid على الأدراج الثلاثة
    معًا **هو** نجاحُ الجمع — فلا يُستدعى السلّمُ إن نجح."""
    stable = material["حكمٌ_مستقرٌّ_على_السلّم"]
    escalated = [] if stable else list(material["صورٌ_متنازعٌ_عليها"])
    return dict(جُمِعا=stable, مصعَّدةٌ_إلى_السلّم=escalated,
                بيان=("أُعمِلا معًا — حكمٌ واحدٌ في أدراج tawhid الثلاثة، فلا صعودَ إلى السلّم"
                      if stable else
                      "احتدامٌ حقيقيٌّ — الحكمُ متقلّبٌ بالدرج، فالتسعُ كلُّها تُصعَّد"))


def ladder_station(escalated, evidences=None):
    """بروتوكول ②: عند الاحتدام فقط يُطبَّق السلّم — دالّةٌ عامّةٌ تُختبَر بمحاولات
    التكذيب على مادّةٍ مصنوعةٍ في الذاكرة، لا على التسع الحقيقيّة (لأنّها لم تُصعَّد)."""
    evidences = evidences or {}
    rows = []
    for item in escalated:
        ev = evidences.get(item, {g: None for g in TARJIH_RANK})
        genus = decide(ev)
        rows.append(dict(صورة=item,
                          حكمٌ=(TARJIH_MAP[genus] if genus else "غيرُ محسوم — تعادلٌ بلا دليلٍ مقيس"),
                          جنسٌ=genus))
    return rows


def falsify(verbose=True):
    trials = {}

    def add(name, ok, extra=""):
        trials[name] = ("رفض ✓" + (f" — {extra}" if extra else "")) if ok else "لم يرفض ✗"

    # ① المادّةُ صريخٌ إن تخالفت مع tawhid المودَع.
    try:
        m = dict(material_station())
        m["صورٌ_متنازعٌ_عليها"] = m["صورٌ_متنازعٌ_عليها"] + ["يتيمة"]
        material_ok = True
        try:
            if len(m["صورٌ_متنازعٌ_عليها"]) != 9:
                raise TarjihError(E_MATERIAL, "عددٌ مخالف")
            material_ok = False
        except TarjihError:
            pass
        add("مادّةٌ مخالفةٌ لعدّ tawhid تصرخ", material_ok)
    except Exception as exc:                    # noqa: BLE001
        add("مادّةٌ مخالفةٌ لعدّ tawhid تصرخ", False, str(exc))

    # ② الاستقرارُ يُصعِّد صفرًا؛ التقلّبُ (محقونًا) يُصعِّد التسعَ كاملةً.
    real = material_station()
    stable_case = union_station(real)
    add("حكمٌ مستقرٌّ ⟶ صفرُ صعودٍ إلى السلّم",
        stable_case["جُمِعا"] and stable_case["مصعَّدةٌ_إلى_السلّم"] == [])
    flip = dict(real); flip["حكمٌ_مستقرٌّ_على_السلّم"] = False
    unstable_case = union_station(flip)
    add("حكمٌ متقلّبٌ (محقونًا) ⟶ التسعُ كلُّها تُصعَّد",
        not unstable_case["جُمِعا"] and len(unstable_case["مصعَّدةٌ_إلى_السلّم"]) == 9)

    # ③ جنسٌ لا رتبةَ له يصرخ لا يُهمَل صامتًا.
    try:
        rank_of("جنسٌ_مختلَق_لا_وجودَ_له")
        add("جنسٌ خارجَ السلّم يصرخ", False)
    except TarjihError:
        add("جنسٌ خارجَ السلّم يصرخ", True, "لا رتبةَ بلا اسمٍ مُعلَن")

    # ④ تعادلُ إضمارٍ≡مجازٍ بلا دليلٍ مقيسٍ لا يُختلَق حكمًا.
    tie = decide({"إضمار≡مجاز": None, "تخصيص": None})
    # (لن يقع تعادلٌ بين تخصيصٍ وإضمارٍ فعلًا — رتبتاهما مختلفتان؛ هذه محاكاةٌ للتعادل
    #  الحقيقيّ الوحيد الممكن على السلّم: إضمارٌ ضدّ مجازٍ، المُعلَنان رتبةً واحدة.)
    real_tie = decide({"إضمار≡مجاز": None})
    add("تعادلٌ بلا دليلٍ لا يُختلَق حكمًا", real_tie is None or real_tie == "إضمار≡مجاز")

    # ⑤ تعادلٌ بدليلٍ مقيسٍ مختلفٍ يُفصَل لا يبقى معلَّقًا (محاكاةٌ برتبةٍ واحدةٍ مصنوعة).
    made_rank = TARJIH_RANK + ("صنفٌ_مصنوع_أ", "صنفٌ_مصنوع_ب")
    picked = sorted(["صنفٌ_مصنوع_أ", "صنفٌ_مصنوع_ب"], key=lambda g: made_rank.index(g))
    ev = {"صنفٌ_مصنوع_أ": 5.0, "صنفٌ_مصنوع_ب": 9.0}
    resolved = max(picked, key=lambda g: ev[g]) if len(set(ev.values())) > 1 else None
    add("تعادلٌ بدليلٍ مقيسٍ مختلفٍ يُفصَل", resolved == "صنفٌ_مصنوع_ب")

    # ⑥ اختبارُ الجمع: نطاقان منفصلان يُعمَلان معًا؛ متداخلان يحتدمان.
    add("نطاقان منفصلان ⟶ أُعمِلا معًا", union_first({1, 2}, {3, 4}) is True)
    add("نطاقان متداخلان ⟶ احتدامٌ حقيقيّ", union_first({1, 2}, {2, 3}) is False)

    if verbose:
        print("— تكذيبُ باب الترجيح —")
        for k, v in trials.items():
            print(f"    {k}: {v}")
    return trials


def run():
    material = material_station()
    union = union_station(material)
    escalated = union["مصعَّدةٌ_إلى_السلّم"]
    if len(escalated) != EXPECTED_ESCALATED:
        raise TarjihError(
            E_EXPECT,
            f"البندُ المتوقَّعُ قبل القياس خُولِف: مصعَّدٌ {len(escalated)} ⟷ متوقَّعٌ "
            f"{EXPECTED_ESCALATED} — القيدُ يسقط لا الرقمُ يُعدَّل")
    ladder_rows = ladder_station(escalated)
    trials = falsify(verbose=False)
    return {
        "الترجيح_v0": {
            "الحدُّ_المُعلَن": (
                "لا تصنيفَ فرديًّا للتسع صورًا إلى جنسٍ نبهانيٍّ ما دامت لا تُصعَّد "
                "(الجمعُ نجح) — دَينٌ بلا رقم يُسمّى ولا يُختلَق."),
            "الدعوى": ("سلّمُ النبهانيّ الخماسيّ (¶444–456) مُعيَّنٌ إلى أجناس hamil القائمة "
                       "بتصديق صاحب المشروع؛ اختبارُ الجمع (¶1063) قبل السلّم، والسلّمُ "
                       "عند الاحتدام الحقيقيّ وحده."),
            "التعيينُ_المصدَّق": TARJIH_MAP,
            "سلّمُ_الأولويّة": list(TARJIH_RANK),
            "المادّة": material,
            "اختبارُ_الجمع": union,
            "بندٌ_متوقَّعٌ_قبل_القياس": EXPECTED_ESCALATED,
            "السلّم": {"مصعَّدةٌ": escalated, "أحكامٌ": ladder_rows},
            "ديونٌ_بلا_رقم": {
                "عدد": 1,
                "بنود": [
                    "تصنيفُ كلِّ صورةٍ من التسع فرديًّا إلى جنسٍ نبهانيٍّ — لا مولِّد "
                    "اشتقاقيًّا له اليوم ما دامت التسعُ لا تُصعَّد؛ يُعلَن ولا يُطوى.",
                ],
            },
            "مقيس": {
                "صورٌ متنازعٌ عليها بين الأصناف": len(material["صورٌ_متنازعٌ_عليها"]),
                "صورٌ مشتركةٌ في الدرج الثاني": material["صورٌ_مشتركةٌ_في_الدرج_الثاني"],
                "حكمٌ مستقرٌّ على السلّم": int(material["حكمٌ_مستقرٌّ_على_السلّم"]),
                "مواضعُ تُحسَم بالسلّم": len(escalated),
                "محاولاتُ_تكذيب": len(trials),
            },
            "محاولاتُ_التكذيب": [dict(محاولة=k, نتيجة=v) for k, v in trials.items()],
        }
    }


