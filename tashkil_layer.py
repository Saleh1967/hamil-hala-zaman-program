# ═══ ⑤ المواضع: تُبنى من القارئ المصادَم وحدَه، ولا يُقرَأ المجمَّدُ مرّتين ═══════════════
def sites(marked):
    """مواضعُ الرسم: لكلِّ حرفٍ مرسومٍ سياقُه الرسميُّ وجوابا المهمّتين.

    والسياقُ **رسميٌّ خالص**: الحرفُ وجيرانُه وخانتُه من حدود الكلمة — لا حركةَ فيه.
    فما يُقاس ههنا يصلح حرفًا بحرفٍ لنصٍّ عارٍ لا شكلَ فيه.
    """
    out = []
    for vi, verse in enumerate(marked):
        for word in verse:
            sk = "".join(c for c, _, _ in word)
            last = len(word) - 1
            for li, (ch, st, sh) in enumerate(word):
                out.append(dict(
                    آية=vi, ch=ch, idx=li, word=sk,
                    slot="بداية" if li == 0 else ("خاتمة" if li == last else "حشو"),
                    p1=sk[li - 1] if li >= 1 else "^",
                    p2=sk[li - 2] if li >= 2 else "^^",
                    n1=sk[li + 1] if li < last else "$",
                    n2=sk[li + 2] if li < last - 1 else "$$",
                    مضعَّف=bool(sh), هيئة=st))
    return out


def context_of(site, keys):
    return tuple(site[k] for k in keys)


# ═══ ⑥ الفاتورة: المكيالُ العامُّ يُستدعى مرّةً لكلِّ سياق ═══════════════════════════════
def bill_of(S, keys, key):
    """فاتورةُ نموذجٍ مشروطٍ بتًّا — **بلا حسابٍ محليّ**: `price` لكلِّ سياقٍ ثمّ تُجمَع.

    فيكون L(D|M) مجموعَ بياناتِ السياقات، وL(M) مجموعَ جداولها بسياسةِ الترميز نفسِها
    المُعلَنة في `deposit_law` — لا سياسةَ ثانيةً ولا ثمنًا يُكتَب بيد.
    """
    groups = defaultdict(list)
    for s in S:
        groups[context_of(s, keys)].append(s[key])
    data = model = 0.0
    for answers in groups.values():
        p = price(answers, 0)
        data += p["بيانات"]
        model += p["نموذج"]
    ratio, deg = degenerate(len(groups), len(S))
    return dict(خلايا=len(groups), بيانات=round(data, 2), نموذج=round(model, 2),
                كلفة=round(data + model, 2), للموضع=round((data + model) / len(S), 4),
                نسبةُ_الانحلال=ratio, منحلّ=deg)


def ladder(S, task):
    """سلّمُ الرتب لمهمّةٍ: فاتورةُ كلِّ رتبةٍ · الفائزةُ · موضعُ الانعطاف · حكمُ المكذِّب."""
    key = TASK_KEY[task]
    rungs = [dict(رتبة=name, حقول=list(keys), **bill_of(S, keys, key))
             for name, keys in RUNGS]
    fab = dict(رتبة=FABRICATED[0], حقول=list(FABRICATED[1]),
               **bill_of(S, FABRICATED[1], key))
    best = min(rungs, key=lambda r: r["كلفة"])
    turn = next((rungs[i]["رتبة"] for i in range(1, len(rungs))
                 if rungs[i]["كلفة"] > rungs[i - 1]["كلفة"]), None)
    delta = best["كلفة"] - fab["كلفة"]
    tested, n0 = n0_gate("n₀ مواضع", len(S), THRESHOLDS)
    return dict(مهمّة=task, حقلٌ_مغلق=list(TASK_FIELD[task]), مواضع=len(S),
                رتب=rungs, المكذِّبُ_المصنوع=fab, الفائزة=best["رتبة"],
                انعطافٌ_عند=turn, Δ=round(delta, 2),
                حكم=verdict(delta) if tested else "غيرُ مختبَرة",
                **{"n₀": n0, "بلغت_n₀": tested})


# ═══ ⑦ القسمةُ الحاكمة: داخلٌ (رسم) ⟷ خاتمةٌ (إعراب) ══════════════════════════════════
def split_bill(S, task, rung_name):
    """المبدأُ يُقاس لا يُقال: أهي الخاتمةُ أغلى من الداخل بالرتبة نفسِها؟"""
    keys = dict(RUNGS)[rung_name]
    key = TASK_KEY[task]
    parts = {}
    for name, want in (("داخل", False), ("خاتمة", True)):
        sub = [s for s in S if (s["slot"] == "خاتمة") == want]
        parts[name] = dict(مواضع=len(sub), **bill_of(sub, keys, key))
    ratio = parts["خاتمة"]["للموضع"] / parts["داخل"]["للموضع"]
    return dict(رتبة=rung_name, قسمة=parts, نسبةُ_الغلاء=round(ratio, 4),
                حكم=("الخاتمةُ أغلى — فالفرقُ بين طبقتي الرسم والإعراب معدودٌ لا مقول"
                     if ratio > 1 else "الخاتمةُ ليست أغلى — دعوى ت٣ ساقطة"))


# ═══ ⑧ التطبيقُ على المحجوب: توزيعُ احتمالاتٍ لا حكم ═══════════════════════════════════
# القسمةُ سياسةُ المشروع المعلنة (`induction_engine.split_alternating`): المتناوبُ على
# الآيات — لا اختيارَ بعد القياس، ولا نصفٌ يُنتقى ليُربَح.
def predict(S, task, rung_name):
    """يُدرَّب على الآيات الزوجية ويُطبَّق على الفردية: إصابةٌ وحدُّ اشتباهٍ مُختبَر.

    والمخرَجُ **ليس حكمًا**: لكلِّ موضعٍ مرشَّحون وأوزانُهم بتنعيم α=1 على الحقل المغلق،
    والسياقُ المجهولُ يردُّ توزيعًا مسطَّحًا — فالجهلُ يُعلَن ولا يُخفى خلف ترجيحٍ مخترَع.
    """
    keys = dict(RUNGS)[rung_name]
    key, field = TASK_KEY[task], TASK_FIELD[task]
    m = len(field)
    train = [s for s in S if s["آية"] % 2 == 0]
    test = [s for s in S if s["آية"] % 2 == 1]
    table = defaultdict(Counter)
    for s in train:
        table[context_of(s, keys)][s[key]] += 1

    tau = THRESHOLDS["τ حدُّ الاشتباه"]["قيمة"]
    hit = sharp = sharp_hit = blunt_hit = 0
    by_slot = {"داخل": [0, 0], "خاتمة": [0, 0]}
    for s in test:
        c = table.get(context_of(s, keys), Counter())
        n = sum(c.values())
        ranked = sorted(((c[f] + 1) / (n + m), f) for f in field)[::-1]
        margin = ranked[0][0] - ranked[1][0]
        ok = ranked[0][1] == s[key]
        hit += ok
        part = by_slot["خاتمة" if s["slot"] == "خاتمة" else "داخل"]
        part[0] += 1
        if margin >= tau:
            sharp += 1
            sharp_hit += ok
            part[1] += 1
        else:
            blunt_hit += ok
    blunt = len(test) - sharp
    a_sharp = sharp_hit / sharp if sharp else 0.0
    a_blunt = blunt_hit / blunt if blunt else 0.0
    gap = a_sharp - a_blunt
    limit = THRESHOLDS["فرقُ الإصابة"]["قيمة"]
    return dict(
        مهمّة=task, رتبة=rung_name, تدريب=len(train), اختبار=len(test),
        إصابة=round(hit / len(test), 4), عتبة=tau,
        حادّ=sharp, إصابةُ_الحادّ=round(a_sharp, 4),
        مشتبه=blunt, إصابةُ_المشتبه=round(a_blunt, 4),
        فرقُ_الإصابة=round(gap, 4), حدُّ_الفرق=limit, العتبةُ_تفرز=bool(gap >= limit),
        حدّةٌ_بالخانة={k: dict(مواضع=v[0], حادّ=v[1],
                                نسبة=round(v[1] / v[0], 4) if v[0] else 0.0)
                        for k, v in by_slot.items()},
        صنف="[شاهد]",
        شرطُ_تقاعده=("يصير حكمًا إذا جاء نصٌّ مشكولٌ مستقلٌّ يؤيّده أو قاعدةٌ رياضيةٌ "
                      "تُثبته — وإلّا بقي بصنف احتياجه معلنًا"))


# ═══ ⑨ محاولاتُ التكذيب — تُكتَب لتُردّ، والنجاحُ فيها يُسقِط البابَ لا يُزيّنه ══════════
def falsify(S):
    T = []

    def t(name, ok, note):
        T.append(dict(محاولة=name, نجحت=not ok, أثر=note))

    # ① لو كانت الشدّةُ نادرةً لما استحقّت مهمّةً أولى.
    sh = sum(1 for s in S if s["مضعَّف"])
    tested, n0 = n0_gate("n₀ مواضع", sh, THRESHOLDS)
    t("مواضعُ التضعيف دون n₀ فتسقط دعوى ت١", tested,
      f"مواضعُ الشدّة {sh:,} ≥ n₀={n0}")

    # ② لو كان السياقُ لا يُغني عن المسطَّح لسقط السلّمُ من أوّله.
    for task in TASK_KEY:
        flat = bill_of(S, (), TASK_KEY[task])["كلفة"]
        one = bill_of(S, ("ch",), TASK_KEY[task])["كلفة"]
        t(f"الرسمُ لا يُنبئ عن {task} (م١ ≥ م٠)", one < flat,
          f"م١ {one:,.0f} < م٠ {flat:,.0f}")

    # ③ لو ربحت كلُّ زيادةِ سياقٍ لكان «المزيدُ أفضلُ» قانونًا — وهو ما ينفيه الانعطاف.
    up = bill_of(S, RUNGS[-1][1], "مضعَّف")["كلفة"]
    mid = bill_of(S, RUNGS[4][1], "مضعَّف")["كلفة"]
    t("زيادةُ السياق ربحٌ دائمٌ في التضعيف", up > mid,
      f"م٦ {up:,.0f} > م٤ {mid:,.0f} — السلّمُ ينعطف")

    # ④ لو كان الحقلُ مفتوحًا لَدخلته هيئةٌ لم تُعلَن.
    seen = {s["هيئة"] for s in S}
    t("هيئةٌ خارجَ الحقل الثمانيِّ المغلق", seen <= set(HK.STATES),
      f"هيئاتٌ واقعةٌ {len(seen)} ⊆ المعلَن {len(HK.STATES)}")

    # ⑤ لو كان المكذِّبُ المصنوعُ أرخصَ لسقطت دعوى ت٢ في مهمّةٍ من المهمّتين.
    for task in TASK_KEY:
        L = ladder(S, task)
        t(f"جدولُ المواضع أرخصُ من القاعدة في {task}", L["Δ"] < 0,
          f"Δ {L['Δ']:+,.0f} — {L['حكم']}")

    # ⑥ لو انحلَّت الرتبةُ الفائزةُ لصارت القاعدةُ جدولًا باسمٍ آخر.
    best = ladder(S, "ط٢ الهيئة")
    win = next(r for r in best["رتب"] if r["رتبة"] == best["الفائزة"])
    t("الرتبةُ الفائزةُ منحلّةٌ فوق حدِّ |Σ|/N", not win["منحلّ"],
      f"|Σ|/N {win['نسبةُ_الانحلال']} ≤ {DEGENERACY_CEILING}")

    # ⑦ لو تساوت إصابةُ الحادِّ والمشتبه لكانت العتبةُ زينة.
    P = predict(S, "ط٢ الهيئة", best["الفائزة"])
    t("عتبةُ الاشتباه لا تفرز (فرقُ إصابةٍ دون الحدّ)", P["العتبةُ_تفرز"],
      f"فرقُ الإصابة {P['فرقُ_الإصابة']:.4f} ≥ {P['حدُّ_الفرق']}")

    # ⑧ لو ادّعى البابُ حكمًا على غير المشكول لخالف مبدأه.
    t("التنبُّؤُ أُعلن حكمًا لا شاهدًا", P["صنف"] == "[شاهد]",
      f"صنفُ المخرَج {P['صنف']} بشرطِ تقاعدٍ معلن")

    # ⑨ لو خلت رتبةُ حكمٍ من سلّم imla_layer لانفتحت طبقةٌ سادسة.
    t("حكمٌ على رتبةٍ خارجَ سلّم imla_layer",
      all(r in IM.LAYER_NAME for _, r, _, _ in RULINGS),
      f"رتبُ الأحكام {sorted({r for _, r, _, _ in RULINGS})} ⊆ السلّم")

    return T


