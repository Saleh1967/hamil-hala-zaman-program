# ▸ Ⓐ **كسرُ الوصل — طرحٌ لا تفسير** (جنسٌ سادسٌ يُضاف لاتفاقية §٩): الكسرةُ ههنا تخلُّصٌ من
#   التقاء الساكنين قبل همزة الوصل، **ليست إعرابًا** فلا تُسأل عن جارِّها. وكاشفُها شرطان
#   معًا، وكلاهما من البايتات ولا دَورَ فيه:
#     ① التالي **رأسُ وصل** — والحدُّ مختومٌ سلفًا في `i3lal_layer.is_wasl_head` (ألفٌ عاريةٌ
#        في أوّل الكلمة)، **يُورَث ولا يُكتَب ثانيةً** كما وُرِث JARR.
#     ② **شهادةُ السكون**: هيكلُ الكلمة نفسُه يَرِد في المجمَّد مرّةً أخرى **ساكنَ الآخر**.
#   والشرطُ ② هو الذي يمنع المِكنسة: «الرحمنِ الرحيم» لا تَرِد ساكنةً قطّ فتبقى مجرورةً
#   مسؤولًا عنها، و«وإذِ استسقى» و«فمنِ اضطر» و«وقالتِ اليهود» تَرِد فتُطرَح. **ولا أُدخل
#   قائمةً يدويّةً من المبنيات**: الشاهدُ من المجمَّد أو لا طرحَ — فالقائمةُ اليدويةُ تُفصَّل
#   على العتبة والشاهدُ لا يُفصَّل. وثمنُ هذا التحفُّظ معلن: **يبقى كسرُ وصلٍ لم يُشهَد له
#   بالسكون فلا يُطرَح** (بشرِ · ليستِ · وذرِ · يذكرِ)، **ويُعَدّ في المتبقّي بالاسم** —
#   كاشفٌ يُقصِّر خيرٌ من كاشفٍ يبتلع.
#
# ▸ Ⓑ Ⓒ **توسيعُ علامة جرّ السابق — تفسيرٌ لا طرح**، وهو تصحيحُ عيبٍ في باب التابع: شرطُه
#   الحاليُّ `سابقٌ آخرُه كسرة` — وهذا يفترض أنّ **علامةَ الجرّ الكسرةُ وحدَها**، وهو خطأ
#   مودَعٌ في الكود. فالسابقُ يكون مجرورًا و**ليس آخرُه كسرة** في بابين معلنين:
#     Ⓑ **مقصورٌ أو ممدود** (اليتامى · القربى · الهدى) — جرُّه **مقدَّر**، لا يظهر.
#     Ⓒ **مثنًى أو جمعُ مذكرٍ سالم** (الصديقين · المؤمنين) — علامتُه **الياء** والنونُ مفتوحة.
#   ويُشترَط في اللاحق ما يُشترَط في التابع اليوم (عاطفٌ ملتصقٌ أو تعريفٌ)، **ولا يُفتَح البابُ
#   لكلّ ما بعد مقصورٍ** — وإلّا صار الباب مِكنسة. وهذان **بابان مستقلّان معدودان بالاسم**،
#   فإن جاعا عُرف جوعُهما، وإن ابتلعا عُرف ابتلاعُهما.
