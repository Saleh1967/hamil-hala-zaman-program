# ▸ **أوّلًا، ما قِيس في التشخيص يُعلَن مقيسًا لا متوقَّعًا** (وإلّا كان التسجيلُ تمثيلًا):
#   فُحصت عيّنتا الجنسين فانكشفت ثلاثةُ ميكانيزماتٍ، وقيست أعدادُها على المتبقّي قبل الكتابة:
