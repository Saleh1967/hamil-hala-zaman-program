TEMPLATES = ["فعل","فعلل","فاعل","أفعل","تفعلل","تفاعل","انفعل","افتعل","افعلل","استفعل"]
def rx(t):
    lg = defaultdict(list); out = ""; idx = 0
    for ch in t:
        if ch in "فعل": lg[ch].append(idx + 1); out += "(.)"; idx += 1
        else: out += ch
    return re.compile("^" + out + "$"), lg
