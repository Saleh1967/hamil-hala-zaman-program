#   ① المصنِّفُ يبتلع المشارك: «مالك» و«يوم» صُنِّفا فعلًا فجاع بابُ الإضافة — إصلاحُ §٥①.
#   ② تابعٌ غير معطوف: النعتُ والبدلُ والتوكيدُ وعطفُ البيان **ليست في جدول المفسّرات أصلًا**
#      (الجدولُ أعلن الرُّبعَ ونسي الثلاثة) — «لله ربِّ العالمين» · «الرحمنِ الرحيم».
#   ③ جارٌّ تحت عاطفة: «ومن الناس» — العاطفُ الملتصقُ يحجب الجارَّ عن الجدول.
#   ④ أجوفُ السَّند (أوّلُ آيةٍ بتابعٍ أو خبرٍ عن محذوف) — **لا يُفتَح له بابٌ مظنون**، بل
#      يُبوَّب بالاسم في سجلّ السقوط، فالسقوطُ المسمّى نتيجةٌ تُودَع لا تُخفى.
# والمصنِّفُ يُصلَح **بكاشفاتٍ معلنةٍ منتهية** لا بقاعدةٍ مفتوحة، وكلُّها من البايتات وحدَها:
#   اسمٌ بالعلامة: تنوينٌ (علامةُ اسمٍ خالصة) · «ال» بصورها · خاتمةٌ مكسورة (لا يُكسَر آخرُ
#   فعلٍ قطّ) · تاءٌ مربوطة · ألفٌ ولامٌ بعد جارٍّ ملتصق. وفعلٌ بالقالب **مع حركاته** لا
#   بهيكله وحدَه — فـ«فاعِل» المشارك يفارق «فاعَل» الفعل بكسرةِ عينه، وهذا هو **موضعُ
#   استثناء المشارك المعلن**. وصورُ المصدر المبدوءةُ بألفٍ (افتعال/انفعال/استفعال) تفارق
#   قوالبَها بطول الهيكل، وما بقي منها يُستثنى بعلامة الاسم نفسِها.
# وأولويةُ التقاطع ③ **تُعلَن استثناءً محدودًا**: قلعُ العاطف الملتصق (و/ف بفتحة) قبل عرض
#   السابق على JARR وعرضِ الكلمة على JPRE — **عند التقاطع وحدَه**، ولا يُمَسّ ترتيبُ
