#    شرط الإسقاط: إن جاء غيرُ المفسَّر ≥ 400، أو تجاوز جنسٌ توقعَه بـ×2، سقط التسجيل وتُعاد صياغته.»
# وأجناسُ السقوط الثلاثةُ المشخَّصةُ من العيّنة (① معلنٌ سلفًا · ②③ لم يرهما أحدٌ قبلها):
#   ① المصنِّفُ يبتلع المشارك: «مالك» و«يوم» صُنِّفا فعلًا فجاع بابُ الإضافة — إصلاحُ §٥①.
#   ② تابعٌ غير معطوف: النعتُ والبدلُ والتوكيدُ وعطفُ البيان **ليست في جدول المفسّرات أصلًا**
#      (الجدولُ أعلن الرُّبعَ ونسي الثلاثة) — «لله ربِّ العالمين» · «الرحمنِ الرحيم».
#   ③ جارٌّ تحت عاطفة: «ومن الناس» — العاطفُ الملتصقُ يحجب الجارَّ عن الجدول.
#   ④ أجوفُ السَّند (أوّلُ آيةٍ بتابعٍ أو خبرٍ عن محذوف) — **لا يُفتَح له بابٌ مظنون**، بل
#      يُبوَّب بالاسم في سجلّ السقوط، فالسقوطُ المسمّى نتيجةٌ تُودَع لا تُخفى.
# والمصنِّفُ يُصلَح **بكاشفاتٍ معلنةٍ منتهية** لا بقاعدةٍ مفتوحة، وكلُّها من البايتات وحدَها:
#   اسمٌ بالعلامة: تنوينٌ (علامةُ اسمٍ خالصة) · «ال» بصورها · خاتمةٌ مكسورة (لا يُكسَر آخرُ
#   فعلٍ قطّ) · تاءٌ مربوطة · ألفٌ ولامٌ بعد جارٍّ ملتصق. وفعلٌ بالقالب **مع حركاته** لا
#   بهيكله وحدَه — فـ«فاعِل» المشارك يفارق «فاعَل» الفعل بكسرةِ عينه، وهذا هو **موضعُ
#   استثناء المشارك المعلن**. وصورُ المصدر المبدوءةُ بألفٍ (افتعال/انفعال/استفعال) تفارق
#   قوالبَها بطول الهيكل، وما بقي منها يُستثنى بعلامة الاسم نفسِها.
# وأولويةُ التقاطع ③ **تُعلَن استثناءً محدودًا**: قلعُ العاطف الملتصق (و/ف بفتحة) قبل عرض
#   السابق على JARR وعرضِ الكلمة على JPRE — **عند التقاطع وحدَه**، ولا يُمَسّ ترتيبُ
#   البوّابات الخمس في induction_engine.gate (فذاك حدٌّ مختومٌ لا يُعدَّل من هنا).
# والختمُ إن جاء فهو **بعديٌّ في أصله** (§٧): الأبوابُ رُئيت ثم صيغت، وهذا مُعلَنٌ لا مطموس.
# ═══════════ الجولة الرابعة — اتفاقيةُ تضييق البسط: تسجيلٌ مسبقٌ موقَّع قبل التشغيل ═══════
# أمرَ صاحبُ المستودع بتضييق البسط بعد أن عُرضت مادّتُه في الجولة الثالثة ولم تُطرَح. فهذا
# **تسجيلُها المسبق**، مكتوبٌ قبل أن يُشغَّل التضييقُ مرّةً واحدة، ومعه شرطُ إسقاطه.
#
# ▸ الاتفاقيةُ الحاكمة، واحدةً معلنة: **يُطرح من البسط ما لا يُطالَب بتفسيرِ جرِّه** — أي
#   ما ليست كسرتُه إعرابَ جرٍّ أصلًا. وهي خمسةُ أجناسٍ **منتهيةٍ مسمّاةٍ بكاشفٍ من البايتات**:
#     ⓐ حرفٌ مستقلٌّ (من · عن · بل · أم …) — الحرفُ مبنيٌّ لا يُعرَب.
#     ⓑ مبنيٌّ على الكسر بقائمةٍ منتهيةٍ مسمّاة (هؤلاء · هذه · يومئذ …).
#     ⓒ فعلٌ خاتمتُه كسرة (نونُ التوكيد والوقاية) — كسرةُ بناءٍ لا جرّ.
#     ⓓ جمعٌ مؤنثٌ سالمٌ بعد فعلٍ — **منصوبٌ بالكسرة** نيابةً، فليس مجرورًا.
#     ⓔ منادًى بعد «يا» — مبنيٌّ أو منصوب، وكسرتُه ليست جرًّا.
#   وكسرُ الوصل (386 المودَعُ في harakat_v0.json) **لا يُطرَح ههنا**: مقامُه ذاك، ولا يُجسَر
#   بين مقامين بلا قاعدة عبورٍ معلنة (waqf_layer.align_verse).
#
# ▸ **شرطُ النزاهة، وهو ألزمُ من الاتفاقية نفسِها**: التضييقُ يُطبَّق على **البسط كلِّه**
#   (11,420 موضعًا) لا على المتبقّي وحدَه. ولو طُبِّق على المتبقّي فقط لكان طرحًا انتقائيًّا
#   يخدم العتبة: يُنقِص المقامَ من حيث يؤلم ويبقيه من حيث ينفع. ولذلك **يُعَدّ المطروحُ
#   صنفين معروضين**: مطروحٌ كان مفسَّرًا (خسارةٌ في الأبواب) · مطروحٌ كان ساقطًا (ربحٌ في
#   العتبة). **فإن كان كلُّ المطروحِ من الساقط فالاتفاقيةُ مفصَّلةٌ على العتبة، وتُردّ.**
#
# ▸ توقيعي قبل التشغيل، بفواصل إسقاطٍ معلنة (هذه المرّة الأرقامُ منّي أنا، فليُحكَم بها عليّ):
#   - المطروحُ من البسط كلِّه: **250–700** موضعًا. إن جاء < 150 فالاتفاقيةُ صوريةٌ لا تضييق،
#     وإن جاء > 1,200 فهي مِكنسةٌ تبتلع المجرورَ الصحيح — وكلاهما إسقاط.
#   - **نسبةُ المطروحِ الذي كان مفسَّرًا ≥ 25%**. فإن كان المطروحُ كلُّه (أو 90%+) من
#     الساقط، فالاتفاقيةُ فُصِّلت على العتبة — **سقطت وتُردّ ولا يُعتدّ بمخرجها**.
#   - غيرُ المفسَّر بعد التضييق: **400–560**. وأقولها صريحةً: **لا أتوقّع نزولَه تحت 400**،
#     لأنّ أكبرَ أجناس المتبقّي (أجوفُ السَّند 201 · سابقٌ غيرُ مجرور 177) **ليست من مادّة
#     التضييق أصلًا** — وهي مجروراتٌ حقيقيّةٌ عجز الجدولُ عنها. فمن ظنّ أنّ التضييقَ يبلغ
#     بالعتبة فقد ظنّ أنّ الطرحَ يفسّر، والطرحُ لا يفسّر شيئًا.
#   - المقامُ الخامُ **يبقى معروضًا أبدًا** بمصالحةٍ محروسة (مضيَّق + مطروح = 11,420)، فلا
#     يُنقَل رقمٌ بلا مقامه كما لم يُنقَل سريرُ سترلنج بلا صيغته.
# ▸ **وحكمُ الجولة الثالثة لا يُمَسّ**: سقوطُها مثبتٌ في §٨ بأرقامه، ولا يُرفَع بمقامٍ جديد.
