def nominal_mark(w):
    """أوّلُ كاشفِ اسمٍ ينطبق على الكلمة، أو None — معدودٌ ومعروض."""
    sk = "".join(c for c, _ in w)
    if w[-1][1].startswith("تنوين"): return "تنوين"
    body = sk[1:] if (sk[:1] in JPRE and w[0][1] == "كسرة") else sk
