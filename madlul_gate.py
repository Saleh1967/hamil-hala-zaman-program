def unique_anchor(text, phrase, what):
    """موضعُ عبارةٍ **فريدةٍ** — وتكرارُها أو غيابُها صريخٌ لا تخمين."""
    folded = DG.fold(phrase)
    n = text.count(folded)
    if n != 1:
        raise MadlulError(
            E_SEAL,
            f"{what}: «{phrase[:40]}…» وقعت {n} مرّةً — والمرساةُ لا تكون إلا فريدة")
    i = text.index(folded)
    return dict(إزاحة=len(text[:i].encode("utf-8")),
                طول=len(folded.encode("utf-8")),
                بصمة=hashlib.sha256(folded.encode("utf-8")).hexdigest()[:16])


def in_slice(slice_text, phrase):
    """وقوعُ عبارةٍ في بايتات بابها: كلمةً قائمةً إن كانت مفردةً، وعبارةً إن تركّبت.

    والمفردةُ تُقبَل أيضًا مسبوقةً بواو العطف وحدَها، لأنّ المتنَ يسرد الأدواتِ
    معطوفةً («وهي ضه وره وبه») — وهذا **التخفيفُ الوحيد**، معلنٌ ومحدود: لا
    يُقبَل لصقٌ آخرُ ولا جزءُ كلمة، والمصنوعُ يُعرَض عليه في `falsify` فيُرَدّ.
    """
    folded = DG.fold(phrase)
    if " " in folded:
        return folded in slice_text
    if not folded:
        return False
    return any(w == folded or w == "و" + folded for w in slice_text.split())


