# madlul_gate.py — بابُ المدلول: خانةُ حروف الهجاء · معجمُ حروف المعاني · المبنيّاتُ الثلاث.
#
# ــ ٠) ما يُتعلَّم ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# في «أبحاث اللغة» من الشخصية ج٣ قسَم النبهانيُّ اللفظَ **باعتبار المدلول وحدَه**
# خمسةَ أقسام، وقد بُنيت تلك القسمةُ وصُودمت في `aqsam_gate` — **بناءً لا صدقًا**.
# وهذا البابُ يفتح ثلاثةَ أبوابٍ لازمةٍ لصدقها، كلَّ واحدٍ بمقياسه:
#
#   (أ) **خانةُ «لفظًا مفردًا مهمَلًا»** — وهي حروفُ الهجاء. وفصلُها عن أختها
#       «لفظًا مفردًا مستعمَلًا» **ليس** قلّةَ ورودٍ في مدوَّنةٍ، بل نصُّ صاحبِ
#       القسمة: «فحروفُ ضربٍ وهي ضه وره وبه لم توضع لمعنًى، مع أنّ كلًّا منها قد
#       وُضع له اسمٌ، فللأوّل الضادُ وللثاني الراءُ وللثالث الباء». فالاسمُ
#       (الضادُ) مستعمَلٌ، ومدلولُه (ضه) مهمَل — **والخانةُ لفظٌ ومعناها لفظ**،
#       كما قال: «فكلمةُ حروفِ الهجاء لفظٌ ومعناها كذلك لفظ، ولكنّه لفظٌ مهمَل».
#       وهذا عينُ ما في أختها المستعمَلة: «مثل لفظِ الكلمة… فهي لفظٌ ومعناها
#       كذلك لفظ» — فالفصلُ في **الوضعِ لمعنًى**، لا في العدِّ.
#       ونصيبُ الخانةِ في المجمَّد **صفرٌ منصوصٌ من صاحب القسمة نفسِه**: «إنّ
#       القرآنَ ليس فيه لفظٌ مهمَل»، «وأمّا أوائلُ السور فإنّ لها معانيَ… والحقُّ
#       فيها أنّها أسماءٌ للسور، وعليه لا تكون من المهمَل». فالصفرُ **مقروءٌ من
#       نصِّه ومصادَمٌ بمواضع الفواتح في المجمَّد**، لا مستنتَجٌ من سكوتنا.
#
#   (ب) **معجمُ مدلولِ حروف المعاني** — ولا يُستورَد من خارج: النبهانيُّ نفسُه
#       وضعه في متنه، أحدَ عشرَ صنفًا بأدواتها ومعانيها، وصدَّره بقوله: «ولا بدّ
#       من تفسير الحروف التي تشتدّ الحاجةُ في الفقه إلى معرفتها». فكلُّ أداةٍ
#       وكلُّ مدلولٍ ههنا **يُصادَم ببايتات صنفه**، ولا تُكتَب دلالةٌ بيدٍ.
#       ثمّ يُعرَض كلُّ صنفٍ على **الفاتورة** قاعدةَ تقسيمٍ مشروطٍ على المجمَّد،
#       فيقوم ما يدفع ثمنَه ويسقط ما لا يدفع — بالمقياس لا بالذوق.
#
#   (ج) **مدلولُ المبنيّات الثلاث** (الموصولُ · الإشارةُ · النداء) — وهذه ليست
#       في الشخصية إلا النداءَ وحدَه (صنفُها السادس)، والموصولُ والإشارةُ
#       **غائبان عن المتن وغيابُهما مقيسٌ لا مطويّ**. فيُطلَب لهما مصدرٌ مختومٌ
#       من خارج، ويُقبَل بـ**قاعدة النسختين** عينِها في `dalalat_gate`: لا يُقبَل
#       مدخلٌ إلا إذا وقع في **كلِّ نسخ كتابٍ مختومٍ واحدٍ** على الأقلّ. وما لم
#       يقع فهو **معلَّقٌ باسمه**، لا مطروحٌ ولا مقبول.
#
# ــ ١) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا يقيس أنّ قسمةَ «المدلولِ وحدَه» **صادقةٌ** بتمامها — يقيس ثلاثةَ أبوابٍ
#     منها: فصلَ خانةِ المهمَل بنصِّه، ومعجمَ الحروف بفاتورته، ومصدرَ المبنيّات
#     بقاعدة نسختيه. وما بقي من الخانات الخمس **دَينٌ يُسمّى ولا يُسعَّر**.
#   • وقوعُ الأداةِ صورةً في المجمَّد **ليس** دليلَ أنّها أداةٌ في ذلك الموضع
#     (فـ«ما» و«من» و«لا» صورٌ مشتركة). ولذلك لا يُدَّعى تحليلٌ نحويّ: الفاتورةُ
#     تسعِّر **صورةً تُطلِق على تاليها**، وهذا كلُّ ما تقوله.
#   • ردُّ أداةٍ إلى فرقةٍ في صنفٍ **بيدنا**، ولذلك كُتب لكلِّ فرقةٍ مرساتُها
#     ولكلِّ أداةٍ مدلولُها منصوصَين، ويُصادَمان ببايتات الصنف ليُراجَع الردّ.
#   • ألفيةُ ابن مالكٍ مختومةٌ **بنسخةٍ واحدة**، فهي ههنا **ضابطٌ بنيويّ**: تُعرَض
#     على قاعدة النسختين لتُثبِت أنّها **لا تُحقِّق** وحدَها، ولا يُقرَأ منها قبول.
