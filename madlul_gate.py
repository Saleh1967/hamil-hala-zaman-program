def lexicon_slices(text):
    """بايتاتُ كلِّ صنفٍ: من مرساته إلى مرساة تاليه — وآخرُها إلى ذيل المعجم."""
    head = text.index(DG.fold(MU3JAM_HEAD))
    tail = text.index(DG.fold(MU3JAM_TAIL))
    if not head < tail:
        raise MadlulError(E_SEAL, "ذيلُ المعجم قبل صدره — فرزٌ مختلّ")
    starts = [text.index(DG.fold(s["مرساة"])) for s in MU3JAM]
    if starts != sorted(starts) or starts[0] <= head or starts[-1] >= tail:
        raise MadlulError(E_SEAL, "مراسي الأصناف ليست على ترتيب المتن داخل المعجم")
    bounds = starts + [tail]
    return {s["صنف"]: text[bounds[k]:bounds[k + 1]] for k, s in enumerate(MU3JAM)}


def lexicon_rows(text, slices):
    """صفُّ كلِّ صنفٍ: فرقُه وأدواتُه ومدلولاتُها، كلُّها مصادَمةٌ في بايتاته."""
    rows = []
    for sanf in MU3JAM:
        body = slices[sanf["صنف"]]
        bands = []
        for band in sanf["فرق"]:
            if band["مرساة"] is not None and body.count(DG.fold(band["مرساة"])) != 1:
                raise MadlulError(
                    E_SEAL,
                    f"«{sanf['صنف']}»: مرساةُ فرقةِ «{band['فرقة']}» ليست فريدةً في بابها")
            tools = [dict(أداة=a, مدلول=m,
                          الأداةُ_في_بابها=in_slice(body, a),
                          المدلولُ_في_بابها=(None if m is None else in_slice(body, m)))
                     for a, m in band["أدوات"]]
            bands.append(dict(فرقة=band["فرقة"], مرساة=band["مرساة"], أدوات=tools))
        flat = [t for b in bands for t in b["أدوات"]]
        rows.append(dict(
            ترتيب=sanf["ترتيب"], صنف=sanf["صنف"], فرق=bands,
            عددُ_الفرق=len(bands),
            أدوات=len(flat),
            أدواتٌ_مميّزة=len({t["أداة"] for t in flat}),
            مدلولاتٌ_منصوصة=sum(1 for t in flat if t["مدلول"] is not None),
            أدواتٌ_بلا_مدلول=sum(1 for t in flat if t["مدلول"] is None),
            كلُّها_في_بابها=all(t["الأداةُ_في_بابها"] for t in flat)
                            and all(t["المدلولُ_في_بابها"] is not False for t in flat)))
    return rows


