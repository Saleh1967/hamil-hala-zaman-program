def band_forms(row, present):
    """صورُ صنفٍ في المقام: أدواتُه المفردةُ وحدَها — والمركَّبةُ لا تُقاس صورةً."""
    return sorted({DG.fold(t["أداة"]) for b in row["فرق"] for t in b["أدوات"]
                   if " " not in DG.fold(t["أداة"])} & present)


def rivals_of(stream, candidates, size):
    """ضوابطُ المثل: RIVALS فرقةً عشوائيّةً بالعدد نفسِه وببذرةٍ معلنةٍ قبل القياس."""
    rng = random.Random(TG.CONTROL_SEED)
    out = []
    for _ in range(RIVALS):
        forms = tuple(rng.sample(candidates, size))
        try:
            out.append(TG.split_bill(stream, TG.fire_of(stream, forms=set(forms)),
                                     forms))
        except TG.Ta3allumError as exc:
            raise MadlulError(exc.code, exc.message) from exc
    return out


def priced(stream, forms, candidates, name):
    """فاتورةُ فرقةٍ كاملةً: الحكمُ المفردُ ثمّ الحكمُ المميِّزُ بمقارنةِ المثل.

    والحكمان **لا يُخلَطان**: الأوّلُ حكمُ `ta3allum_gate.rule_bill` وحدَه، وقد
    قِيس أنّه **لا يفصل ههنا** (فرقةٌ عشوائيّةٌ تناله). والثاني هو المميِّز:
    غلبةُ أدنى ضوابط المثل جميعًا.
    """
    try:
        bill = TG.rule_bill(stream, tuple(forms), TG.fire_of(stream, forms=set(forms)),
                            random.Random(TG.CONTROL_SEED))
    except TG.Ta3allumError as exc:
        raise MadlulError(exc.code, exc.message) from exc
    rivals = rivals_of(stream, candidates, len(forms))
    beats = bill["Δ"] < min(rivals)
    bill.update(صنف=name, في_الميدان=True, ضوابطُ_المثل=RIVALS,
                أدنى_المثل=round(min(rivals), 1),
                وسيطُ_المثل=round(sorted(rivals)[len(rivals) // 2], 1),
                غلبَ_المثل=bool(beats),
                حكمٌ_مميِّز=("فاصلٌ بمقارنةِ المثل" if beats
                            else "غيرُ فاصلٍ — لم يغلب ضوابطَ المثل"))
    return bill


def lexicon_station(rows):
    """ميدانُ المعجم: كلُّ صنفٍ بفاتورته وبضوابط مثله، والثمنُ مقيسٌ قبل الاستعمال."""
    _, stream, _ = corpus()
    present = set(stream)
    candidates, _ = TG.hypothesis_space(stream)

    bills = []
    for row in rows:
        forms = band_forms(row, present)
        if not forms:
            bills.append(dict(صنف=row["صنف"], في_الميدان=False, صور=[],
                              حكم="خارجَ الميدان — لا تقع صورُ أدواته في المجمَّد"))
            continue
        bills.append(priced(stream, forms, candidates, row["صنف"]))

    forms = sorted({f for r in rows for f in band_forms(r, present)})
    whole = priced(stream, forms, candidates, "المعجمُ كلُّه قاعدةً واحدة")

    # **برهانُ خواءِ الحكم المفرد**: فرقةٌ عشوائيّةٌ بعددِ صورِ المعجم تُسعَّر
    #   بالمكيال نفسِه — فإن نالت «مُودَعةٌ بالبرهان» فالقبولُ المفردُ لا يفصل.
    rng = random.Random(TG.CONTROL_SEED)
    hollow_forms = tuple(rng.sample(candidates, len(forms)))
    hollow = TG.rule_bill(stream, hollow_forms,
                          TG.fire_of(stream, forms=set(hollow_forms)),
                          random.Random(TG.CONTROL_SEED))
    tokens = sum(1 for s in stream if s in set(forms))
    return dict(
        مقام=len(stream),
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ضوابطُ_المثل=RIVALS,
        صورٌ_واقعةٌ_في_المقام=len(forms),
        مواضعُها=tokens,
        نصيبُها=round(tokens / len(stream), 4),
        ثمنُ_إعلان_المعجم=round(TG.declaration_cost(forms), 1),
        أصناف=bills,
        المعجمُ_كلُّه=whole,
        خواءُ_الحكم_المفرد=dict(
            بيان=("فرقةٌ عشوائيّةٌ من فضاء `ta3allum_gate` بعددِ صورِ المعجم نفسِه — "
                  "إن نالت «مُودَعةٌ بالبرهان» فالحكمُ المفردُ لا يفصل ههنا، "
                  "والمميِّزُ مقارنةُ المثل وحدَها"),
            عدد=len(hollow_forms), Δ=hollow["Δ"], حكم=hollow["حكم"],
            خاوٍ=bool(hollow["حكم"] == "مُودَعةٌ بالبرهان")),
    )


