# ═══ ② محطّةُ البناء — الشجرةُ مقروءةٌ واشتقاقُها مُصادَم ═══════════════════
def bina_station(text):
    """قسمةُ «المدلولِ وحدَه» كما بُنيت في `aqsam_gate`: فصولُها منصوصةٌ في
    بايتات المتن، وعددُها **مشتقٌّ** من فصولها ومصادَمٌ بمنصوصه.

    ولا تُكتَب ههنا عقدةٌ واحدةٌ بيد: لو زِيد فصلٌ هناك تغيَّر العددُ ههنا
    بمقياسه، ولو زُحزح نصُّه صرخت المصادمة. **فمصدرُ الحقيقة واحد.**
    """
    if QISMA_NAME not in AG.QISMAT:
        raise QismaError(E_SEAL, f"قسمةُ «{QISMA_NAME}» ليست في شجرة الأقسام")
    q = AG.QISMAT[QISMA_NAME]
    derived, names = AG.derive(q["شجرة"])
    phrase, stated = q["منصوص"]
    rows = []
    for node in q["شجرة"]:
        hits = text.count(DG.fold(node["فصل"]))
        if hits != 1:
            raise QismaError(E_SEAL, f"فصلٌ ليس فريدًا في المتن ({hits}): {node['فصل']}")
        rows.append(dict(فصل=node["فصل"], بيان=node["بيان"], مواضع=hits))
    if text.count(DG.fold(q["صدر"])) != 1:
        raise QismaError(E_SEAL, "صدرُ القسمة ليس فريدًا في المتن — صريخ")
    if text.count(DG.fold(phrase)) < 1:
        raise QismaError(E_SEAL, f"عبارةُ العدد غائبةٌ عن المتن: {phrase}")
    if derived != stated:
        raise QismaError(E_SEAL, f"المشتقُّ {derived} خالف المنصوصَ {stated}")
    return dict(
        قسمة=QISMA_NAME, حيثية=q["حيثية"], صدر=q["صدر"],
        فصول=rows, عددُ_الفصول=len(rows),
        أقسامٌ_مشتقّة=derived, منصوص=stated, أسماءُ_الأقسام=list(names),
        بيان=("البناءُ مقروءٌ من `aqsam_gate` ومُصادَمٌ ببايتات المتن — "
              "والبناءُ **لا يستلزم الصدق**، وصدقُه هو المقيسُ في هذا الباب"),
    )


# ═══ ③ محطّةُ الإذن — المحوران يُقرآن من وديعتهما ═══════════════════════════
def axis_station():
    """المحورُ الثاني مفتوحٌ بمكياله، والثالثُ مغلقٌ **بسببٍ منصوص** هو عينُ
    ما يقيسه هذا الباب. فإن أُغلق الثاني أو فُتح الثالثُ أو زُحزح السببُ
    صرخ البابُ — فلا يُقاس على ختمٍ زائل."""
    mih = _deposit(MIHWAR_DEPOSIT)["المحاور_v0"]
    axes = mih.get("المحاور") or mih.get("محاور") or []
    by_name = {a.get("محور"): a for a in axes}
    if AXIS_OPEN not in by_name or AXIS_SHUT not in by_name:
        raise QismaError(E_SEAL, "محورٌ من المحورين غائبٌ عن وديعة المحاور")
    second, third = by_name[AXIS_OPEN], by_name[AXIS_SHUT]
    if not (second.get("مفتوح") and second.get("تحقّقَ_شرطُه")):
        raise QismaError(E_SEAL, f"محورُ «{AXIS_OPEN}» ليس مفتوحًا — لا يُقاس فيه")
    if third.get("مفتوح"):
        raise QismaError(E_SEAL, f"محورُ «{AXIS_SHUT}» فُتح — اجتماعٌ قبل أفرادِه")
    cause = third.get("سبب", "")
    missing = [t for t in AXIS_CAUSE if t not in cause]
    if missing:
        raise QismaError(E_SEAL, "سببُ إغلاقِ المحور الثالثِ زُحزح عن طرفيه "
                                 "الثابتين: " + " · ".join(missing))
    return dict(
        المحورُ_الثاني=dict(محور=AXIS_OPEN, مكيال=second.get("مكيال"),
                            مفتوح=True, رتبة=second.get("رتبة")),
        المحورُ_الثالث=dict(محور=AXIS_SHUT, مفتوح=False, سبب=third.get("سبب"),
                            رتبة=third.get("رتبة")),
        طرفا_السبب=list(AXIS_CAUSE),
        بيان=("سببُ إغلاقِ الثالثِ منصوصٌ وطرفاه ثابتان: أنّ الفردَ المعنيَّ "
              "**صدقُ المدلولِ وحدَه**، وأنّ الاجتماعَ **لا يُقاس قبل أفرادِه**. "
              "وهذا البابُ يعرض ذلك الفردَ على **مكيالِ السطح** فيبلغ به ما "
              "يبلغ، ولا يفتح به محورًا. وعرضُه على مكيالِ **الوضع** بابٌ آخرُ "
              "هو `sidq_gate`، وإليه تُنسَب أرقامُ ذلك المكيال"),
    )


# ═══ ④ الميدان — المجمَّدُ وحدَه صورًا ═══════════════════════════════════════
def corpus():
    try:
        verses, stream, texts = TG.corpus_surfaces()
        candidates, counts = TG.hypothesis_space(stream)
    except TG.Ta3allumError as exc:
        raise QismaError(E_MISSING, exc.message) from exc
    if len(stream) < MIN_N:
        raise QismaError(E_SHAPE, f"مقامُ الكلماتِ {len(stream)} دون حدِّ التسعير")
    return verses, stream, texts, candidates, counts


def field_station(verses, stream, counts, candidates):
    return dict(
        آيات=len(verses), مواضع=len(stream), صورٌ_متمايزة=len(counts),
        مرشّحون=len(candidates),
        حدُّ_التسعير=MIN_N, سقفُ_الانحلال=TG.COVER_CEILING,
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ثمنُ_إعلانِ_الفضاء=round(TG.declaration_cost(candidates), 1),
    )


# ═══ ⑤ الفصلُ الأوّل: مفردٌ ⟷ مركّب — فصلُ وحدةٍ يردُّه حارسُ الانحلال ═══════
def ifrad_station(verses, stream):
    """وحدةُ المقامِ الكلمةُ، فكلُّ موضعٍ **مفردٌ بالبناء**: نصيبُ الفصل الكلُّ،
    فيردُّه حارسُ الانحلالِ **قبل** أن تُفتَح له فاتورةٌ — وهذا ترتيبُ
    `rule_bill` المعلن بعينه، لا استثناءً ههنا.

    والمركَّبُ يُعَدُّ بوحدةٍ أخرى (الآية) ليُعلَم أنّ الخانةَ ليست خاليةً في
    اللغة بل **خارجَ وحدةِ مقامنا** — وسمُ وحدةٍ لا حكمُ مدلول.
    """
    singles = sum(1 for s in stream if " " not in s)
    share = round(singles / len(stream), 4)
    degenerate = share >= TG.COVER_CEILING
    return dict(
        فصل="قد يكون مفرداً، وقد يكون مركباً",
        مكيالٌ_سطحيّ="وحدةُ التقطيع — فاصلُ البياض",
        مواضعُ_المفرد=singles, نصيب=share,
        مركّبٌ_بوحدةِ_الآية=len(verses),
        منحلّة=bool(degenerate),
        حكم=("مردودٌ بالانحلال — فصلٌ يُطلِق على المقام كلِّه لا يقسمه، "
             "فلا تُفتَح له فاتورة" if degenerate else "يُسعَّر"),
        بيان=("حاسمٌ بالبناء ولا يشتري بتًّا: فصلُ **وحدةٍ** لا فصلُ مدلول — "
              "والمركَّبُ خارجَ وحدةِ المقام، عمًى معلنٌ لا خانةٌ خالية"),
    )


# ═══ ⑥ الفصلُ الثاني: مستعمَلٌ ⟷ مهمَل — مكيالُ الندرةِ يُعرَض فيُرَدّ ═══════
def ihmal_station(text, counts):
    """المكيالُ السطحيُّ المعروضُ: **الندرة** (صورةٌ لا تقع إلا مرّةً). ويُرَدّ
    بعدده وبنصِّ صاحبِ القسمة معًا:

      • نصُّه: «إنّ القرآن ليس فيه لفظ مهمل» · «والحقُّ فيها أنّها أسماءٌ
        للسور» — مُصادَمان ببايتات بابهما في `madlul_gate.HIJA_ANCHORS`.
      • وعدُّه: لو كانت الندرةُ إهمالًا لَحكم المكيالُ بالإهمال على آلافِ
        صورٍ نصُّه يكذّبها، ونصيبُ الفواتحِ منها **ضئيلٌ مقيس**.

    ومواضعُ الفواتحِ تُقرَأ من ختمِ `madlul_v0.json` وتُصادَم — لا يُكتَب رقمٌ
    مرّتين في المستودع.
    """
    anchors = {}
    for key in ("صفرُ المهمَل في القرآن", "أوائلُ السور أسماءٌ للسور"):
        phrase = MG.HIJA_ANCHORS.get(key)
        if phrase is None:
            raise QismaError(E_SEAL, f"مرساةٌ غائبةٌ عن `madlul_gate`: {key}")
        hits = text.count(DG.fold(phrase))
        if hits != 1:
            raise QismaError(E_SEAL, f"مرساةٌ ليست فريدةً في المتن ({hits}): {key}")
        anchors[key] = phrase
    faw = {DG.fold(f) for f in MG.FAWATIH}
    present = sorted(f for f in faw if counts.get(f, 0) > 0)
    places = sum(counts.get(f, 0) for f in faw)
    sealed = _deposit(MADLUL_DEPOSIT)["المدلول_v0"]["خانةُ_حروف_الهجاء"]["صفرُ_المجمَّد"]
    if sealed["مواضعُ_الفواتح"] != places:
        raise QismaError(E_SEAL, f"مواضعُ الفواتحِ {places} خالفت ختمَ المدلول "
                                 f"{sealed['مواضعُ_الفواتح']}")
    rare = sorted(s for s, n in counts.items() if n == 1)
    rare_faw = [s for s in rare if s in faw]
    share = round(len(rare_faw) / len(rare), 6) if rare else 0.0
    return dict(
        فصل="قد يكون مستعملاً، وقد يكون مهملاً",
        مكيالٌ_سطحيّ="الندرة — صورةٌ لا تقع إلا مرّةً واحدة",
        مراسٍ=anchors,
        صورٌ_نادرة=len(rare), فواتحُ_في_النادر=len(rare_faw),
        نصيبُ_الفواتحِ_من_النادر=share,
        صورُ_الفواتحِ_الحاضرة=present, مواضعُ_الفواتح=places,
        حكم=("مردودٌ بعدده وبنصِّ صاحبِ القسمة — الندرةُ ليست إهمالًا: "
             "لو كانت لَحكمت بالإهمال على ما يكذّبه نصُّه"),
        بيان=("الفصلُ نفسُه **لا يُرَدّ**: المردودُ مكيالُه السطحيُّ وحدَه. "
              "وخانةُ المهمَلِ في مقامنا صفرٌ **بحكم صاحبِ القسمة** لا بسكوتنا"),
    )


# ═══ ⑦ الفصلُ الثالث: مدلولٌ معنًى ⟷ مدلولٌ لفظ — ميدانٌ يُعَدّ ولا يُلفَّق ═══
def lafz_names():
    """طائفةُ أسماءِ اللفظِ **مغلقةٌ مقروءةٌ من موضعين**: أسماءُ الهجاء من
    `madlul_gate`، وأمثلةُ أقسامِ «المدلولِ وحدَه» التي مدلولُها لفظٌ من شجرة
    `aqsam_gate` — وهي أمثلةُ الأقسامِ الأربعةِ سوى «المدلول معنى»."""
    q = AG.QISMAT[QISMA_NAME]
    amthila = q["أمثلة"]
    if MA3NA_LEAF not in amthila:
        raise QismaError(E_SEAL, f"مثالُ «{MA3NA_LEAF}» غائبٌ عن الشجرة — صريخ")
    lafz = [v for k, v in sorted(amthila.items()) if k != MA3NA_LEAF]
    return tuple(MG.HIJA_NAMES), tuple(lafz), amthila[MA3NA_LEAF]


def hikaya_station(counts):
    """الطائفةُ تُعَدُّ **صورةً** في المجمَّد، ولا يُقال ما عنته في موضعها.
    فإن لم يبلغ ميدانُها حدَّ التسعيرِ المعلنَ خُتم السقوطُ **بالمقام** —
    على سنّةِ `ihala_gate` في التمييزِ والحال: لا يُسعَّر قانونٌ على ميدانٍ
    لا يحتمله، ولا يُطوى غيابُه."""
    hija, lafz, ma3na = lafz_names()
    rows = []
    for name in sorted(set(hija) | set(lafz)):
        folded = DG.fold(name)
        rows.append(dict(اسم=name, صورة=folded, مواضع=counts.get(folded, 0)))
    present = [r for r in rows if r["مواضع"] > 0]
    field = sum(r["مواضع"] for r in rows)
    return dict(
        فصل="قد يكون معنى، وقد يكون لفظاً",
        مكيالٌ_سطحيّ="وقوعُ صورِ طائفةِ أسماءِ اللفظِ في المجمَّد",
        طائفة=dict(أسماءُ_الهجاء=len(hija), أمثلةٌ_مدلولُها_لفظ=list(lafz),
                   مثالُ_المعنى=ma3na, صورٌ_في_الطائفة=len(rows)),
        صورٌ_حاضرة=[r["اسم"] for r in present],
        ميدانُ_الطائفة=field,
        بلغَ_حدَّ_التسعير=bool(field >= MIN_N),
        حكم=("ساقطٌ بالمقام — ميدانُ الطائفةِ دون حدِّ التسعير، فلا يُسعَّر "
             "عليه فصلٌ ولا يُدَّعى حسمُه" if field < MIN_N else "يُسعَّر"),
        الدَّينُ_باقٍ=bool(field < MIN_N),
        بيان=("وقوعُ الصورةِ لا يفصل الحكايةَ من الاستعمال: الصورةُ هي هي في "
              "الوجهين، والفاصلُ **الوضعُ** — وهو محورٌ آخرُ بمكيالٍ آخر"),
    )


# ═══ ⑧ محطّةُ الصنعة — قسمةٌ تُبنى من الصورة وحدَها ثمّ تُسعَّر ═══════════════
def cell_of(form, space):
    """قسمُ الصورةِ من الفصلين المعلنين — واحدٌ لا غير، جامعةٌ مانعةٌ بالبناء."""
    member = form in space
    holds = any(f in form for f in space if f != form)
    if member:
        return CELLS[0] if holds else CELLS[1]
    return CELLS[2] if holds else CELLS[3]


def sanaa_station(stream, candidates):
    """صنعةُ البناء مطبَّقةً: مقسَمٌ واحدٌ (الصورة) · حيثيةٌ معلنةٌ (نسبتُها إلى
    الفضاء) · فصلان **من عندنا** · عددٌ مشتقٌّ ٢×٢ · وشاهدٌ لكلِّ قسمٍ من
    المقام. ثمّ **الفاتورةُ تحكم** — والنتيجةُ تُعلَن كما تقع."""
    space = set(candidates)
    fires = {c: set() for c in CELLS}
    sample = {}
    for i, s in enumerate(stream):
        c = cell_of(s, space)
        fires[c].add(i)
        sample.setdefault(c, s)
    derived = 1
    for _ in FUSUL:
        derived *= 2
    if derived != len(CELLS):
        raise QismaError(E_SEAL, f"عددُ الأقسامِ المشتقُّ {derived} خالف المعلنَ")
    rows = []
    for c in CELLS:
        fire = fires[c]
        share = round(len(fire) / len(stream), 4)
        if not fire:
            raise QismaError(E_SHAPE, f"قسمٌ لا يقع في المقام: {c}")
        if share >= TG.COVER_CEILING:
            rows.append(dict(قسم=c, إطلاق=len(fire), نصيب=share, شاهد=sample[c],
                             منحلّة=True, حكم="مردودةٌ بالانحلال"))
            continue
        try:
            bill = TG.rule_bill(stream, tuple(candidates), fire,
                                random.Random(TG.CONTROL_SEED))
        except TG.Ta3allumError as exc:
            raise QismaError(exc.code, exc.message) from exc
        rows.append(dict(قسم=c, إطلاق=bill["إطلاق"], نصيب=bill["نصيب"],
                         شاهد=sample[c], **{"Δ": bill["Δ"]},
                         ضابط=bill["ضابط"], منحلّة=bill["منحلّة"], حكم=bill["حكم"]))
    accepted = sum(1 for r in rows if r["حكم"] == "مُودَعةٌ بالبرهان")
    return dict(
        مقسَم="الصورة", حيثية="نسبةُ الصورةِ إلى الفضاء المعلن — بلا قراءةِ مدلول",
        فصولٌ_من_عندنا=[dict(فصل=f, سؤال=s) for f, s in FUSUL],
        إقرار=("الفصلان **من عندنا لا من المتن** — يُعلَن ذلك ولا يُنسَب إلى "
               "إمامٍ ما لم يقله"),
        أقسامٌ_مشتقّة=derived, أقسام=rows,
        مُودَعة=accepted, مردودة=len(rows) - accepted,
        حكم=("البناءُ الصحيحُ ليس صدقًا — قسمةٌ جامعةٌ مانعةٌ مشتقّةُ العددِ "
             "ردَّتها الفاتورةُ كلَّها" if accepted == 0 else
             "قسمةٌ مبنيّةٌ اشترى بعضُ أقسامِها بتًّا — والعددُ معروض"),
    )


def control_station(stream):
    """ضابطُ القبول: قاعدةُ الكتابِ المختومةُ تُعاد فاتورتُها وتُصادَم بختمها —
    فالمكيالُ **يقبل** في هذا الميدان نفسِه، والردُّ ردُّ مقياسٍ لا عجزُ مكيال."""
    trig = DG.TRIGGERS.get(CONTROL_RULE)
    if trig is None or not trig.get("صور"):
        raise QismaError(E_SEAL, f"قاعدةُ الضابطِ «{CONTROL_RULE}» غائبةٌ عن بابها")
    forms = tuple(trig["صور"])
    try:
        fire = TG.fire_of(stream, forms=set(forms))
        bill = TG.rule_bill(stream, forms, fire, random.Random(TG.CONTROL_SEED))
    except TG.Ta3allumError as exc:
        raise QismaError(exc.code, exc.message) from exc
    sealed = None
    for row in _deposit(TA3ALLUM_DEPOSIT)["التعلُّم_v0"]["قواعدُ_الكتاب"]:
        if row["صفّ"] == CONTROL_RULE:
            sealed = row
    if sealed is None:
        raise QismaError(E_SEAL, f"قاعدةُ «{CONTROL_RULE}» غائبةٌ عن وديعة التعلُّم")
    if bill["Δ"] != sealed["Δ"] or bill["حكم"] != sealed["حكم"]:
        raise QismaError(E_SEAL, f"ضابطُ القبولِ خالف ختمَه: {bill['Δ']} ⟷ "
                                 f"{sealed['Δ']}")
    return dict(قاعدة=CONTROL_RULE, صور=list(forms), إطلاق=bill["إطلاق"],
                **{"Δ": bill["Δ"]}, ضابط=bill["ضابط"], حكم=bill["حكم"],
                مصادَمٌ_بوديعة=TA3ALLUM_DEPOSIT)


# ═══ ⑨ سدادُ الديون — ما سُدَّ برقمه، وما بقي باسمه ══════════════════════════
def debts_station(ifr, ihm, hik, san):
    """الدَّينُ المسمّى يُسدَّد **بقدر ما قِيس** لا بدعوى: يُنقَل من «مسمًّى بلا
    قياس» إلى «مقيسٌ بحكمه»، وما بقي منه يبقى باسمه بلا رقم."""
    paid = [
        dict(دَين="صدقُ قسمةِ «المدلولِ وحدَه» — أيُحسَم من السطح؟",
             موضعُه="MADLUL.md §⑤ · aqsam_gate §٢ · mihwar_v0.json المحورُ الثالث",
             سُدَّ_بـ=("ثلاثةُ فصولٍ عُرضت على السطح: فصلُ الوحدةِ مردودٌ "
                       "بالانحلال · مكيالُ الإهمالِ مردودٌ بعدده · فصلُ المعنى "
                       "واللفظِ ساقطٌ بالمقام"),
             حكم="لا يُحسَم من سطحِ «الدالِّ وحدَه» — والمحورُ الثالثُ يبقى مغلقًا",
             أرقامُه=dict(نصيبُ_المفرد=ifr["نصيب"],
                          نصيبُ_الفواتحِ_من_النادر=ihm["نصيبُ_الفواتحِ_من_النادر"],
                          ميدانُ_الطائفة=hik["ميدانُ_الطائفة"])),
        dict(دَين="أتقوم صنعةُ بناء القواعد على السطح وحدَه؟",
             موضعُه="aqsam_gate §٠ — الخطواتُ الخمس",
             سُدَّ_بـ="قسمةٌ رباعيّةٌ بُنيت بالخطوات الخمسِ وسُعِّرت أقسامُها",
             حكم=san["حكم"],
             أرقامُه=dict(أقسامٌ_مشتقّة=san["أقسامٌ_مشتقّة"],
                          مُودَعة=san["مُودَعة"], مردودة=san["مردودة"])),
    ]
    return dict(مسدَّدٌ_بقياسه=paid, عددُ_المسدَّد=len(paid),
                بلا_رقم=list(DEBTS), عددُ_ما_بلا_رقم=len(DEBTS))


# ═══ ⑩ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ، ونجاحُ واحدةٍ يُسقِط البابَ ═════
def falsify(text, stream, candidates, bna, ifr, ihm, hik, san, ctl):
    T = []

    # ① البناءُ مقروءٌ لا مكتوب: العددُ مشتقٌّ من الفصول ومصادَمٌ بمنصوصه.
    T.append(("العددُ المشتقُّ خالف المنصوصَ", bna["أقسامٌ_مشتقّة"] != bna["منصوص"]))
    T.append(("أسماءُ الأقسامِ ليست بعدد المشتقّ",
              len(bna["أسماءُ_الأقسام"]) != bna["أقسامٌ_مشتقّة"]))
    T.append(("فصلٌ من فصول القسمةِ ليس فريدًا في المتن",
              any(r["مواضع"] != 1 for r in bna["فصول"])))

    # ② الفصلُ الأوّل: لو لم يُطلِق على الكلِّ لَما صحَّ وصفُه بالانحلال.
    T.append(("فصلُ الوحدةِ خُتم منحلًّا ونصيبُه دون السقف",
              ifr["منحلّة"] and ifr["نصيب"] < TG.COVER_CEILING))
    T.append(("المركَّبُ بوحدةِ الآيةِ صفرٌ — عمًى ادُّعي ولم يُعَدّ",
              ifr["مركّبٌ_بوحدةِ_الآية"] <= 0))

    # ③ الفصلُ الثاني: المكيالُ مردودٌ بعدده — فلو غلبت الفواتحُ النادرَ لَبطل
    #    الردُّ. والنصيبُ يجب أن يكون ضئيلًا مقيسًا لا مقولًا.
    T.append(("نصيبُ الفواتحِ من النادرِ بلغ العُشرَ فأكثر",
              ihm["نصيبُ_الفواتحِ_من_النادر"] >= 0.1))
    T.append(("الصورُ النادرةُ دون الفواتحِ عددًا — لا ميدانَ للردّ",
              ihm["صورٌ_نادرة"] <= ihm["فواتحُ_في_النادر"]))
    T.append(("مواضعُ الفواتحِ صفرٌ وقد خُتمت", ihm["مواضعُ_الفواتح"] <= 0))

    # ④ الفصلُ الثالث: الحكمُ يُشتَقُّ من الميدانِ لا من الرغبة.
    T.append(("ميدانُ الطائفةِ بلغَ الحدَّ وخُتم ساقطًا بالمقام",
              hik["بلغَ_حدَّ_التسعير"] and "بالمقام" in hik["حكم"]))
    T.append(("الدَّينُ رُفِع والميدانُ دون الحدّ",
              not hik["بلغَ_حدَّ_التسعير"] and not hik["الدَّينُ_باقٍ"]))
    T.append(("طائفةُ أسماءِ اللفظِ خلت من أسماء الهجاء الثمانيةِ والعشرين",
              hik["طائفة"]["أسماءُ_الهجاء"] != 28))

    # ⑤ القسمةُ المبنيّةُ جامعةٌ مانعة: كلُّ موضعٍ في قسمٍ واحدٍ لا غير.
    space = set(candidates)
    counted = sum(r["إطلاق"] for r in san["أقسام"])
    T.append(("أقسامُ القسمةِ المبنيّةِ لا تستوعب المقام", counted != len(stream)))
    T.append(("قسمٌ من القسمةِ المبنيّةِ خلا من شاهد",
              any(not r.get("شاهد") for r in san["أقسام"])))
    T.append(("صورةٌ وقعت في قسمين — القسمةُ ليست مانعة",
              any(len({cell_of(s, space)}) != 1 for s in stream[:1000])))

    # ⑥ الحَكَمُ ليس عاجزًا: ضابطُ القبولِ مُودَعٌ ومصادَمٌ بختمه.
    T.append(("ضابطُ القبولِ لم يُودَع — فالردُّ عجزُ مكيالٍ لا حكمُ مقياس",
              ctl["حكم"] != "مُودَعةٌ بالبرهان"))

    # ⑦ ولا يُقرَأ مدلولٌ ههنا: الطائفةُ مقروءةٌ صورةً، والمتنُ مصادَمٌ لا مفسَّر.
    T.append(("متنُ الشخصيةِ خلا من صدرِ القسمة", DG.fold(bna["صدر"]) not in text))

    # ⑧ الديونُ تُسمّى ولا تُرقَّم.
    T.append(("دَينٌ حملَ رقمًا", any(any(ch.isdigit() for ch in d) for d in DEBTS)))

