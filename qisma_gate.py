# ═══ ① الودائعُ القائمةُ تُقرَأ ولا تُنسَخ ═══════════════════════════════════
def _deposit(name):
    path = os.path.join(ROOT, name)
    if not os.path.exists(path):
        raise QismaError(E_MISSING, f"وديعةٌ غائبةٌ عن الشجرة: {name}")
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


