# qisma_gate.py — بابُ القسمة: **أيُحسَم صدقُ قسمةِ «المدلولِ وحدَه» من سطحِ
#                 «الدالِّ وحدَه»؟** — وصنعةُ بناء القواعد مطبَّقةً ومقيسة.
#
# §٠ الدَّينُ المعروضُ للسداد بنصِّه. في `aqsam_gate` **بُنيت** قسمةُ «المدلولِ
#    وحدَه» خمسةَ أقسامٍ باشتقاقٍ من فصولٍ منصوصة، وخُتم هناك أنّ البابَ
#    «لا يقيس أنّ القسمةَ **صادقةٌ على العربية**». وفي `MADLUL.md` بقي الدَّينُ
#    بلفظه: «ودَينُ صدقِ قسمةِ المدلولِ وحدَه **يبقى مسمًّى**». وفي
#    `mihwar_v0.json` المحورُ الثالثُ («الدالُّ والمدلولُ معًا») **مغلقٌ** وسببُ
#    إغلاقه منصوصٌ: «**وصدقُ المدلولِ وحدَه لم يُقَس بعد**». فهذا البابُ يقيس
#    ذلك السببَ بعينه، **ولا يُوسِّع الدعوى**: المقيسُ **أيُحسَم الفصلُ من
#    الصورة** — لا أنّ القسمةَ صادقةٌ ولا أنّها باطلة.
#
# §١ المكيالُ واحدٌ ومُعلَن: **سطحُ «الدالِّ وحدَه»**. ولا يُقرَأ ههنا مدلولُ
#    صورةٍ واحدة: كلُّ مكيالٍ يُعرَض على الفصول الثلاثةِ إمّا صورةٌ في بايتات
#    المجمَّد، وإمّا وقوعٌ معدودٌ فيها. والحَكَمُ فاتورةُ `ta3allum_gate.rule_bill`
#    وحدَها بترتيبها المعلن (الانحلالُ أوّلًا · ثمّ الفاتورة · ثمّ الضابط)،
#    ولا عتبةَ سواها ولا يدُ أحد.
#
# §٢ وثلاثةُ فصولٍ لا يُخلَط حكمُ أحدها بالآخر — ولكلٍّ سؤالٌ واحدٌ قابلٌ للتكذيب:
#    ① **مفردٌ ⟷ مركّب**: مكيالُه السطحيُّ **وحدةُ التقطيع** (فاصلُ البياض)،
#       وهو حاسمٌ بالبناء — ولذلك **لا يشتري بتًّا**: نصيبُه الكلُّ، فيردُّه
#       حارسُ الانحلالِ قبل أن تُفتَح له فاتورة. فهو فصلُ **وحدةٍ** لا فصلُ مدلول.
#    ② **مستعمَلٌ ⟷ مهمَل**: مكيالُه السطحيُّ المعروضُ **الندرة**، ويُقاس
#       فيُرَدّ بعدده: نصيبُ فواتحِ السورِ من الصورِ النادرة ضئيلٌ مقيس،
#       ولو صحَّ المكيالُ لَحكم بالإهمال على آلافٍ يُكذِّبها نصُّ صاحبِ القسمة
#       («إنّ القرآن ليس فيه لفظ مهمل» · «والحقُّ فيها أنّها أسماءٌ للسور»).
#    ③ **مدلولٌ معنًى ⟷ مدلولٌ لفظ**: طائفةُ أسماءِ اللفظِ مغلقةٌ معلنةٌ قبل
#       القياس (أسماءُ الهجاء الثمانيةُ والعشرون من `madlul_gate` وأمثلةُ
#       الأقسامِ المنصوصةُ في `aqsam_gate`)، ومواضعُها في المجمَّد **تُعَدّ**؛
#       فإن لم تبلغ حدَّ التسعيرِ المعلنَ خُتم السقوطُ **بالمقام** ولم يُلفَّق
#       حكمٌ على ميدانٍ لا يحتمله.
#
# §٣ وصنعةُ بناء القواعد **تُطبَّق ههنا لا تُوصَف**: تُبنى قسمةٌ رباعيّةٌ من
#    الصورة وحدَها بخطوات `aqsam_gate` الخمس (مقسَمٌ واحدٌ · حيثيةٌ معلنةٌ ·
#    فصلان منصوصان **مُقَرٌّ بأنّهما من عندنا لا من المتن** · عددٌ مشتقٌّ
#    ٢×٢ · شاهدٌ لكلِّ قسمٍ من المقام)، ثمّ **تُسعَّر أقسامُها بالفاتورة**.
#    ونتيجتُها تُعلَن كما تقع: **البناءُ الصحيحُ ليس صدقًا** — قسمةٌ جامعةٌ
#    مانعةٌ مشتقّةُ العددِ قد تردُّها الفاتورةُ كلَّها. ولئلّا يُقرَأ الردُّ عجزًا
#    في المكيال، يُعرَض معها **ضابطُ قبولٍ** من الميدان نفسِه: قاعدةٌ مختومةٌ
#    في `ta3allum_v0.json` تُعاد فاتورتُها ههنا وتُصادَم بختمها.
#
# §٤ وما لا يُدَّعى — ويُختَم بعدده ولا يُحذَف:
#    ① **لا يُدَّعى أنّ القسمةَ باطلة**: المقيسُ عجزُ **السطحِ** عن حسمها، وهذا
#       حكمٌ على المكيال لا على المقسوم. وفتحُ المحورِ الثالثِ يبقى موقوفًا.
#    ② **لا يُدَّعى أنّ صورةً بعينها مهمَلةٌ أو مستعمَلة**: المقيسُ نصيبُ
#       مكيالِ الندرةِ من الفواتح وحدَه.
#    ③ **لا يُقرَأ مدلولُ صورةٍ واحدة**: طائفةُ أسماء اللفظِ تُعَدُّ **صورةً**،
#       ولا يُقال ما عنته في موضعها — وتعيينُ ذلك دَينٌ يُسمّى بلا رقم.
#
# المخارج: 0 نجاح · 2 ختمٌ خالف · 3 شكلٌ خالف إعلانَه · 4 بايتاتٌ غائبة.
#
