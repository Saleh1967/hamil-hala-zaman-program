def collide(measured):
    extra = [k for k in measured if k not in SEALED_QISMA]
    if extra:
        raise QismaError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    bad = [(k, SEALED_QISMA[k], measured.get(k)) for k in SEALED_QISMA
           if k not in measured or measured[k] != SEALED_QISMA[k]]
    if bad:
        raise QismaError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_QISMA)


