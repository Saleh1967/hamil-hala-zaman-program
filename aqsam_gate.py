# ═══ ① بايتاتُ المتن والأئمّة — مصادَمةً قبل أن تُقرَأ ══════════════════════════════
def matn_text():
    """متنُ الشخصية ج٣ من بابه الوحيد `dalalat_gate` — مصادَمٌ بختمه قبل أن يُقرَأ."""
    try:
        blob, _ = DG.matn_bytes()
    except DG.DalalaError as exc:
        raise AqsamError(exc.code, exc.message) from exc
    return blob.decode("utf-8", "replace")


def imam_folded():
    """بايتاتُ نسخِ الأئمّة مطويّةً — مصادَمةً بالبيان قبل أن تُقرَأ."""
    try:
        rows = sources_census.manifest_rows()
    except sources_census.CensusError as exc:
        raise AqsamError(exc.code, exc.message) from exc
    out = {}
    for editions in IMAMS.values():
        for sid in editions:
            try:
                path, _ = sources_census.sealed_bytes(sid, rows)
            except sources_census.CensusError as exc:
                raise AqsamError(E_MISSING, exc.message) from exc
            with open(path, "rb") as fh:
                out[sid] = DG.fold(fh.read().decode("utf-8", "replace"))
    return out


def unique_anchor(text, phrase, what):
    """موضعُ عبارةٍ **فريدةٍ** في المتن — وتكرارُها أو غيابُها صريخٌ لا تخمين."""
    n = text.count(phrase)
    if n != 1:
        raise AqsamError(
            E_SEAL,
            f"{what}: «{phrase[:40]}…» وقعت {n} مرّةً في المتن — والمرساةُ لا تكون "
            f"إلا فريدة")
    i = text.index(phrase)
    return dict(إزاحة=len(text[:i].encode("utf-8")),
                طول=len(phrase.encode("utf-8")),
                بصمة=hashlib.sha256(phrase.encode("utf-8")).hexdigest()[:16])


def chapter_slices(text):
    """بايتاتُ كلِّ قسمةٍ: من صدرها إلى صدر تاليتها — وآخرُها إلى أوّل عنوانٍ بعده."""
    starts = [(name, text.index(q["صدر"])) for name, q in QISMAT.items()]
    if [i for _, i in starts] != sorted(i for _, i in starts):
        raise AqsamError(E_SEAL, "صدورُ القسمات ليست على ترتيب المتن — فرزٌ مختلّ")
    out, bounds = {}, [i for _, i in starts] + [len(text)]
    for k, (name, start) in enumerate(starts):
        end = bounds[k + 1]
        if name == list(QISMAT)[-1]:
            tail = text.find("\nالترادف\n", start)
            end = tail if tail > start else end
        out[name] = text[start:end]
    return out


# ═══ ② صنعةُ البناء: العددُ يُشتَقُّ من الشجرة ولا يُدَّعى ══════════════════════════
def derive(tree, node=0, seen=None, prefix=""):
    """عدُّ أوراقِ الشجرة من عقدتها الأولى — والعددُ محسوبٌ لا مكتوب.

    الفرعُ «قسم» ورقةٌ تُعَدُّ واحدًا، والفرعُ «عقدة» يُحوَّل إلى العقدة التالية
    فيُعَدُّ بعددِ أوراقها. ودورةٌ في الإحالة صريخٌ: شجرةٌ لا تنتهي لا تُعَدّ.
    """
    seen = set() if seen is None else seen
    if node in seen:
        raise AqsamError(E_SEAL, f"شجرةُ الفصول دائرةٌ عند العقدة {node}")
    if node >= len(tree):
        raise AqsamError(E_SEAL, f"إحالةٌ إلى عقدةٍ ليست في الشجرة: {node}")
    seen = seen | {node}
    total, leaves = 0, []
    for branch in tree[node]["فروع"]:
        kind, a = branch[0], branch[1]
        if kind == "قسم":
            total += 1
            leaves.append(prefix + a)
        elif kind == "عقدة":
            sub, sub_leaves = derive(tree, a, seen, prefix + branch[2])
            total += sub
            leaves.extend(sub_leaves)
        else:
            raise AqsamError(E_SEAL, f"صنفُ فرعٍ غيرُ معلن: {kind}")
    return total, leaves


def leaves_of(q):
    """أوراقُ الشجرة (اسمُ القسم بمساره · مثالُه) على ترتيب الشجرة لا بترتيبٍ بيد.

    ومثالُ كلِّ قسمٍ يُطلَب باسمه المُركَّب، فاسمٌ لا مثالَ له صريخٌ: لا قسمَ بلا شاهد.
    """
    names, out = derive(q["شجرة"])[1], []
    if len(set(names)) != len(names):
        raise AqsamError(E_SEAL, f"اسمُ قسمٍ تكرّر في القسمة: {names}")
    for a in names:
        if a not in q["أمثلة"]:
            raise AqsamError(E_SEAL, f"القسمُ «{a}» بلا مثالٍ مُعلَن")
        out.append((a, q["أمثلة"][a]))
    return out


def build_row(name, q, chapter):
    """سجلُّ قسمةٍ واحدة: اشتقاقُها · مصادمتُها بالمنصوص · شواهدُ فصولها وأقسامها."""
    derived, _ = derive(q["شجرة"])
    phrase, stated = q["منصوص"]
    if phrase not in chapter:
        raise AqsamError(E_SEAL, f"«{name}»: عبارةُ العدد «{phrase}» ليست في بايتات بابها")
    fusul = [dict(فصل=n["فصل"], بيان=n["بيان"], منصوصٌ_في_بابها=bool(n["فصل"] in chapter))
             for n in q["شجرة"]]
    aqsam = [dict(قسم=a, مثال=b,
                  اسمُه_في_بابها=bool(a in chapter),
                  مثالُه_في_بابها=bool(b in chapter))
             for a, b in leaves_of(q)]
    return dict(
        قسمة=name, مقسَم=MAQSAM, حيثية=q["حيثية"],
        عقد=len(q["شجرة"]), مشتقّ=derived, منصوص=stated, عبارةُ_العدد=phrase,
        صادقَ_الاشتقاق=bool(derived == stated),
        فصول=fusul, أقسام=aqsam,
        بايتاتُ_بابها=len(chapter.encode("utf-8")))


# ═══ ③ محورُ النقل: أقوالُ الأئمّة استقراءٌ يَعضُد، ولا تدخل الاشتقاق ═══════════════
def transmitted(term, folded):
    """أئمّةٌ وقع عندهم اسمُ القسم في نسخِهم **كلِّها** — قاعدةُ النسخ نفسُها."""
    needle = DG.fold(term)
    return sorted(i for i, eds in IMAMS.items()
                  if all(folded[e].count(needle) for e in eds))


def naql_rows(rows, folded):
    """لكلِّ اسمِ قسمٍ: من نقله وكم عدَّتُهم — محورٌ ثانٍ لا يمسُّ حكمَ الاشتقاق."""
    out = []
    for row in rows:
        for part in row["أقسام"]:
            imams = transmitted(part["قسم"], folded)
            out.append(dict(قسمة=row["قسمة"], قسم=part["قسم"],
                            نقلَه=imams, عدد=len(imams),
                            متواتر=len(imams) >= TAWATUR_FLOOR))
    return out


# ═══ ④ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ ════════════════════════════════════════
def falsify(text, chapters, rows, naql, folded):
    """كلُّ محاولةٍ تُرَدُّ بـ(اسمٍ · أنجحت). ونجاحُ واحدةٍ يُسقِط الباب."""
    T = []

    # ① المرساةُ الجامعةُ ليست في المتن أو ليست فريدة: فالقسماتُ الثلاثُ منسوبةٌ
    #    إليه بلا موضعٍ يُصادَم.
    T.append(("مرساةُ القسمات الثلاث ليست فريدةً في المتن",
              text.count(ROOT_ANCHOR) != 1))

    # ② **المحكُّ**: العددُ مكتوبٌ بيدٍ لا مشتقٌّ من الشجرة. تُحذَف عقدةُ التفريع
    #    الأخيرةُ من كلِّ قسمةٍ ذاتِ عقدتين فأكثر، فإن لم يتغيّر عددُها المشتقُّ
    #    فالاشتقاقُ صوريٌّ والعددُ محفوظٌ في مكانٍ آخر.
    rigid = []
    for name, q in QISMAT.items():
        tree = q["شجرة"]
        if len(tree) < 2:
            continue
        trimmed = [dict(n, فروع=[f for f in n["فروع"]
                                 if not (f[0] == "عقدة" and f[1] >= len(tree) - 1)])
                   for n in tree[:-1]]
        try:
            rigid.append(derive(trimmed)[0] == derive(tree)[0])
        except AqsamError:
            rigid.append(False)
    T.append(("حذفُ عقدةٍ لم يغيّر العددَ المشتقّ — عددٌ مكتوبٌ لا محسوب", any(rigid)))

    # ③ الاشتقاقُ لا يصادم: لو لم تُصادَم عبارةُ العدد المنصوصةُ في المتن لكان
    #    المشتقُّ رقمًا يصدّق نفسَه.
    T.append(("قسمةٌ خالف مشتقُّها منصوصَها ومرّت",
              any(not r["صادقَ_الاشتقاق"] for r in rows)))

    # ④ فصلٌ ليس في بايتات بابه: فالعقدةُ مردودةٌ إلى المتن بلا نصّ.
    T.append(("فصلٌ من فصول الشجرة ليس في بايتات بابه",
              any(not f["منصوصٌ_في_بابها"] for r in rows for f in r["فصول"])))

    # ⑤ قسمٌ بلا شاهدٍ من المتن: اسمًا أو مثالًا.
    T.append(("قسمٌ اسمُه أو مثالُه ليس في بايتات بابه",
              any(not (p["اسمُه_في_بابها"] and p["مثالُه_في_بابها"])
                  for r in rows for p in r["أقسام"])))

    # ⑥ اسمُ قسمٍ مصنوعٌ يقع في المتن أو عند إمام: فالمصادمةُ تقبل ما ليس فيه.
    T.append(("اسمُ قسمٍ مصنوعٌ وقع في المتن أو عند إمام",
              FABRICATED_NAME in text or bool(transmitted(FABRICATED_NAME, folded))))

    # ⑦ الحيثياتُ ليست ثلاثًا متمايزة: لو اتّحدت حيثيتان لكانت قسمةٌ مكرَّرة.
    T.append(("حيثيتان متّحدتان — قسمةٌ مكرَّرةٌ بلا اعتبارٍ جديد",
              len({q["حيثية"] for q in QISMAT.values()}) != len(QISMAT)))

    # ⑧ النقلُ يدخل الاشتقاق: لو كان «صادقَ الاشتقاق» تابعًا للتواتر لسقط
    #    استقلالُ المحورين. ويُقاس: هل كلُّ أسماء القسمات متواترةٌ أو كلُّها دونه؟
    counts = {r["متواتر"] for r in naql}
    T.append(("أسماءُ الأقسام كلُّها في جانبٍ واحدٍ من حدّ التواتر — محورٌ لا يميّز",
              len(counts) < 2))

    # ⑨ المقسَمُ يتبدّل بين القسمات: لو اختلف المقسَمُ لَما صحّ أن تُسمّى قسماتٍ
    #    لشيءٍ واحد، ولَما جاز أن يقع اللفظُ في قسمٍ من كلٍّ منها.
    T.append(("المقسَمُ تبدّل بين القسمات",
              len({r["مقسَم"] for r in rows}) != 1))

    return [dict(محاولة=n, نجحت=bool(ok)) for n, ok in T]


# ═══ ⑤ التشغيل ═════════════════════════════════════════════════════════════════════
def run():
    text = matn_text()
    folded = imam_folded()
    anchors = {name: unique_anchor(text, q["صدر"], f"صدرُ «{name}»")
               for name, q in QISMAT.items()}
    anchors["المرساةُ الجامعة"] = unique_anchor(text, ROOT_ANCHOR, "مرساةُ القسمات")
    chapters = chapter_slices(text)
    rows = [build_row(name, q, chapters[name]) for name, q in QISMAT.items()]
    naql = naql_rows(rows, folded)
    trials = falsify(text, chapters, rows, naql, folded)

    # ترتيبان لا يُخلَطان: ترتيبُ الأبواب في المتن، وترتيبُ العدِّ في جملة الإعلان.
    declared_order = sorted(
        QISMAT, key=lambda n: ROOT_ANCHOR.index(
            {"الدالُّ وحدَه": "للدال وحده",
             "المدلولُ وحدَه": "للمدلول وحده",
             "الدالُّ والمدلولُ معًا": "الدال والمدلول"}[n]))

    measured = {
        "قسمات": len(rows),
        "مقسَمٌ واحد": len({r["مقسَم"] for r in rows}),
        "عقدُ الفصول": sum(r["عقد"] for r in rows),
        "أقسامٌ مشتقّة": sum(r["مشتقّ"] for r in rows),
        "قسماتٌ صادقَ اشتقاقُها منصوصَها": sum(1 for r in rows if r["صادقَ_الاشتقاق"]),
        "فصولٌ منصوصةٌ في المتن": sum(1 for r in rows for f in r["فصول"]
                                      if f["منصوصٌ_في_بابها"]),
        "أقسامٌ لها شاهدٌ في بابها": sum(
            1 for r in rows for p in r["أقسام"]
            if p["اسمُه_في_بابها"] and p["مثالُه_في_بابها"]),
        "أئمّة": len(IMAMS),
        "معذورون": len(EXCUSED),
        "أسماءٌ متواترة": sum(1 for r in naql if r["متواتر"]),
        "أسماءٌ دون الحدّ": sum(1 for r in naql if not r["متواتر"]),
        "محاولاتُ_تكذيب": len(trials),
    }
    for key, sealed in SEALED_AQSAM.items():
        if measured[key] != sealed:
            raise AqsamError(E_SEAL, f"«{key}» = {measured[key]} ≠ المختوم {sealed}")
    if any(t["نجحت"] for t in trials):
        raise AqsamError(E_SEAL, "محاولةُ تكذيبٍ نجحت — البابُ ساقط")

    return {"الأقسام_v0": {
        "صنعةُ_البناء": [
            "مقسَمٌ واحدٌ لا يتبدّل بين القسمات — وهو «اللفظ»",
            "حيثيةٌ معلنةٌ تسبق القسمة فلا تُخلَط حيثيتان",
            "فصلٌ منصوصٌ بلفظه لكلِّ عقدةٍ من الشجرة",
            "العددُ يُشتَقُّ من الشجرة ثمّ يُصادَم بالمنصوص في المتن",
            "لكلِّ قسمٍ اسمٌ ومثالٌ منصوصان في بايتات بابه"],
        "المراسي": anchors,
        "ترتيبُ_الأبواب": list(QISMAT),
        "ترتيبُ_الإعلان": declared_order,
        "الترتيبان_يتّفقان": bool(list(QISMAT) == declared_order),
        "القسمات": rows,
        "محورُ_النقل": dict(
            بيان=("أقوالُ الأئمّة استقراءٌ يَعضُد لا حجّةٌ على البرهان؛ تُقاس على "
                  "حِدَة ولا تدخل الاشتقاق — والفيصلُ الاشتقاقُ والمصادمة"),
            أئمّة=[dict(إمام=i, نسخ=list(e)) for i, e in IMAMS.items()],
            معذورون=[dict(e) for e in EXCUSED],
            حدُّ_التواتر=TAWATUR_FLOOR,
            أسماء=naql),
        "محاولاتُ_التكذيب": trials,
        "الحدُّ_المُعلَن": (
            "البابُ يقيس **بناءَ القسمة** لا صدقَها على العربية: أنّ فصولَها منصوصةٌ "
            "وأنّ عددَها مشتقٌّ من شجرتها وأنّ أسماءَها وأمثلتَها في بايتاتها. وصدقُ "
            "القسمة موقوفٌ على النقل، وهو محورٌ يُعَدُّ ولا يُخلَط. وردُّ عبارةِ المتن "
            "إلى عقدةٍ في شجرةٍ بيدنا، ولذلك كُتب نصُّ كلِّ فصلٍ ليُصادَم ويُراجَع."),
        "مقيس": measured,
    }}


