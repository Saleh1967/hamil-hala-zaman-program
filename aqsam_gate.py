# aqsam_gate.py — بابُ الأقسام الثلاثة: **كيف تُبنى القاعدةُ** عند النبهانيِّ، مقيسًا.
#
# ــ ٠) ما يُتعلَّم ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# في «أبحاث اللغة» من الشخصية ج٣ بنى النبهانيُّ **ثلاثَ قواعدَ مرتَّبةً** على اللفظ:
#
#   ① قاعدةُ **الدالِّ وحدَه**            (ص ١٢٨)  ⟶ ثلاثةُ أقسام
#   ② قاعدةُ **المدلولِ وحدَه**           (ص ١٣١)  ⟶ خمسةُ أقسام
#   ③ قاعدةُ **الدالِّ والمدلولِ معًا**    (ص ١٣٤)  ⟶ سبعةُ أقسام
#
# وعلّتُه في الثلاث منصوصةٌ في متنه: «فكان اللفظُ هو الدالَّ على المعنى، وكان المعنى
# هو المدلولَ عليه باللفظ؛ ولهذا كانت أبحاثُ اللغة هي أبحاثًا عن الألفاظ وحدَها،
# وأبحاثًا عن الألفاظ والمعاني، وأبحاثًا عن المعاني».
#
# **والمتعلَّمُ ليس الأقسامَ، بل صنعةَ بنائها.** وهي خمسُ خطواتٍ تُنتزَع من فعله لا
# من قوله، وتُصادَم على بايتاته في كلِّ تشغيل:
#
#   ⑴ **مقسَمٌ واحدٌ** لا يتبدّل بين القسمات الثلاث — وهو «اللفظ».
#   ⑵ **حيثيةٌ معلنةٌ** تسبق القسمة: باعتبار الدالِّ وحدَه · المدلولِ وحدَه · كليهما.
#      فلا تُخلَط حيثيتان في قسمةٍ واحدة، ولذلك أمكن أن يقع اللفظُ الواحدُ في قسمٍ
#      من كلِّ قسمةٍ بلا تناقض.
#   ⑶ **فصلٌ منصوصٌ بلفظه** لكلِّ عقدةٍ من شجرة القسمة، منفصلةً حقيقيةً حاصرةً مانعة
#      («قد يكون معنًى، وقد يكون لفظًا» · «إمّا أن يتّحدا، أو يتكثّر…»).
#   ⑷ **العددُ يُشتَقُّ من الشجرة** ضربًا وجمعًا، **ولا يُدَّعى**: فخمسةُ المدلول
#      هي ١ + (٢×٢)، وسبعةُ الدالِّ والمدلول هي ٣ + (١ + ١ + ٢). ثمّ يُصادَم
#      المشتقُّ بالعدد المنصوص في المتن، فإن خالفه صُرِخ.
#   ⑸ **لكلِّ قسمٍ اسمٌ ومثالٌ منصوصان** في بايتات بابه — فلا قسمَ بلا شاهدٍ من المتن.
#
# وهذا هو الجوابُ المقيس عن «كيف تُبنى القواعد»: **قسمةٌ بفصلٍ منصوصٍ على مقسَمٍ
# واحدٍ بحيثيةٍ معلنة، وعددُها محسوبٌ من فصولها لا مكتوبٌ بيدٍ.**
#
# ــ ١) البرهانُ هو الفيصلُ، وأقوالُ الأئمّة استقراءٌ ـــــــــــــــــــــــــــــــ
# النبهانيُّ نفسُه يقرّر أنّ طريقَ معرفة اللغة **النقلُ**: «طريقُ معرفة اللغة العربية
# هي النقلُ المتواترُ وخبرُ الآحاد»، وأنّ **العقلَ لا يضع لغةً**. فأقوالُ سيبويهِ
# والمبرّدِ وابنِ جنّي والسرخسيِّ وابنِ هشامٍ ههنا **استقراءٌ يَعضُد**، لا حجّةٌ
# على البرهان: يُقاس تواترُ أسماء الأقسام في بايتاتهم **على حِدَة**، ويُقاس
# اشتقاقُ العدد وشاهدُ المتن **على حِدَة**، ولا يقرأ أحدُهما الآخر.
# **والفيصلُ الاشتقاقُ والمصادمة**: قسمةٌ لا يُشتقُّ عددُها من فصولها تسقط وإن
# تواترت أسماؤها؛ وقسمةٌ يُشتقُّ عددُها تقوم وإن لم يذكرها إمام.
#
# ــ ٢) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • البابُ يقيس **بناءَ القسمة**: أنّ فصولَها منصوصةٌ وأنّ عددَها مشتقٌّ وأنّ
#     أسماءَها وأمثلتَها في بايتاتها. ولا يقيس أنّ القسمةَ **صادقةٌ على العربية** —
#     ذلك موقوفٌ على النقل، وهو محورٌ آخرُ يُعَدُّ ولا يُخلَط.
#   • ردُّ عبارةِ المتن إلى عقدةٍ في شجرةٍ **بيدنا**، وهو أضعفُ حلقةٍ ههنا؛ ولذلك
#     كُتب لكلِّ عقدةٍ **نصُّ فصلِها** ويُصادَم بالبايتات، ليُراجَع الردُّ نفسُه.
#   • والأئمّةُ خمسةٌ بما وُجد في الشجرة المتاحة، والخليلُ والأصمعيُّ — وهما اللذان
#     سمّاهما النبهانيُّ في الآحاد — **معذوران باسمهما** في البيان وههنا.
#
