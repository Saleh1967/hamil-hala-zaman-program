# tawlid_gate.py — بابُ التوليدِ الحتميّ: أيُولَّد نصٌّ يُعيد ثوابتَ الشاهدِ
#                  نفسَها، أم أنّ بلوغَها لا يكون إلّا بإعارةِ المقامِ كلِّه؟
#
# §٠ العلّةُ التي يقتلها هذا الباب. التوليدُ في المستودعات عادةً ثلاثُ آفات:
#    ① **بذرةٌ من عندنا** تُجرَّب حتى يحسُن المخرَج، فيصير الحسنُ انتقاءً لا
#       قياسًا؛ ② **لا إعادةَ قياس**، فيُقرأ المخرَجُ بالعين ويُمدَح بالذوق؛
#       ③ **شاهدٌ ثانٍ** يُكتَب للمولَّد غيرِ الذي قيس به الأصل، فيتصالح
#       الرقمان لأنّهما لم يلتقيا. وههنا تُقتَل الثلاثُ بثلاثةِ قيودٍ معلنة:
#       البذرةُ **مشتقّةٌ من بصمةِ المجمَّدِ المختومةِ** ولا تُكتَب بيد؛
#       والمخرَجُ **يُعاد قياسُه**؛ والقياسُ **بالدوالِّ الثلاثِ عينِها** التي
#       قيس بها المجمَّد — دالّةٌ واحدةٌ لا نسختان.
#
# §١ صيغُ الشاهدِ الثلاث — تُعلَن قبل التوليدِ وتُطبَّق على الطرفين سواءً:
#    ① **طولُ الكلمة**: متوسّطُ حروفِ الصورةِ بعد نزعِ الحركات (`HL.skel`).
#    ② **الوظيفيُّ ⟷ الجذعيّ**: نصيبُ الكلماتِ التي صورتُها أداةٌ من معجمِ
#       الحروفِ المنتزَعِ من المتن (`madlul_gate.MU3JAM` عبر
#       `mabna_gate.declared_tools`) — معجمٌ مستورَدٌ لا منسوخٌ ههنا.
#    ③ **اللاحقات**: نصيبُ المقشورِ بالجولةِ الأولى من `induction/online_peel.py`
#       بنصِّها — وهي مختومةٌ هناك (`SEALED_R1`)، ومصادمةُ ختمِها حارسٌ في
#       هذا الباب: لو بُدِّلت الدالّةُ لَسقط الباب.
#
# §٢ وΔ **ليس من عندنا**. حدُّ المطابقةِ هو **تذبذبُ الشاهدِ نفسِه** عند سحبٍ
#    بحجمِ المقامِ نفسِه: إحدى عشرةَ إعادةَ سحبٍ من توزيعِ الكلماتِ المشهود،
#    وΔ أقصى فارقٍ بلغته عن ثابتِ المجمَّد. فهو **ضجيجُ السحبِ مقيسًا** لا
#    سماحةً تُوسَّع حتى يمرَّ المولَّد.
#
# §٢½ وبإزائه **تذبذبُ النصفين** (الزوجيُّ ⟷ الفرديُّ). وقد كُتب ههنا أوّلَ
#    مرّةٍ أنّه «أضيقُ بالبناء» لأنّه قسمةٌ لا إعادةُ سحب — **وهذه الدعوى
#    كذّبها القياسُ فسقطت، ورقمُها مختومٌ بعدده لا محذوفٌ لأنّه خالف**:
#    ففي «نصيبِ المقشور» بلغ النصفان ٠٫٠٠٥٨ وΔ ٠٫٠٠٢٣ — أي **ضعفين ونصفًا
#    فوقَه**. ومعنى ذلك مقيسٌ لا مقول: إعادةُ السحبِ تفترض أنّ الكلماتِ
#    **قابلةٌ للتبادلِ** على طولِ المتن، وشطرا المتنِ يكذّبان ذلك في هذا
#    الشاهدِ وحدَه — فثمّ بناءٌ على طولِ المتنِ لا يراه سحبُ الحقيبة.
#    فالطرفان **مقامان لا يُجمَعان**: Δ ضجيجُ السحب، والنصفان اختلافُ
#    الشطرين؛ ويُعَدّ الشواهدُ التي تجاوز فيها الثاني الأوّلَ وتُسمّى.
#    ولأنّ الحدَّ الأضيقَ قد يُجمِّل، **يُعاد الحكمُ بالحدِّ الأوسعِ منهما**
#    ويُختَم أيتبدّل أم يثبت — متانةٌ مقيسةٌ لا موعودةٌ في تعليق.
#
# §٣ والسلّمُ ستُّ رتبٍ تصعد في المعرفةِ المُعارة، **وكلُّ إعارةٍ تُسمّى في
#    وديعتها**: رتبةٌ تُطابق شاهدًا أعارته بالبناءَ **لا تكسب شيئًا** —
#    والمطابقةُ المعتَدُّ بها هي **ما لم يُعَر**. ولذلك يُفصَل في كلِّ خانةٍ
#    «طابق» عن «طابقَ بإعارة»، ويُشتَقّ حكمُ الرتبةِ منهما لا يُكتَب.
#
# §٤ ما لا يُدَّعى:
#    ① **لا يُدَّعى أنّ المولَّدَ عربيّة**: الشواهدُ الثلاثةُ **إحصاءُ حقيبةٍ**
#       لا نحو — لا ترى ترتيبًا ولا إسنادًا ولا معنى، ومحاولةُ تكذيبٍ تُثبت
#       عماها عن الترتيب بخلطِ المولَّدِ وإعادةِ قياسه.
#    ② **ولا يُدَّعى أنّ «مقشور» لاحقةٌ صرفيّة**: هي **صورةُ آخِرٍ** بجدولٍ
#       موروثٍ محروسٍ، وحارساها (التاءُ والمبنيّ) من هناك لا من ههنا.
#    ③ **وطولُ الآيةِ مُعارٌ لا مولَّد**: عددُ الكلماتِ في كلِّ آيةٍ يُؤخَذ من
#       المجمَّد ليتساوى المقامان، وهذا دَينٌ يُسمّى بلا رقم.
#    ④ **والرتبةُ العليا تحصيلُ حاصل**: «معجميٌّ بالتواتر» هو عينُ إعادةِ
#       السحبِ التي اشتُقَّ منها Δ، فمطابقتُه للثلاثةِ **مُعارةٌ كلُّها**
#       ولا تُقرَأ نجاحًا — بل تُبقي البوّابةَ قابلةً للاجتياز، فلا تكون
#       بوّابةً لا يعبرها شيءٌ بالبناء.
