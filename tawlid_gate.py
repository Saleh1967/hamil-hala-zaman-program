def collide(measured):
    bad = [(k, SEALED_TAWLID[k], measured[k]) for k in SEALED_TAWLID
           if k not in measured or measured[k] != SEALED_TAWLID[k]]
    extra = [k for k in measured if k not in SEALED_TAWLID]
    if extra:
        raise TawlidError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    if bad:
        raise TawlidError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_TAWLID)


