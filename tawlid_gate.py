# ═══ ① البذرةُ من الختمِ نفسه ═════════════════════════════════════════════════
def sealed_fingerprint():
    """بصمةُ المجمَّدِ: تُنتزَع من بايتاتِ `algebra_engine.py` ثمّ **تُصادَم**
    بالبصمةِ المحسوبةِ حيًّا على بايتاتِ المجمَّد. فإن تخالفتا فلا توليد.

    ولِمَ انتزاعٌ من البايتات لا استيراد؟ لأنّ محرّكَ الجبرِ يستورد `numpy`
    وليس من شرطِ هذا الباب، **ولأنّ النسخَ رقمًا مكتوبًا ههنا هو عينُ العطل
    الذي نحرسه**: البذرةُ تتبع الختمَ ولا يتبعها.
    """
    host = os.path.join(ROOT, SEAL_HOST)
    if not os.path.exists(host):
        raise TawlidError(E_CORPUS, f"«{SEAL_HOST}» غائبٌ — لا بذرةَ بلا ختم")
    claimed = None
    with open(host, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith(SEAL_NAME):
                claimed = line.split("=", 1)[1].strip().strip('"').strip("'")
                break
    if not claimed or len(claimed) != 64:
        raise TawlidError(E_SEAL, f"«{SEAL_NAME}» لم يُنتزَع من «{SEAL_HOST}»")
    if not os.path.exists(HL.CORPUS):
        raise TawlidError(E_CORPUS, "المجمَّدُ غائبٌ — لا قياسَ على غيابٍ مطويّ")
    live = hashlib.sha256(open(HL.CORPUS, "rb").read()).hexdigest()
    if live != claimed:
        raise TawlidError(E_SEAL, f"بصمةُ المجمَّدِ خالفت ختمَها: {live} ⟷ {claimed}")
    return live


def seed_of(fingerprint, tag):
    """بذرةُ كلِّ رتبةٍ مشتقّةٌ: sha256(البصمة ‖ اسمُ الرتبة) ⟶ ستّةَ عشرَ محرفًا.

    فلا بذرةَ تُجرَّب ولا رتبةَ تُمنَح بذرةً أحسنَ من أختها: كلُّ بذرةٍ **دالّةٌ
    في الختمِ واسمِ الرتبةِ المعلنِ قبل القياس**، ولا مدخلَ لليدِ بينهما.
    """
    return int(hashlib.sha256((fingerprint + "‖" + tag).encode("utf-8"))
               .hexdigest()[:16], 16)


# ═══ ② صيغُ الشاهدِ — دالّةٌ واحدةٌ تُطبَّق على المجمَّدِ والمولَّدِ سواءً ═══════
def witness_length(words):
    """① متوسّطُ حروفِ الصورة."""
    return sum(len(w) for w in words) / len(words)


def witness_function(words, tools):
    """② نصيبُ ما صورتُه أداةٌ من معجمِ الحروفِ المستورَد."""
    return sum(1 for w in words if w in tools) / len(words)


def witness_suffix(words):
    """③ نصيبُ المقشورِ بجولةِ `online_peel.peel` الأولى — بنصِّها لا بنسخةٍ."""
    return sum(1 for w in words if OP.peel(w)[2] == "مقشور") / len(words)


def measure(words, tools):
    """الشواهدُ الثلاثةُ دفعةً — وهي **المدخلُ الوحيدُ** لأيِّ قياسٍ في هذا الباب."""
    if not words:
        raise TawlidError(E_SHAPE, "قياسٌ على مقامٍ خالٍ — صريخٌ لا رقم")
    return {SHAWAHID[0]: witness_length(words),
            SHAWAHID[1]: witness_function(words, tools),
            SHAWAHID[2]: witness_suffix(words)}


def r4(x):
    """تقريبٌ معلنٌ — و«−0.0» تُسوّى صفرًا لئلّا تختلف الوديعةُ بصورةِ الصفر."""
    v = round(float(x), DIGITS)
    return 0.0 if v == 0 else v


# ═══ ③ الميدانُ وجداولُ السحب ════════════════════════════════════════════════
def corpus_words():
    """صورُ كلماتِ المجمَّدِ وأطوالُ آياته — لا يُطرَح موضعٌ ههنا."""
    verses = parse_verses(HL.CORPUS)
    words, shape = [], []
    for v in verses:
        n = 0
        for w in v:
            if not w:
                continue
            words.append(HL.skel(w))
            n += 1
        shape.append(n)
    if len(words) < MIN_N:
        raise TawlidError(E_SHAPE, "المقامُ دون حدِّ القياس المعلن")
    return words, shape


def table(counter):
    """جدولُ سحبٍ تراكميٌّ **بمفاتيحَ مرتَّبة** — فترتيبُ القاموسِ لا يدخل الحتميّة."""
    keys = sorted(counter)
    cum, total = [], 0
    for k in keys:
        total += counter[k]
        cum.append(total)
    return keys, cum, total


def draw(rng, tb):
    keys, cum, total = tb
    return keys[bisect.bisect_right(cum, rng.randrange(total))]


def build_tables(words):
    """جداولُ المعرفةِ المُعارةِ للرتب — كلُّها مشتقّةٌ من المجمَّدِ ومسمّاةٌ برتبتها."""
    letters = sorted({c for w in words for c in w})
    if not letters:
        raise TawlidError(E_SHAPE, "لا حرفَ في الميدان")
    bi, tri = defaultdict(Counter), defaultdict(Counter)
    for w in words:
        p = "^"
        for c in w:
            bi[p][c] += 1
            p = c
        p = "^^"
        for c in w:
            tri[p][c] += 1
            p = p[1] + c
    return dict(
        حروف=letters,
        أقصى_طول=max(len(w) for w in words),
        أطوال=table(Counter(len(w) for w in words)),
        أحادي=table(Counter(c for w in words for c in w)),
        ثنائي={k: table(v) for k, v in bi.items()},
        ثلاثي={k: table(v) for k, v in tri.items()},
        كلماتٌ_بالتواتر=table(Counter(words)),
        كلماتٌ_بالنوع=table(Counter({w: 1 for w in set(words)})),
    )


# ═══ ④ سلّمُ التوليد — حتميٌّ ببذرةٍ مشتقّةٍ من الختم ═════════════════════════
def generate(name, n, tb, fingerprint):
    """يولّد `n` صورةً حتميًّا. البذرةُ من الختمِ واسمِ الرتبة، والمولِّدُ
    **محلّيٌّ** (`random.Random`) لا الحالةُ العامّة — فلا يُبدّل مخرَجَه
    استدعاءٌ سابقٌ في مكانٍ آخرَ من الشجرة، وذلك مُثبَتٌ بمحاولةِ تكذيب."""
    rng = random.Random(seed_of(fingerprint, name))
    if name == "معجميٌّ بالتواتر":
        return [draw(rng, tb["كلماتٌ_بالتواتر"]) for _ in range(n)]
    if name == "معجميٌّ بالنوع":
        return [draw(rng, tb["كلماتٌ_بالنوع"]) for _ in range(n)]
    letters, out = tb["حروف"], []
    for _ in range(n):
        length = (rng.randrange(1, tb["أقصى_طول"] + 1) if name == "مسطَّح"
                  else draw(rng, tb["أطوال"]))
        if name == "مسطَّح":
            out.append("".join(letters[rng.randrange(len(letters))]
                               for _ in range(length)))
        elif name == "أحاديّ":
            out.append("".join(draw(rng, tb["أحادي"]) for _ in range(length)))
        elif name == "ثنائيّ":
            chars, p = [], "^"
            for _ in range(length):
                c = draw(rng, tb["ثنائي"][p]) if p in tb["ثنائي"] \
                    else draw(rng, tb["أحادي"])
                chars.append(c)
                p = c
            out.append("".join(chars))
        elif name == "ثلاثيّ":
            chars, p = [], "^^"
            for _ in range(length):
                c = draw(rng, tb["ثلاثي"][p]) if p in tb["ثلاثي"] \
                    else draw(rng, tb["أحادي"])
                chars.append(c)
                p = p[1] + c
            out.append("".join(chars))
        else:
            raise TawlidError(E_SHAPE, f"رتبةٌ لا مولِّدَ لها: {name}")
    return out


def text_of(words, shape):
    """النصُّ المولَّدُ مصفوفًا على **أطوالِ آياتِ المجمَّد** — إعارةٌ مسمّاةٌ دَينًا."""
    lines, i = [], 0
    for n in shape:
        lines.append(" ".join(words[i:i + n]))
        i += n
    return "\n".join(lines) + "\n"


# ═══ ⑤ محطّةُ Δ — حدُّ المطابقةِ مقيسٌ لا مكتوب ═══════════════════════════════
def delta_station(words, tools, tb, fingerprint):
    """Δ = أقصى فارقٍ بلغه الشاهدُ في إحدى عشرةَ إعادةَ سحبٍ بحجمِ المقامِ نفسِه.

    ويُعرَض بإزائه تذبذبُ النصفين (زوجيٌّ ⟷ فرديّ). وقد ادُّعي أوّلَ مرّةٍ
    أنّه أضيقُ **بالبناء** — و**كذّبه القياسُ في المقشور**، فلا تُحذَف الدعوى
    بل يُعَدّ ما تجاوزَ ويُسمّى، ويُشتَقّ منه الحدُّ الأوسعُ ليُعادَ به الحكم.
    """
    base = measure(words, tools)
    spread = {k: 0.0 for k in SHAWAHID}
    n = len(words)
    for t in range(RIVALS):
        rng = random.Random(seed_of(fingerprint, f"{BOOT_TAG}{t}"))
        redraw = [draw(rng, tb["كلماتٌ_بالتواتر"]) for _ in range(n)]
        got = measure(redraw, tools)
        for k in SHAWAHID:
            spread[k] = max(spread[k], abs(got[k] - base[k]))
    even = measure(words[::2], tools)
    odd = measure(words[1::2], tools)
    halves = {k: abs(even[k] - odd[k]) for k in SHAWAHID}
    if min(spread.values()) <= 0:
        raise TawlidError(E_SEAL, "Δ صفرٌ في شاهد — حدٌّ لا يعبره شيءٌ بالبناء")
    # الشواهدُ التي كذّبت دعوى «النصفان أضيقُ بالبناء» — تُعَدّ وتُسمّى.
    # والمقارنةُ على الأرقامِ المقرَّبةِ المودَعةِ نفسِها لا على غيرِ المودَع،
    # فلا يختلف ما يقرؤه القارئُ عمّا يحكم به الباب.
    exceeded = sorted(k for k in SHAWAHID if r4(halves[k]) > r4(spread[k]))
    # والحدُّ الأوسعُ ليس تعديلًا لـΔ بعدَ رؤيةِ المخرَج — بل **حدٌّ ثانٍ
    # يُعرَض بإزائه** ليُقاس أثرُ اختيارِ الحدِّ على الحكم.
    widest = {k: max(r4(spread[k]), r4(halves[k])) for k in SHAWAHID}
    return dict(
        ثوابتُ_المجمَّد={k: r4(base[k]) for k in SHAWAHID},
        Δ={k: r4(spread[k]) for k in SHAWAHID},
        تذبذبُ_النصفين={k: r4(halves[k]) for k in SHAWAHID},
        الحدُّ_الأوسع=widest,
        شواهدُ_تجاوزَ_فيها_النصفان_Δ=exceeded,
        عددُ_ما_تجاوز=len(exceeded),
        دعوى_النصفين_أضيقُ_بالبناء=("ساقطةٌ بالقياس" if exceeded
                                      else "لم تُكذَّب في هذا المقام"),
        مقامُ_إعادةِ_السحب=n,
        إعاداتُ_السحب=RIVALS,
        بيان=("Δ تذبذبُ الشاهدِ نفسِه في إعادةِ سحبٍ بحجمِ المقام — لا سماحةٌ "
              "تُوسَّع حتى يمرَّ المولَّد. وتذبذبُ النصفين **مقامٌ ثانٍ لا "
              "يُجمَع إليه**: إعادةُ السحبِ تفترض قابليّةَ التبادلِ على طولِ "
              "المتن، وتجاوزُ النصفين Δ في شاهدٍ يكذّب ذلك الافتراضَ في ذلك "
              "الشاهدِ وحدَه — فيُعَدّ ويُسمّى، ويُعادُ الحكمُ بالحدِّ الأوسع"),
    ), base, spread


# ═══ ⑥ البوّابة — إعادةُ القياسِ بالصيغِ عينِها ═══════════════════════════════
def gate_station(words, shape, tools, tb, fingerprint, base, spread, widest):
    """كلُّ رتبةٍ تُولَّد ثمّ **يُعاد قياسُها** بالدوالِّ الثلاثِ عينِها.

    والحكمُ مشتقٌّ لا مكتوب: خانةٌ «طابق» إن كان |مقيس − ثابت| ≤ Δ، و«طابقَ
    بإعارة» إن كان الشاهدُ في مُعارِ الرتبةِ المعلن. فرتبةٌ لا تُطابق إلّا ما
    أعارته **لم تكسب شيئًا**، وهذا هو الفرقُ بين توليدٍ وبين نسخ.

    ويُعاد الحكمُ في كلِّ خانةٍ **بالحدِّ الأوسعِ** أيضًا (أوسعُ Δ وتذبذبِ
    النصفين)، لا ليُبدَّل به الحكمُ بل **ليُقاس أثرُ اختيارِ الحدّ**: فلو
    تبدّل الحكمُ بتبدُّلِ الحدِّ لَكان البابُ قائمًا على اختيارِنا لا على
    القياس — وذلك يُعرَض بعدده لا يُوعَد في تعليق.
    """
    rows, texts = [], {}
    for rung in RUNGS:
        name = rung["اسم"]
        gen = generate(name, len(words), tb, fingerprint)
        if len(gen) != len(words):
            raise TawlidError(E_SHAPE, f"«{name}» خالفَ مقامَ المجمَّد عددًا")
        got = measure(gen, tools)
        text = text_of(gen, shape)
        texts[name] = text
        cells = {}
        for k in SHAWAHID:
            gap = r4(abs(got[k] - base[k]))
            hit = gap <= r4(spread[k])
            cells[k] = dict(مقيس=r4(got[k]), فارق=gap, طابق=bool(hit),
                            طابقَ_بالحدِّ_الأوسع=bool(gap <= widest[k]),
                            مُعار=k in rung["مُعار"])
        earned = sorted(k for k in SHAWAHID
                        if cells[k]["طابق"] and not cells[k]["مُعار"])
        matched = sorted(k for k in SHAWAHID if cells[k]["طابق"])
        wide = sorted(k for k in SHAWAHID if cells[k]["طابقَ_بالحدِّ_الأوسع"])
        rows.append(dict(
            رتبة=rung["رتبة"], اسم=name, يعلم=rung["يعلم"],
            خانات=cells,
            شواهدُ_طابقت=len(matched),
            شواهدُ_طابقت_بلا_إعارة=len(earned),
            شواهدُ_طابقت_بالحدِّ_الأوسع=len(wide),
            مُعارٌ_مُعلَن=sorted(rung["مُعار"]),
            بصمةُ_المولَّد=hashlib.sha256(text.encode("utf-8")).hexdigest()[:16],
            حكم=("طابقَ الشواهدَ الثلاثةَ بإعارتها كلِّها — تحصيلُ حاصل"
                 if len(matched) == M_SHAHID and not earned else
                 "طابقَ الشواهدَ الثلاثةَ ومنها ما لم يُعَر"
                 if len(matched) == M_SHAHID else
                 f"سقطَ — طابقَ {len(matched)} من {M_SHAHID}")))
    passed = [r for r in rows if r["شواهدُ_طابقت"] == M_SHAHID]
    wide_passed = [r for r in rows if r["شواهدُ_طابقت_بالحدِّ_الأوسع"] == M_SHAHID]
    earners = [r for r in rows if r["شواهدُ_طابقت_بلا_إعارة"] > 0]
    stable = ({r["اسم"] for r in passed} == {r["اسم"] for r in wide_passed})
    return dict(
        رتب=rows,
        رتبٌ_عبرت=len(passed),
        رتبٌ_عبرت_بالحدِّ_الأوسع=len(wide_passed),
        الحكمُ_ثابتٌ_على_الحدَّين=bool(stable),
        رتبٌ_عبرت_بلا_إعارةٍ_تامّة=sum(
            1 for r in passed if r["شواهدُ_طابقت_بلا_إعارة"] > 0),
        رتبٌ_كسبت_شاهدًا_بلا_إعارة=len(earners),
        بيانُ_الحدَّين=("العابرون بالحدِّ الأضيقِ هم العابرون بالأوسع — "
                        "فالحكمُ لا يقوم على اختيارِ الحدّ" if stable else
                        "تبدّل العابرون بتبدُّلِ الحدِّ — فالحكمُ قائمٌ على "
                        "اختيارِنا لا على القياس، وذلك يُعلَن لا يُطوى"),
        حكم=("لم تبلغ الشواهدَ الثلاثةَ رتبةٌ إلّا بإعارتها كلِّها — "
             "فالمقيسُ أنّ إحصاءَ الحرفِ لا يولّد ثوابتَ المعجم"
             if passed and all(r["شواهدُ_طابقت_بلا_إعارة"] == 0 for r in passed)
             else "رتبةٌ بلغت الشواهدَ ومنها ما لم يُعَر" if passed
             else "لم تعبر رتبةٌ — والبوّابةُ لا يعبرها شيءٌ فتُراجَع"),
    ), texts


# ═══ ⑦ محطّةُ السلّم — الصعودُ مقيسٌ لا مقول ═══════════════════════════════════
def ladder_station(gate):
    """أفارقُ الشاهدِ الثالثِ تنقص صعودًا في رتبِ الحرفِ الثلاث؟ عدٌّ لا دعوى."""
    chain = ["أحاديّ", "ثنائيّ", "ثلاثيّ"]
    by = {r["اسم"]: r for r in gate["رتب"]}
    gaps = [by[c]["خانات"][SHAWAHID[2]]["فارق"] for c in chain]
    return dict(
        سلسلةُ_الحرف=chain,
        أفارقُ_المقشور=gaps,
        ينقص_صعودًا=all(b < a for a, b in zip(gaps, gaps[1:])),
        أضيقُ_فارقٍ=min(gaps),
        أضيقُ_فارقٍ_بلغه_الحرف=chain[gaps.index(min(gaps))],
        كم_ضعفًا_فوقَ_Δ=None,
        بيان=("اللاحقةُ **صورةُ آخِرٍ**، فإحصاءُ الحرفِ يقترب منها ولا يبلغها؛ "
              "والوظيفيُّ **معجمٌ**، فلا يقترب — والفرقُ بين الاقترابين "
              "معروضٌ بعدده لا بوصف"),
    )


# ═══ ⑧ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ ═══════════════════════════════════
def falsify(words, shape, tools, tb, fingerprint, dlt, gate, texts):
    T = []
    add = lambda name, hit: T.append((name, bool(hit)))
    base = dlt["ثوابتُ_المجمَّد"]

    # ① الحتميّة: بذرةٌ واحدةٌ ⟶ نصٌّ واحد، مرّتين.
    again = generate("ثلاثيّ", len(words), tb, fingerprint)
    add("التوليدُ لم يُعِد نفسَه ببذرته",
        hashlib.sha256(text_of(again, shape).encode("utf-8")).hexdigest()
        != hashlib.sha256(texts["ثلاثيّ"].encode("utf-8")).hexdigest())

    # ② ولا تدخله الحالةُ العامّة: عبثٌ بـ`random` قبلَه لا يبدّل مخرَجَه.
    state = random.getstate()
    random.seed(20260929)
    [random.random() for _ in range(97)]
    meddled = generate("ثنائيّ", len(words), tb, fingerprint)
    random.setstate(state)
    add("الحالةُ العامّةُ بدّلت المولَّد",
        meddled != generate("ثنائيّ", len(words), tb, fingerprint))

    # ③ البذرةُ دالّةٌ في الختمِ لا رقمٌ مكتوب: ختمٌ مبدَّلٌ يعطي بذرةً أخرى،
    #    واسمُ رتبةٍ آخرُ يعطي بذرةً أخرى — فلا رتبةَ تنال بذرةَ أختها.
    add("بذرةُ الرتبةِ لا تتبع الختم",
        seed_of(fingerprint, "ثلاثيّ") == seed_of("0" * 64, "ثلاثيّ"))
    add("بذرتان لرتبتين تساوتا",
        len({seed_of(fingerprint, r["اسم"]) for r in RUNGS}) != M_RUNG)

    # ④ الشاهدُ الثالثُ هو الموروثُ بعينه: نصيبُ المقشورِ على المجمَّدِ يُعيد
    #    ختمَ `online_peel.SEALED_R1` بعدده. فلو نُسخت الدالّةُ ههنا وانحرفت
    #    لَسقط البابُ — ولا يُقبَل «شاهدٌ يشبه الشاهد».
    add("شاهدُ اللاحقةِ خالفَ ختمَه الموروث",
        sum(1 for w in words if OP.peel(w)[2] == "مقشور")
        != OP.SEALED_R1["مقشور"])
    add("مقامُ الشاهدِ خالفَ ختمَه الموروث",
        len(words) != OP.SEALED_R1["كلمات"])

    # ⑤ معجمُ الأدواتِ مستورَدٌ لا منسوخ — ولا جدولَ أدواتٍ في هذا الملفّ.
    add("جدولُ أدواتٍ ثانٍ في هذا الباب",
        any(k in globals() for k in ("MU3JAM", "TOOLS", "TOOLS_TABLE")))
    add("معجمُ الأدواتِ انكمشَ عن عدَّته", len(tools) < 60)

    # ⑥ البوّابةُ تَرفُض فعلًا: الرتبةُ المسطَّحةُ لا تعبر شاهدًا واحدًا.
    flat = next(r for r in gate["رتب"] if r["اسم"] == "مسطَّح")
    add("المسطَّحُ عبرَ شاهدًا — بوّابةٌ لا ترفض", flat["شواهدُ_طابقت"] > 0)

    # ⑦ والبوّابةُ تَقبَل فعلًا: رتبةٌ واحدةٌ على الأقلِّ تعبر الثلاثةَ —
    #    وإلّا كانت بوّابةً لا يعبرها شيءٌ بالبناء، وذلك عطلٌ لا برهان.
    add("لم تعبر رتبةٌ البوّابةَ — حدٌّ مستحيل", gate["رتبٌ_عبرت"] == 0)

    # ⑧ وΔ لا يبتلع الفرق: فارقُ المسطَّحِ في كلِّ شاهدٍ أضعافُ Δ.
    add("Δ ابتلعَ فارقَ المسطَّح",
        any(flat["خانات"][k]["فارق"] <= dlt["Δ"][k] for k in SHAWAHID))

    # ⑨ وΔ ليس سماحةً مفتوحة: في كلِّ شاهدٍ أصغرُ من الثابتِ الذي يحرسه.
    add("Δ بلغَ ثابتَه — حدٌّ بلا معنى",
        any(dlt["Δ"][k] >= abs(base[k]) for k in SHAWAHID if base[k]))

    # ⑩ دعوى «النصفان أضيقُ بالبناء» كذّبها القياسُ — فلا تُقتَل الوديعةُ بها،
    #    بل **يُحرَس اتّساقُ العدِّ مع الأرقام**: ما أُعلِن متجاوِزًا متجاوِزٌ
    #    فعلًا، وما لم يُعلَن ليس بمتجاوِز، والعدُّ يوافق التسمية. ولو طُويَ
    #    التجاوزُ من الوديعةِ لَسقط الباب.
    over = sorted(k for k in SHAWAHID
                  if dlt["تذبذبُ_النصفين"][k] > dlt["Δ"][k])
    add("عدُّ ما تجاوزَ فيه النصفان Δ خالفَ أرقامَه",
        dlt["شواهدُ_تجاوزَ_فيها_النصفان_Δ"] != over
        or dlt["عددُ_ما_تجاوز"] != len(over))
    add("حكمُ دعوى النصفين لا يوافق عدَّه",
        dlt["دعوى_النصفين_أضيقُ_بالبناء"].startswith("ساقطة") != bool(over))
    # ⑩½ والحدُّ الأوسعُ أوسعُ فعلًا ولا ينقص عن Δ في شاهد — وإلّا لم يكن حدًّا ثانيًا.
    add("الحدُّ الأوسعُ نقصَ عن Δ في شاهد",
        any(dlt["الحدُّ_الأوسع"][k] < dlt["Δ"][k] for k in SHAWAHID))
    add("الحدُّ الأوسعُ ساوى Δ في الشواهدِ كلِّها — حدٌّ ثانٍ لا وجودَ له",
        all(dlt["الحدُّ_الأوسع"][k] == dlt["Δ"][k] for k in SHAWAHID))
    # ⑩¾ ومتانةُ الحكم: العابرون بالحدَّين واحدٌ — والعَلَمُ المكتوبُ يوافق ذلك.
    add("متانةُ الحكمِ على الحدَّين كُتبت ولم تُحسَب",
        gate["الحكمُ_ثابتٌ_على_الحدَّين"]
        != (gate["رتبٌ_عبرت"] == gate["رتبٌ_عبرت_بالحدِّ_الأوسع"]
            and all(r["شواهدُ_طابقت"] == M_SHAHID
                    for r in gate["رتب"]
                    if r["شواهدُ_طابقت_بالحدِّ_الأوسع"] == M_SHAHID)))

    # ⑪ الشواهدُ عمياءُ عن الترتيب — وذلك يُثبَت بالخلطِ لا يُوعَد في تعليق.
    shuffled = list(generate("ثلاثيّ", len(words), tb, fingerprint))
    random.Random(seed_of(fingerprint, "خلط")).shuffle(shuffled)
    straight = generate("ثلاثيّ", len(words), tb, fingerprint)
    add("الشواهدُ رأت الترتيبَ — فالدعوى أوسعُ من المقيس",
        measure(shuffled, tools) != measure(straight, tools))

    # ⑫ والمقامان متساويان: المولَّدُ بعددِ كلماتِ المجمَّدِ وعددِ آياته.
    add("المولَّدُ خالفَ مقامَ المجمَّدِ كلمةً",
        any(len(generate(r["اسم"], len(words), tb, fingerprint)) != len(words)
            for r in RUNGS[:1]))
    add("النصُّ المولَّدُ خالفَ عدَّةَ الآيات",
        any(len(texts[r["اسم"]].strip().split("\n")) != len(shape)
            for r in RUNGS))

    # ⑬ القياسُ على الخالي صريخٌ لا رقم.
    try:
        measure([], tools)
        add("القياسُ على مقامٍ خالٍ أعطى رقمًا", True)
    except TawlidError:
        add("القياسُ على مقامٍ خالٍ أعطى رقمًا", False)

    # ⑭ والبصمةُ تُصادَم: ختمٌ مختلَقٌ يُسقِط التوليدَ ولا يمرُّ صامتًا.
    add("بصمةٌ مختلَقةٌ ساوت المختومة",
        sealed_fingerprint() == "0" * 64)

    # ⑮ والرتبُ معلنةٌ بعدَّتها وأسمائها لا تتكرّر.
    add("عدَّةُ الرتبِ خالفت إعلانَها", len(RUNGS) != M_RUNG)
    add("اسمُ رتبةٍ تكرّر", len({r["اسم"] for r in RUNGS}) != M_RUNG)
    add("شاهدٌ خارجَ الصيغِ الثلاثِ المعلنة",
        any(set(r["خانات"]) != set(SHAWAHID) for r in gate["رتب"]))

    # ⑯ و«المُعار» ليس رأيًا: ما أُعلِن مُعارًا يُصادَم بالبناء — فكلُّ رتبةٍ
    #    تسحب أطوالَها من توزيعِ المجمَّدِ تُعير «طولَ الكلمة» ولا بدّ، ومن
    #    لا تسحبها لا تُعيره. ولو زِيدَ مُعارٌ بلا بناءٍ لَسقط الباب.
    borrows_len = {"أحاديّ", "ثنائيّ", "ثلاثيّ", "معجميٌّ بالتواتر"}
    add("إعلانُ «مُعار» خالفَ البناءَ في طولِ الكلمة",
        any((SHAWAHID[0] in r["مُعار"]) != (r["اسم"] in borrows_len)
            for r in RUNGS))

    # ⑰ والديونُ تُسمّى ولا تُرقَّم.
    add("دَينٌ حملَ رقمًا", any(any(ch.isdigit() for ch in d) for d in DEBTS))

    fired = [n for n, hit in T if hit]
    if fired:
        raise TawlidError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return len(T)


