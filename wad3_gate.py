def field_station(rows):
    """② الميدانُ القابلُ للتكذيب — جامعٌ مانعٌ، وخارجُه تحصيلُ حاصلٍ يُسمّى بعدده."""
    by_form = defaultdict(Counter)
    for r in rows:
        by_form[r["صورة"]][r["علامة"]] += 1
    field_forms = {f for f, c in by_form.items() if len(c) > 1}
    inside = [r for r in rows if r["صورة"] in field_forms]
    outside = len(rows) - len(inside)

    # الجامع: الحالاتُ الثماني تستوعب المقامَ بفارق صفرٍ ولا حالةَ تاسعة.
    ends = Counter(r["علامة"] for r in rows)
    stray = sorted(set(ends) - set(HL.STATES))
    if stray:
        raise Wad3Error(E_SEAL, f"علامةٌ خارجَ الحقل الثمانيّ: {stray} — صريخ")
    if sum(ends.values()) != len(rows):
        raise Wad3Error(E_SEAL, "مجموعُ الحالات خالفَ المقام — الجامعُ سقط")
    if len(inside) + outside != len(rows):
        raise Wad3Error(E_SEAL, "ميدانٌ + خارجُه ≠ المقام — القسمةُ ليست جامعة")

    # المانع: رحلةٌ ذهابًا وإيابًا بالقسمة نفسِها. خارجَ الميدان تُستعاد العلامةُ
    # من جدول الصور بلا بتٍّ واحدٍ يُدفَع، وداخلَه تُستعاد بعلامةٍ مصرَّحٍ بها.
    lookup = {f: next(iter(c)) for f, c in by_form.items() if len(c) == 1}
    back, explicit = 0, 0
    for r in rows:
        if r["صورة"] in field_forms:
            explicit += 1
            back += 1                                   # العلامةُ مصرَّحٌ بها
        elif lookup.get(r["صورة"]) == r["علامة"]:
            back += 1                                   # استُعيدت من الجدول
    if back != len(rows):
        raise Wad3Error(E_SEAL, f"الرحلةُ ناقصة {back}/{len(rows)} — المانعُ سقط")
    if explicit != len(inside):
        raise Wad3Error(E_SEAL, "المصرَّحُ به خالفَ الميدان — قسمةٌ مضطربة")

    return dict(
        مقام=len(rows),
        صورٌ_مختلفة=len(by_form),
        صورُ_الميدان=len(field_forms),
        مواضعُ_الميدان=len(inside),
        مواضعُ_خارجه=outside,
        نصيبُ_الميدان=round(len(inside) / len(rows), 4),
        الحالاتُ_الثماني={k: ends[k] for k in HL.STATES},
        مجموعُ_الحالات=sum(ends.values()),
        الرحلةُ_تامّة=back,
        مصرَّحٌ_بها=explicit,
        # أدنى علاماتِ صورةٍ في الميدانِ وأقصاها: الأدنى شاهدُ **قاعدةِ العزل**
        # (لا صورةَ أحاديّةَ العلامةِ تسلَّلت)، والأقصى شاهدُ أنّ الميدانَ ليس
        # تحصيلَ حاصلٍ مقنَّعًا — ولولاهما لكان عدُّ الصورِ رقمًا بلا معنى.
        أدنى_علاماتِ_صورة=min(len(by_form[f]) for f in field_forms),
        أقصى_علاماتِ_صورة=max(len(by_form[f]) for f in field_forms),
        تحصيلُ_الحاصل=(
            f"خارجَ الميدان {outside:,} موضعًا صورتُها تحدّد علامتَها وحدَها، "
            "فقراءتُها منها تحصيلُ حاصلٍ لا مكسبَ فيه — تُسمّى بعددها ولا تُحتسَب"),
        قاعدةُ_العزل="صورةٌ جاءت بعلامتين فأكثرَ في المجمَّد — لا عتبةَ تواتر",
        صورُ_الميدان_الأعلى=[
            f"{f}×{sum(by_form[f].values()):,} ({len(by_form[f])} علامات)"
            for f in sorted(field_forms,
                            key=lambda x: -sum(by_form[x].values()))[:12]],
    ), inside


# ═══ ③ مصادمةُ مكاييلِ الوضعِ فوقَ الصورة ═══════════════════════════════════════════
def ce(keys, ends):
    """بتّ/كلمةٍ خارجَ العيّنة بسياسة `harakat_layer` عينِها — لا سياسةَ ثانية.

    والحقلُ m=8 مقروءٌ من `HL.M` لا مكتوبٌ ههنا، فمن غيَّر الحقلَ غيَّر القياسَ معًا.
    """
    if len(keys) != len(ends):
        raise Wad3Error(E_USAGE, "طولُ المكيال خالفَ طولَ الموصوف")
    if len(keys) < MIN_N:
        raise Wad3Error(E_SEAL, f"مقامٌ دونَ حدِّ العيّنة {MIN_N} — لا حكمَ عليه")
    return HL.heldout_ce(list(zip(keys, ends)), 0, HL.M)


def scale_row(inside, field, name, key, note, rng):
    """صفُّ مكيالٍ واحد: مكسبُه فوقَ الصورة، ثمّ إحدى عشرةَ فرقةً مخلوطةً بعدّته."""
    ends = [r["علامة"] for r in inside]
    vals = [r[key] for r in inside]
    joint = [r["صورة"] + "⊗" + v for r, v in zip(inside, vals)]
    gain = field - ce(joint, ends)

    rivals = []
    for i in range(RIVALS):
        shuffled = list(vals)
        rng.shuffle(shuffled)
        mixed = [r["صورة"] + "⊗" + v for r, v in zip(inside, shuffled)]
        rivals.append(round(field - ce(mixed, ends), 4))
    top = max(rivals)

    beat = gain > top
    positive = gain > 0
    if not positive and not beat:
        ruling = "ساقطٌ بالوجهين — لا يشتري ولا يغلب المثل"
    elif not positive:
        ruling = "ساقطٌ بالثمن — يغلب المثلَ ولا يشتري بتًّا فوقَ الصورة"
    elif not beat:
        ruling = "ساقطٌ بالضابط — يشتري ولا يغلب المثل"
    else:
        ruling = "مُودَعٌ بالوجهين"
    return dict(مكيال=name, بيان=note, قيمٌ=len(set(vals)),
                مكسبٌ_فوقَ_الصورة=round(gain, 4),
                مكسبٌ_كلّيٌّ_بالبتّ=round(gain * len(inside), 1),
                أعلى_المثل=top, ضوابطُ_المثل=rivals,
                غلبَ_المثل=beat, مكسبٌ_موجب=positive, حكم=ruling)


