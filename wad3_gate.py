# wad3_gate.py — بابُ الوضع: علامةُ الآخِر، أتُعرَف بالصورةِ أم بالموضع؟
#
# ــ ٠) ما يُتعلَّم ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# في `mihwar_v0.json` ثلاثةُ محاورَ مرتَّبةٍ، والثاني منها **مفتوحٌ بختمه**:
#   محورٌ: «المدلولُ وحدَه» · مفتوح: true · تحقّقَ_شرطُه: true
#   مكيالٌ: «**الوضعُ** — ولا يُعرَف الوضعُ بالصورة»
# وهذا البابُ يقيس تلك الجملةَ بعينها رقمًا: يأخذ **علامةَ الآخِر** موصوفًا —
# وهي الحقلُ المغلقُ الثمانيُّ في `harakat_layer.STATES` لا حقلًا مخترَعًا — ثمّ
# يسأل: أيشتري **الوضعُ** (ما يُعرَف بموضع الكلمة لا بصورتها) بتًّا واحدًا فوقَ
# ما تملكه **الصورةُ** نفسُها؟ فإن لم يشترِ سقط المكيالُ برقمه، وإن اشترى أُودِع.
#
# وخمسةُ مكاييلَ تُصادَم والأدنى حَكَمٌ — وهي **كلُّ** ما في الشجرة ممّا يُعرَف
# بالموضع: الحاكمُ السابق (`harakat_layer.governor` بأصنافه الثلاثة المعلنة) ·
# الكلمةُ السابقةُ صورةً · الكلمةُ التاليةُ صورةً · شرطُ الوصل (`is_wasl_head`) ·
# موضعُ الكلمة من الآية. ولا سادسَ يُخترَع ههنا: ما لم يكن في الشجرة مختومًا
# فليس مكيالًا، وما كان فمُدرَجٌ كلُّه بلا انتقاء.
#
# ــ ١) الميدانُ القابلُ للتكذيب — يُعزَل قبل القياس لا بعده ــــــــــــــــــــــ
# أكثرُ صورِ المجمَّد تأتي بعلامةٍ واحدةٍ لا ثانيةَ لها، فقراءةُ علامتها من صورتها
# **تحصيلُ حاصل** — كهويّة `mirror.py` الـ1.0000 التي أُسقطت. فيُعزَل **ميدانُ
# التكذيب**: الصورُ التي تأتي بعلامتين فأكثرَ في المجمَّد. وهذا العزلُ:
#   • **مُعلَنٌ قبل القياس** ومشتقٌّ بقاعدةٍ واحدة (عدّةُ علاماتِ الصورة > 1)،
#   • و**جامعٌ مانع**: ميدانٌ + خارجُه = كلُّ الكلمات بفارق صفرٍ ولا دلوَ «أخرى»،
#   • ويُسعَّر خارجُه بعددِه ولا يُحتسَب مكسبًا — فالتحصيلُ يُسمّى ولا يُخفى.
#
# ــ ٢) الدَّينُ الذي يُسدَّد ههنا ـــــــــــــــــــــــــــــــــــــــــــــــــــ
# في `harakat_v0.json` دَينٌ مختومٌ معلَّقٌ بحكم T₃:
#   «هل ارتفاعُ H عند الخاتمة أثرُ الحاكم السابق؟ — البندان ٣ و٤ **مقامان لم
#    يُجمَعا في رقم**، والربطُ دعوى لا نتيجة.»
# ويُسدَّد ههنا بجمعهما في **مقامٍ واحدٍ بسياسةٍ واحدة**: الخاتمةُ والداخلُ من
# الكلمات التي لها سابقةٌ (فلها حاكم)، كلاهما بـ`heldout_ce` عينِها. فيُقرَأ
# نصيبُ الحاكم من فضل الخاتمة رقمًا — لا نفيًا ولا إثباتًا بالدعوى.
#
# ــ ٣) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • لا يقيس **الإعرابَ** — يقيس **العلامةَ** وحدَها: الحركةَ الظاهرةَ على آخِر
#     الرسم. والنيابةُ (الواوُ والألفُ والياءُ والنونُ وحذفُها) والمقدَّرُ في
#     المقصور والمنقوص **خارجَ مقامه**، ويُسمَّيان دَينين بعددهما لا يُدّعيان.
#   • ولا يقيس أنّ قسمةَ «المدلولِ وحدَه» صدَقت بتمامها: يقيس مكيالَ محورها
#     المختوم على موصوفٍ واحدٍ مختوم. وما بقي دَينٌ يُسمّى ولا يُسعَّر.
#   • ووقوعُ الحاكم صورةً ليس تحليلًا نحويًّا: `governor` يقسم الصورةَ السابقةَ
#     ثلاثةً بجدولٍ معلن، وهذا كلُّ ما يقوله — ولا يُقرَأ منه إعرابُ ما بعده.
#   • وغلبةُ ضوابطِ المثلِ **وحدَها لا تفصل** ههنا، وخواؤها **مقيسٌ لا مدَّعًى**:
#     المكاييلُ الخمسةُ كلُّها تغلب المثلَ وفيها ما مكسبُه سالب. فالحكمُ حكمان
#     معًا: مكسبٌ موجبٌ فوقَ الصورة **و**غلبةُ المثل — ومن سقط أحدُهما سقط.
#
