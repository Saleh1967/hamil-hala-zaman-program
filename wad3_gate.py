def corpus_rows():
    """كلُّ كلمةٍ في المجمَّد بصورتها وعلامةِ آخرها ومكاييلِ وضعها الخمسة.

    ولا يُطرَح موضعٌ ولا يُصفّى: الطرحُ كلُّه بعدَ هذا في `field` بقاعدةٍ معلنة.
    """
    verses = parse_verses(HL.CORPUS)
    rows = []
    for words in verses:
        for i, w in enumerate(words):
            if not w:
                continue
            rows.append(dict(
                صورة=HL.skel(w),
                علامة=w[-1][1],
                حاكم=HL.governor(words[i - 1]) if i else "∅",
                سابقة=HL.skel(words[i - 1]) if i else "∅",
                تالية=HL.skel(words[i + 1]) if i + 1 < len(words) else "∅",
                وصل=str(i + 1 < len(words) and HL.is_wasl_head(words[i + 1])),
                موضع="صدر" if i == 0 else ("عجز" if i + 1 == len(words) else "حشو")))
    return verses, rows


