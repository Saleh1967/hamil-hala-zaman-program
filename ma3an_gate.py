# ma3an_gate.py — بابُ «الدالِّ والمدلولِ معًا»: مصفوفةُ التكثُّر على ميدانٍ مختوم.
#
# ــ ٠) ما يُتعلَّم ههنا ــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
# في «أبحاث اللغة» من الشخصية ج٣ قسَم النبهانيُّ اللفظَ ثلاثَ قسماتٍ متدرّجة:
# **باعتبار الدالِّ وحدَه** (بُنيت وصُودقت في `aqsam_gate`)، و**باعتبار المدلولِ
# وحدَه** (فُتحت خانةٌ منها في `madlul_gate` ومكيالُها في `wad3_gate`)، ثمّ
# **باعتبار الدالِّ والمدلولِ معًا**. وهذا البابُ للثالثة وحدَها.
#
# والثالثةُ **ليست قائمةً تُحفَظ، بل مولِّدٌ منصوصٌ بلفظه**:
#
#   «ينقسم اللفظ باعتبار الدال والمدلول، أي باعتبار اللفظ والمعنى، إلى سبعة
#    أقسام… وذلك **لأن اللفظ والمعنى إما أن يتحدا، أو يتكثر اللفظ ويتكثر
#    المعنى، أو يتكثر اللفظ مع اتحاد المعنى، أو يتكثر المعنى مع اتحاد اللفظ**»
#
# فهي **مصفوفةُ تكثُّرٍ 2×2**: (لفظٌ: واحدٌ/متكثّر) × (معنًى: واحدٌ/متكثّر). وكلُّ
# خانةٍ من الأربع مرساتُها في المتن بلفظها، تُقرأ ولا تُكتَب بيد.
#
# ــ ١) الكشفُ المقيس: السبعةُ ليست سبعَ خاناتٍ ــــــــــــــــــــــــــــــــــــــ
# الخامسُ والسادسُ والسابعُ (المنقولُ · الحقيقةُ · المجاز) **يشتركون مع الرابع
# (المشترك) في خانةٍ واحدة** — نصُّه فيهم جميعًا «أن يكون اللفظ واحدًا والمعنى
# كثيرًا»، ولا يفصلهم عن المشترك إلا **النقلُ**: «لم يوضع لكلِّ واحدٍ بل وُضع
# لمعنًى **ثمّ نُقل** إلى غيره». فالبنيةُ إذن:
#
#     ثلاثُ خاناتٍ باسمٍ واحد (المنفرد · المتباين · المترادف)
#   + خانةٌ رابعةٌ تنشطر بمحور النقل أربعةَ أسماء (مشترك · منقول · حقيقة · مجاز)
#   = 7 — وهو عددُه المنصوص، **مشتقًّا لا منقولًا**.
#
# ومحورُ النقل **خاملٌ بمانعِ مصدر**: يحتاج مقامَين زمنيَّين (وضعٌ أوّلُ واستعمالٌ
# ثانٍ) ولا ثانيَ في الشجرة — فيُسمّى ولا يُرقَّم.
#
# ــ ٢) الميدان: لماذا معجمُ حروف المعاني وحدَه ــــــــــــــــــــــــــــــــــــــ
# المصفوفةُ تحتاج **الضلعين معًا**: عدَّ الألفاظ وعدَّ المعاني. وعدُّ المعاني غائبٌ
# عن المستودع كلِّه إلا في موضعٍ واحدٍ مختوم: **معجمُ حروف المعاني** في
# `madlul_gate.MU3JAM` — فكلُّ مدخلٍ فيه أداةٌ **ومدلولٌ منصوصٌ مصادَمٌ ببايتات
# صنفه**. فهو الميدانُ الوحيدُ الذي تُجرى عليه المصفوفةُ **بصفر مصدرٍ جديد**،
# والمعجمُ يُستورَد من بابه ولا يُعاد كتبُه ههنا حرفًا.
#
# ــ ٣) الحارسُ اللازم: الترادفُ الكاذب ـــــــــــــــــــــــــــــــــــــــــــــ
# في المعجم أدواتٌ **بلا مدلولٍ منصوص** (`مدلول is None`). ولو أُدخلت لصار الغيابُ
# نفسُه «معنًى مشتركًا» بينها، فانعقدت منها **طائفةُ ترادفٍ وهميّةٌ** ليست في
# المتن ولا في اللغة. فتُقصى بحارسٍ معلنٍ، **وأثرُ إقصائها مقيسٌ** في
# `الترادفُ_الكاذب`: يُبنى الرسمُ مرّتين — بإقصاءٍ وبغيره — ويُعرَض الفرق.
#
# ــ ٤) كيف تُشتقّ الخانات: مركّباتُ الاتصال لا العدُّ بالمدخل ـــــــــــــــــــــ
# «تكثُّرُ اللفظ» و«تكثُّرُ المعنى» وصفان **للعلاقة** لا للمدخل المفرد. فيُبنى رسمٌ
# ثنائيُّ الطرف (لفظٌ ⟷ معنًى) حدُّه زوجٌ منصوص، ثمّ تُؤخذ **مركّباتُ اتصاله**:
# مركَّبٌ بلفظٍ واحدٍ ومعنًى واحدٍ ⟶ منفرد · بألفاظٍ ومعنًى واحدٍ ⟶ مترادف ·
# بلفظٍ واحدٍ ومعانٍ ⟶ خانةُ النقل · وما تكثّر طرفاه ⟶ **متشابكٌ**.
# و«المتباين» في نصِّه علاقةٌ **بين** مركَّبين لا خانةٌ فيها مدخل («كالسواد
# والبياض») — فيُعَدُّ أزواجَ المركّبات لا أعضاءً، وهذا فرقٌ يُعلَن لا يُطوى.
# و**المتشابكُ خانةٌ لا اسمَ لها في السبعة** — فهي دَينٌ يُسمّى بعدده ولا يُلحَق
# بخانةٍ تشبهه.
#
# ــ ٥) الحدُّ المُعلَن: ما لا يقوله هذا الباب ــــــــــــــــــــــــــــــــــــــ
#   • **لا يفتح المحورَ الثالث**: `mihwar_v0.json` يختمه مغلقًا لأنّ صدقَ
#     «المدلولِ وحدَه» لم يُقَس، ولا يُقاس اجتماعٌ قبل أفرادِه — وهذا البابُ لا
#     يرفع ذلك الختمَ ولا يدّعي مكيالَ المحور («نسبةُ الصورة إلى وضعها»).
#     يسدِّد بندًا واحدًا منه وحدَه: أنّ القسمةَ الثالثةَ **مولِّدٌ لا قائمة**.
#   • لا يقيس أنّ قسمةَ «الدالِّ والمدلولِ معًا» **صادقةٌ** — يقيس أنّ مولِّدَها
#     منصوصٌ وأنّ خاناتِه الأربعَ **تنطبق إقفالًا** على ميدانٍ مختومٍ واحد.
#   • الميدانُ **أدواتُ معانٍ لا لغةٌ**: 52 لفظًا و43 معنًى، لا المجمَّدُ كلُّه.
#     وتعميمُ المصفوفةِ يحتاج عدَّ المعنى خارجَ الأدوات — وهو الدَّينُ المسمّى.
#   • «معنًى متكثّرٌ» ههنا = **مدلولان منصوصان في المتن**، لا اجتهادَ دلالةٍ منّا.
#   • وقوعُ الصورةِ في المجمَّد **ليس** تحليلًا نحويًّا — الفاتورةُ تسعِّر صورةً
#     تُطلِق على تاليها، كما في `madlul_gate` سواءً بسواء.
#   • الحكمُ المفردُ (`TG.rule_bill` وحدَه) **خاوٍ ههنا بوديعةِ `madlul`** —
#     فالمميِّزُ مقارنةُ ضوابط المثل وحدَها، ويُعاد قياسُ خوائه لا يُنقَل ادّعاءً.
#
# المخارج: 0 نجاح · 2 خطأُ استعمال · 3 بايتاتٌ غائبة · 4 ختمٌ خالف وديعتَه.
#
# التشغيل:
#   python ma3an_gate.py                 تقريرٌ معدودٌ على stdout
