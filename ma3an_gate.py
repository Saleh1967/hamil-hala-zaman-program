def falsify(text, qisma, matrix, price):
    """كلُّ محاولةٍ تنجح ⟶ البابُ ساقط. ولا تُبتلَع واحدةٌ منها."""
    T = []

    # ① مرساةٌ مصنوعةٌ في المتن تُقبَل؟
    try:
        unique_anchor(text, FABRICATED_ANCHOR, "مرساةٌ مصنوعة")
        T.append(("① مرساةٌ مصنوعةٌ قُبلت", True))
    except Ma3anError:
        T.append(("① مرساةٌ مصنوعةٌ قُبلت", False))

    # ② لفظٌ مصنوعٌ دخل الميدان؟
    forms = {f for r in matrix["مركّبات"] for f in r["ألفاظ"]}
    T.append(("② لفظٌ مصنوعٌ دخل الميدان", FABRICATED_FORM in forms))

    # ③ مدلولٌ مصنوعٌ دخل الميدان؟
    senses = {s for r in matrix["مركّبات"] for s in r["معانٍ"]}
    T.append(("③ مدلولٌ مصنوعٌ دخل الميدان", FABRICATED_SENSE in senses))

    # ④ حارسُ الإقصاء زائد؟ — لو لم يبتلع الغيابُ مركَّبًا لكان الحارسُ زينةً.
    T.append(("④ حارسُ الإقصاء زائدٌ — الغيابُ لا يبتلع مركَّبًا",
              not matrix["حارسُ_الإقصاء"]["الحارسُ_لازم"]))

    # ⑤ المُقصى دخل الرسم؟ — عقدُ الرسم لا تُطابق ألفاظَه ومعانيَه.
    m = matrix["مقام"]
    T.append(("⑤ المُقصى دخل الرسم",
              m["عقد"] != m["ألفاظٌ_مميّزة"] + m["معانٍ_مميّزة"]
              or m["بمدلولٍ_منصوص"] + m["بلا_مدلولٍ_منصوص"] != m["مداخلُ_المعجم"]))

    # ⑥ الإقفالُ انكسر؟ — مركَّبٌ بلا خانةٍ أو خانةٌ بلا مركَّب.
    T.append(("⑥ الإقفالُ انكسر", not matrix["إقفال"]["مقفَل"]))

    # ⑦ مركَّبٌ وقع في خانتين؟ — المصفوفةُ مانعةٌ كما هي جامعة.
    T.append(("⑦ مركَّبٌ وقع في خانتين",
              sum(c["مركّبات"] for c in matrix["خانات"]) != len(matrix["مركّبات"])))

    # ⑧ السبعةُ ادُّعيت سبعَ خانات؟ — مشتقُّها أربعُ خاناتٍ إحداها تنشطر.
    T.append(("⑧ السبعةُ ادُّعيت سبعَ خانات",
              len(CELLS) == 7 or not qisma["إقفالُ_العدد"]["مقفَل"]))

    # ⑨ محورُ النقل رُقِّم؟ — وهو خاملٌ بمانعِ مصدرٍ فلا رقمَ له.
    T.append(("⑨ محورُ النقل حمل رقمًا",
              any(k not in ("أسماء", "خانتُه", "خاملٌ_بمانع", "بيان")
                  for k in qisma["محورُ_النقل"])))

    # ⑩ خانةٌ خارجَ الميدان حملت Δ؟ — ما لم يُسعَّر لا يُسعَّر له Δ.
    T.append(("⑩ خانةٌ خارجَ الميدان حملت Δ",
              any("Δ" in b for b in price["خانات"] if not b["في_الميدان"])))

    # ⑪ غلبت كلُّ خانةٍ ضوابطَ مثلها؟ — لو غلبتها كلُّها لكانت المقارنةُ خاويةً.
    arena = [b for b in price["خانات"] if b["في_الميدان"]]
    T.append(("⑪ غلبت كلُّ خانةٍ ضوابطَ مثلها — فالمقارنةُ خاوية",
              bool(arena) and all(b["غلبَ_المثل"] for b in arena)))

    # ⑫ الحكمُ المفردُ فصل؟ — قِيس أنّه لا يفصل، فلو ردَّ العشوائيَّ سقطت دعوانا.
    T.append(("⑫ الحكمُ المفردُ ردَّ الفرقةَ العشوائيّة — فدعوى خوايه باطلة",
              not price["خواءُ_الحكم_المفرد"]["خاوٍ"]))

    # ⑬ ادُّعي فتحُ المحور؟ — `mihwar_v0.json` يختمه مغلقًا، وهذا البابُ لا يرفعه.
    T.append(("⑬ ادُّعي فتحُ المحور خلافَ ختمِ `mihwar_v0.json`",
              bool(qisma.get("فتحَ_المحور"))))

    return [dict(محاولة=n, نجحت=bool(ok)) for n, ok in T]


