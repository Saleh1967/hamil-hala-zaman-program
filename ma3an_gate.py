def matn_text():
    """متنُ الشخصية مطويًّا — من `madlul_gate` وحدَه، فالمتنُ بابُه واحد."""
    try:
        return MG.matn_text()
    except MG.MadlulError as exc:
        raise Ma3anError(exc.code, exc.message) from exc


def unique_anchor(text, phrase, what):
    """موضعُ عبارةٍ **فريدةٍ** — وتكرارُها أو غيابُها صريخٌ لا تخمين."""
    folded = DG.fold(phrase)
    n = text.count(folded)
    if n != 1:
        raise Ma3anError(
            E_SEAL,
            f"{what}: «{phrase[:40]}…» وقعت {n} مرّةً — والمرساةُ لا تكون إلا فريدة")
    i = text.index(folded)
    return dict(إزاحة=len(text[:i].encode("utf-8")),
                طول=len(folded.encode("utf-8")),
                نصّ=phrase)


def qisma_station(text):
    """صدرُ القسمة ومولِّدُها وخاناتُها — كلُّها مصادَمةٌ فريدةً في بايتات المتن."""
    head = unique_anchor(text, HEAD, "صدرُ القسمة")
    names = unique_anchor(text, NAMES, "أسماءُ الأقسام السبعة")
    gen = unique_anchor(text, GENERATOR, "مولِّدُ المصفوفة")
    if not head["إزاحة"] < names["إزاحة"] < gen["إزاحة"]:
        raise Ma3anError(E_SEAL, "المولِّدُ ليس بعد صدرِ القسمة وأسمائها في المتن")

    cells = [dict(اسم=c["اسم"], لفظ=c["لفظ"], معنى=c["معنى"],
                  مرساة=unique_anchor(text, c["مرساة"], f"خانةُ «{c['اسم']}»"))
             for c in CELLS]
    starts = [c["مرساة"]["إزاحة"] for c in cells]
    if starts != sorted(starts) or starts[0] <= gen["إزاحة"]:
        raise Ma3anError(E_SEAL, "خاناتُ المصفوفة ليست على ترتيب المتن بعد مولِّدها")

    naql = [dict(اسم=n["اسم"],
                 مرساة=unique_anchor(text, n["مرساة"], f"محورُ النقل: «{n['اسم']}»"))
            for n in NAQL]
    if [n["مرساة"]["إزاحة"] for n in naql] != sorted(n["مرساة"]["إزاحة"] for n in naql):
        raise Ma3anError(E_SEAL, "أسماءُ محور النقل ليست على ترتيب المتن")
    if naql[0]["مرساة"]["إزاحة"] <= starts[-1]:
        raise Ma3anError(E_SEAL, "محورُ النقل قبل خانات المصفوفة — فرزٌ مختلّ")

    # إقفالُ العدد: 3 خاناتٍ باسمٍ واحد + خانةُ النقل بأسمائها الأربعة = 7.
    derived = (len(CELLS) - 1) + (1 + len(NAQL))
    if derived != 7:
        raise Ma3anError(E_SEAL, f"الأقسامُ المشتقّةُ {derived} ≠ سبعةَ المتن")

    return dict(
        صدر=head, أسماء=names, مولِّد=gen,
        بيان=("القسمةُ مولِّدٌ منصوصٌ لا قائمةٌ تُحفَظ: طرفان (لفظٌ ومعنًى) في "
              "حالتين (واحدٌ ومتكثّر) ⟶ أربعُ خانات. والخامسُ والسادسُ والسابعُ "
              "نصُّهم «اللفظ واحد والمعنى كثير» — فهم في خانة الرابع نفسِها، "
              "ولا يفصلهم عنه إلا **النقل**، وهو بُعدٌ زمنيٌّ لا خانةٌ رابعة"),
        خانات=cells,
        حدُّ_المشترك=dict(
            نصّ=MUSHTARAK_LIMIT,
            في_المتن=DG.fold(MUSHTARAK_LIMIT) in text,
            بيان="المشتركُ ما وُضع لكلِّ معنًى ابتداءً — وهذا حدُّه الفاصلُ عن المنقول"),
        محورُ_النقل=dict(
            أسماء=naql,
            خانتُه="لفظٌ واحد × معنًى متكثّر — خانةُ المشترك عينُها",
            خاملٌ_بمانع="مانعُ مصدر",
            بيان=("فصلُ المنقولِ والحقيقةِ والمجاز عن المشترك يحتاج **مقامَين "
                  "زمنيَّين**: وضعٌ أوّلُ واستعمالٌ ثانٍ، ثمّ شهرةُ الثاني. ولا "
                  "مقامَ ثانيًا في الشجرة — فالمحورُ يُسمّى ولا يُرقَّم")),
        إقفالُ_العدد=dict(
            خاناتٌ_باسمٍ_واحد=len(CELLS) - 1,
            خانةُ_النقل_بأسمائها=1 + len(NAQL),
            مشتقّ=derived,
            منصوص=7,
            مقفَل=bool(derived == 7)),
    )


# ═══ ③ الميدان: الرسمُ الثنائيُّ ومركّباتُ اتصاله ══════════════════════════════════
def lexicon_pairs(keep_void=False):
    """أزواجُ (لفظ · معنًى) من معجم `madlul_gate` — والأدواتُ بلا مدلولٍ تُقصى.

    و`keep_void` لا يُستعمَل في القياس البتّة، بل في `الترادفُ الكاذب` وحدَه
    ليُعرَض **أثرُ إسقاط الحارس مقيسًا**، لا موعوظًا به.
    """
    pairs, void = [], 0
    for sanf in MG.MU3JAM:
        for band in sanf["فرق"]:
            for form, sense in band["أدوات"]:
                if sense is None:
                    void += 1
                    if not keep_void:
                        continue
                    sense = VOID_SENSE
                pairs.append((form, sense))
    return pairs, void


def components(pairs):
    """مركّباتُ اتصال الرسم الثنائيِّ — كلُّ مركَّبٍ (ألفاظُه · معانيه)."""
    adj = {}
    for form, sense in pairs:
        adj.setdefault(("ل", form), set()).add(("م", sense))
        adj.setdefault(("م", sense), set()).add(("ل", form))
    seen, comps = set(), []
    for node in sorted(adj):
        if node in seen:
            continue
        stack, blob = [node], set()
        while stack:
            cur = stack.pop()
            if cur in seen:
                continue
            seen.add(cur)
            blob.add(cur)
            stack.extend(adj[cur] - seen)
        comps.append((sorted(v for t, v in blob if t == "ل"),
                      sorted(v for t, v in blob if t == "م")))
    return sorted(comps)


def cell_of(forms, senses):
    """خانةُ مركَّبٍ في المصفوفة — بطرفيه وحدَهما، ولا اجتهادَ فوقَهما."""
    many_f, many_s = len(forms) > 1, len(senses) > 1
    if not many_f and not many_s:
        return "المنفرد"
    if many_f and not many_s:
        return "المترادف"
    if not many_f and many_s:
        return "خانةُ النقل (المشترك وما نُقل)"
    return "متشابك — لا اسمَ له في السبعة"


def matrix_station(text):
    """المصفوفةُ على الميدان المختوم: خاناتُها مشتقّةٌ وإقفالُها مصادَم."""
    pairs, void = lexicon_pairs()
    entries = void + len(pairs)
    comps = components(pairs)
    rows = [dict(ألفاظ=f, معانٍ=s, عددُ_الألفاظ=len(f), عددُ_المعاني=len(s),
                 خانة=cell_of(f, s))
            for f, s in comps]

    forms = sorted({f for f, _ in pairs})
    senses = sorted({s for _, s in pairs})
    nodes = sum(len(r["ألفاظ"]) + len(r["معانٍ"]) for r in rows)
    if nodes != len(forms) + len(senses):
        raise Ma3anError(E_SEAL, f"عقدُ المركّبات {nodes} ≠ {len(forms) + len(senses)}")

    counts = {name: sum(1 for r in rows if r["خانة"] == name)
              for name in ("المنفرد", "المترادف", "خانةُ النقل (المشترك وما نُقل)",
                           "متشابك — لا اسمَ له في السبعة")}
    if sum(counts.values()) != len(rows):
        raise Ma3anError(E_SEAL, "مركَّبٌ لم يقع في خانة — فالمصفوفةُ ليست جامعة")

    # **المتباينُ علاقةٌ بين مركَّبين لا خانةٌ فيها عضو** — فيُعَدُّ أزواجًا.
    tabayun = len(rows) * (len(rows) - 1) // 2

    # **الترادفُ الكاذب**: لو أُسقط الحارسُ لصار الغيابُ **عقدةً جامعةً** تجذب
    #   كلَّ أداةٍ بلا مدلولٍ ومَن جاورها، فتبتلع مركّباتٍ قائمةً في كتلةٍ واحدة.
    void_pairs, _ = lexicon_pairs(keep_void=True)
    void_comps = components(void_pairs)
    fake = max((len(f) for f, s in void_comps if VOID_SENSE in s), default=0)

    return dict(
        بيان=("«تكثُّرُ اللفظ» و«تكثُّرُ المعنى» وصفان للعلاقة لا للمدخل — فتُشتقّ "
              "الخاناتُ بمركّبات اتصال رسمٍ ثنائيِّ الطرف، حدُّه زوجٌ منصوصٌ في "
              "المتن، ولا يُكتَب انتماءٌ بيد"),
        مقام=dict(
            مداخلُ_المعجم=entries,
            بمدلولٍ_منصوص=len(pairs),
            بلا_مدلولٍ_منصوص=void,
            ألفاظٌ_مميّزة=len(forms),
            معانٍ_مميّزة=len(senses),
            عقد=nodes),
        حارسُ_الإقصاء=dict(
            بيان=("الأدواتُ بلا مدلولٍ منصوصٍ تُقصى **قبل** الرسم: لو دخلت لصار "
                  "الغيابُ نفسُه عقدةً جامعةً يتّصل بها كلُّ من لا مدلولَ له، "
                  "فتبتلع مَن جاورها في كتلةِ ترادفٍ وهميّةٍ ليست في المتن ولا "
                  "في اللغة — والأثرُ مقيسٌ بعدده لا موعوظٌ به"),
            مُقصًى=void,
            الترادفُ_الكاذب=fake,
            مركّباتٌ_بإسقاط_الحارس=len(void_comps),
            مركّباتٌ_ابتُلعت=len(comps) - len(void_comps),
            الحارسُ_لازم=bool(fake > 1 and len(void_comps) < len(comps))),
        مركّبات=rows,
        خانات=[dict(اسم=k, مركّبات=v) for k, v in counts.items()],
        التباين=dict(
            عدد=tabayun,
            بيان=("«كالسواد والبياض» — المتباينُ علاقةٌ **بين** مركَّبين لا خانةٌ "
                  "فيها عضو، فيُعَدُّ أزواجَ المركّبات لا أعضاءً. وهذا فرقٌ يُعلَن "
                  "لا يُطوى")),
        دَينُ_المتشابك=dict(
            عدد=counts["متشابك — لا اسمَ له في السبعة"],
            بيان=("مركَّبٌ تكثّر طرفاه معًا: فيه ترادفٌ واشتراكٌ متشابكان، ولا اسمَ "
                  "له في السبعة — فلا يُلحَق بخانةٍ تشبهه، ويُسمّى بعدده دَينًا")),
        إقفال=dict(
            مجموعُ_الخانات=sum(counts.values()),
            مركّبات=len(rows),
            مقفَل=bool(sum(counts.values()) == len(rows) and nodes == len(forms) + len(senses))),
    )


# ═══ ④ الفاتورةُ حَكَمًا على خانات المصفوفة ═══════════════════════════════════════
def corpus():
    """مقامُ المجمَّد — من `madlul_gate` وحدَه، ولا يُعاد بناؤه."""
    try:
        return MG.corpus()
    except MG.MadlulError as exc:
        raise Ma3anError(exc.code, exc.message) from exc


def cell_forms(rows, name, present):
    """صورُ خانةٍ في المقام: ألفاظُها المفردةُ وحدَها — والمركَّبةُ لا تُقاس صورة."""
    return sorted({DG.fold(f) for r in rows if r["خانة"] == name for f in r["ألفاظ"]
                   if " " not in DG.fold(f)} & present)


def rivals_of(stream, candidates, size):
    """ضوابطُ المثل: RIVALS فرقةً عشوائيّةً بالعدد نفسِه وببذرةٍ معلنةٍ قبل القياس."""
    rng = random.Random(TG.CONTROL_SEED)
    out = []
    for _ in range(RIVALS):
        forms = tuple(rng.sample(candidates, size))
        try:
            out.append(TG.split_bill(stream, TG.fire_of(stream, forms=set(forms)),
                                     forms))
        except TG.Ta3allumError as exc:
            raise Ma3anError(exc.code, exc.message) from exc
    return out


def priced(stream, forms, candidates, name):
    """فاتورةُ خانةٍ: الحكمُ المفردُ ثمّ المميِّزُ بمقارنةِ المثل — ولا يُخلَطان."""
    try:
        bill = TG.rule_bill(stream, tuple(forms), TG.fire_of(stream, forms=set(forms)),
                            random.Random(TG.CONTROL_SEED))
    except TG.Ta3allumError as exc:
        raise Ma3anError(exc.code, exc.message) from exc
    rivals = rivals_of(stream, candidates, len(forms))
    beats = bill["Δ"] < min(rivals)
    bill.update(خانة=name, في_الميدان=True, ضوابطُ_المثل=RIVALS,
                أدنى_المثل=round(min(rivals), 1),
                وسيطُ_المثل=round(sorted(rivals)[len(rivals) // 2], 1),
                غلبَ_المثل=bool(beats),
                حكمٌ_مميِّز=("فاصلةٌ بمقارنةِ المثل" if beats
                            else "غيرُ فاصلةٍ — لم تغلب ضوابطَ المثل"))
    return bill


def price_station(rows):
    """ميدانُ التسعير: كلُّ خانةٍ بفاتورتها، والانكماشُ من اللفظ إلى الصورة معلَن."""
    _, stream, _ = corpus()
    present = set(stream)
    candidates, _ = TG.hypothesis_space(stream)

    bills = []
    for name in ("المنفرد", "المترادف", "خانةُ النقل (المشترك وما نُقل)",
                 "متشابك — لا اسمَ له في السبعة"):
        forms = cell_forms(rows, name, present)
        if len(forms) < 2:
            bills.append(dict(خانة=name, في_الميدان=False, صور=len(forms),
                              حكم=("خارجَ الميدان — دون صورتين في المجمَّد، "
                                   "ولا تُسعَّر فرقةٌ لا مثيلَ لها")))
            continue
        bill = priced(stream, forms, candidates, name)
        bill["صور"] = len(forms)
        bills.append(bill)

    every = sorted({f for r in rows for f in r["ألفاظ"]
                    if " " not in DG.fold(f)})
    seen = sorted({DG.fold(f) for f in every} & present)
    rng = random.Random(TG.CONTROL_SEED)
    hollow_forms = tuple(rng.sample(candidates, len(seen)))
    hollow = TG.rule_bill(stream, hollow_forms,
                          TG.fire_of(stream, forms=set(hollow_forms)),
                          random.Random(TG.CONTROL_SEED))
    return dict(
        مقام=len(stream),
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ضوابطُ_المثل=RIVALS,
        انكماشُ_الميدان=dict(
            ألفاظٌ_مفردة=len(every),
            صورٌ_واقعةٌ_في_المقام=len(seen),
            بيان=("الميدانُ 52 لفظًا، ولا يُسعَّر منها إلا ما وقع صورةً في "
                  "المجمَّد — والانكماشُ يُعلَن بعدده ولا يُخفى تحت المقام")),
        ثمنُ_إعلان_الميدان=round(TG.declaration_cost(seen), 1),
        خانات=bills,
        خواءُ_الحكم_المفرد=dict(
            بيان=("فرقةٌ عشوائيّةٌ بعددِ صورِ الميدان نفسِه — إن نالت «مُودَعةٌ "
                  "بالبرهان» فالحكمُ المفردُ لا يفصل ههنا، والمميِّزُ مقارنةُ "
                  "المثل وحدَها. وهو مُعادٌ قياسُه ههنا لا منقولٌ من `madlul`"),
            عدد=len(hollow_forms), Δ=hollow["Δ"], حكم=hollow["حكم"],
            خاوٍ=bool(hollow["حكم"] == "مُودَعةٌ بالبرهان")),
    )


