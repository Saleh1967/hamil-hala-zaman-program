def falsify(stream, candidates, harvest, abwab, twk, hdf, tas, wit, j2):
    T = []

    # ① الحصرُ مسحٌ: مجموعُ الدواوينِ هو عددُ ما حُصِر، ولا ديوانَ خارجَ الخريطة.
    T.append(("المحصورُ خالف مجموعَ الدواوين",
              harvest["عددُ_المحصور"] + harvest["عددُ_المسدَّد"] !=
              sum(len(read_rows(dig(load(f), p, f), sh, f))
                  for f, p, sh, _ in READERS)))
    T.append(("ديونٌ مطويّةٌ ظهرت ولم يُصرَخ", harvest["ديونٌ_مطويّة"] != 0))
    T.append(("الحصرُ خلا من دَين", harvest["عددُ_المحصور"] == 0))

    # ② لو كان المسحُ أعمى لَما رأى الصفوفَ المفردةَ خارجَ الدواوين. فظهورُها
    #    بعددٍ موجبٍ **دليلُ أنّ المشطَ يعمل**، وهي معلنةٌ خارجَ الحصر لا مطويّة.
    T.append(("المشطُ لم يرَ صفًّا مفردًا خارجَ الدواوين",
              harvest["عددُ_المفرد"] <= 0))

    # ③ سلّمُ الموانعِ يُميِّز: لو أعطى المانعَ نفسَه لكلِّ مدخلٍ لَما كان سلّمًا.
    T.append(("سلّمُ الموانعِ أعطى مانعًا واحدًا للأبواب كلِّها",
              len({b["مانع"] for b in abwab}) < 2))
    T.append(("سلّمُ الموانعِ خالف حدَّه الموروث",
              mana_of(IG.MIN_N - 1, None, None) != "مانعُ المقام" or
              mana_of(IG.MIN_N, TG.COVER_CEILING, True) != "مانعُ الانحلال" or
              mana_of(IG.MIN_N, 0.0, False) != "مانعُ المكيال" or
              mana_of(IG.MIN_N, 0.0, True) != NO_MANI3))

    # ④ بابٌ بلغَ حدَّ التسعيرِ وجاء بلا نصيبٍ ⟵ يجب أن يُصرَخ لا أن يُقدَّر.
