#
# §٠ السؤالُ بنصِّه: **ما الذي يمنع سدادَ كلِّ دَين؟** فالديونُ في هذه الشجرةِ
#    تُسمّى ولا تُرقَّم، وقد بلغت من الكثرةِ ما يُخشى معه أن يصير التسميةُ
#    عادةً بلا أثر. فهذا البابُ لا يسدِّد دَينًا ولا يفتح محورًا: يَحصُر
#    الديونَ **مسحًا لا استظهارًا**، ثمّ يُلحِق بكلِّ بابٍ من الأبوابِ السبعةِ
#    المسمّاةِ **مانعَه** مشتقًّا من رقمه بسلّمٍ معلنٍ قبل القياس.
#
# §١ الأبوابُ السبعةُ المسمّاةُ في السؤال: **المدلول · التوكيد · الإضمار ·
#    الحذف · الإحالة · إعرابُ الجملة · التمييزُ والحال**. وأربعةٌ منها
#    **مقيسةٌ سلفًا** فأرقامُها تُقرَأ من ودائعها حيًّا ولا تُكتَب ههنا مرّةً
#    ثانية (المدلول · الإحالة · إعرابُ الجملة · التمييزُ والحال)، وثلاثةٌ
#    **بلا رقمٍ في الشجرة** فتُقاس ههنا قياسًا جديدًا (التوكيد · الإضمار ·
#    الحذف). وكلُّ بابٍ يُودَع **مصدرُ رقمه** بلفظه — فلا يلتبس المقروءُ
#    بالمقيس.
#
# §٢ **سلّمُ الموانع**: أربعُ درجاتٍ مرتَّبةٍ معلنةٍ، تُقرَأ على ثلاثةِ أرقامٍ
#    لكلِّ بابٍ (ميدانٌ · نصيبٌ · فاصلٌ)، وأوّلُ درجةٍ تنطبق هي المانع:
#      ① ميدانٌ دون `ihala_gate.MIN_N` ⟶ **مانعُ المقام** (ولا يُطلَب نصيبٌ
#         لما سقط بالمقام — لا يُقدَّر رقمٌ لغائب).
#      ② نصيبٌ ≥ `ta3allum_gate.COVER_CEILING` ⟶ **مانعُ الانحلال**.
#      ③ لم يفصل ⟶ **مانعُ المكيال**.
#      ④ وإلّا ⟶ **لا مانعَ في القياس** — والدَّينُ حينئذٍ في التعيينِ لا في
#         القياس، ويُسمّى كذلك ولا يُدَّعى أنّه سُدَّ.
#    والحدّان ① و② **موروثان** من بابيهما، لا يُكتَبان ههنا.
#
# §٣ **مفرداتُ الموانع ستٌّ مغلقة**، ولكلِّ واحدةٍ **شاهدٌ مختومٌ** في الشجرة
#    يُقرَأ حيًّا — فلا مانعَ بلا شاهد، ويُعَدُّ «ما بلا شاهد» ويُودَع. وثمنُ
#    إعلانِ هذه الخريطةِ **مقيسٌ قبل أن تُستعمَل** بـ`declaration_cost`،
#    سنّةَ `mihwar_gate`.
#
# §٤ **الحصرُ مسحٌ لا استظهار**: تُمشَّط ودائعُ الشجرةِ كلُّها، ويُلتقَط كلُّ
#    موضعِ دَينٍ بمفرداتٍ معلنة، ثمّ يُصادَم الملتقَطُ بخريطةِ القُرّاء
#    المعلنة. فإن ظهر موضعُ دَينٍ لا قارئَ له صرخ البابُ — وبهذا يصير
