# ═══ ⑥ تصنيفُ الديونِ المحصورة — قراءةٌ بمفرداتٍ معلنةٍ لا قياس ═══════════════
def matches_of(text, table=MAWANI3):
    return [m["اسم"] for m in table
            if any(a in text for a in m["مراسٍ"])]


def tasnif_station(harvest, table=MAWANI3):
    rows, unclassified, multi = [], [], 0
    for d in harvest["ديونٌ_محصورة"]:
        hit = matches_of(d["نصّ"], table)
        if len(hit) > 1:
            multi += 1
        name = hit[0] if hit else None
        if name is None:
            unclassified.append(d["نصّ"])
        rows.append(dict(وديعة=d["وديعة"], نصّ=d["نصّ"],
                         مانع=name or "غيرُ مصنَّف", طابقَ=len(hit)))
    tally = {m["اسم"]: sum(1 for r in rows if r["مانع"] == m["اسم"])
             for m in table}
    tally["غيرُ مصنَّف"] = len(unclassified)
    return dict(صفوف=rows, جدول=tally, مصنَّف=len(rows) - len(unclassified),
                غيرُ_مصنَّف=len(unclassified), أسماءُ_غيرِ_المصنَّف=unclassified,
                طابقَ_أكثرَ_من_مانع=multi,
                بيان=("التصنيفُ قراءةٌ بمفرداتٍ معلنةٍ في نصِّ الدَّين، "
                      "لا قياسٌ على مقام — وثمنُ إعلانها مقيس"))


# ═══ ⑥½ الجولةُ الثانية: جدولٌ مولَّدٌ، وإعادةُ التصنيفِ كلِّه، وتصريحُ ما تبدّل ══
def widened(extra, table=MAWANI3):
    """جدولُ موانعَ يُبنى بزيادةِ مراسٍ على `مانعِ المقام` وحدَه — بنيةً واحدة."""
    out = []
    for m in table:
        m2 = dict(m)
        if m["اسم"] == "مانعُ المقام":
            m2["مراسٍ"] = tuple(m["مراسٍ"]) + tuple(
                a for a in extra if a not in m["مراسٍ"])
        out.append(m2)
    return tuple(out)


def moved_between(first, second):
    """ما تبدّل موضعُه بين تصنيفين — صفًّا صفًّا، لا عدَّ جدولٍ مجمَّع."""
    return [dict(وديعة=a["وديعة"], نصّ=a["نصّ"], من=a["مانع"], إلى=b["مانع"])
            for a, b in zip(first["صفوف"], second["صفوف"])
            if a["مانع"] != b["مانع"]]


