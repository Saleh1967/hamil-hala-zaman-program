# ═══ ① مسحُ الشجرةِ: كلُّ موضعِ دَينٍ يُلتقَط ثمّ يُصادَم بخريطةِ القُرّاء ═════
def deposits():
    """ودائعُ الشجرة: كلُّ `*.json` في الجذر سوى وديعةِ هذا الباب — مرتَّبةً لا عشوائية."""
    return sorted(f for f in os.listdir(ROOT)
                  if f.endswith(".json") and f != SELF_DEPOSIT)


def walk_sites(node, path, out):
    """كلُّ موضعٍ مفتاحُه من مفردات المسح — وما تحت «مقيس» أرقامٌ لا ديون."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k == MEASURED_KEY:
                continue
            p = path + (k,)
            if k in CONTAINER_KEYS:
                out.append(("ديوان", p))
            elif k in TALLY_KEYS:
                out.append(("إحصاء", p))
            elif k in ROW_KEYS:
                out.append(("صفّ", p))
            walk_sites(v, p, out)
    elif isinstance(node, list):
        for item in node:
            walk_sites(item, path + ("[]",), out)


def dig(obj, path, where):
    for k in path:
        if not isinstance(obj, dict) or k not in obj:
            raise DuyunError(E_SHAPE, f"موضعٌ مفقودٌ في {where}: {'/'.join(path)}")
        obj = obj[k]
    return obj


def load(name):
    p = os.path.join(ROOT, name)
    if not os.path.exists(p):
        raise DuyunError(E_MISSING, f"وديعةٌ غائبةٌ: {name}")
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def read_rows(raw, shape, where):
    """نصوصُ ديوانٍ واحدٍ بشكلِه المعلن — ولا يُوحَّد شكلٌ بيد."""
    if shape == "بنودٌ_بعدد":
        if not isinstance(raw, dict) or "بنود" not in raw:
            raise DuyunError(E_SHAPE, f"شكلٌ خالف «بنودٌ بعدد» في {where}")
        items = raw["بنود"]
        if raw.get("عدد") != len(items):
            raise DuyunError(E_SEAL, f"عدَّةُ الديوانِ خالفت بنودَه في {where}")
    elif shape == "بنود":
        items = raw
    elif shape == "صفوف":
        items = []
        for r in raw:
            key = next((k for k in ROW_KEYS if k in r), None)
            if key is None:
                raise DuyunError(E_SHAPE, f"صفٌّ بلا مفتاحِ دَينٍ في {where}")
            bay = next((r[k] for k in BAYAN_KEYS if k in r), "")
            items.append(f"{r[key]} — {bay}" if bay else str(r[key]))
    else:
        raise DuyunError(E_SHAPE, f"شكلٌ غيرُ معلنٍ: {shape}")
    if not all(isinstance(s, str) and s.strip() for s in items):
        raise DuyunError(E_SHAPE, f"بندُ دَينٍ ليس نصًّا في {where}")
    return list(items)


def harvest_station():
    """حصرُ الديون: قراءةٌ بخريطةٍ معلنةٍ، ومسحٌ يُثبِت أنّ الخريطةَ لم تُغفِل موضعًا."""
    files = deposits()
    sites = []
    for f in files:
        found = []
        walk_sites(load(f), (), found)
        sites += [(f, kind, p) for kind, p in found]

    covered = {(f, p) for f, p, _, _ in READERS} | set(TALLY_SITES)
    rows, paid = [], []
    for f, path, shape, band in READERS:
        where = f"{f} → {'/'.join(path)}"
        got = read_rows(dig(load(f), path, f), shape, where)
        for s in got:
            (rows if band == "بلا_رقم" else paid).append(
                dict(وديعة=f, موضع='/'.join(path), نصّ=s))

    # مسحٌ لا استظهار: كلُّ ديوانٍ أو إحصاءٍ التُقط لا بدّ أن يكون في الخريطة.
    hidden = sorted({f"{f} → {'/'.join(p)}" for f, kind, p in sites
                     if kind in ("ديوان", "إحصاء") and (f, p) not in covered})
    if hidden:
        raise DuyunError(E_SEAL, "ديوانٌ مطويٌّ لا قارئَ له: " + " · ".join(hidden))

    # صفوفٌ خارجَ كلِّ ديوان: ديونٌ مفردةٌ في صفوفِ أبوابها — **خارجَ هذا الحصر
    #   بإعلان**، وتُعَدُّ ولا تُطوى.
    prefixes = sorted(p for _, p in covered)
    singles = []
    for f, kind, p in sites:
        if kind != "صفّ":
            continue
        if any((f, pre) in covered and p[:len(pre)] == pre for pre in prefixes):
            continue
        singles.append((f, '/'.join(p)))
    singles = sorted(set(singles))

    return dict(ودائعُ_ممسوحة=len(files), مواضعُ_الدواوين=len(READERS),
                مواضعُ_الإحصاء=len(TALLY_SITES),
                ديونٌ_محصورة=rows, عددُ_المحصور=len(rows),
                مسدَّدٌ_بقياسه=paid, عددُ_المسدَّد=len(paid),
                مفردٌ_خارجَ_الحصر=[dict(وديعة=f, موضع=p) for f, p in singles],
                عددُ_المفرد=len(singles), ديونٌ_مطويّة=len(hidden))


# ═══ ② سلّمُ الموانعِ — أربعُ درجاتٍ مرتَّبةٍ، وحدّاها موروثان ══════════════
def mana_of(n, share, fasl):
    """مانعُ بابٍ من رقمه: أوّلُ درجةٍ تنطبق — ولا يُقدَّر رقمٌ لغائب."""
    if n < IG.MIN_N:
        return "مانعُ المقام"
    if share is None or fasl is None:
        raise DuyunError(E_SHAPE, "بابٌ بلغَ حدَّ التسعيرِ وجاء بلا نصيبٍ أو فاصل")
    if share >= TG.COVER_CEILING:
        return "مانعُ الانحلال"
    if not fasl:
        return "مانعُ المكيال"
    return NO_MANI3


