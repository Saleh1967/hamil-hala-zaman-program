def collide(measured):
    extra = [k for k in measured if k not in SEALED_DUYUN]
    if extra:
        raise DuyunError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    bad = [(k, SEALED_DUYUN[k], measured.get(k)) for k in SEALED_DUYUN
           if k not in measured or measured[k] != SEALED_DUYUN[k]]
    if bad:
        raise DuyunError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_DUYUN)


