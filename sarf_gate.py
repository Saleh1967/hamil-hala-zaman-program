# ═══ ⑨ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ، ونجاحُ واحدةٍ يُسقِط البابَ ═══════
def falsify(rows, fld, tan, niy, al, hjr, bil):
    T = []
    add = lambda name, hit: T.append((name, bool(hit)))

    # ① الحقولُ مغلقةٌ معلنةُ الحجم، ولا خانةَ سرّيّةَ وراءَ «لا صورةَ له».
    add("خلايا الصورةِ خالفت إعلانَها", len(SUWAR) != M_SURA)
    add("صورةٌ خارجَ الخلايا الأربع",
        any(r["بنية"] not in SUWAR for r in rows))
    add("خلايا الصورةِ لا تستوعب الكلماتِ كلَّها",
        sum(fld["صورٌ_حاضرة"].values()) != fld["كلمات"])
    add("خانةُ صورةٍ خاليةٌ بالبناء", min(fld["صورٌ_حاضرة"].values()) <= 0)

    # ② الوكيلُ لا يبتلع ألفَ التنوينِ المرسومة ولا التاءَ المربوطة.
    add("«عذابا» قُرئت صيغةَ منتهى الجموع", muntaha("عذابا"))
    add("«ملائكة» قُرئت صيغةَ منتهى الجموع", muntaha("ملائكة"))
    add("«مساجد» لم تُقرَأ صيغةَ منتهى الجموع", not muntaha("مساجد"))
    add("«مصابيح» لم تُقرَأ صيغةَ منتهى الجموع", not muntaha("مصابيح"))

    # ③ موضعُ الجرِّ لا يشترط علامةَ جرٍّ — فلو اشترطها لكان القياسُ دورًا،
    #    ودليلُه بالعدّ: في مواضعِه علاماتٌ غيرُ الكسرةِ بكثرة.
    site = [r for r in rows if r["جر"]]
    add("موضعُ الجرِّ لا يقع فيه إلّا مكسور",
        all(r["علامة"] in ("كسرة", "تنوين كسر") for r in site))
    add("مواضعُ الجرِّ لم تبلغ حدَّ الفاتورة", len(site) < MIN_N)

    # ④ النيابةُ ليست تحصيلَ حاصل: لو كانت الفتحةُ نصيبَ الميدانِ لا نصيبَ
    #    الصنف، لبلغَها خلطُ الوسمِ على الميدانِ نفسِه. والمحاولةُ تفحص
    #    **موافقةَ الحكمِ لعدده** لا أن يكون الحكمُ قيامًا: فالساقطُ يُختَم
    #    بعدده ولا يُسقِط البابَ، والقائمُ يُصادَم بمثلِه وبخلفيّته.
    for k in ("الصورتان", "المعجمُ_المنتهي"):
        up = niy[k]["حكم"].startswith("نابت")
        add(f"نيابةُ «{k}» خُتمت قائمةً وضابطُ مثلٍ بلغَها",
            up and niy[k]["أعلى_المثل"] >= niy[k]["نصيبُ_الفتحة"])
        add(f"نيابةُ «{k}» خُتمت قائمةً ولم تغلب خلفيّتَها",
            up and niy[k]["نصيبُ_الفتحة"] <= niy[k]["الخلفية"])
        add(f"نيابةُ «{k}» خُتمت ساقطةً وهي غالبةٌ مثلَها وخلفيّتَها",
            not up and niy[k]["نصيبُ_الفتحة"] > niy[k]["أعلى_المثل"]
            and niy[k]["نصيبُ_الفتحة"] > niy[k]["الخلفية"])
        add(f"ضوابطُ مثلِ «{k}» ليست {RIVALS}",
            len(niy[k]["ضوابطُ_المثل"]) != RIVALS)

    # ⑤ شرطُ «أل» يفصل حقًّا: ولو كان الفصلُ أثرَ قسمةٍ عشوائيّةٍ لبلغه أدنى المثل.
    add("أدنى مثلِ الفتحةِ بأل بلغَ المقيس",
        al["بأل"]["نصيبُ_الفتحة"] >= al["أدنى_مثلِ_الفتحةِ_بأل"])
    add("الفارقُ لا يوافق طرفيه",
        abs(al["الفارق"] - (al["بلا_أل"]["نصيبُ_الفتحة"]
                            - al["بأل"]["نصيبُ_الفتحة"])) > 1.5e-4)

    # ⑥ الحَجْرُ مقيسٌ لا مرغوب: لو فصلَ الشرطُ المقصورَ لَرُفع الحَجْرُ عنه،
    #    والوديعةُ تعلن أيَّ الأمرين وقع.
    add("المقصورُ حُجِر وقد فصلَه الشرط",
        hjr["شرطُ_«أل»_فصلَه"] and "محجور" in hjr["حكم"])
    add("المقصورُ رُفع حَجْرُه ولم يفصله الشرط",
        not hjr["شرطُ_«أل»_فصلَه"] and "محجور" not in hjr["حكم"])

    # ⑦ الفاتورةُ لا تُقرَأ من المعرَّفِ بأل وحدَه: الرقمان مختومان معًا،
    #    وحذفُ الداخليِّ لأنّه أصغرُ هو العطلُ الذي يحرسه هذا الحارس.
    add("فاتورةُ غيرِ المعرَّفِ غابت عن الوديعة", "حكم" not in bil["غيرُ_المعرَّف"])
    add("فاتورةُ غيرِ المعرَّفِ لم تغلب مثلَها",
        bil["غيرُ_المعرَّف"]["المكسب"] <= bil["غيرُ_المعرَّف"]["أعلى_المثل"])

    # ⑧ المعجمُ يُقرَأ من موضعه ولا يُنسَخ ههنا ولا يُوسَّع بعد القياس.
    add("المعجمُ المنتهي نُسخ ههنا", "MAMNU3" in globals() and
        MAMNU3 is not sys.modules["jar_gate"].MAMNU3)
    add("حجمُ المعجمِ خالفَ موضعَه",
        fld["حجمُ_المعجمِ_المنتهي"] != len(sys.modules["jar_gate"].MAMNU3))

    # ⑨ خطأُ الوكيلِ معروضٌ مسمًّى: منوَّنٌ التقطه الوكيلُ يُسمّى ولا يُطمَس.
    add("منوَّنون على الوكيلِ بلا تسمية",
        tan["منوَّنون_على_الوكيل"] > 0 and not tan["مسمَّون"])

    # ⑩ خريطةُ الصورِ مُسعَّرةٌ قبل أن تُستعمَل، ولا يُقدَّر ثمنٌ لغائب.
    add("ثمنُ إعلانِ الخريطةِ غيرُ موجب", fld["ثمنُ_إعلانِ_الخريطة"] <= 0)

    # ⑪ الديونُ تُسمّى ولا تُرقَّم، وأسبابُ المنعِ الاثنا عشرَ معلنةٌ كلُّها.
    add("دَينٌ حملَ رقمًا", any(any(c.isdigit() for c in d) for d in DEBTS))
    add("أسبابُ المنعِ ليست اثنَي عشرَ", len(ASBAB) != 12)
    add("سببٌ بلا سندِ قياسٍ معلن", any(not a[2] for a in ASBAB))

    # ⑫ ولو كان حدُّ الشاهدِ حليةً لقبِل المقياسُ ميدانًا دونَه بلا صريخ.
    try:
        priced("ميدانٌ مصنوع", ["ا"] * (MIN_N - 1), ["فتحة"] * (MIN_N - 1))
        tiny = True
    except SarfError:
        tiny = False
    add("الفاتورةُ تقبل مقامًا دونَ حدِّ التسعير", tiny)

    fired = [n for n, hit in T if hit]
    if fired:
        raise SarfError(E_SEAL, "محاولةُ تكذيبٍ نجحت: " + " · ".join(fired))
    return len(T)


