# ═══ ① الإحداثياتُ — كلُّها من البايتاتِ وحدَها ════════════════════════════════
def stem(s):
    """الجذعُ المعروضُ للصورة: نزعُ اللواصقِ الرسميّةِ ثمّ لاحقةِ الضميرِ الموروثة.
    والنزعُ **معلَنٌ لا صامت**: «مساكنهم» صورتُها صورةُ «مساكن»، و«عبادته» تدخل
    معها — وثمنُ ذلك مقيسٌ في خطأِ الوكيل، لا مستورٌ باشتراطٍ بعديّ."""
    while len(s) > 3 and s[0] in PRE:
        s = s[1:]
    p = pron_suffix(s)
    if p and len(s) - len(p) >= 3:
        s = s[:-len(p)]
    return s


def has_al(s):
    return s.startswith("ال") and len(s) > 3


def body_of(s):
    """ما بعدَ «أل» إن كانت — فالصورةُ تُقرأ من البنيةِ لا من التعريف."""
    return s[2:] if has_al(s) else s


def muntaha(b):
    """صيغةُ منتهى الجموع بالرسم: ألفٌ بعدَ حرفين فصاعدًا، يليها حرفان (مفاعِل)
    أو ثلاثةٌ أوسطُها حرفُ علّة (مفاعيل). وخاتمةُ الصيغةِ صحيحةٌ — فالمختومُ
    بألفٍ أو واوٍ أو ياءٍ أو تاءٍ مربوطةٍ أو همزةٍ خارجٌ بالبناء، وبه تسقط
    ألفُ التنوينِ المرسومة («عذابا») ولا تُقرَأ صيغةً."""
    if len(b) < 4 or b[-1] in "اوىيةء":
        return False
    for i in range(2, len(b) - 2):
        if b[i] == "ا":
            rest = len(b) - i - 1
            if rest == 2 or (rest == 3 and b[i + 2] in "ويا"):
                return True
    return False


def sura_of(s):
    """صورةُ الاسمِ في خلايا أربعٍ مغلقة — والأولويةُ معلنةٌ: الصيغةُ ثمّ المقصورةُ
    ثمّ الممدودة، ولا خانةَ سرّيّةَ وراءَ «لا صورةَ له»."""
    b = body_of(s)
    if muntaha(b):
        return SUWAR[0]
    if len(b) >= 4 and b.endswith("ى"):
        return SUWAR[1]
    if len(b) >= 5 and b.endswith("اء"):
        return SUWAR[2]
    return SUWAR[3]


def in_mu3jam(s):
    """المعجمُ الموروثُ المنتهي في `jar_gate.MAMNU3` — يُقرَأ من موضعه ولا يُنسَخ."""
    return body_of(s) in MAMNU3 or s in MAMNU3


def jar_site(v, i):
    """موضعُ الجرِّ **بحدِّه المعلن**: كلمةٌ سُبقت بجارٍّ منفصلٍ من القائمةِ
    الموروثةِ (`induction_engine.JARR`)، أو صُدِّرت بجارٍّ ملتصقٍ مكسور
    (`JPRE`). ولا يُشترَط ههنا علامةُ جرٍّ في البايتات — فالعلامةُ هي المحكومُ
    عليها، واشتراطُها دورٌ يُبطِل القياس."""
    w = v[i]
    s = sk(w)
    if s[:1] in JPRE and w[0][1] == "كسرة" and len(s) > 2:
        return True
    return i > 0 and sk(v[i - 1]) in JARR


def r4(x):
    """تقريبٌ إلى أربعةٍ بلا صفرٍ سالب — لئلّا يفترق رقمٌ عن ختمِه بإشارةِ صفر."""
    y = round(x, 4)
    return 0.0 if y == 0 else y


def ce(keys, vals):
    return HL.heldout_ce(list(zip(keys, vals)), 0, M_ALAMA)


def priced(name, keys, vals):
    """صفٌّ مُسعَّر: الحدُّ الأدنى مفتاحٌ واحدٌ ثابت، والمكسبُ فوقَه، والحكمُ من
    إشارةِ المكسبِ ومن غلبتِه على أعلى ضوابطِ المثل."""
    if len(vals) < MIN_N:
        raise SarfError(E_SHAPE, f"مقامُ «{name}» {len(vals)} دون {MIN_N}")
    base = ce([0] * len(vals), vals)
    cond = ce(keys, vals)
    rivals = []
    for t in range(RIVALS):
        ks = list(keys)
        random.Random(SEED * 100 + t + 1).shuffle(ks)
        rivals.append(r4(base - ce(ks, vals)))
    gain, top = r4(base - cond), max(rivals)
    return {
        "الاسم": name, "مقام": len(vals),
        "بلا_معرفة": r4(base), "بالمعرفة": r4(cond),
        "المكسب": gain, "أعلى_المثل": top, "ضوابطُ_المثل": rivals,
        "حكم": "مُودَعٌ بالبرهان" if gain > 0 and gain > top else "ساقطٌ بالثمن",
    }


def share(rows, mark):
    """نصيبُ علامةٍ بعينها في ميدان — ولا يُقسَم على فراغ."""
    return r4(sum(1 for r in rows if r["علامة"] == mark) / len(rows)) if rows else 0.0


def flag_rivals(field, flag, mark, want):
    """ضوابطُ المثل لشاهدِ النسبة: يُخلَط **الوسمُ وحدَه** على الميدانِ نفسِه،
    فيبقى المقامُ وتبقى العلاماتُ ويُهدَم الاقتران. والمردودُ نصيبُ العلامةِ في
    الطائفةِ الموسومةِ عند كلِّ خلط."""
    out = []
    for t in range(RIVALS):
        fl = [r[flag] for r in field]
        random.Random(SEED * 100 + t + 1).shuffle(fl)
        g = [r for r, f in zip(field, fl) if f == want]
        out.append(share(g, mark))
    return out


# ═══ ② الميدان — المجمَّدُ وحدَه ══════════════════════════════════════════════
def corpus():
    verses = parse_verses(HL.CORPUS)
    if not verses:
        raise SarfError(E_CORPUS, "المجمَّدُ خالٍ — لا مقامَ يُقاس عليه")
    words = [w for v in verses for w in v]
    if len(words) < MIN_N:
        raise SarfError(E_SHAPE, f"مقامُ الكلماتِ {len(words)} دون الحدِّ المعلن")
    return verses, words


def rows_of(verses):
    """صفُّ كلِّ كلمةٍ في المجمَّد: صورتُها · أمعرَّفةٌ بأل · أفي المعجمِ المنتهي ·
    علامةُ آخرها · أفي موضعِ جرٍّ معلن. ولا يُطرَح موضعٌ ههنا البتّة."""
    out = []
    for v in verses:
        for i, w in enumerate(v):
            s = stem(sk(w))
            out.append({
                "صورة": sk(w), "جذع": s, "بنية": sura_of(s),
                "بأل": has_al(s), "معجم": in_mu3jam(s),
                "علامة": END(w), "جر": jar_site(v, i),
                "فعل": word_class(w) == "فعل",
            })
    return out


def field_station(verses, rows):
    counts = Counter(r["بنية"] for r in rows)
    forms = sorted({r["جذع"] for r in rows
                    if r["بنية"] in JUDGED or r["معجم"]})
    return {
        "آيات": len(verses), "كلمات": len(rows),
        "خلايا_الصورة": M_SURA, "خلايا_العلامة": M_ALAMA,
        "حجمُ_المعجمِ_المنتهي": len(MAMNU3),
        "صورٌ_حاضرة": {k: counts[k] for k in SUWAR},
        "مواضعُ_الجرِّ_المعلنة": sum(1 for r in rows if r["جر"]),
        "مواضعُ_المعجمِ_المنتهي": sum(1 for r in rows if r["معجم"]),
        "ثمنُ_إعلانِ_الخريطة": round(TG.declaration_cost(forms), 1),
        "حدُّ_موضعِ_الجرّ": ("جارٌّ منفصلٌ قبلَها من `induction_engine.JARR`، أو "
                            "جارٌّ ملتصقٌ مكسورٌ في صدرها — ولا تُشترَط علامةُ "
                            "جرٍّ في البايتات لئلّا يكون القياسُ دورًا"),
    }


# ═══ ③ محطّةُ التنوين — نقصٌ مقيسٌ، وخطأُ الوكيلِ مسمًّى ═════════════════════════
def tanwin_station(rows):
    """«لا يقبل التنوين» — فيُقاس نصيبُ التنوينِ على كلِّ صنفٍ غيرِ معرَّفٍ بأل،
    ويُصادَم بنصيبِه في الخلفيّة. والمنوَّنون الذين التقطهم الوكيلُ **يُسمَّون
    بأعيانهم**: هم خطؤه لا نقضُ القاعدة، وسَتْرُهم هو العطل."""
    bare = [r for r in rows if not r["بأل"]]
    out, rates = {}, {}
    for k in SUWAR:
        g = [r for r in bare if r["بنية"] == k]
        n = len(g)
        t = sum(1 for r in g if r["علامة"].startswith("تنوين"))
        rates[k] = r4(t / n) if n else 0.0
        out[k] = {"مقام": n, "منوَّن": t, "نصيبُ_التنوين": rates[k]}
    g = [r for r in bare if r["معجم"]]
    t = sum(1 for r in g if r["علامة"].startswith("تنوين"))
    out["المعجمُ المنتهي"] = {"مقام": len(g), "منوَّن": t,
                              "نصيبُ_التنوين": r4(t / len(g)) if g else 0.0}
    named = Counter(r["صورة"] for r in bare
                    if r["بنية"] in JUDGED and r["علامة"].startswith("تنوين"))
    judged_n = sum(out[k]["منوَّن"] for k in JUDGED)
    return {
        "أصناف": out,
        "خلفيّةُ_التنوين": rates[SUWAR[3]],
        "منوَّنون_على_الوكيل": judged_n,
        "مسمَّون": [f"{f}×{n}" for f, n in named.most_common(12)],
        "حكم": ("نقصٌ مقيسٌ — ونصيبُ التنوينِ على الصورتين دونَ خلفيّته"
                if max(rates[k] for k in JUDGED) < rates[SUWAR[3]]
                else "ساقطٌ بالعدّ — الوكيلُ يُنوَّن كخلفيّته"),
        "بيان": ("التنوينُ الواقعُ على الوكيلِ **خطؤه** لا نقضُ القاعدة، "
                 "ومخالفوه مسمَّون بأعيانهم في هذه الوديعة"),
    }


# ═══ ④ محطّةُ النيابة — الفتحةُ في موضعِ الجرّ ═════════════════════════════════
def niyaba_station(rows):
    """نيابةُ الفتحةِ عن الكسرة: تُقاس في **موضعِ الجرِّ المعلن** وحدَه، على
    غيرِ المعرَّفِ بأل، وتُصادَم بخلفيّتها وبضوابطِ مثلها. والميدانان
    (الصورةُ · المعجمُ) **لا يُجمَعان في رقمٍ واحد**: لكلٍّ سندُه."""
    site = [r for r in rows if r["جر"] and not r["فعل"]]
    if len(site) < MIN_N:
        raise SarfError(E_SHAPE, f"مواضعُ الجرِّ {len(site)} دون {MIN_N}")
    bare = [r for r in site if not r["بأل"]]
    khalfiyya = [r for r in bare if r["بنية"] == SUWAR[3] and not r["معجم"]]
    bg = share(khalfiyya, "فتحة")

    def one(name, sel):
        g = [r for r in bare if sel(r)]
        if len(g) < MIN_SHAHID:
            raise SarfError(E_SHAPE, f"ميدانُ «{name}» {len(g)} دون {MIN_SHAHID}")
        for r in bare:
            r["_وسم"] = sel(r)
        obs = share(g, "فتحة")
        riv = flag_rivals(bare, "_وسم", "فتحة", True)
        top = max(riv)
        named = Counter(r["صورة"] for r in g if r["علامة"] != "فتحة")
        return {
            "ميدان": len(g), "نصيبُ_الفتحة": obs,
            "نصيبُ_الكسرة": r4(sum(1 for r in g if r["علامة"] in
                                   ("كسرة", "تنوين كسر")) / len(g)),
            "الخلفية": bg, "أعلى_المثل": top, "ضوابطُ_المثل": riv,
            "مخالفون_مسمَّون": [f"{f}×{n}" for f, n in named.most_common(8)],
            "حكم": ("نابت الفتحةُ — غلبت خلفيّتَها ومثلَها"
                    if obs > bg and obs > top else "ساقطٌ بالنسبة"),
        }

    out = {
        "مواضعُ_الجرِّ_بلا_أل": len(bare),
        "خلفيّةُ_الفتحة": bg,
        "الصورتان": one("الصورتان", lambda r: r["بنية"] in JUDGED and not r["معجم"]),
        "المعجمُ_المنتهي": one("المعجمُ المنتهي", lambda r: r["معجم"]),
    }
    for r in bare:
        r.pop("_وسم", None)
    out["حكم"] = ("الصورةُ والمعجمُ نابا معًا — بسندين لا يُجمَعان"
                  if out["الصورتان"]["حكم"].startswith("نابت")
                  and out["المعجمُ_المنتهي"]["حكم"].startswith("نابت")
                  else "أحدُ السندين سقط — والسقوطُ مختومٌ بعدده")
    return out


# ═══ ⑤ محطّةُ «أل» — شرطُ القاعدةِ يُكذَّب بنفسِه ═══════════════════════════════
def al_station(rows):
    """القاعدةُ تشترط بنفسِها عَودَ الكسرةِ مع «أل». فالصورةُ واحدةٌ والتعريفُ
    مختلف — وهذا أقوى ما يُكذَّب به الباب: لو كانت الفتحةُ أثرَ صورةٍ لا أثرَ
    منعٍ لَما فرّقها التعريف."""
    site = [r for r in rows if r["جر"] and not r["فعل"]]
    field = [r for r in site if r["بنية"] in JUDGED and not r["معجم"]]
    for part, n in (("الميدان", len(field)),):
        if n < MIN_SHAHID:
            raise SarfError(E_SHAPE, f"{part} {n} دون {MIN_SHAHID}")
    bare = [r for r in field if not r["بأل"]]
    al = [r for r in field if r["بأل"]]
    if min(len(bare), len(al)) < MIN_SHAHID:
        raise SarfError(E_SHAPE, "إحدى طائفتَي «أل» دون حدِّ الشاهد")
    riv = flag_rivals(field, "بأل", "فتحة", True)
    return {
        "ميدانُ_الصورتين_في_الجرّ": len(field),
        "بلا_أل": {"ميدان": len(bare), "نصيبُ_الفتحة": share(bare, "فتحة"),
                   "نصيبُ_الكسرة": r4(sum(1 for r in bare if r["علامة"] in
                                          ("كسرة", "تنوين كسر")) / len(bare))},
        "بأل": {"ميدان": len(al), "نصيبُ_الفتحة": share(al, "فتحة"),
                "نصيبُ_الكسرة": r4(sum(1 for r in al if r["علامة"] in
                                       ("كسرة", "تنوين كسر")) / len(al))},
        "أدنى_مثلِ_الفتحةِ_بأل": min(riv), "ضوابطُ_المثل": riv,
        "الفارق": r4(share(bare, "فتحة") - share(al, "فتحة")),
        "حكم": ("شرطُ «أل» فاصلٌ مقيس — الفتحةُ تسقط بالتعريفِ دونَ ما يبلغه مثلُها"
                if share(al, "فتحة") < min(riv) and share(bare, "فتحة") > share(al, "فتحة")
                else "ساقطٌ بالشرط — التعريفُ لم يفصل"),
    }


# ═══ ⑥ محطّةُ الحَجْر — المقصورُ تعذُّرٌ لا نيابة ═══════════════════════════════
def hajr_station(rows):
    """المقصورُ **يُحجَر بالقياس لا بالرأي**: يُعرَض عليه شرطُ القاعدةِ نفسُه
    (عَودُ الكسرةِ مع «أل»)، فإن لم يفصله فالفتحةُ على آخره تعذُّرٌ لا نيابة —
    وما لا يفصله شرطُ القاعدةِ لا يُحكَم له بها ولا عليها."""
    site = [r for r in rows if r["جر"] and not r["فعل"]]
    field = [r for r in site if r["بنية"] == SUWAR[1]]
    bare = [r for r in field if not r["بأل"]]
    al = [r for r in field if r["بأل"]]
    if min(len(bare), len(al)) < MIN_SHAHID:
        raise SarfError(E_SHAPE, "ميدانُ المقصورِ دون حدِّ الشاهد — لا حَجْرَ يُقاس")
    f_bare, f_al = share(bare, "فتحة"), share(al, "فتحة")
    k_all = r4(sum(1 for r in field if r["علامة"] in ("كسرة", "تنوين كسر"))
               / len(field))
    return {
        "ميدانُ_المقصورِ_في_الجرّ": len(field),
        "بلا_أل": len(bare), "بأل": len(al),
        "نصيبُ_الفتحةِ_بلا_أل": f_bare, "نصيبُ_الفتحةِ_بأل": f_al,
        "نصيبُ_الكسرةِ_في_الميدان": k_all,
        "شرطُ_«أل»_فصلَه": bool(f_al < f_bare),
        "حكم": ("محجورٌ بحدِّه المقيس — لا مردودٌ ولا مقبول"
                if not (f_al < f_bare) else "فصلَه الشرطُ — يُرفَع الحَجْر"),
        "بيان": ("الفتحةُ على آخرِ المقصورِ **تعذُّرٌ** لا نيابة: نصيبُها مع «أل» "
                 "لم ينقص، والكسرةُ لا تقع في ميدانه أصلًا — فما لا يفصله شرطُ "
                 "القاعدةِ لا يُحكَم له بها"),
    }


# ═══ ⑦ فاتورةُ المقام — والجوارُ حدُّها الأدنى ═════════════════════════════════
def bill_station(rows):
    """رقمان يُختَمان معًا: فاتورةُ المقامِ الكاملِ (والمعرَّفُ بأل خانةٌ فيها —
    ونصيبُه من المكسبِ تحصيلُ حاصلٍ معلن، لأنّ «أل» تمنع التنوينَ بالنصّ)، ثمّ
    **الفاتورةُ في غيرِ المعرَّفِ وحدَه** — وهي الحَكَمُ، لأنّ حدَّها الأدنى
    جوارُها لا العدم."""
    keys = [r["بنية"] if not r["بأل"] else "معرَّفٌ بأل" for r in rows]
    vals = [r["علامة"] for r in rows]
    full = priced("الصورةُ ⟶ علامةُ الآخِر (المقامُ الكامل)", keys, vals)
    bare = [r for r in rows if not r["بأل"]]
    inner = priced("الصورةُ ⟶ علامةُ الآخِر (غيرُ المعرَّف)",
                   [r["بنية"] for r in bare], [r["علامة"] for r in bare])
    return {
        "المقامُ_الكامل": full, "غيرُ_المعرَّف": inner,
        "حكم": ("الصورةُ تشتري بتًّا في غيرِ المعرَّفِ أيضًا — فليست تحصيلَ حاصل"
                if inner["حكم"] == "مُودَعٌ بالبرهان" else "ساقطٌ بالثمن"),
    }


