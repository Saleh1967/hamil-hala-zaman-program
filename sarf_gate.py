# sarf_gate.py — بابُ الصرفِ ومنعِه: أيُقام على البايتاتِ وحدَها حدُّ «المتمكّنِ
#                غيرِ الأمكن»، وأتنوب الفتحةُ عن الكسرةِ حيث قيل تنوب؟
#
# §٠ الدَّينُ المعروضُ للسداد. في `mabna_gate` دَينٌ مختومٌ باسمه: «الممنوعُ من
#    الصرفِ **محجورٌ بحدِّه المقيس** — لا يُردُّ ولا يُقبَل — لأنّ شرطَه وزنٌ
#    ومعجمٌ (عَلَميّةٌ · عُجمةٌ · وصفيّة) لا ختمَ لهما ههنا». وههنا **يُسَدَّد
#    شطرٌ منه لا كلُّه**: ما كان من أسبابِ المنعِ **ذا صورةٍ في الرسم** أو **ذا
#    معجمٍ منتهٍ مسمًّى في الشجرة** يُقاس ويُختَم بعدده؛ وما لا صورةَ له ولا
#    معجمَ يبقى **دَينًا يُسمّى بلا رقم**. ورقمُ `mabna_gate` المختومُ لا يُمَسّ.
#
# §١ القاعدةُ المنصوصةُ تُترجَم إلى مقتضًى قابلٍ للتكذيب. «الاسمُ المتمكّنُ غيرُ
#    الأمكن: معربٌ لا يقبل التنوينَ ويُجَرُّ بالفتحةِ نيابةً عن الكسرة، ما لم
#    يُضَف أو يُعرَّف بـ«أل»». فمقتضاها المقيسُ ثلاثةٌ لا واحد:
#    ① نقصُ التنوينِ على ما التقطه الوكيلُ — ويُقاس، ويُسمّى المخالفون.
#    ② **نيابةُ الفتحةِ في موضعِ الجرّ** — نصيبٌ يُصادَم بضوابطِ مثلِه.
#    ③ **عَودُ الكسرةِ مع «أل»** — وهو الشرطُ الذي نصَّت عليه القاعدةُ بنفسِها،
#       فهو أقوى ما يُكذَّب به: الصورةُ واحدةٌ والتعريفُ مختلف.
#
# §٢ والحدُّ الأدنى ههنا **الخلفيةُ في موضعِ الجرِّ نفسِه** لا العدم: نصيبُ
#    الفتحةِ في سائرِ المجرورات. فالمقيسُ **فضلُ الصنفِ على خلفيّته**، لا فضلُ
#    «وقوعِ الفتحةِ» على الصفر — وهذه سنّةُ الجوارِ في `ihala_gate` بعينها.
#
# §٣ وما لا يُدَّعى — ويُختَم بعدده، ولا يُرفَع بتبويب:
#    ① **لا يُدَّعى أنّ الوكيلَ يعرف صيغةَ منتهى الجموع**: المقيسُ صورةُ الرسمِ
#       (ألفٌ بعدها حرفان، أو ثلاثةٌ أوسطُها حرفُ علّة)، وخطؤه **مقيسٌ مسمًّى**
#       بالمنوَّنين الذين التقطهم وليسوا من الصيغة.
#    ② **لا يُدَّعى عَلَميّةٌ ولا عُجمةٌ بالرسم**: المعجمُ الموروثُ في
#       `jar_gate.MAMNU3` **قائمةٌ منتهيةٌ مسمّاةٌ** تُقرأ من موضعها ولا تُنسَخ
#       ههنا ولا تُوسَّع بعد القياس — ومخالفُها يُسمّى ولا يُطمَس.
#    ③ **والمقصورُ محجورٌ بالقياس لا بالرأي**: الفتحةُ على آخره **تعذُّرٌ** لا
#       نيابة، والدليلُ مقيسٌ: شرطُ «أل» لا يفصله — بل نصيبُ الفتحةِ فيه مع
#       «أل» أعلى منه بلا «أل». فما لا يفصله شرطُ القاعدةِ لا يُحكَم له بها.
#    ④ **ولا يُمَسّ حكمُ `jar_gate`**: المأخوذُ منه المصنِّفُ ولاحقةُ الضميرِ
#       والمعجمُ المنتهي وحدَها — لا أبوابُه ولا تغطيتُه ولا اتفاقيةُ تضييقه.
#       وموضعُ الجرِّ ههنا **معلَنٌ بحدِّه**: ما سُبق بجارٍّ منفصلٍ مسمًّى أو
#       صُدِّر بجارٍّ ملتصقٍ مكسور — ولا يُستعار `is_majrur` لأنّه يشترط علامةَ
#       جرٍّ في البايتات، وهو عينُ ما نحن نقيسه فيكون دورًا.
