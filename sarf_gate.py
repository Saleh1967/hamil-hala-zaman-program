def collide(measured):
    bad = [(k, SEALED_SARF[k], measured[k]) for k in SEALED_SARF
           if k not in measured or measured[k] != SEALED_SARF[k]]
    extra = [k for k in measured if k not in SEALED_SARF]
    if extra:
        raise SarfError(E_SEAL, "قيمٌ مقيسةٌ بلا ختم: " + " · ".join(extra))
    if bad:
        raise SarfError(E_SEAL, "أختامٌ خالفت: " + " · ".join(
            f"{k}: وديعة {a} ⟷ مقيس {b}" for k, a, b in bad))
    return len(SEALED_SARF)


