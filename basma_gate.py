# ═══ ② القراءةُ: بايتةٌ مصادَمةٌ أوّلًا، ولا محرفَ يُقرأ قبل ذلك ════════════════
SKEL = re.compile("[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")
NOT_ARABIC = re.compile("[^\u0621-\u064A]+")
TOKEN_MIN_LEN = 2


def tokens(text):
    """الصورُ بقاعدةٍ واحدةٍ معلنة: تُسقَط العلاماتُ والتطويل، ويُقطَع على غير
    الحرف العربيِّ، وما دون محرفين لا يُعَدُّ صورة. قاعدةٌ واحدةٌ لكلِّ الحاويات
    — فلا تُقشَّر حاويةٌ بمسطرةٍ وتُقشَّر أختُها بأخرى."""
    return [w for w in NOT_ARABIC.split(SKEL.sub("", text)) if len(w) >= TOKEN_MIN_LEN]


def home_text():
    """حاويةُ الاستخراج: ختمُها **يُقرَأ من كود مستخرِجها** لا يُنسَخ ههنا."""
    path = os.path.join(ROOT, shakhsiyya_extract.MATN)
    if not os.path.exists(path):
        raise BasmaError(E_MISSING,
                         f"متنُ حاوية الاستخراج غائبٌ ({path}) — "
                         f"يُستخرَج بـ«python shakhsiyya_extract.py --emit»")
    raw = open(path, "rb").read()
    if len(raw) != shakhsiyya_extract.MATN_BYTES:
        raise BasmaError(E_SEAL,
                         f"متنُ الاستخراج: الطولُ {len(raw)} بإزاء "
                         f"{shakhsiyya_extract.MATN_BYTES} — ختمٌ مخالف")
    got = hashlib.sha256(raw).hexdigest()
    if got != shakhsiyya_extract.MATN_SHA256:
        raise BasmaError(E_SEAL, f"متنُ الاستخراج: البصمةُ {got} خالفت الختمَ")
    return raw.decode("utf-8"), got


def witness_text(source_id, rows):
    """شاهدُ اختبارٍ مصادَمٌ بالبيان، ثمّ متنُه بعد الترويسة — والتقشيرُ بطبقته."""
    try:
        path, digest = sources_census.sealed_bytes(source_id, rows)
    except sources_census.CensusError as exc:
        raise BasmaError(exc.code, exc.message) from exc
    text = normalize.read_text(path)
    _, body = normalize.split_header(text, path)
    return body, digest


# ═══ ③ الاستخراجُ الآليّ — لا لفظَ منه مكتوبٌ بيدنا ═══════════════════════════
def extract_candidates(counts):
    """المرشَّحون بقاعدة `PREREG['قاعدةُ_الاستخراج']` — مرتَّبون لا عشوائيّون."""
    return sorted(w for w, c in counts.items()
                  if c >= CAND_MIN_COUNT and len(w) >= CAND_MIN_LEN)


def rival_pool(counts, cands):
    """ميدانُ الأمثال: صورُ حاوية الاستخراج دون المرشَّحين — لا من حاويات الاختبار،
    فلا تُسحَب الأمثالُ من الميدان الذي يُقاس عليه."""
    taken = set(cands)
    return sorted(w for w, c in counts.items()
                  if c >= POOL_MIN_COUNT and w not in taken)


def draw_rival(cands, pool, counts, seed):
    """طائفةٌ عشوائيّةٌ بعدد المرشَّحين، كلُّ عضوٍ منها في نطاق تواتر مقابله.

    وفارقُ التواتر **يُقاس ويُودَع**: تمامُ المطابقة دعوى، والفارقُ رقم.
    """
    rng = random.Random(seed)
    used, out, gap = set(), [], []
    for w in cands:
        c = counts[w]
        band = [x for x in pool
                if x not in used and c * BAND_LO <= counts[x] <= c * BAND_HI]
        if not band:                       # النطاقُ خلا — أقربُ عشرين تواترًا
            band = sorted((x for x in pool if x not in used),
                          key=lambda x: (abs(counts[x] - c), x))[:20]
        if not band:
            raise BasmaError(E_PREREG,
                             "ميدانُ الأمثال نفد — طائفةٌ لا تُسحَب بعددِ المرشَّحين")
        pick = rng.choice(band)
        used.add(pick)
        out.append(pick)
        gap.append(abs(counts[pick] - c) / c)
    return out, statistics.mean(gap)


# ═══ ④ القياس: نصيبٌ لكلِّ حاويةٍ بمقامها، ولا مقامَ يُجمَع بمقام ═══════════════
def share(words, vocab):
    """نصيبُ طائفةٍ في حاويةٍ — على عدد الطائفة لا على مقام الحاوية، فالمقامان
    يُعرَضان ولا يُخلَطان."""
    return sum(1 for w in words if w in vocab) / len(words)


def hard_residue(words, vocabs):
    """البقايا الصلبة: ما غابَ عن شهود المؤلّفين الآخرين **كلِّهم** — مسمّاةً."""
    return [w for w in words if not any(w in v for v in vocabs)]


def verdict_h1(real, rivals):
    """حدُّ H₁ المُعلَن قبل القياس — ثلاثُ مفرداتٍ لا رابعَ لها."""
    if real > max(rivals):
        return "ثبتت"
    if real <= min(rivals):
        return "سقطت"
    return "معلَّقة"


def verdict_h2(won, total):
    """حدُّ H₂ المُعلَن قبل القياس."""
    if won == total:
        return "ثبتت"
    if won * 2 <= total:
        return "سقطت"
    return "معلَّقة"


def measure():
    """الجولةُ كلُّها مرّةً واحدة — ومخرَجُها بنيةٌ تُقرأ ولا تُعاد حسابًا."""
    rows = sources_census.manifest_rows()
    home_raw, home_digest = home_text()
    home_tokens = tokens(home_raw)
    counts = collections.Counter(home_tokens)

    cands = extract_candidates(counts)
    pool = rival_pool(counts, cands)
    if not cands:
        raise BasmaError(E_PREREG, "قاعدةُ الاستخراج لم تُعطِ مرشَّحًا — لا قياسَ على خواء")

    vocabs, stands = {}, []
    for sid, author, title, died in WITNESSES:
        body, digest = witness_text(sid, rows)
        toks = tokens(body)
        vocabs[sid] = set(toks)
        stands.append({"شاهد": sid, "مؤلّف": author, "كتاب": title, "وفاة": died,
                       "بصمة": digest, "مقامُ_الكلمات": len(toks),
                       "مقامُ_الصور": len(vocabs[sid])})

    rivals = [draw_rival(cands, pool, counts, SEED0 + i) for i in range(RIVALS)]
    rival_sets = [r for r, _ in rivals]
    gap = statistics.mean(g for _, g in rivals)

    order = [sid for sid, *_ in WITNESSES]
    vlist = [vocabs[sid] for sid in order]

    # ــ H₂: نصيبُ الطائفة في كلِّ حاويةٍ بإزاء أدنى أمثالها ــــــــــــــــــــــ
    grounds, won = [], 0
    for row in stands:
        v = vocabs[row["شاهد"]]
        real = share(cands, v)
        rs = [share(r, v) for r in rival_sets]
        beat = real > min(rs)
        won += beat
        grounds.append({**row,
                        "نصيبُ_الطائفة": round(real, 4),
                        "أدنى_المثل": round(min(rs), 4),
                        "أعلى_المثل": round(max(rs), 4),
                        "غلبَ_أدنى_المثل": beat,
                        "مرشَّحون_حاضرون": sum(1 for w in cands if w in v)})

    # ــ H₁: البقايا الصلبةُ بإزاء بقايا الأمثال ـــــــــــــــــــــــــــــــــ
    residue = hard_residue(cands, vlist)
    rival_res = [len(hard_residue(r, vlist)) for r in rival_sets]

    h1 = verdict_h1(len(residue), rival_res)
    h2 = verdict_h2(won, len(stands))

    return {
        "التسجيلُ_المسبق": {**PREREG, "بصمة": prereg_seal()},
        "حاويةُ_الاستخراج": {
            "ملفّ": shakhsiyya_extract.MATN, "بصمة": home_digest,
            "مقامُ_الكلمات": len(home_tokens), "مقامُ_الصور": len(counts)},
        "المرشَّحون": cands,
        "الميدان": {"شهود": stands},
        "ضابطُ_المثل": {
            "طوائف": RIVALS,
            "تمايزُ_الطوائف": len({tuple(r) for r in rival_sets}),
            "فارقُ_التواتر_النسبيّ": round(gap, 4),
            "ميدانُ_السحب": len(pool),
            "بقايا_الأمثال": sorted(rival_res)},
        "H₁": {"دعوى": PREREG["H₁"], "حدّ": PREREG["حدُّ_H₁"], "حكم": h1,
               "البقايا_الصلبة": residue,
               "أدنى_بقايا_المثل": min(rival_res),
               "أعلى_بقايا_المثل": max(rival_res)},
        "H₂": {"دعوى": PREREG["H₂"], "حدّ": PREREG["حدُّ_H₂"], "حكم": h2,
               "حاوياتٌ_غلبَ_فيها": won, "حاويات": len(stands),
               "أرض": grounds},
        "الديون": list(DEBTS),
    }


# ═══ ⑤ محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ، ونجاحُ واحدةٍ يُسقِط البابَ ═════════
def falsify(M):
    """اثنتا عشرةَ محاولةً تُعرَض على المكيال نفسِه. و«نجحت» تعني أنّ البابَ سمح
    بما أعلن أنّه يمنعه — فيسقط."""
    T = []
    counts = collections.Counter(tokens(home_text()[0]))
    cands = M["المرشَّحون"]
    rows = sources_census.manifest_rows()
    vlist = [set(tokens(witness_text(sid, rows)[0])) for sid, *_ in WITNESSES]

    # ① طائفةٌ مختلقةٌ تنال حكمًا موجبًا في H₂ — لا يجوز: لا تقع في حاويةٍ البتّة.
    T.append(("طائفةٌ مختلقةٌ غلبت أمثالَها",
              any(share(FABRICATED, v) > 0 for v in vlist)))

    # ② الاستخراجُ يعتمد العشوائيّة: بذرةٌ أخرى تُبدِّل المرشَّحين.
    random.seed(1234)
    T.append(("المرشَّحون تبدّلوا ببذرةٍ أخرى",
              extract_candidates(counts) != cands))

    # ③ مرشَّحٌ ليس في حاوية الاستخراج — قائمةٌ مزروعةٌ تسلّلت.
    T.append(("مرشَّحٌ خارجَ حاوية الاستخراج",
              any(counts[w] < CAND_MIN_COUNT or len(w) < CAND_MIN_LEN for w in cands)))

    # ④ البقايا الصلبةُ ليست من المرشَّحين — بقيّةٌ لُفِّقت.
    T.append(("بقيّةٌ صلبةٌ خارجَ المرشَّحين",
              not set(M["H₁"]["البقايا_الصلبة"]) <= set(cands)))

    # ⑤ البقيّةُ الصلبةُ وقعت في شاهدٍ — فليست صلبة.
    T.append(("بقيّةٌ صلبةٌ وقعت في شاهد",
              any(any(w in v for v in vlist) for w in M["H₁"]["البقايا_الصلبة"])))

    # ⑥ حاويةُ الاستخراج دسّت في الميدان — تسرُّبٌ يجعل النصيبَ واحدًا بالبناء.
    T.append(("حاويةُ الاستخراج في الميدان",
              any(r["شاهد"].startswith("shakhsiyya") for r in M["الميدان"]["شهود"])))

    # ⑦ المقاماتُ جُمِعت: نصيبٌ محسوبٌ على مجموع الحاويات لا على كلِّ واحدةٍ وحدَها.
    T.append(("نسبةٌ خارجَ حدِّها",
              any(not 0.0 <= r["نصيبُ_الطائفة"] <= 1.0 for r in M["H₂"]["أرض"])))

    # ⑧ المقامُ صفرٌ أو غائب: قياسٌ على حاويةٍ لم تُقرَأ.
    T.append(("مقامٌ صفرٌ في الميدان",
              any(r["مقامُ_الكلمات"] < 1 or r["مقامُ_الصور"] < 1
                  for r in M["الميدان"]["شهود"])))

    # ⑨ الأمثالُ طائفةٌ واحدةٌ مكرّرة — ضابطٌ لا يضبط.
    T.append(("الأمثالُ غيرُ متمايزة",
              M["ضابطُ_المثل"]["تمايزُ_الطوائف"] < RIVALS))

    # ⑩ مثلٌ سُحِب من المرشَّحين أنفسِهم — ضابطٌ يقيس نفسَه.
    T.append(("ميدانُ السحب يلامس المرشَّحين",
              bool(set(rival_pool(counts, cands)) & set(cands))))

    # ⑪ حكمٌ خارجَ المفردات الثلاث المُعلَنة.
    T.append(("حكمٌ خارجَ المفردات",
              M["H₁"]["حكم"] not in PREREG["مفرداتُ_الحكم"]
              or M["H₂"]["حكم"] not in PREREG["مفرداتُ_الحكم"]))

    # ⑫ دَينٌ حمل رقمًا — وما لم يُقَس لا يُسعَّر.
    T.append(("دَينٌ حمل رقمًا",
              any(isinstance(v, (int, float)) and not isinstance(v, bool)
                  for d in M["الديون"] for v in d.values())))

    return [{"محاولة": k, "نجحت": bool(v)} for k, v in T]


