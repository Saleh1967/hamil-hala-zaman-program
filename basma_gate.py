# basma_gate.py — بابُ البصمة · الجولةُ الخامسة (R5): «هل تخصُّ البصمةُ مؤلِّفَها؟»
#
# العلّةُ التي يقتلها هذا الملفّ: جولةٌ سابقةٌ (R4) سجّلت مانعًا مكتوبًا نصُّه أنّ
# السؤالَ — «هل البصمةُ تخصُّ النبهانيَّ أم تعمُّ الكتبَ العربية؟» — يحتاج **مادّةً
# مرخّصةً من مؤلِّفٍ آخر، وهي غيرُ موجودة**. والمانعُ ساقطٌ ههنا: في هذه الشجرة
# تسعةُ شهودٍ من تسعةِ مؤلّفين آخرين، كلُّهم مختومون في `sources_manifest.tsv`
# بالطول وsha256، ويُجلَبون بـ`fetch_source.sh`. فموضعُ المانع الصحيحُ «غيرُ
# مجلوبة» لا «غيرُ موجودة» — والفرقُ حاكم: الأوّلُ عملٌ يُنجَز، والثاني يُغلق البابَ.
#
# فهذا البابُ يرفع المانعَ بالقياس لا بالدعوى.
#
# — وستّةُ قيودٍ لا يُطوى واحدٌ منها في الصمت —
#
#   ① **التسجيلُ المسبقُ قبل القياس**: الفرضيّتان وحدُّ الحكم ومفرداتُ الحكم
#      وبذورُ ضابط المثل — كلُّها مكتوبةٌ في `PREREG` أدناه **قبل** أيِّ دالّةٍ
#      تقيس، ويُختَم نصُّها بـsha256 فيُودَع. فتبديلُ حدٍّ بعد رؤية الرقم يُبدِّل
#      الختمَ، ولا يمرُّ صامتًا.
#
#   ② **لا قائمةَ مزروعة**: المرشَّحون يُستخرَجون آليًّا من حاوية الاستخراج
#      وحدَها بقاعدةٍ معلنةٍ (`CAND_MIN_COUNT` · `CAND_MIN_LEN`). لم نكتب لفظًا
#      واحدًا منهم بيدنا. والمزروعُ هو المسطرةُ لا القاعدة.
#
#   ③ **لا قياسَ على بايتةٍ غيرِ مصادَمة**: كلُّ حاويةٍ يُصادَم طولُها وبصمتُها
#      قبل أن يُقرأ منها محرف — الشهودُ بـ`sources_census.sealed_bytes`،
#      وحاويةُ الاستخراج ببصمةِ `shakhsiyya_extract` **تُقرَأ من كوده** لا
#      تُنسَخ ههنا، فلا تتخلّف نسخةٌ ثانيةٌ صامتة.
#
#   ④ **ضابطُ المثل شرطُ صدقِ الجولة**: كلُّ رقمٍ يُقابَل بإحدى عشرةَ طائفةً
#      عشوائيّةً من حاوية الاستخراج نفسِها، مطابقةً في العدد ومقيَّدةً بنطاقٍ
#      تكراريٍّ معلَن. والرقمُ الذي لا يغلب أمثالَه **يُعلَن خاويًا** — كما سقط
#      الحكمُ المفردُ في `madlul_gate` حين نالته فرقةٌ عشوائيّة. وتمامُ المطابقة
#      لا يُدَّعى: فارقُها النسبيُّ مقيسٌ ومُودَعٌ في الوديعة.
#
#   ⑤ **المقاماتُ تُعرَض ولا تُجمَع**: لكلِّ حاويةٍ مقامُها (كلماتُها وصورُها)،
#      ونسبتُها محسوبةٌ على مقامها وحدَه. ولا يُجمَع مقامُ البخاريِّ بمقام
#      الألفيّة — والألفيّةُ بتسعة آلاف كلمةٍ تُعرَض بمقامها ولا تُطرَح.
#
#   ⑥ **والحكمُ ثلاثٌ لا اثنتان**: «ثبتت · سقطت · معلَّقة». والثالثةُ ليست
#      مهربًا: حدُّها مكتوبٌ في `PREREG` قبل القياس — ما غلبَ أدنى المثل ولم
#      يغلب أعلاه **معلَّقٌ**، لا مقبولٌ ولا مردود.
#
# ومفرداتُ الدَّين على عادة هذه الشجرة: الدَّينُ يُسمّى ولا يُسعَّر. وأثقلُ ديون
# هذه الجولةِ أنّها **لا تفصل المؤلِّفَ عن العصر**: شهودُها كلُّهم من القرن
# الثاني إلى الخامس، والمستخرَجُ منه من القرن العشرين. فسقوطُ فرضيّةٍ ههنا
# سقوطٌ مشتركٌ بين العاملين، ولا يُنسَب إلى أحدهما.
#
# المخارج: 0 نجاح · 2 خطأُ استعمال · 3 بايتاتُ حاويةٍ غائبة
#          · 4 ختمٌ خالف · 5 تسجيلٌ مسبقٌ خُولِف.
#
# التشغيل:
#   python basma_gate.py                      تقريرٌ معدودٌ على stdout
#   python basma_gate.py --json <ملفّ>        الوديعةُ إلى ملفّ (مولِّدُ الأختام)
