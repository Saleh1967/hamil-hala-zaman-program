def main(argv=None):
    ap = argparse.ArgumentParser(description="بابُ البصمة — R5")
    ap.add_argument("--json", metavar="ملفّ", help="وديعةُ الباب إلى ملفّ")
    ap.add_argument("--doc", nargs="?", const=DOC, metavar="ملفّ",
                    help="الوثيقةُ المولَّدة (BASMA.md ما لم يُسمَّ غيرُها)")
    a = ap.parse_args(argv)
    try:
        R = run()
        if a.json:
            with open(a.json, "w", encoding="utf-8") as fh:
                json.dump(R, fh, ensure_ascii=False, indent=2, sort_keys=True)
            print(f"JSON ⟵ {a.json}")
        if a.doc:
            write_doc(R, a.doc)
            print(f"الوثيقة ⟵ {a.doc}")
        show(R)
    except BasmaError as exc:
        print(f"صريخ: {exc.message}", file=sys.stderr)
        return exc.code
    return 0


if __name__ == "__main__":
    sys.exit(main())
