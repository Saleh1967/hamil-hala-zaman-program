    trial("⑬ محطّةُ النسبة تَرمي صادقَ النسبة بالخطأ", true_attribution_passes)

    # ⑭ أضدادُ المثل تُلتقَط كلُّها **والضابطُ السليمُ ينجو**.
    trial("⑭ ملفَّقٌ مرَّ أو ضابطٌ سليمٌ سقط",
          lambda: rivals_station(random.Random(7))["المقياسُ_يُفرِّق"])

    # ⑮ المقابلةُ لا تَدمِج: مجموعُ ما نملك لا يَرِث المُدَّعى.
    trial("⑮ المقابلةُ دمجت المُدَّعى بما نملك",
          lambda: ours_station(CLAIMED_TABLE, ours())["دُمِج"] is False)

    # ⑯ كلُّ عددٍ يخرج من الباب معلَّقٌ — ولا واحدَ منها مُرخَّص.
    def nothing_licensed():
        f = measure_under_the_protocol("عيّنة", lambda: 1, SUSPENDED_HALVES)
        return f.standing == CONDITIONAL and not f.is_licensed
    trial("⑯ رقمٌ أعجميٌّ يخرج مُرخَّصًا", nothing_licensed)

    # ⑰ الديونُ تُسمّى بلا رقم: لا عددَ عشريًّا في نصِّ دَين.
    #    والمقصودُ أرقامُ العدّ (لاتينيّةً أو هنديّةً)، لا إشاراتُ الفصول
    #    كـ«§②» — فالإحالةُ ليست مقدارًا يُدَّعى.
    DIGITS = set("0123456789٠١٢٣٤٥٦٧٨٩")
    trial("⑰ دَينٌ حمل عددًا",
          lambda: not any(set(d) & DIGITS for d in DEBTS))

    passed = [t["محاولة"] for t in trials if not t["رُدَّت"]]
    return dict(عدد=len(trials), رُدَّت=len(trials) - len(passed),
                نجحت=len(passed), أسماءُ_ما_نجح=passed, محاولات=trials)


