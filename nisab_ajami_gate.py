# ── محاولاتُ التكذيب — تُشغَّل ولا تُقرَأ ──────────────────────────────────────
def falsify():
    """محاولاتٌ تُجرَّب على البابِ نفسِه — ونجاحُ واحدةٍ يُسقِطه.

    و`fn` تُعيد **True متى رُدَّت المحاولة** (أي: دافعَ البابُ عن نفسه).
    """
    trials, rng = [], random.Random(20261001)

    def trial(name, fn):
        try:
            ok = bool(fn())
        except Exception:                                  # noqa: BLE001
            ok = False
        trials.append(dict(محاولة=name, رُدَّت=ok))

    # ① البروتوكول: رقمٌ مُسلَّمٌ مكان الدالّة — الأسبقيّةُ تسقط فيُرَدّ.
    def raw_number_refused():
        try:
            measure_under_the_protocol("رقمٌ مُسلَّم", 426)
        except ProtocolError as e:
            return e.code == E_USAGE
        return False
    trial("① رقمٌ مُسلَّمٌ مكان الدالّة يُقبَل", raw_number_refused)

    # ② ولا يُقبَل نصٌّ ولا قائمةٌ ولا سواهما من المحسوب سلفًا.
    def precomputed_refused():
        for bad in ("426", [426], {"ع": 426}, 4.26, True):
            try:
                measure_under_the_protocol("محسوبٌ سلفًا", bad)
                return False
            except ProtocolError:
                continue
        return True
    trial("② صنفٌ محسوبٌ سلفًا يُقبَل عادًّا", precomputed_refused)

    # ③ منعُ الترقية: «مرخَّصٌ» ونصفٌ موقوفٌ قائم.
    def no_promotion():
        try:
            DeclaredFigure(1, P.LICENSED, ("نصفٌ موقوف",))
        except ProtocolError:
            return True
        return False
    trial("③ عددٌ يُكتَب مرخَّصًا ونصفُه موقوف", no_promotion)

    # ④ والتعليقُ بلا اسمٍ كتمانٌ — فيُرَدّ.
    def no_silent_conditional():
        try:
            DeclaredFigure(1, CONDITIONAL, ())
        except ProtocolError:
            return True
        return False
    trial("④ تعليقٌ بلا نصفٍ مسمًّى يُقبَل", no_silent_conditional)

    # ⑤ حالٌ غيرُ معلنٍ يُرَدّ — فلا رابعَ للثلاثة.
