# ═══ ⑤ حارسُ المقام — عمودٌ بمقامين يَسقُط حتى يُعلَن المطويّ ═════════════════
def denominator_guard(table, claimed_total):
    """المجموعُ المُعلَن يُصادَم بجمعِ الصفوف، والمطويُّ يُسمّى بعدده.

    وهذا حارسٌ موروثٌ في هذا المِعمل: `dictionary_engine` يَحرُس مقامَه
    بـ`letter_blocks == Nw`، و`jumla_links` يُفرِد مقامَيه ولا يجمعهما.
    """
    by_den = {}
    for row in table:
        by_den.setdefault(row["مقام"], []).append(row)
    full = sum(r["قيمة"] for r in table)
    # أيُّ مقامٍ وحدَه يُعطي المجموعَ المُعلَن؟ ذاك هو المجموعُ الصادقُ ضمنًا.
    matching = [d for d, rs in by_den.items()
                if sum(r["قيمة"] for r in rs) == claimed_total]
    folded = [r for r in table if r["مقام"] not in matching]
    return dict(
        مقاماتٌ_في_العمود=len(by_den), أسماءُ_المقامات=sorted(by_den),
        جمعُ_الصفوفِ_كما_كُتبت=full, المجموعُ_المُعلَن=claimed_total,
        المقامُ_المجموعُ_ضمنًا=matching,
        المطويُّ_عددًا=full - claimed_total,
        أسماءُ_المطويّ=[r["اسم"] for r in folded],
        عمودٌ_بمقامين=len(by_den) > 1,
        الجدولُ_قائم=(len(by_den) == 1 and full == claimed_total),
        حدّ=(f"عمودٌ فيه {len(by_den)} مقاماتٍ، والمجموعُ المُعلَن يَجمع "
             f"«{'·'.join(matching)}» وحدَه، فالمطويُّ "
             f"{full - claimed_total:,} في {[r['اسم'] for r in folded]}"
             if len(by_den) > 1 else "مقامٌ واحدٌ والمجموعُ مصادَم"))


