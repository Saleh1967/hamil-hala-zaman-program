RIVALS = 11


def forged_tables(rng):
    """جداولُ ملفَّقة — أرقامٌ ومعرِّفاتٌ مصنوعة، تُعرَض كما يُعرَض المُدَّعى.

    ولا يكفي أن تُرَدَّ **كلُّها**: بابٌ يَرُدُّ كلَّ شيءٍ لا يُفرِّق. فيُعرَض
    معها في `rivals_station` صفٌّ **سليمٌ بالبناء** يجب أن يَنجوَ، وإلّا سقط
    الباب بالحارس نفسِه.
    """
    out = []
    for i in range(RIVALS):
        a = rng.randrange(50, 900)
        b = rng.randrange(1000, 9000)
        out.append(("ملفَّقٌ #%d" % (i + 1), (
            dict(اسم="نواةٌ ملفَّقة", قيمة=a, منسوبٌ_إلى="arXiv:%04d.%05d"
                 % (rng.randrange(1, 2400), rng.randrange(1, 99999)), مقام="أنماط"),
            dict(اسم="جذورٌ ملفَّقة", قيمة=b,
                 منسوبٌ_إلى="Anonymous (%d)" % rng.randrange(1990, 2024), مقام="جذور"),
            dict(اسم="جذوعٌ ملفَّقة", قيمة=a * b, منسوبٌ_إلى="مجهول", مقام="جذوع"),
        )))
    return out


def rivals_station(rng):
    """الملفَّقُ يُعرَض على المحطّتين اللتين لا تحتاجان نصًّا خارجيًّا.

    ومعه **ضابطٌ سليمٌ بالبناء**: جدولٌ مقامُه واحدٌ ومجموعُه مصادَمٌ ولا صفَّ
    فيه مشتقٌّ من غيره. فإن سقط الضابطُ كما يسقط الملفَّقُ فالمقياسُ يضرب
    بسيفٍ واحدٍ ولا يُفرِّق — **والبابُ يَسقُط حينئذٍ**.
    """
    caught, rows = 0, []
    for name, tbl in forged_tables(rng):
        ind = independence_station(tbl, {})
        den = denominator_guard(tbl, sum(r["قيمة"] for r in tbl))
        bad = ind["مصدرٌ_واحدٌ_عُدَّ_مرارًا"]
        hit = bool(bad) or den["عمودٌ_بمقامين"]
        caught += hit
        rows.append(dict(ضدّ=name, التُقِط=hit,
                         مشتقٌّ=bool(bad), عمودٌ_بمقامين=den["عمودٌ_بمقامين"]))

    control = (
        dict(اسم="ضابطٌ أ", قيمة=7, منسوبٌ_إلى="—", مقام="أنماط"),
        dict(اسم="ضابطٌ ب", قيمة=11, منسوبٌ_إلى="—", مقام="أنماط"),
        dict(اسم="ضابطٌ ج", قيمة=13, منسوبٌ_إلى="—", مقام="أنماط"),
    )
    c_ind = independence_station(control, {})
    c_den = denominator_guard(control, sum(r["قيمة"] for r in control))
    control_survives = (not c_ind["مصدرٌ_واحدٌ_عُدَّ_مرارًا"]
                        and not c_den["عمودٌ_بمقامين"]
                        and c_den["الجدولُ_قائم"])
    return dict(
        أضدادٌ_عُرضت=RIVALS, أضدادٌ_التُقِطت=caught, صفوف=rows,
        الضابطُ_نجا=control_survives,
        المقياسُ_يُفرِّق=(caught == RIVALS and control_survives),
        حدّ=(f"التُقِط {caught}/{RIVALS} ملفَّقًا، **ونجا الضابطُ السليم** — "
             "فالمقياسُ يُفرِّق ولا يضرب بسيفٍ واحد" if control_survives else
             "الضابطُ السليمُ سقط كما سقط الملفَّق — المقياسُ لا يُفرِّق"))


