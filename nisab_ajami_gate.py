def main(argv=None):
    ap = argparse.ArgumentParser(description="بابُ النصاب الأعجميّ")
    ap.add_argument("--json", metavar="مسار", help="إيداعُ القياس")
    ap.add_argument("--doc", metavar="مسار", nargs="?", const="NISAB-AJAMI.md",
                    help="الوثيقةُ المولَّدة")
    a = ap.parse_args(argv)
    try:
        R = run()
        if a.json:
            with open(a.json, "w", encoding="utf-8") as fh:
                json.dump(R, fh, ensure_ascii=False, indent=2, sort_keys=True)
            print(f"JSON ⟵ {a.json}")
        if a.doc:
            write_doc(R, a.doc)
            print(f"الوثيقة ⟵ {a.doc}")
        show(R)
        if R["النصاب_الأعجميّ_v0"]["سقوط"]:
            return E_FELL
    except ProtocolError as exc:
        print(f"صريخ: {exc.message}", file=sys.stderr)
        return exc.code
    return 0


if __name__ == "__main__":
    sys.exit(main())
