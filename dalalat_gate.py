# ثلاثةَ افتراضاتٍ كانت في خطّته الأولى — فتُكتَب ههنا لا في تقريرٍ يُنسى:
#   ① **الدعاوى السبعُ لا تنطبق على سبعةِ صفوف**: النصُّ يقسم اللفظَ باعتبار الدالِّ
#      ثلاثًا (مطابقة · تضمّن · التزام)، ثمّ يفرّع الالتزامَ أربعًا (اقتضاء · تنبيهٌ
#      وإيماء · إشارة · مفهوم)، ثمّ يحصر المفهومَ في موافقةٍ ومخالفة، والمخالفةَ في
#      أربعةٍ «ليس غير». فالدعاوى سبعٌ والصفوفُ **أحدَ عشرَ**، وعدُّهما معلنٌ أدناه
#      في `CLAIMS` و`ROWS` لا مضمرٌ في الذهن.
#   ② **وأكثرُ التعريفات بلا مُطلِقٍ لفظيّ**: خمسةٌ من أحدَ عشرَ صفًّا يسمّي تعريفُها
#      لفظًا يُطلِقها («إن» · «حتى» و«إلى» · لفظُ العدد · «لن» · الفاء)، والستّةُ
#      الباقيةُ تُعرَّف بمعنًى لا صورةَ له. فمقامُها **لا يُنتزَع**، ولا يُصنَع لها
#      مُطلِقٌ من خارج تعريفها: ذاك اختلاقُ وسمٍ لم يكتبْه المؤلِّف.
#   ③ **وشواهدُه ليست كلُّها في حدِّنا**: تسعةَ عشرَ شاهدًا مقيسةً من بايتات المتن،
#      ستّةٌ منها حديثٌ لا يقع في المجمَّد. فهي **عيّنةٌ افتتاحيةٌ لا برهان**: تُعَدُّ
#      وتُعلَن، ولا يدخل منها شيءٌ حكمًا — وهذا صنفُ «حدُّنا لا حدُّهم» بعينه.
#
# ــ ١) العلّةُ التي يفتحها هذا الباب ـــــــــــــــــــــــــــــــــــــــــــــــــــ
# الدعاوى السبعُ تُنقَل في كتب الأصول ويُبنى عليها الاستنباطُ بلا سؤالٍ واحد: **بأيِّ
# مقامٍ تُكذَّب؟** وبابٌ يقبلها كلَّها يظلم النصَّ لأنّه صدّق ما لا يُقاس، وبابٌ يردُّها
# كلَّها يظلمه لأنّه ردَّ ما لم يعرضْه أصلًا. فالمقصودُ ههنا ليس الحكمَ على الأصول، بل
# **ثلاثةُ أرقام**: كم دعوى انتُزع مقامُها من تعريفها · توزيعُ الأصناف الأربعة ·
# ونصيبُ شواهده الواقعةِ في حدِّنا معدودًا لا مُهمَلًا.
#
# ــ ٢) الشرطُ القاطع: الإيماءُ لا يدخل خانةَ حكمٍ البتّة ـــــــــــــــــــــــــــــــ
# دلالةُ التنبيه والإيماء أوسعُ الدعاوى مقامًا (آلافُ مواضعِ الفاء)، وأشدُّها إغراءً
# بالقبول. وتعريفُها نفسُه يشترط أن يكون الوصفُ **مناسبًا**، والنصُّ يصرّح: «أو كان
