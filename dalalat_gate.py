# ═══ التطبيعُ — واحدٌ يُطبَّق على الطرفين معًا ════════════════════════════════════════
# المتنُ فيه تطويلٌ مدسوسٌ داخلَ الكلمة (اثـْنَيْنِ · ثـُمَّ · الغايـة)، والمجمَّدُ مشكول.
# فلا يُقارَن مطبَّعٌ بغير مطبَّع: هذا الطيُّ يُجرَّد به الطرفان قبل أيِّ مصادمةِ شاهد.
_STRIP = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")
_FOLD = {"\u0671": "ا", "\u0622": "ا", "\u0623": "ا", "\u0625": "ا",
         "\u0649": "ي", "\u0629": "ه", "\u0624": "و", "\u0626": "ي"}
_NONAR = re.compile(r"[^\u0621-\u064A\s]")


def fold(text):
    text = _STRIP.sub("", text)
    for a, b in _FOLD.items():
        text = text.replace(a, b)
    return re.sub(r"\s+", " ", _NONAR.sub(" ", text)).strip()


def surface(word):
    """صورةُ الكلمة بعد الطيّ — الحروفُ وحدَها بلا علامة."""
    return "".join(_FOLD.get(ch, ch) for ch, _, _ in word)


