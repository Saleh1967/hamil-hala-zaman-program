# ═══ ① بايتاتُ المتن مصادَمةً قبل أن تُقرَأ ═════════════════════════════════════════
def matn_bytes():
    """بايتاتُ المتن المقيس بختمه — والختمُ يُقرأ من `shakhsiyya_extract` لا من نسخة."""
    path = os.path.join(ROOT, SX.MATN)
    if not os.path.exists(path):
        raise DalalaError(E_MISSING, f"بايتاتُ المتن غائبة: {SX.MATN}")
    blob = open(path, "rb").read()
    got = hashlib.sha256(blob).hexdigest()
    if got != SX.MATN_SHA256 or len(blob) != SX.MATN_BYTES:
        raise DalalaError(E_SEAL, f"متنُ الشخصية ج٣ خالف ختمَه ({got}، {len(blob)} بايتًا)")
    return blob, got


def anchor(name, blob):
    """المرساةُ مصادَمةً: المقتطَعُ عند الإزاحة المجمَّدة، وفرادتُه في المتن.

    ولا يُبحَث عن النصِّ ليُصحَّح موضعُه: لو بحثنا عنه لصار الاسمُ هو السندَ من جديد.
    """
    a = ANCHORS[name]
    if a["نوع"] not in ANCHOR_KINDS:
        raise DalalaError(E_SEAL, f"مرساةُ «{name}»: نوعٌ خارج المفردات المُعلَنة")
    off, ln = a["إزاحة"], a["طول"]
    if off < 0 or off + ln > len(blob):
        raise DalalaError(E_SEAL, f"مرساةُ «{name}»: إزاحةٌ خارج المتن ({off}+{ln})")
    cut = blob[off:off + ln]
    try:
        text = cut.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise DalalaError(E_SEAL, f"مرساةُ «{name}»: إزاحةٌ تقطع محرفًا") from exc
    if blob.count(cut) != 1:
        raise DalalaError(E_SEAL,
                          f"مرساةُ «{name}»: مقتطَعٌ متكرِّرٌ ({blob.count(cut)}) — إشارةٌ غامضة")
    return dict(نوع=a["نوع"], إزاحة=off, طول=ln, نص=text,
                بصمة=hashlib.sha256(cut).hexdigest())


# ═══ ② مقامُ كلِّ مُطلِقٍ في المجمَّد — بالصورة ثمّ بالعلامة ═══════════════════════
def fires(name, words):
    """مواضعُ إطلاقِ مُطلِقٍ في المجمَّد: بالصورة وحدَها، ثمّ بالصورة مع العلامة.

    والفرقُ بينهما هو **الذوبان**: ما تبتلعه الصورةُ وليس من باب التعريف. وحيث لا
    أثرَ للعلامة في البابِ يُكتَب ذلك صراحةً (`انضباط=None`) ويتساوى العددان —
    وهذا **صفرٌ بالمحور المعلن لا صفرٌ مطلق**، ودَينُه مكتوبٌ في `TRIGGERS`.
    """
    t = TRIGGERS[name]
    if t["صور"] is None:                          # مُطلِقُ الإيماء: صدرُ الكلمة
        naive = [i for i, w in enumerate(words) if w[0][0] == t["صدر"]]
    else:
        naive = [i for i, w in enumerate(words) if surface(w) in t["صور"]]
    if t["انضباط"] is None:
        precise = list(naive)
    elif t["انضباط"] == "غيرُ مشدَّدةٍ بكسر الهمزة":
        precise = [i for i in naive
                   if not words[i][1][2] and words[i][0][1] == "كسرة"]
    else:                                         # مفردةٌ خارج المُعلَن — صريخ لا صمت
        raise DalalaError(E_SEAL, f"انضباطٌ غيرُ مُعلَنٍ للمُطلِق «{name}»")
    dissolved = len(naive) - len(precise)
    ratio = round(dissolved / len(naive), 4) if naive else 0.0
    return dict(بالصورة=len(naive), بالعلامة=len(precise),
                ذائب=dissolved, نسبةُ_الذوبان=ratio, مواضع=precise)


def maqam_bill(positions, universe_size):
    """فاتورةُ المقام بالمكيال العامّ — **عرضٌ لا حكم**.

    تيّارٌ ثنائيٌّ على كلمات المجمَّد: أهذه من مقام الدلالة أم لا. ويُسعَّر برتبتين،
    فـΔ يقول هل لتوزُّع المقام بنيةٌ تُشترى ببتّات أم هو رشٌّ بلا بنية. ولا يدخل
    هذا الرقمُ الحكمَ: الخانةُ (أ) محجوزةٌ بمقام الحكم لا بالفاتورة.
    """
    hit = set(positions)
    stream = ["١" if i in hit else "٠" for i in range(universe_size)]
    p0, p1 = price(stream, 0)["كلفة"], price(stream, 1)["كلفة"]
    return {"رتبة_٠": round(p0, 2), "رتبة_١": round(p1, 2),
            "Δ": round(p1 - p0, 2), "حكمُ_الفاتورة": verdict(p1 - p0)}


# ═══ ③ الحكمُ بأصنافِه الأربعة — بالأولوية المعلنة ═══════════════════════════════════
def row_verdict(row, fire):
    """الحكمُ الواحد: القيدُ ثمّ المُطلِقُ ثمّ n₀ ثمّ الفاصل — ولا صمتَ بينها.

    والترتيبُ جزءٌ من الحكم: قيدٌ لا صورةَ له يُسقِط الدعوى إلى (ج) **قبل** أن يُنظَر
    في مقامها، لأنّ مقامًا كبيرًا تحت قيدٍ غيرِ منضبطٍ لا يشتري قابليةَ تكذيب.
    """
    if row["قيد"] is not None:
        return "ج", "قيدٌ لا صورةَ له في تعريفها"
    if row["مُطلِق"] is None:
        return "ج", "لا مُطلِقَ منصوصًا في تعريفها"
    tested, floor = n0_gate("n₀ مواضع", fire["بالعلامة"], THRESHOLDS)
    if not tested:
        return "ج", f"مواضعُ الإطلاق {fire['بالعلامة']} دون n₀ = {floor}"
    cap = THRESHOLDS["فاصلُ الذوبان"]["قيمة"]
    if fire["نسبةُ_الذوبان"] > cap:
        return "د", f"ذوبانُ الصورة {fire['نسبةُ_الذوبان']:.4f} فوق الفاصل {cap}"
    if not HUKM_MAQAM_SEALED:
        return "ب", "مقامُ الحكم الشرعيِّ غيرُ مودَعٍ بختمه — فلا تبلغ (أ)"
    return "أ", "استوفت الشروطَ الخمسة"


# ═══ ④ المنعُ القاطع: الإيماءُ لا يدخل خانةَ حكمٍ البتّة ═══════════════════════════
def ban_imaa_verdict(rows):
    """منعٌ **يُنفَّذ** لا يُقرَأ: صفُّ الإيماء لا يخرج من (ج) بحال.

    ويُحرَس بشقَّين لئلّا تكون الحراسةُ صادقةً خاوية:
    ① **المطابقة**: حكمُ الخطِّ المنفَّذ على الإيماء يجب أن يكون (ج) حرفًا بحرف.
    ② **ذو أثر**: يُعاد حسابُ حكمِه بعد **رفعِ قيده** — فإن جاء (ج) كذلك فالمنعُ
       يحرس الخواء ويسقط الباب؛ وإن خرج عن (ج) فالمنعُ يحرس شيئًا وقد نفَّذه.
    """
    row = next(r for r in rows if r["صفّ"] == "الإيماء")
    lifted = dict(row["صفّ_خام"])
    lifted["قيد"] = None
    without, _ = row_verdict(lifted, row["إطلاق"])
    return dict(الحكمُ_المنفَّذ=row["حكم"], بلا_قيدٍ=without,
                ذو_أثر=without != "ج", عطب=row["حكم"] != "ج")


# ═══ ⑤ شواهدُه: مقيسةٌ من بايتاته، ومعدودةٌ بحدِّنا ═════════════════════════════════
def shawahid_census(matn_folded, corpus_folded):
    """كلُّ شاهدٍ يُصادَم مرّتين: أذكره النبهانيُّ فعلًا؟ وأيقع في حدِّنا؟

    والأولى **شرطُ صدق**: شاهدٌ لا يقع في بايتات المتن دعوى منسوبةٌ إليه لم يقلْها،
    فيسقط البابُ بالمخرج 4. والثانيةُ **إعلانٌ لا حكم**: ما خرج عن المجمَّد يُعَدّ
    ويُعرَض، ولا يُخصَم به من دعوى ولا يُضاف إليها.
    """
    rows, missing = [], []
    for slot, sample in SHAWAHID.items():
        for text in sample:
            in_matn = matn_folded.count(text)
            if not in_matn:
                missing.append((slot, text))
            rows.append(dict(صفّ=slot, شاهد=text, في_المتن=in_matn,
                             في_حدِّنا=bool(corpus_folded.count(text))))
    if missing:
        head = " · ".join(f"{s}: «{t[:30]}…»" for s, t in missing[:3])
        raise DalalaError(E_SEAL, f"شاهدٌ منسوبٌ إلى النبهانيِّ لا يقع في بايتات متنه — {head}")
    inside = sum(1 for r in rows if r["في_حدِّنا"])
    return dict(مذكورة=len(rows), في_حدِّنا=inside, خارجَ_حدِّنا=len(rows) - inside,
                صفوف=rows)


