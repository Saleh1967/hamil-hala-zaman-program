def main(argv=None):
    ap = argparse.ArgumentParser(
        description="بابُ الوظائف السبع — ديوانُ المانع، بلا قياسٍ جديد")
    ap.add_argument("--json", metavar="ملفّ", help="وديعةُ الباب إلى ملفّ")
    ap.add_argument("--doc", nargs="?", const=DOC, metavar="ملفّ",
                    help="WAZA2IF.md مولَّدةً من الوديعة")
    ap.add_argument("--seal", action="store_true", help="إعادةُ كتابة SHA256SUMS.txt")
    ap.add_argument("--check", action="store_true", help="التحقُّقُ من ختم البيت")
    a = ap.parse_args(argv)
    try:
        if a.check:
            n = check_sums()
            print(f"ختمُ البيت: {n} ملفًّا مختومًا — كلُّها بفارق صفر ✓")
        R = run()
        show(R)
        if a.json:
            with open(a.json, "w", encoding="utf-8") as fh:
                json.dump(R, fh, ensure_ascii=False, indent=2, sort_keys=True)
                fh.write("\n")
            print(f"\nJSON ⟵ {a.json}")
        if a.doc:
            write_doc(R, a.doc)
            print(f"الوثيقة ⟵ {a.doc}")
        if a.seal:
            print(f"ختمُ البيت ⟵ {write_sums()} ملفًّا")
    except Waza2ifError as exc:
        print(f"صريخ: {exc.message}", file=sys.stderr)
        return exc.code
    return 0


if __name__ == "__main__":
    sys.exit(main())
