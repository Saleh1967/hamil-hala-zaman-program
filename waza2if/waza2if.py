# waza2if.py — بابُ الوظائف السبع: ديوانُ المانع، ودعوى «لا وظيفةَ تُصدِّق نفسَها».
#
# ══ الحدُّ المعلن قبل كلِّ شيء ═══════════════════════════════════════════════════════
# هذا البابُ **لا يقيس قاعدةً جديدة**، ولا يُسعِّر بتًّا على المجمَّد، ولا يحكم على
# قسمةٍ بصدقٍ أو ردّ. مهمّتُه واحدةٌ: أن يُسمّي **الوظائفَ السبعَ** المتعاونةَ في هذا
# المستودع، وأن يُثبت عنها **دعوى انغلاقٍ واحدة**:
#
#   **لا وظيفةَ ههنا تُصدِّق نفسَها**: كلُّ وظيفةٍ لها مانعٌ منفَّذٌ **خارجَ
#   منفِّذيها** — وما لا مانعَ له يُسمّى دَينًا ولا يُعَدُّ سليمًا بالسكوت.
#
# وهذه دعوى **انغلاقٍ لا دعوى رقم**، فبرهانُها جمعٌ ومصادمةٌ لا قياسٌ جديد. ولذلك:
#   ① **لا رقمَ يُكتَب في هذا الملفّ البتّة** غيرَ عدِّ البنود المعلنةِ فيه. كلُّ مانعٍ
#      بختمٍ يُسمّي **ختمًا قائمًا** في `induction/seals.json`، فتُقرأ قيمتُه من
#      **وديعته** بمسارها وتُصادَم بالمسجَّل. فمن أراد أن يُدخل رقمًا من عنده لم يجد
#      له بابًا.
#   ② **والدَّينُ لا رقمَ له**: ما لم يُنفَّذ مانعُه لا يُكتَب عددُه ههنا ولو كان
#      معلومًا — بل يُسمّى باسمه وموضعِه ويُوسَم دَينًا. فلو حُمِّل دَينٌ رقمًا سقط
#      البابُ. (وهذا هو بعينه شرطُ `mihwar_gate`: **الدَّينُ يُعلَن ولا يُسعَّر**.)
#   ③ **والمانعُ خارجَ الوظيفة**: حَكَمُ كلِّ مانعٍ مسارٌ في الشجرة، ويُصرَخ إن وقع
#      ذلك الحَكَمُ بين منفِّذي الوظيفة نفسِها. فالمدقِّقُ لا يُدقِّق نفسَه.
#
# ══ الاستقلالُ محفوظ (CONTRIBUTING.md §٨) ═══════════════════════════════════════════
#   • لا يستورد هذا الملفُّ شجرةَ المشروع البتّة، ولا يُستورَد منها: يُشغَّل عمليةً
#     منفصلةً بالمكتبة القياسيّة وحدَها.
#   • ويقرأ غيرَه **من بايتاته المودَعة لا من كوده**: سجلُّ الأختام من
#     `induction/seals.json`، والودائعُ من ملفّاتها، والحرّاسُ من بايتات `ci.yml`.
#   • ومجلَّدُه مختومٌ بذاته في `SHA256SUMS.txt`، و`--check` يصرخ على ملفٍّ غيرِ
#     مختومٍ كما يصرخ على ختمٍ خُولِف.
#
# ══ المنهجُ الذي يُحاكَم به (بنودُ `burhan/THE-PROOF.md` السبعة) ═══════════════════════
#   ① الأساسُ يُعلَن قبل العدّ — المقامُ ههنا: بنودُ هذا الملفّ وبايتاتُ الشجرة، لا غير.
#   ② المتوقَّعُ يُسجَّل قبل التشغيل — `SEALED_WAZA2IF` مكتوبٌ في البايتات ويُصادَم.
#   ③ القيدُ الساقطُ يُثبَّت بعدده — «وظائفُ بلا مانعٍ منفَّذ» يُعرَض عددُها.
#   ④ ما لم يُعلَن متوقَّعُه يبقى معلَّقًا — والدَّينُ يُسمّى ولا يُسعَّر.
#   ⑤ كلُّ حارسٍ يَعُدُّ غيرَ الصفر في صورةٍ مكذِّبة — `falsify` اثنتا عشرةَ محاولة.
