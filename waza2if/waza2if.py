# ═══ ② حلُّ المواضع: القيدُ يُحَلّ ولا يُختار ═════════════════════════════════════════
def resolve_deposit(name, _cache={}):
    """موضعُ الوديعة **بمسحِ الشجرة** لا بمسارٍ مُدَّعًى — و0 أو >1 مطابقًا صريخ.

    وهذه سنّةُ `fetch_source.sh` بعينها: المسارُ يُحَلّ، فلو نُقلت وديعةٌ غدًا إلى
    مجلَّدٍ آخر لم يشِخ هذا البابُ صامتًا، ولو تكرّر اسمُها في موضعين لم يُختَر
    أحدُهما بالهوى.
    """
    if name in _cache:
        return _cache[name]
    hits = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in (".git", "__pycache__")]
        if name in files:
            hits.append(os.path.join(base, name))
    if len(hits) != 1:
        raise Waza2ifError(E_MISSING if not hits else E_SEAL,
                           f"الوديعة «{name}»: {len(hits)} موضعًا في الشجرة — "
                           f"لا يُحَلُّ مسارُها ولا يُختار")
    _cache[name] = hits[0]
    return hits[0]


def read_seals():
    """سجلُّ الأختام **من بايتاته المودَعة لا من كوده** — انضباطُ الاستقلال.

    و`induction/seals.json` نفسُها مُصادَمةٌ في CI بما يُنتجه السجلُّ حيًّا، فقراءتُها
    ههنا ليست قراءةَ نسخةٍ ثانيةٍ تشيخ بل قراءةُ الأصلِ من موضعه المحروس.
    """
    if not os.path.isfile(SEALS_JSON):
        raise Waza2ifError(E_MISSING, f"سجلُّ الأختام غائبٌ عن القرص: {SEALS_JSON}")
    with open(SEALS_JSON, encoding="utf-8") as fh:
        return json.load(fh)["سجلُّ_الأختام"]["أختام"]


def seal_by_name(name, registry):
    """الختمُ باسمه — ولا يُقبَل اسمان لختمٍ واحدٍ ولا اسمٌ بلا ختم."""
    hits = [s for s in registry if s["اسم"] == name]
    if len(hits) != 1:
        raise Waza2ifError(E_SEAL,
                           f"مانعٌ يُسمّي ختمًا لا وجودَ له أو له أختامٌ متعدّدة: "
                           f"«{name}» ({len(hits)})")
    return hits[0]


