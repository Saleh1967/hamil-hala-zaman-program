def corpus_rows():
    """كلُّ كلمةٍ بصورتها وعلامةِ آخرها وشرطِ وصلِ تاليها. ولا يُطرَح موضعٌ ههنا."""
    verses = parse_verses(HL.CORPUS)
    rows = []
    for words in verses:
        for i, w in enumerate(words):
            if not w:
                continue
            rows.append(dict(
                صورة=HL.skel(w),
                علامة=w[-1][1],
                وصل=str(i + 1 < len(words) and HL.is_wasl_head(words[i + 1])),
                # صورةُ السابقةِ **داخلَ الآية** — وأوّلُ الآيةِ «∅» لا يرث آخرَ
                # ما قبلَها: فالعاملُ لا يعبُر حدَّ الآيةِ المفروض، كما في
                # `wad3_gate.corpus_rows` سواءً بسواء.
                سابقة=HL.skel(words[i - 1]) if i else "∅",
                صنف=None))
    return rows


def declared_tools():
    """أدواتُ المعجمِ الأحدَ عشرَ صنفًا مستورَدةً من `madlul_gate.MU3JAM`.

    تُردُّ خريطةً: صورةُ الأداةِ ⟶ صنفُها. والأصنافُ هي **العواملُ** التي تُقاس
    في §③ — فلا جدولَ عواملَ ثانٍ يُخترَع ههنا.
    """
    table = {}
    for sanf in MG.MU3JAM:
        for firqa in sanf["فرق"]:
            for adat in firqa["أدوات"]:
                table.setdefault(adat[0], sanf["صنف"])
    if len(MG.MU3JAM) < 11 or len(table) < 60:
        raise MabnaError(E_SEAL, "معجمُ الأدواتِ انكمشَ عن عدَّته — قسمةٌ بلا إعلان")
    return table


def division_station(rows, tools):
    """القسمةُ المُعلَنة، ودعوى «المبنيُّ لا يتغيّر آخرُه» تُعرَض للعدّ.

    والعدُّ **تامّ**: كلُّ صورةِ أداةٍ حاضرةٍ في المجمَّد تُفحَص علاماتُها كلُّها،
    ولا عتبةَ تواترٍ ولا انتقاء.
    """
    by_form = defaultdict(Counter)
    for r in rows:
        by_form[r["صورة"]][r["علامة"]] += 1
    present = sorted(f for f in tools if f in by_form)
    varying = sorted(f for f in present if len(by_form[f]) > 1)
    inside = [r for r in rows if r["صورة"] in set(present)]
    outside = [r for r in rows if r["صورة"] not in set(present)]
    if len(inside) + len(outside) != len(rows):
        raise MabnaError(E_SEAL, "القسمةُ لا تستوعب المقامَ — موضعٌ بلا خانة")
    top = sorted(varying, key=lambda f: -sum(by_form[f].values()))[:10]
    return dict(
        مقام=len(rows),
        صورٌ_مختلفة=len(by_form),
        أدواتٌ_مُعلَنة=len(tools),
        أدواتٌ_حاضرةٌ_صورةً=len(present),
        مواضعُ_المبنيِّ_المُعلَن=len(inside),
        مواضعُ_سواه=len(outside),
        متغيّرةُ_الآخِر=len(varying),
        لازمةُ_الآخِر=len(present) - len(varying),
        دعوى_اللزوم="المبنيُّ ما لزم آخرُه حالةً واحدة",
        حكمُ_دعوى_اللزوم=(
            "ساقطةٌ بالعدّ" if varying else "قائمةٌ بالعدّ"),
        أعلى_المتغيّرات=[
            f"{f}×{sum(by_form[f].values()):,} ({len(by_form[f])} علامات)"
            for f in top],
    ), inside, outside


# ═══ ② الفاتورةُ الموروثةُ وضوابطُ المثل ═══════════════════════════════════════
def ce(keys, ends):
    """بتّ/كلمةٍ خارجَ العيّنة بسياسة `harakat_layer` عينِها — لا سياسةَ ثانية.

    والحقلُ m=8 مقروءٌ من `HL.M` لا مكتوبٌ ههنا، فمن غيَّر الحقلَ غيَّر القياسَ معًا.
    """
    if len(keys) != len(ends):
        raise MabnaError(E_USAGE, "طولُ المكيال خالفَ طولَ الموصوف")
    if len(keys) < MIN_N:
        raise MabnaError(E_SEAL, f"مقامٌ دونَ حدِّ العيّنة {MIN_N} — لا حكمَ عليه")
    return HL.heldout_ce(list(zip(keys, ends)), 0, HL.M)


def wasl_gain(sub):
    """مكسبُ شرطِ الوصلِ **فوقَ الصورة** في طائفةٍ: الجوارُ الصورةُ لا المقامُ العاري."""
    ends = [r["علامة"] for r in sub]
    base = ce([r["صورة"] for r in sub], ends)
    both = ce([r["صورة"] + "⊗" + r[WASL_KEY] for r in sub], ends)
    return round(base - both, 4), round(base, 4), round(both, 4)


def rivals_of(rows, by_form, target_n):
    """إحدى عشرةَ فرقةً من الصورِ بعدّةِ **المواضعِ** نفسِها تقريبًا — لا بعدّةِ الصور.

    والعلّة: لو خُلِطت الصورُ بعددها لجاءت الفرقةُ بمواضعَ أقلَّ بكثيرٍ (فأدواتُ
    المعجم من أكثرِ الصورِ ورودًا)، فيكون الفارقُ فارقَ مقامٍ لا فارقَ قسمة.
    """
    pool = sorted(by_form)
    out = []
    for t in range(RIVALS):
        rng = random.Random(TG.CONTROL_SEED * 100 + t)
        shuffled = pool[:]
        rng.shuffle(shuffled)
        pick, n = set(), 0
        for f in shuffled:
            pick.add(f)
            n += sum(by_form[f].values())
            if n >= target_n:
                break
        out.append(wasl_gain([r for r in rows if r["صورة"] in pick])[0])
    return out


def bits_station(rows, inside, outside):
    """**هذه هي المحطّة**: أتُشترى القسمةُ بالبتّ أم هي اسمان على شيءٍ واحد؟

    والمقياسُ ليس «أيتغيّر آخرُ المبنيّ؟» — فقد تغيّر بالعدّ. بل: **أيُفسَّر
    تغيُّرُه بشرطِ الوصلِ وحدَه؟** فإن اشترى الوصلُ في المبنيِّ ولم يشترِ فيما
    سواه فالقسمةُ **مضمونُها مقيس**: المبنيُّ ما كان تغيُّرُ آخرِه وصليًّا.
    """
    by_form = defaultdict(Counter)
    for r in rows:
        by_form[r["صورة"]][r["علامة"]] += 1
    g_in, b_in, w_in = wasl_gain(inside)
    g_out, b_out, w_out = wasl_gain(outside)
    riv = rivals_of(rows, by_form, len(inside))
    beat = g_in > max(riv)
    return dict(
        مقامُ_المبنيّ=len(inside),
        مقامُ_سواه=len(outside),
        المبنيُّ_بالصورة=b_in,
        المبنيُّ_بالصورةِ_والوصل=w_in,
        مكسبُ_الوصلِ_في_المبنيّ=g_in,
        سواه_بالصورة=b_out,
        سواه_بالصورةِ_والوصل=w_out,
        مكسبُ_الوصلِ_في_سواه=g_out,
        الفارق=round(g_in - g_out, 4),
        مكسبٌ_كلّيٌّ_بالبتّ=round(g_in * len(inside), 1),
        بذرةُ_الضابط=TG.CONTROL_SEED,
        ضوابطُ_المثل=riv,
        أعلى_المثل=max(riv),
        غلبَ_المثل=beat,
        حكم=("مُودَعةٌ بالوجهين — اشترت بتًّا وغلبت مثلَها"
             if (g_in > 0 and beat and g_out <= 0) else
             "ساقطةٌ — القسمةُ لا تُشترى بالبتّ"),
        بيان=(
            "القسمةُ **مضمونُها مقيس**: شرطُ الوصلِ يشتري في المبنيِّ ولا يشتري "
            "فيما سواه — فالمبنيُّ ما كان تغيُّرُ آخرِه وصليًّا لا إعرابيًّا"),
    )


# ═══ ③ العوامل: أصنافُ المعجمِ الأحدَ عشرَ مكيالًا ═══════════════════════════════
def awamil_station(rows, tools):
    """العواملُ صنفًا صنفًا، حاكمةً على الكلمةِ التالية، **فوقَ الصورة**.

    وهذا تضييقُ ما سقط في `wad3_gate` بثلاثةِ أصناف (−0.0016): ههنا أصنافُ
    المعجمِ كلُّها — فإن سقطت ههنا أيضًا فالسقوطُ ليس خشونةَ التصنيف.
    """
    ends = [r["علامة"] for r in rows]
    base = ce([r["صورة"] for r in rows], ends)
    with_gov = ce([r["صورة"] + "⊗" + (r["صنف"] or "∅") for r in rows], ends)
    gain = round(base - with_gov, 4)
    used = sorted({r["صنف"] for r in rows if r["صنف"]})
    return dict(
        # الأصنافُ **مُعلَنةٌ إحدى عشرةَ** في المعجم، و**حاضرةٌ ثمانيةٌ** حاكمةً في
        # المجمَّد — والفرقُ يُعلَن ولا يُطوى: ثلاثةُ أصنافٍ لم تقع سابقةً لكلمة.
        أصنافٌ_مُعلَنة=len(MG.MU3JAM),
        أصنافُ_العوامل=len(used),
        أسماؤها=used,
        مواضعُ_مسبوقةٍ_بعامل=sum(1 for r in rows if r["صنف"]),
        بالصورةِ_وحدَها=round(base, 4),
        بالصورةِ_والعامل=round(with_gov, 4),
        مكسبٌ_فوقَ_الصورة=gain,
        مكسبٌ_كلّيٌّ_بالبتّ=round(gain * len(rows), 1),
        حكم=("مُودَعٌ" if gain > 0 else "ساقطٌ بالثمن"),
        بيان=(
            "أصنافُ المعجمِ كلُّها حاكمةً لا تشتري بتًّا فوقَ الصورة — وهو "
            "تصديقُ سقوطِ الحاكمِ الثلاثيِّ في `wad3_gate`، فالسقوطُ ليس "
            "خشونةَ التصنيف"),
    )


# ═══ ④ المعتلُّ الآخِر ═════════════════════════════════════════════════════════
ILLA = ("ا", "و", "ى", "ي")       # حروفُ العلّةِ في الرسم — كما في `i3lal_layer.MADD`
BARE = ("عري", "سكون")            # خاتمةُ «العلامةُ المقدَّرة» في الحقل الثمانيّ


def mu3tall_station(rows):
    """دعوى «المعتلُّ علامتُه مقدَّرة» تُعرَض للعدّ التامّ: نصيبُ العاري/الساكن.

    والقسمةُ رسميّةٌ محضةٌ (آخِرُ الرسمِ حرفُ علّة) — لا دعوى معجميةَ فيها.
    """
    mu = [r for r in rows if r["صورة"][-1] in ILLA]
    sa = [r for r in rows if r["صورة"][-1] not in ILLA]
    if len(mu) + len(sa) != len(rows):
        raise MabnaError(E_SEAL, "قسمةُ الاعتلالِ لا تستوعب المقامَ")
    share = lambda s: round(sum(1 for r in s if r["علامة"] in BARE) / len(s), 4)
    a, b = share(mu), share(sa)
    return dict(
        مواضعُ_المعتلّ=len(mu),
        مواضعُ_الصحيح=len(sa),
        نصيبُ_المقدَّرِ_في_المعتلّ=a,
        نصيبُ_المقدَّرِ_في_الصحيح=b,
        الفارق=round(a - b, 4),
        حكم=("قائمةٌ بالعدّ" if a > b else "ساقطةٌ بالعدّ"),
        بيان=(
            "الدعوى تقول: آخرُ المعتلِّ لا تظهر عليه الحركة. والعدُّ التامُّ "
            "يشهد — والفرقُ مودَعٌ برقمه لا بوصفه"),
    )


# ═══ ⑤ محطّةُ الحَجْر: الممنوعُ من الصرف ═══════════════════════════════════════
def strip_pre(form):
    """نزعُ اللواصقِ الرسميّةِ للكشف عن «ال» وحدَها — إخراجٌ لا قلع."""
    while len(form) > 3 and form[0] in PRE:
        form = form[1:]
    return form


def mamnu_proxy(form):
    """وكيلُ «صيغةِ منتهى الجموع» بالرسم — **وكيلٌ يُقاس خطؤه ثمّ يُحجَر**."""
    s = strip_pre(form)
    if s.startswith("ال"):
        return False                       # معرَّفٌ بـ«ال» — يُصرَف بالنصّ
    return len(s) >= 4 and s[0] == "م" and s[2] == "ا"


def hajr_station(rows):
    """الممنوعُ من الصرف: لا يُردُّ ولا يُقبَل — يُحجَر **بحدِّه المقيس**.

    القاعدةُ المنصوصة: لا يُنوَّن ولا يُجَرُّ بالكسرة. ولو صُدِّق الوكيلُ الرسميُّ
    لسُجِّل نقضٌ بمئاتِ المواضع — وهو نقضٌ على **الوكيل** لا على القاعدة، لأنّ
    الوكيلَ يلتقط «مكان» و«متاع» و«ملائكة» وليست من الصيغة. فيُقاس خطؤه ويُعلَن،
    وتُحجَر القاعدةُ حتّى يُختَم وزنٌ ومعجم — كحكم T₃ في `AUDIT-188.md`.
    """
    caught = [r for r in rows if mamnu_proxy(r["صورة"])]
    if not caught:
        raise MabnaError(E_SEAL, "الوكيلُ لم يلتقط شيئًا — لا حدَّ يُقاس")
    breach = [r for r in caught
              if r["علامة"].startswith("تنوين") or r["علامة"] == "كسرة"]
    rate = round(len(breach) / len(caught), 4)
    named = [f"{f}×{n}" for f, n in
             Counter(r["صورة"] for r in breach).most_common(8)]
    return dict(
        وكيلٌ_رسميّ=MAMNU_PROXY,
        مواضعُ_الوكيل=len(caught),
        مواضعُ_مخالفةٍ=len(breach),
        نسبةُ_خطأِ_الوكيل=rate,
        مخالفاتٌ_مسمّاة=named,
        حكم="محجورةٌ بحدِّها المقيس — لا مردودةٌ ولا مقبولة",
        بيان=(
            f"وكيلُ الرسمِ يُخالَف في {rate:.2%} من التقاطه، ومخالفوه **مسمَّون** "
            "وليسوا من الصيغة أصلًا — فالخطأُ خطأُ الوكيلِ لا نقضُ القاعدة. "
            "ومنعُ الصرفِ يحتاج وزنًا ومعجمًا مختومَين، ولا ختمَ لهما ههنا"),
    )


# ═══ محاولاتُ التكذيب ══════════════════════════════════════════════════════════
def falsify(rows, inside, outside, tools):
    """كلُّ محاولةٍ **تُشغَّل** وتُودَع بنتيجتها. ونجاحُ واحدةٍ يُسقِط الباب."""
    T, by_form = [], defaultdict(Counter)
    for r in rows:
        by_form[r["صورة"]][r["علامة"]] += 1
    add = lambda n, ok, note: T.append(
        dict(محاولة=n, نجحت=bool(ok), بيان=note))

    # ① لو كان مكسبُ الوصلِ في المبنيِّ من **عدّةِ المواضع** لا من القسمة، لبلغته
    #    فرقةٌ عشوائيّةٌ بالعدّة نفسِها. فالضوابطُ الأحدَ عشرَ هي هذه المحاولة.
    g_in = wasl_gain(inside)[0]
    riv = rivals_of(rows, by_form, len(inside))
    add("فرقةٌ عشوائيّةٌ بعدّةِ المواضعِ نفسِها تبلغ مكسبَ المبنيّ",
        max(riv) >= g_in, f"أعلى المثل {max(riv):+.4f} ⟷ المبنيّ {g_in:+.4f}")

    # ② ولو كان المكسبُ في الصورةِ نفسِها لا في الوصل، لبقي بعدَ خلطِ الوصلِ خلطًا.
    rng = random.Random(TG.CONTROL_SEED)
    shuffled = [r[WASL_KEY] for r in inside]
    rng.shuffle(shuffled)
    ends = [r["علامة"] for r in inside]
    base = ce([r["صورة"] for r in inside], ends)
    mixed = base - ce([r["صورة"] + "⊗" + v
                       for r, v in zip(inside, shuffled)], ends)
    add("مكسبُ المبنيِّ يبقى بعدَ خلطِ شرطِ الوصلِ خلطًا",
        mixed >= g_in, f"مخلوطٌ {mixed:+.4f} ⟷ مودَعٌ {g_in:+.4f}")

    # ③ ولو كانت القسمةُ تحصيلَ حاصلٍ لاشترى الوصلُ فيما سواها بمثلِ ما اشترى فيها.
    g_out = wasl_gain(outside)[0]
    add("الوصلُ يشتري فيما سوى المبنيِّ بمثلِ ما يشتري فيه",
        g_out >= g_in, f"سواه {g_out:+.4f} ⟷ المبنيّ {g_in:+.4f}")

    # ④ ولو كان المعجمُ يُقرَأ من ملفٍّ ههنا لا من المتن، لبقي القياسُ قائمًا بلا معجم.
    add("المعجمُ يُنسَخ ههنا لا يُستورَد",
        any(k in globals() for k in ("MU3JAM", "TOOLS_TABLE")),
        "الأدواتُ تُقرأ من `madlul_gate.MU3JAM` وحدَها — لا جدولَ ههنا")

    # ⑤ ولو كان حدُّ العيّنةِ حليةً، لقبِل المقياسُ مقامًا دونَه بلا صريخ.
    try:
        ce(["ا"] * (MIN_N - 1), ["فتحة"] * (MIN_N - 1))
        tiny = True
    except MabnaError:
        tiny = False
    add("الفاتورةُ تقبل مقامًا دونَ حدِّ العيّنة", tiny,
        f"دونَ {MIN_N} تصرخ ولا تُصنِّع رقمًا")

    # ⑥ ولو اختلَّ طولُ المكيالِ عن الموصوفِ لَقِيسَ على أزواجٍ مبتورةٍ صامتًا.
    try:
        ce(["ا"] * MIN_N, ["فتحة"] * (MIN_N - 1))
        ragged = True
    except MabnaError:
        ragged = False
    add("الفاتورةُ تقيس مكيالًا خالفَ طولَ موصوفِه", ragged,
        "الطولان يُصادَمان قبلَ القياس")

    # ⑦ ولو كان وكيلُ منعِ الصرفِ صادقًا لَما خالفَه أحدٌ — والمخالفةُ مقيسة.
    h = hajr_station(rows)
    add("وكيلُ منعِ الصرفِ لا يُخالَف فيُقرَأ حكمًا",
        h["مواضعُ_مخالفةٍ"] == 0,
        f"خُولِف في {h['مواضعُ_مخالفةٍ']:,} من {h['مواضعُ_الوكيل']:,}")

    # ⑧ ولو كانت دعوى «المبنيُّ لا يتغيّر آخرُه» قائمةً لَما وُجدت أداةٌ متغيّرة.
    present = [f for f in tools if f in by_form]
    varying = [f for f in present if len(by_form[f]) > 1]
    add("دعوى لزومِ آخرِ المبنيِّ قائمةٌ بالعدّ", not varying,
        f"{len(varying)} من {len(present)} أداةٍ حاضرةٍ تغيّر آخرُها")

    # ⑨ ولو كانت أصنافُ العواملِ تشتري بتًّا لَانقلبَ حكمُ `wad3_gate` صمتًا.
    a = awamil_station(rows, tools)
    add("أصنافُ العواملِ تشتري بتًّا فوقَ الصورة",
        a["مكسبٌ_فوقَ_الصورة"] > 0,
        f"مكسبُها {a['مكسبٌ_فوقَ_الصورة']:+.4f} — ساقطٌ كالحاكمِ الثلاثيّ")

    # ⑩ ولو كانت قسمةُ الاعتلالِ لا تفرز لَاستوى نصيبُ المقدَّرِ في الطائفتين.
    m = mu3tall_station(rows)
    add("نصيبُ المقدَّرِ يستوي في المعتلِّ والصحيح",
        m["الفارق"] <= 0,
        f"معتلٌّ {m['نصيبُ_المقدَّرِ_في_المعتلّ']} ⟷ صحيحٌ "
        f"{m['نصيبُ_المقدَّرِ_في_الصحيح']}")

    # ⑪ ولو كانت البذرةُ منسوخةً ههنا لَتخالفت ضوابطُ المثلِ بين البابين صامتةً.
    add("بذرةُ الضابطِ منسوخةٌ ههنا لا مستورَدة",
        "CONTROL_SEED" in globals(),
        f"تُقرأ من `ta3allum_gate` — {TG.CONTROL_SEED}")

    # ⑫ ولو كان الحقلُ مكتوبًا ههنا لَتخالفَ مع `harakat_layer` عند تغييره.
    add("حقلُ العلامةِ مكتوبٌ ههنا لا مقروءٌ من طبقته",
        "STATES" in globals() or HL.M != 8,
        f"m={HL.M} مقروءٌ من `harakat_layer.M`")
    return T


